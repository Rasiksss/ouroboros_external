"""The in-process transport: one bounded queue, a publisher and a consumer over it.

Deliberately dumb — it delivers what it was given and nothing else, so a broker provider
replaces it without a caller changing. It knows one thing about a message beyond its
identity: whether the kind says it may be discarded when there is no room.
"""

from __future__ import annotations

import logging
import queue as queue_mod

from new_core.identity import OwnerScope
from ouroboros.agent_events.codec import ensure_wire_safe
from ouroboros.agent_events.interfaces import (
    AgentEvent,
    IAgentEventConsumer,
    IAgentEventPublisher,
)

log = logging.getLogger(__name__)

#: How many messages the queue holds before a publish has to wait. Sized for a burst of
#: one run's live logs and beats while the consumer is busy with a slow handler, times a
#: few concurrent runs. Above it, a run publishing its answer blocks — which is the
#: intended back-pressure and not a failure.
MAX_PENDING_EVENTS = 512


class InMemoryAgentEventPublisher(IAgentEventPublisher):
    """Puts messages on a bounded queue, blocking when it is full.

    The inverse of the background-memory transport, and deliberately: there a dropped
    trigger is regenerated by the next event, here a dropped message is the user's answer
    and regenerates nowhere. Only a kind that declares itself droppable is discarded.
    """

    def __init__(self, queue: queue_mod.Queue[AgentEvent]) -> None:
        self._queue = queue

    def publish(self, event: AgentEvent) -> None:
        # Checked here even though nothing is serialized in-process: without it a producer
        # passes every in-process test and fails on the broker, where the call site that
        # put the value there is no longer in scope.
        ensure_wire_safe(event)
        if type(event).droppable:
            try:
                self._queue.put_nowait(event)
            except queue_mod.Full:
                log.warning(
                    "Dropped a droppable %s: transport full (cap=%d) scope=%s",
                    type(event).__name__,
                    self._queue.maxsize,
                    self.partition_key(event),
                )
            return
        self._queue.put(event)

    @staticmethod
    def partition_key(event: AgentEvent) -> OwnerScope:
        """What delivery is ordered by, read off the base type without naming a kind."""
        return event.scope


class InMemoryAgentEventConsumer(IAgentEventConsumer):
    """Reads messages off the same queue, waiting at most ``timeout`` seconds."""

    def __init__(self, queue: queue_mod.Queue[AgentEvent]) -> None:
        self._queue = queue

    def poll(self, timeout: float = 0.0) -> AgentEvent | None:
        try:
            if timeout <= 0:
                return self._queue.get_nowait()
            return self._queue.get(timeout=timeout)
        except queue_mod.Empty:
            return None

    @staticmethod
    def partition_key(event: AgentEvent) -> OwnerScope:
        """What delivery is ordered by, read off the base type without naming a kind."""
        return event.scope


def create_agent_event_transport(
    maxsize: int = MAX_PENDING_EVENTS,
) -> tuple[InMemoryAgentEventPublisher, InMemoryAgentEventConsumer]:
    """One queue, its two halves. The composition root hands each half to one side."""
    queue: queue_mod.Queue[AgentEvent] = queue_mod.Queue(maxsize=maxsize)
    return InMemoryAgentEventPublisher(queue), InMemoryAgentEventConsumer(queue)


