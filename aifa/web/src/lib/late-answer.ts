/**
 * Ответ, пришедший ПОСЛЕ конца хода: чем догнать ленту.
 *
 * 🔴 ДЕФЕКТ, НАЙДЕННЫЙ ВЛАДЕЛЬЦЕМ 23.08.2026. Прогон станции длиннее хода —
 * нормальный исход, а не сбой: извлечение идёт минутами, ход кончается раньше.
 * Сервер для этого возвращает агента в петлю, тот дописывает ответ и кладёт его
 * в серверную сессию. Но SSE хода к этому моменту закрыт, а восстановление
 * треда на клиенте срабатывало ТОЛЬКО на пустой ленте — то есть в единственном
 * случае, когда лента непуста и ждёт последнее слово, оно не приезжало никогда.
 * Человек десять минут смотрел в молчащий чат при готовой работе.
 *
 * Здесь — чистое правило «чего в ленте не хватает». Отдельно от React, чтобы
 * его исполнял и проверял один и тот же код.
 */

/** Запись серверной истории (`GET /chat/history`). */
export type HistoryEntry = { role: string; content?: string; name?: string };

/** Сообщение ленты — нам важны только роль и текст. */
export type FeedMessage = { role: string; content?: string };

/**
 * Хвост ответов ассистента, который есть на сервере и которого нет в ленте.
 *
 * Сверяем СЧЁТОМ реплик ассистента, а не текстами. Тексты сравнивать нельзя:
 * лента собирается из потоковых дельт и проходит через глушилку пересказа, так
 * что то же самое сообщение отличается от серверного пробелами и обрезкой —
 * по тексту оно выглядело бы новым и удвоилось бы на экране.
 *
 * Пустой массив — «догонять нечего», и это самый частый ответ: обычный ход
 * кладёт ровно столько же реплик, сколько показал.
 */
export function missingAssistantTail(
  feed: readonly FeedMessage[],
  history: readonly HistoryEntry[],
): string[] {
  const серверные = history
    .filter((e) => e.role === "assistant")
    .map((e) => String(e.content || "").trim())
    .filter(Boolean);
  const своих = feed.filter((m) => m.role === "assistant" && String(m.content || "").trim()).length;
  // `slice` за концом отдаёт пустой массив сам — отдельной проверки «сервер
  // отстал от ленты» здесь нет намеренно: она была бы недостижимой строкой.
  return серверные.slice(своих);
}
