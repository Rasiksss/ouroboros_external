import { describe, expect, it } from "vitest";
import { __fitToBudgetНаивно, __fitToBudgetБыстро, type Project } from "./projects";

/**
 * Обрезка зеркала до бюджета: та же граница, но без квадратичной цены.
 *
 * Куплено замером 24.08.2026 на профиле владельца — 104 чата, зеркало 1,47 МБ.
 * Прежняя реализация убавляла по одному и КАЖДЫЙ РАЗ сериализовала весь
 * список заново: 66 вызовов JSON.stringify и 181 мс главного потока на одну
 * запись. Запись идёт на каждой подтяжке с сервера, а подтяжка — на каждый
 * возврат на вкладку; сервер отдаёт 104, зеркало вмещает ~40, список сходится
 * к тому же, и цикл повторяется в полном объёме. После правки — 8,4 мс.
 *
 * Ускорение ничего не стоит только если ГРАНИЦА НЕ СДВИНУЛАСЬ. Поэтому главный
 * тест здесь — не про скорость, а про равенство наивной мере на случайных
 * входах.
 */

function чат(i: number, весКб: number): Project {
  return {
    id: `p${i}`,
    updated_at: 1_000_000 + i,
    messages: [{ id: `m${i}`, role: "user", content: "ы".repeat(весКб * 1024) }],
  } as unknown as Project;
}

describe("обрезка зеркала", () => {
  it("даёт ТОТ ЖЕ ответ, что наивная мера — на разных формах списка", () => {
    // Размер префикса растёт монотонно, поэтому накопление и убавление обязаны
    // сойтись на одном числе. Если разойдутся — сдвинулась граница, а не цена.
    const формы: Project[][] = [
      Array.from({ length: 104 }, (_, i) => чат(i, i % 7 === 0 ? 12 : 2)),
      Array.from({ length: 40 }, (_, i) => чат(i, 30)),
      Array.from({ length: 3 }, (_, i) => чат(i, 800)),
      Array.from({ length: 12 }, (_, i) => чат(i, 1)),
      [чат(0, 4000)],
    ];
    for (const бюджет of [1_572_864, 500_000, 50_000, 1_000]) {
      for (const список of формы) {
        // Сверяем ИМЕНА, а не количество: при равновеликих чатах счёт совпал бы
        // и у обратной сортировки — то есть выбросив свежие вместо старых.
        expect(__fitToBudgetБыстро(список, бюджет).map((p) => p.id)).toEqual(
          __fitToBudgetНаивно(список, бюджет).map((p) => p.id),
        );
      }
    }
  });

  it("влезающий список не режется вовсе", () => {
    const мелкие = Array.from({ length: 5 }, (_, i) => чат(i, 1));
    expect(__fitToBudgetБыстро(мелкие, 1_572_864)).toHaveLength(5);
  });

  it("оставляет СВЕЖИЕ, а выбрасывает старые", () => {
    // Порядок выброса — не вкусовщина: свежий чат может быть ещё не доехавшим
    // до сервера, выбросишь его — исчезнет навсегда. Старые там заведомо есть.
    // Все чаты ОДНОГО веса — тогда «сколько осталось» одинаково при любой
    // сортировке, и единственное, что отличает правильный ответ от обратного,
    // это ИМЕНА. Раньше тест смотрел на счёт и пропускал разворот порядка.
    const список = Array.from({ length: 10 }, (_, i) => чат(i, 100));
    const оставлено = __fitToBudgetБыстро(список, 300_000).map((p) => p.id);
    expect(оставлено.length).toBeGreaterThan(0);
    expect(оставлено.length).toBeLessThan(10);
    expect(оставлено[0]).toBe("p9");
    expect(оставлено).not.toContain("p0");
  });

  it("один чат остаётся, даже если он один не влезает", () => {
    // Пустое зеркало хуже переполненного: по нему загрузка документа говорит
    // «чат не найден в хранилище», и человек видит поломку не по адресу.
    expect(__fitToBudgetБыстро([чат(0, 4000)], 1_000)).toHaveLength(1);
  });

  it("считает запятые и скобки — на бюджете впритык это решает", () => {
    // ⚠️ ПЕРВАЯ РЕДАКЦИЯ ЭТОГО СТОРОЖА БЫЛА НЕГОДНОЙ. Бюджеты в ней были
    // просторные (сотни килобайт при чатах по 2–12 КБ), и мутация «не считать
    // запятые» проходила зелёной: ошибка в n−1 байт не сдвигает границу, когда
    // один элемент весит тысячи. Проверка формулы требует бюджета ВПРИТЫК.
    //
    // Чаты здесь минимальные (~45 байт), бюджет равен ТОЧНОМУ размеру первых
    // пятидесяти. Реализация, забывшая запятую, насчитает свободное место и
    // возьмёт пятьдесят первый — payload выйдет за бюджет.
    const крошки = Array.from({ length: 100 }, (_, i) => ({
      id: `p${i}`,
      updated_at: 1_000_000 + i,
      messages: [],
    })) as unknown as Project[];
    const свежие = [...крошки].sort((a, b) => (b.updated_at ?? 0) - (a.updated_at ?? 0));
    const бюджетВпритык = JSON.stringify(свежие.slice(0, 50)).length;
    const оставлено = __fitToBudgetБыстро(крошки, бюджетВпритык);
    expect(оставлено).toHaveLength(50);
    expect(JSON.stringify(оставлено).length).toBeLessThanOrEqual(бюджетВпритык);
  });

  // ⚠️ ЧЕГО ЭТОТ ФАЙЛ НЕ ПРОВЕРЯЕТ, И ПОЧЕМУ ЭТО СКАЗАНО ВСЛУХ.
  //
  // Слагаемое «скобки массива» (`занято = 2`) непроверяемо в принципе: мутация
  // `занято = 0` даёт два байта запаса, а самый маленький возможный проект в
  // JSON весит десятки. Два байта не могут сдвинуть границу ни на одном входе,
  // который встречается на деле. Слагаемое оставлено ради точности формулы, но
  // сторожа на него нет — и придумывать тест, который «как бы» его покрывает,
  // хуже, чем назвать дыру.
  //
  // Остальные три мутации краснеют: не считать запятые → тест впритык;
  // сортировать наоборот → равенство наивной мере и «оставляет свежие»;
  // уронить последний чат → равенство наивной мере.

  it("укладывается в бюджет ПО ФАКТУ, а не по расчёту", () => {
    // Считаем длину массива формулой (скобки + элементы + запятые). Ошибка в
    // формуле дала бы переполнение при формально верном keep — сверяем с
    // настоящей сериализацией.
    const список = Array.from({ length: 104 }, (_, i) => чат(i, i % 7 === 0 ? 12 : 2));
    const бюджет = 1_572_864;
    expect(JSON.stringify(__fitToBudgetБыстро(список, бюджет)).length).toBeLessThanOrEqual(бюджет);
  });
});

