/**
 * Вырезание markdown-таблиц из ответа агента.
 *
 * ЗАЧЕМ (правка Nate 17.08). Числа прогона показывались в двух видах: в
 * рабочей области — сеткой `ExtractedGrid`, в чате — markdown-таблицей, которую
 * напечатала модель. Разные колонки, разное выравнивание, разное
 * форматирование. Теперь в чате рисуется та же сетка, а markdown-таблица из
 * текста убирается — иначе одни и те же числа встали бы дважды подряд.
 *
 * Режем ТОЛЬКО таблицы и только когда есть чем их заменить: текст вокруг
 * (пояснения, оговорки, ссылки на страницы) остаётся нетронутым.
 */

/** Строка-разделитель GFM-таблицы: `|---|:--:|` и любые её вариации. */
const SEPARATOR = /^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$/;

const isRow = (line: string) => line.trim().startsWith("|");

export function stripGfmTables(text: string): { text: string; had: boolean } {
  const lines = text.split("\n");
  const out: string[] = [];
  let had = false;

  for (let i = 0; i < lines.length; i++) {
    // Таблица опознаётся ПАРОЙ «шапка + разделитель»: одинокая строка с
    // вертикальными чертами таблицей не является (так пишут и текст).
    if (isRow(lines[i]) && i + 1 < lines.length && SEPARATOR.test(lines[i + 1])) {
      had = true;
      i += 1;
      while (i + 1 < lines.length && isRow(lines[i + 1])) i += 1;
      // Пустую строку после таблицы съедаем вместе с ней, иначе на её месте
      // останется дыра в абзацах.
      if (i + 1 < lines.length && !lines[i + 1].trim()) i += 1;
      continue;
    }
    out.push(lines[i]);
  }

  return { text: out.join("\n").trim(), had };
}
