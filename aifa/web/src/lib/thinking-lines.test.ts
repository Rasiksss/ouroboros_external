import { describe, expect, it } from "vitest";
import { thinkingLines } from "./thinking-lines";

/**
 * Полоса размышлений: три строки вместо простыни (правка Nate 17.08).
 *
 * Исходный случай — прогон Мегафона: весь поток печатался одним абзацем и рос
 * без предела, пользователь читал внутреннюю кухню станции вместо работы.
 */
describe("thinkingLines", () => {
  it("отдаёт последние три строки, а не всё подряд", () => {
    const src = [
      "Классифицирую отчёт.",
      "Ячейка ifrs_nf_ru.",
      "Извлекаю показатели.",
      "Считаю коэффициенты.",
      "Собираю таблицу.",
    ].join("\n");
    expect(thinkingLines(src)).toEqual([
      "Извлекаю показатели.",
      "Считаю коэффициенты.",
      "Собираю таблицу.",
    ]);
  });

  it("режет по концу предложения, когда переводов строки нет", () => {
    const src = "Жду результат. Прогресс активный — 131 запись. Проверю, готов ли результат.";
    expect(thinkingLines(src)).toHaveLength(3);
    expect(thinkingLines(src)[2]).toBe("Проверю, готов ли результат.");
  });

  it("🔴 НЕ режет «МегаФон» пополам", () => {
    // Отрицательный контроль на соблазн резать по «строчная+прописная»: так
    // видна граница склейки («результатBridge»), но так же пишется название
    // компании, и каждый её прогон рвался бы на «Мега|Фон».
    const src = "МегаФон: извлекаю показатели";
    expect(thinkingLines(src)).toEqual(["МегаФон: извлекаю показатели"]);
  });

  it("склеенный кусок остаётся ОДНОЙ строкой — её обрежет многоточие", () => {
    const src = "Жду результатBridge разорвал соединение до завершения";
    expect(thinkingLines(src)).toEqual([src]);
  });

  it("пустой текст не даёт пустых строк", () => {
    expect(thinkingLines("")).toEqual([]);
    expect(thinkingLines("\n\n   \n")).toEqual([]);
  });

  it("заголовок markdown начинает новую строку", () => {
    const src = "Таблица собрана\n## МегаФон · 2025 · млн ₽";
    expect(thinkingLines(src)).toEqual(["Таблица собрана", "## МегаФон · 2025 · млн ₽"]);
  });
});
