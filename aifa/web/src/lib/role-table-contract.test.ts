describe("срез ПРОГОНА применяется и в рабочей области", () => {
  /**
   * 🔴 НАЙДЕНО ВЛАДЕЛЬЦЕМ 24.08.2026: «почему агент снова вывел 77 показателей?
   * Мы же уже делали механику чтобы выводил только те, что нужны».
   *
   * Механику сделали — 22.08, в `metrics-panel.tsx`, то есть в карточке на «/».
   * Рабочая область фильтрует СВОИМ путём: `filterRowsByOutputEnums(rows,
   * appliedRole, roleView.outputEnums)`. Для общей роли эта функция отдаёт
   * строки как есть (`isGenericTableRole` → return rows) — и это правильно, у
   * «Общей» своего перечня нет. Но у ПРОГОНА перечень есть
   * (`table_output_enums`), и здесь его не спрашивал никто.
   *
   * Станция сузила состав до 25 имён и честно их прислала — на экран легло 77,
   * весь реестр ячейки. Правило в одном месте из двух, наш постоянный класс.
   *
   * ОТКАТ: убрать `scopeRowsToSlice` из панели → первый тест краснеет.
   */
  it("панель режет строки срезом прогона, а не только ролью", () => {
    expect(PANE).toContain("scopeRowsToSlice(all.metrics, lastRun?.table_output_enums)");
  });

  it("функция среза берётся из общего модуля", () => {
    // Своя копия разошлась бы с общим модулем при первой же правке — ровно
    // так этот дефект и появился, когда экранов было два.
    expect(PANE).toContain('from "@/lib/table-slice"');
  });

  it("порядок: сперва срез прогона, потом раскладка роли", () => {
    // Наоборот нельзя: роль-фильтр для общей роли пропускает всё, и срез
    // прогона применился бы к уже расширенному набору — то есть ни к чему.
    const i = PANE.indexOf("scopeRowsToSlice(all.metrics");
    const j = PANE.indexOf("filterRowsByOutputEnums(свои");
    expect(i).toBeGreaterThan(0);
    expect(j).toBeGreaterThan(i);
  });
});
