import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Роль-формат в рабочей области: условия, без которых выбор роли снова
 * «не работает». Все они немые — экран при отказе выглядит как обычная работа.
 *
 * ИСТОРИЯ (17.08). Владелец спрашивал неделю, почему выбор роли не меняет
 * таблицу. Дефектов оказалось ДВА, и оба немые:
 *
 *  1. БЭКЕНД отбивал запрос 422-й (схема не принимала строковые значения), а
 *     фронт глотал это в `.catch(() => setRoleTable(null))`. На экране —
 *     просто общая таблица. Ответ лежал в access-логе, куда никто не смотрит.
 *  2. ФРОНТ применял роль ТОЛЬКО по клику. Перезагрузил страницу — селектор
 *     показывает «ДИЭ», а таблица общая. Подпись одной роли, колонки другой.
 *
 * 18.08 к ним добавились ещё четыре, найденные разбором против FinEngine:
 * чужая таблица при смене документа, молчание на 200 с `formatted: null`,
 * поток запросов на каждое событие стрима и склейка прогонов в одну раскладку.
 *
 * Проверяем исходник, а не поведение: без DOM-окружения панель не поднять, но
 * все условия — структурные, и регрессия видна в тексте файла. Чистая логика
 * раскладки покрыта отдельно, в formatted-table.test.ts.
 */
function read(rel: string): string {
  return readFileSync(fileURLToPath(new URL(rel, import.meta.url)), "utf8");
}

const PANE = read("../components/workspace/panes/extracted-pane.tsx");
const ACTIONS = read("../components/workspace/panes/doc-actions.tsx");
// PANEL (metrics-panel.tsx, карточка старого экрана «/») снесён в Р20 —
// его половины контрактов ушли вместе с предметом; live-рендерер один:
// extracted-pane, и все проверки ниже держат его.

/**
 * Тело эффекта, который ходит за раскладкой, и его массив зависимостей.
 *
 * Границы ищем РАЗБОРОМ, а не фиксированной строкой. Первая версия резала окно
 * по числу символов и падала на комментарии; вторая искала дословный текст
 * массива зависимостей — и когда в него добавили лишнее, `indexOf` вернул −1,
 * окно молча уехало до конца файла, а тест остался зелёным. Сторож, который
 * зеленеет от поломки своего же якоря, не сторож.
 */
const FORMAT_EFFECT_AT = PANE.indexOf("void formatMetricsForRole(");
const DEPS_MATCH = /\}, \[([^\]]*)\]\);/.exec(PANE.slice(FORMAT_EFFECT_AT));
const FORMAT_EFFECT = PANE.slice(FORMAT_EFFECT_AT, FORMAT_EFFECT_AT + (DEPS_MATCH?.index ?? 0));
const FORMAT_EFFECT_DEPS = DEPS_MATCH?.[1] ?? "";

describe("отказ раскладки виден пользователю", () => {
  it("ошибку роль-формата показываем, а не проглатываем", () => {
    expect(FORMAT_EFFECT).toContain(".catch(");
    expect(FORMAT_EFFECT).toContain("toast.error");
  });

  it("🔴 немого `.catch(() => setRoleTable(null))` больше нет", () => {
    // Отрицательный контроль ровно на прежнюю строку: вернётся — вернётся и
    // неделя вопросов «почему роль не работает».
    expect(PANE).not.toContain(".catch(() => setRoleTable(null))");
    expect(PANE).not.toContain(".catch(() => setRoleView(null))");
  });

  it("🔴 200 с пустой раскладкой тоже назван — это не ошибка сети", () => {
    // Для трёх пар роль×отчётность бэкенд отдаёт 200 и `formatted: null`.
    // Тоста здесь нет и быть не может — нужна надпись у таблицы.
    expect(FORMAT_EFFECT).toContain("roleLayoutMissingNote");
    expect(PANE).toContain("{roleNote}");
  });
});

describe("роль решает ЗАПУСК, а не вид чужой таблицы", () => {
  /**
   * 🔴 ГРАНИЦА, ПРОВЕДЁННАЯ ВЛАДЕЛЬЦЕМ 23.08.2026 ПОСЛЕ ПРОГОНА 49b398dc:
   *
   *   «Роль влияет только на запуск по детерминированному сценарию — если
   *    пользователь нажал шорткат и выбрал роль. Если поступает вопрос, агент
   *    не должен ограничиваться ролевой принадлежностью.»
   *
   * До этого панель читала `prefs.role` и МОЛЧА перестраивала таблицу любого
   * прогона по общей роли в раскладку постоянной роли. У владельца в настройках
   * CIB: он спросил пять коэффициентов, станция прочитала 22 показателя и
   * отметила к показу 19, а в рабочей области открылось 65 СТРОК — раскладка
   * CIB длинная, строка на показатель на период. Признака чужой раскладки на
   * экране не было ни одного.
   *
   * Вторая половина правила работала и до этого: шорткат называет роль во
   * фразе, модель запускает извлечение с ней, и раскладка приезжает СВОЯ.
   */
  it("панель берёт роль У ПРОГОНА, а не из настроек", () => {
    expect(PANE).toContain("const appliedRole: ExtractionRole = tableRoleOf(");
    expect(PANE).toContain('lastRun?.extraction_role || lastRun?.meta?.role || "other"');
    // Отрицательный контроль к живому дефекту: возврат чтения настроек в
    // панель возвращает молчаливое перестроение чужой таблицы.
    expect(PANE).not.toContain("loadPrefs()");
    expect(PANE).not.toContain('window.addEventListener("finengine:prefs"');
  });

  it("шорткат по-прежнему называет роль во фразе — там она и решает", () => {
    // Это ВТОРАЯ половина границы: настройка роли не умерла, она решает, что
    // отправит кнопка. Сотри её — и детерминированный сценарий команды исчезнет.
    expect(ACTIONS).toContain("loadPrefs()");
    expect(ACTIONS).toContain("Извлеки показатели по реестру роли");
  });

  it("🔴 роль нормализуется ОДНОЙ функцией в обоих местах", () => {
    // Отрицательный контроль на возврат второго нормализатора: пока подпись
    // кнопки считалась по одному списку, а запрос — по другому, `role: "all"`
    // давал «Общая» на экране и запрос несуществующей раскладки в сеть.
    expect(ACTIONS).toContain("tableRoleOf");
    expect(ACTIONS).not.toContain("function roleOf(");
    expect(PANE).not.toContain("function roleOf(");
  });
});

describe("раскладка относится к тому, что на экране", () => {
  it("🔴 чужая таблица не держится при смене документа или прогона", () => {
    // Отрицательный контроль на снятие адреса: без сверки docId/runId на
    // экране остаётся раскладка прошлого документа, ничем не помеченная.
    expect(PANE).toContain("roleView.docId === activeDocId");
    expect(PANE).toContain("roleView.runId === runId");
  });

  it("🔴 строки берутся из ОДНОГО прогона, а не склейкой всех", () => {
    // `collectMetrics` объединял прогоны документа, а подписи колонок брались
    // у свежего: часть чисел молча относилась не к тому периоду.
    // Ищем ВЫЗОВ, а не слово: в комментарии над правкой `collectMetrics`
    // назван намеренно — там объяснено, чем обернулась склейка.
    expect(PANE).toContain("rowsFromExtraction(lastRun)");
    expect(PANE).not.toMatch(/collectMetrics\(/);
  });
});

describe("запрос уходит по делу, а не на каждое событие стрима", () => {
  it("🔴 в зависимостях эффекта нет ни строк, ни пересоздаваемого колбэка", () => {
    // Отрицательный контроль: верните `rows`/`reformat`/`lastRun` в массив — и
    // во время извлечения снова пойдёт POST /metrics/format-role по 2–3 раза в
    // секунду, а побеждать будет последний ПРИШЕДШИЙ ответ.
    expect(FORMAT_EFFECT_DEPS).toContain("runId"); // якорь найден, окно живое
    expect(FORMAT_EFFECT_DEPS).not.toMatch(/\brows\b/);
    expect(FORMAT_EFFECT_DEPS).not.toMatch(/\breformat\b/);
    expect(FORMAT_EFFECT_DEPS).not.toMatch(/\blastRun\b/);
  });

  it("живой прогон не перестраиваем", () => {
    // Окно эффекта должно быть КОРОТКИМ: если якорь съехал, здесь оно
    // растянется на весь остаток файла, и все проверки выше станут пустыми.
    expect(FORMAT_EFFECT.length).toBeGreaterThan(0);
    expect(FORMAT_EFFECT.length).toBeLessThan(PANE.length / 3);
    expect(PANE).toContain('if (runStatus === "running") return;');
  });

  it("🔴 общая роль к серверу не ходит вовсе", () => {
    // FinEngine на other/all возвращается к обычной таблице БЕЗ запроса.
    // Проверка обязана стоять ДО вызова ручки. Сначала убеждаемся, что она
    // вообще есть: `indexOf` на отсутствующей строке даёт −1, а −1 меньше
    // любого индекса — снятая проверка иначе прошла бы как выполненная.
    const gateAt = PANE.indexOf("isGenericTableRole(appliedRole)");
    expect(gateAt).toBeGreaterThan(-1);
    expect(gateAt).toBeLessThan(FORMAT_EFFECT_AT);
  });

  it("опоздавший ответ не побеждает свежий", () => {
    // Проверка нужна в ОБЕИХ ветках цепочки — и в `.then`, и в `.catch`:
    // иначе тост об ошибке отменённого запроса всплывёт поверх живой таблицы.
    // Считаем вхождения, а не наличие: одна ветка из двух — это дыра.
    expect(FORMAT_EFFECT.match(/if \(!alive\) return;/g) ?? []).toHaveLength(2);
    expect(PANE).toContain("alive = false;");
  });
});

describe("вкладки и счётчики говорят про то, что показано", () => {
  it("🔴 поиск доходит до роль-таблицы", () => {
    // Поле поиска оставалось на экране и ничего не делало: `query` в
    // роль-таблицу не передавался вовсе.
    expect(PANE).toContain("filterFormattedTable(dieValuesTable(table), query)");
  });

  it("🔴 вкладка «Сегменты» показывает сегментную половину ДИЭ", () => {
    expect(PANE).toContain("dieSegmentsTable(table)");
  });

  it("🔴 роль сужает ПОКАЗАТЕЛИ, но не сегменты и не состав холдинга", () => {
    // Сторож переписан 18.08: прежняя его редакция закрепляла ЛОЖЬ. Фильтр по
    // `outputEnums` применялся ко ВСЕМ строкам, включая сегментные и строки
    // состава, — у тех своих enum'ов в перечне роли нет и быть не может.
    // Обе вкладки пустели, а панель писала «в этом прогоне их не было», хотя
    // строки лежали в прогоне рядом.
    //
    // Отрицательный контроль двусторонний: вернётся фильтр по всем строкам —
    // первая проверка покраснеет; исчезнет фильтр показателей — вторая.
    // ⚠️ ПИН ОБНОВЛЁН 24.08: между `all.metrics` и роль-фильтром встал срез
    // ПРОГОНА (`scopeRowsToSlice`), поэтому аргументом идёт `свои`. Смысл тот
    // же и проверяется по существу: фильтруются только показатели, а сегменты
    // и состав холдинга в роль-фильтр не попадают вовсе.
    expect(PANE).not.toContain("filterRowsByOutputEnums(rows, appliedRole");
    expect(PANE).toContain("filterRowsByOutputEnums(свои, appliedRole");
    expect(PANE).toContain("const свои = scopeRowsToSlice(all.metrics");
    for (const чужое of ["filterRowsByOutputEnums(all.segments", "filterRowsByOutputEnums(all.group"]) {
      expect(PANE).not.toContain(чужое);
    }
    expect(PANE).toContain("извлечено {scopedRows.length}");
  });

  it("🔴 гейт #142 больше не нужен панели — и это не потеря", () => {
    // Гейт #142 запрещал строить ЧУЖУЮ раскладку по узкому прогону: строк
    // чужого набора в нём нет, половина клеток вышла бы пустой. Теперь панель
    // чужих раскладок не строит вовсе — она берёт роль у самого прогона, — и
    // запрещать нечего. Держим это утверждение сторожем: вернётся выбор роли в
    // панель — вернётся и надобность в гейте, а вместе с ней живой дефект.
    expect(PANE).not.toContain("canReshapeTableRole");
    expect(PANE).not.toContain("chosenRole");
  });
});

