import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * Проводка догона позднего ответа — сторожем ПО ИСХОДНИКУ.
 *
 * ⚠️ ЭТО СЛАБЫЙ СТОРОЖ, И НАЗЫВАЮ ЕГО ТАК ЧЕСТНО. Он проверяет текст файла, а
 * не поведение: компонентных тестов в проекте нет, а заводить рендерер ради
 * одного вызова — отдельная работа. Того же рода сторож уже живёт рядом
 * (`role-table-contract.test.ts`), и заведён он по той же причине.
 *
 * 🔴 ЧТО ОН ДЕРЖИТ. Первая редакция догона стояла внутри `if (terminal)`, то
 * есть срабатывала только на ЧИСТОМ конце хода. Живой прогон 49b398dc: модель
 * досчитала и написала ответ на 1716 знаков, но связь к этому моменту
 * оборвалась, терминала клиент не получил — и владелец увидел ответ только
 * после ручного обновления страницы. Обрыв и есть тот случай, ради которого
 * догон заводился.
 */
const HOOK = readFileSync("src/components/workspace/use-chat-run.ts", "utf8");

describe("догон позднего ответа подключён", () => {
  it("запускается и на обрыве, а не только на чистом конце", () => {
    expect(HOOK).toContain("if (!o.signal?.aborted) chaseLateAnswer(projectId);");
    // Отрицательный контроль к живому дефекту: вызов внутри `if (terminal)`
    // возвращает ровно то поведение, на котором ответ терялся.
    expect(HOOK).not.toContain("if (terminal && !o.signal?.aborted) chaseLateAnswer");
  });

  it("намеренная отмена ответ не дописывает", () => {
    // «Стоп» и уход со страницы — отказ человека от ответа. Дописать его в
    // ленту после этого значит показать то, что просили не показывать.
    expect(HOOK).toContain("o.signal?.aborted");
  });

  it("правило хвоста берётся из lib, а не пишется здесь заново", () => {
    expect(HOOK).toContain('from "@/lib/late-answer"');
    expect(HOOK).toContain("missingAssistantTail(");
  });

  it("🔴 догон живёт, пока жив прогон, а не фиксированную минуту", () => {
    // ДЕФЕКТ 24.08.2026, увиденный владельцем: в чате «Ход завершён без
    // текстового ответа», в рабочей области «Извлечение идёт» — и ответ не
    // приходил НИКОГДА.
    //
    // Первая редакция догона делала шесть кругов по десять секунд — одну
    // минуту. Рассуждение было такое: «сервер даёт не больше трёх продолжений,
    // дольше ждать нечего». Ошибка в том, что продолжение начинается не сразу,
    // а КОГДА КОНЧИТСЯ ПРОГОН, — а прогон идёт до двадцати пяти минут. Догон
    // успевал сдаться раньше, чем на сервере появлялось, что догонять.
    expect(HOOK).toContain("findRunningExtraction(cur, null)");
    expect(HOOK).toContain("LATE_ANSWER_MAX_MS");
    // Отрицательный контроль: возврат счётчика попыток вернёт ту же минуту.
    expect(HOOK).not.toContain("LATE_ANSWER_TRIES");
  });

  it("потолок ожидания покрывает обещание навыка", () => {
    // Навык обещает «6–25 минут»; догон обязан пережить самый долгий прогон,
    // иначе он снова будет сдаваться раньше, чем появится ответ.
    const m = HOOK.match(/LATE_ANSWER_MAX_MS = (\d+) \* 60_000/);
    expect(m, "потолок задан не минутами — сверить не с чем").toBeTruthy();
    expect(Number(m![1])).toBeGreaterThanOrEqual(25);
  });
});
