/**
 * Размышления агента → последние N строк для мерцающей полосы.
 *
 * ЖАЛОБА (Nate, 17.08). «Нужно, чтобы было три строки, и чтобы они такой
 * мерцающей полосой просто обновлялись. Пользователь не должен видеть
 * настолько технически подробные инструкции.» На экране было обратное: весь
 * поток размышлений печатался ОДНИМ абзацем и рос до простыни — «Bridge
 * разорвал соединение… Progress застрял на 132 строках… Попробую перезапустить
 * с отключением…». Аналитик читал внутреннюю кухню станции вместо работы.
 *
 * ЧТО ДЕЛАЕМ ЗДЕСЬ. Только режем поток на строки и отдаём последние. Ни
 * фильтров «по смыслу», ни переписывания текста: что модель сказала, то и
 * показываем — просто не всё сразу. Отучать модель от технических подробностей
 * — дело тела навыка (`station-skills/aifa-extract/SKILL.md`), а не интерфейса:
 * фильтр в UI скрыл бы симптом и оставил причину.
 *
 * ⚠️ ПОЧЕМУ НЕ РЕЖЕМ ПО «СКЛЕЙКЕ» вида «результатBridge». Соблазн был: куски
 * приезжают без разделителя, и граница видна глазом — строчная буква, сразу за
 * ней прописная. Но ровно так пишется «МегаФон», и разрез дал бы «Мега|Фон» в
 * каждом прогоне по этой компании. Поэтому границы только надёжные: перевод
 * строки, конец предложения и заголовок markdown. Склейка остаётся одной
 * длинной строкой — и это не беда: строка в полосе обрезается многоточием.
 */

const LIMIT = 3;

export function thinkingLines(text: string, limit: number = LIMIT): string[] {
  const parts = String(text || "")
    .split(/\n+/)
    .flatMap((line) => line.split(/(?<=[.!?…])\s+/))
    .flatMap((line) => line.split(/(?=^#{1,6}\s)/m))
    .map((s) => s.trim())
    .filter(Boolean);
  return parts.slice(-limit);
}
