/**
 * Отпечаток ЖИВОЙ сборки фронта.
 *
 * Значение печётся в бандл на этапе сборки (ARG NEXT_PUBLIC_BUILD_ID), поэтому
 * ответ этой ручки — отпечаток контейнера, который работает ПРЯМО СЕЙЧАС, а
 * код открытой вкладки несёт отпечаток той сборки, из которой был загружен.
 * Расхождение = вкладка крутит устаревший код.
 *
 * Почему это важно: старая вкладка продолжает писать в общее хранилище и на
 * сервер по прежнему протоколу — так терялись документы и чаты, а поймать её
 * было нечем. Теперь она сама себя объявляет.
 */
// Обработчики маршрутов не кэшируются по умолчанию (docs 15-route-handlers) —
// отдельный force-dynamic не нужен, заголовок no-store добивает прокси.
export function GET() {
  return Response.json(
    { build: process.env.NEXT_PUBLIC_BUILD_ID ?? "dev" },
    { headers: { "Cache-Control": "no-store" } },
  );
}
