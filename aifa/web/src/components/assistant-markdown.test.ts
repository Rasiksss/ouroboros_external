import { describe, expect, it } from "vitest";

import { collapseRuns } from "./assistant-markdown";

/**
 * Вырожденный повтор одного знака не должен распирать вёрстку.
 *
 * Живой случай 17.08.2026: модель сорвалась на фразе «в собранном дайджесте за
 * по» и выдала 394 подряд «П» — строка ушла на всю ширину экрана.
 *
 * ПОЧЕМУ ЭТО НУЖНО И НА ФРОНТЕ, хотя поток уже обрывается на бэкенде: тот
 * ответ УЖЕ СОХРАНЁН в истории и будет рисоваться при каждом открытии чата.
 * Защита на отрисовке лечит и прошлое, и то, что бэкенд однажды пропустит.
 */
describe("collapseRuns", () => {
  it("сворачивает живой случай и объясняет, что произошло", () => {
    const text = "в собранном дайджесте за по" + "П".repeat(394);
    const out = collapseRuns(text);
    expect(out).not.toContain("П".repeat(40));
    expect(out).toContain("в собранном дайджесте за по");
    expect(out).toContain("394");
    expect(out.length).toBeLessThan(100);
  });

  // Ложное срабатывание тут ХУЖЕ пропуска: разделители и выравнивание —
  // нормальная разметка, и резать её нельзя.
  it.each([
    ["линия под заголовком", "Заголовок\n" + "-".repeat(80) + "\nстрока"],
    ["разделитель таблицы", "=".repeat(90)],
    ["выравнивание пробелами", "| Показатель" + " ".repeat(100) + "| Значение |"],
    ["решётки", "#".repeat(50)],
  ])("не трогает разметку: %s", (_name, text) => {
    expect(collapseRuns(text)).toBe(text);
  });

  it("не трогает обычный текст", () => {
    const text = "Обычный ответ про IBM и NVIDIA. Ничего необычного тут нет.";
    expect(collapseRuns(text)).toBe(text);
  });

  it("короткий повтор — это ещё не вырождение", () => {
    const text = "нуууу" + "у".repeat(20);
    expect(collapseRuns(text)).toBe(text);
  });

  it("у букв порог строже, чем у знаков разметки", () => {
    // 40 букв — уже вырождение; 40 дефисов — законная линия.
    expect(collapseRuns("а".repeat(40))).not.toBe("а".repeat(40));
    expect(collapseRuns("-".repeat(40))).toBe("-".repeat(40));
  });

  it("пустой текст не ломает вызов", () => {
    expect(collapseRuns("")).toBe("");
  });
});
