import { describe, expect, it } from "vitest";
import { layout, wrap } from "@/components/analysis-chart";
import type { AnalysisChart } from "@/lib/api";

/** Раскладка водопада — единственная арифметика на фронте, и врёт она ФОРМОЙ,
 * а не цифрой: подпись под столбиком остаётся верной, даже когда сам столбик
 * нарисован не оттуда. Такую ошибку глазами ловят постфактум, у пользователя,
 * — как #143. Проверяется чистая логика, без браузера и jsdom (см. комментарий
 * в vitest.config.mts). */

// Тот же водопад, что собирает бэкенд: 120 000 − 85 000 = 35 000, дальше
// −21 000 процентов и −19 000 аренды → остаток −5 000.
const POINTS: AnalysisChart["points"] = [
  { label: "Операционный поток", value: 120_000, kind: "start" },
  { label: "Капзатраты", value: -85_000, kind: "delta" },
  { label: "Свободный поток", value: 35_000, kind: "total" },
  { label: "Проценты", value: -21_000, kind: "delta" },
  { label: "Аренда", value: -19_000, kind: "delta" },
  { label: "Остаток", value: -5_000, kind: "total" },
];

describe("раскладка водопада", () => {
  it("приращение начинается там, где кончился предыдущий столбик", () => {
    const bars = layout(POINTS);
    // Именно это делает водопад водопадом: −85 000 висит от 120 000 до 35 000,
    // а не растёт от нуля вниз, как в обычной гистограмме.
    expect(bars[1].from).toBe(120_000);
    expect(bars[1].to).toBe(35_000);
    expect(bars[3].from).toBe(35_000);
    expect(bars[4].to).toBe(-5_000);
  });

  it("итог рисуется от нуля своим значением, а не накопленной суммой", () => {
    // Значение итога пришло из таблицы заземления; накопленная сумма — наша.
    // Разойдись они — показать обязаны ТАБЛИЧНОЕ число, иначе на графике
    // появится третье, которого нет нигде (дефект эталона: 41 150 против
    // 32 393 в двух артефактах одного прогона).
    const drifted = POINTS.map((p, i) =>
      i === 2 ? { ...p, value: 44_500 } : p,
    );
    const bars = layout(drifted);
    expect(bars[2].from).toBe(0);
    expect(bars[2].to).toBe(44_500);
  });

  it("значения переносятся один в один — ни делителей, ни округления", () => {
    // Масштаб оси задаёт поле unit спецификации; любой множитель здесь
    // превратил бы график в ложь, не показав ни одной неверной цифры.
    const bars = layout(POINTS);
    expect(bars.map((b) => b.value)).toEqual(POINTS.map((p) => p.value));
  });
});

describe("перенос подписи столбика", () => {
  it("ни одно слово не теряется, даже когда строк не хватает", () => {
    // РЕАЛЬНЫЙ ДЕФЕКТ: первая версия при упоре в лимит строк прекращала набор,
    // и «Чистый операционный денежный поток» подписывался как «Чистый
    // операционный денежный» — столбик молча менял смысл.
    for (const label of [
      "Чистый операционный денежный поток",
      "Погашение обязательств по аренде",
      "Остаток после процентов и аренды",
      "Приобретение основных средств и нематериальных активов",
    ]) {
      expect(wrap(label).join(" ")).toBe(label);
    }
  });
});
