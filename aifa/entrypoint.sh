#!/bin/sh
set -eu

# Обёртка wrapper 1.0.0.aef.fastapi при виде /app/app запускает собранный бандл
# и сама меняет каталог на /app/_internal. Для PyInstaller это рабочий каталог,
# а `finengine.config` читает `.env` относительно него. Держим его в /app: там
# лежат данные стенда, а не внутренности бандла.
cd /app

# ДВА ПУТИ ЗАПУСКА. Если бандл собран (наша сборка, см. Dockerfile) — стартуем из
# него: код уже упакован, данные берутся из /app/finengine-data. Если бандла нет
# (сборку отдала обёртка или она упала) — запускаем main.py интерпретатором:
# main.py сам дописывает пути к исходникам и данным, поэтому поднимается и так,
# дороже по памяти, но живой, а не мёртвый под.
if [ -x /app/app ]; then
    echo "[entrypoint] запуск из бандла /app/app"
    exec /app/app
fi

echo "[entrypoint] бандла нет, запуск из исходников /app/main.py"
exec /opt/venv/bin/python /app/main.py
