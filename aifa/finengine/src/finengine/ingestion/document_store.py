"""Доступ к реестру документов. Одна дверь, за ней база — и больше ничего.

ЧТО ЭТО ТАКОЕ. Реестр загруженных документов: метаданные по `doc_id` и куски
для сборки постраничного вида. На нём стоит весь бэкенд — `api/main.py`,
`api/station_turn.py`, `api/internal_docs.py`, `llm/tools.py`,
`orchestrator/agent.py`. Сама реализация живёт в `store/documents.py`
(`SqlDocumentStore`, строка на документ); здесь только вход к ней.

=== ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ (снос FAISS 15.08.2026, снос пикла 26.08.2026) ===

Раньше это был `ingestion/indexer.py` с классом `VectorIndex`, и в нём жили ДВА
разных предмета: хранилище документов и векторный поиск. Владелец потребовал
снести FAISS целиком; на инвентаре выяснилось, что «просто удалить файл» нельзя
— вместе с поиском уехали бы метаданные документов у шести потребителей.
Поэтому предметы разделили: поиск вырезали, хранилище осталось и было названо
тем, чем оно является.

⚠️ 26.08.2026 СНЕСЁН И ФАЙЛОВЫЙ РЕЕСТР — класс `DocumentStore` поверх
`data/index/meta.pkl`. Это последний рудимент эпохи FAISS: каталог назывался
`index` потому, что рядом лежал векторный индекс. Три места
(`streams_full_context`, `streams_sync`, `streams_unrestricted`) поднимали этот
пикл НАПРЯМУЮ при `index is None`, минуя переключатель, — то есть на стенде,
где реестр давно в Postgres, они читали бы пустой файл и отвечали «документ не
найден». Четвёртое (`two_stage_extractor`) звало уже несуществующий
`VectorIndex` и падало с `ModuleNotFoundError`.

Заодно ушёл in-process синглтон, который `architecture.md` 3.2 (🔴 MUST)
называет багом: у каждой реплики был свой `_docs` в памяти, и они затирали файл
друг друга. Держалось это только на `--workers 1`, а стенд с 26.08 на двух.

⚠️ КОГДА ПОИСК ПО ДОКУМЕНТАМ ПОНАДОБИТСЯ СНОВА (#195, «документы не влезают в
контекст») — он проектируется заново под целевую схему, а не воскрешается
отсюда. Возврат того кода — регрессия, а не решение.

Прочитать СТАРЫЙ пикл (у прода реестр всё ещё в нём) умеет переездный скрипт
`store/migrate_documents.py` — там для этого свой читатель, намеренно
отвязанный от боевого пути.
"""
from __future__ import annotations

import logging

from finengine import config
from finengine.store.documents import SqlDocumentStore

log = logging.getLogger(__name__)

_store: tuple[str, SqlDocumentStore] | None = None


def get_store() -> SqlDocumentStore:
    """Реестр документов. Адрес базы ОБЯЗАТЕЛЕН — молчаливого запасного нет.

    Отказ здесь громкий намеренно. Пока запасной путь был, ненастроенный контур
    работал «как будто получилось»: документы записывались в файл, которого
    никто не читает, и пропажа всплывала часом позже словами «документ не
    найден».
    """
    global _store
    # Через модуль, а не через ссылку с импорта: объект настроек в прогоне
    # набора успевает раздвоиться, и связанная ссылка отдаёт старое
    # значение (разбор — в `store/engine.схема`).
    url = (config.settings.documents_database_url or "").strip()
    # В ключе и схема контура: она живёт внутри движка (store/engine.py), и по
    # одному адресу с двумя схемами кэш отдавал бы реестр чужого контура.
    from finengine.store.engine import схема  # noqa: PLC0415 — разрыв цикла: engine не должен тянуть хранилища

    ключ = f"{url}|{схема()}"
    if _store is not None and _store[0] == ключ:
        return _store[1]
    if not url:
        raise RuntimeError(
            "реестр документов не настроен: пуст FINENGINE_DOCUMENTS_DATABASE_URL. "
            "Файлового запасного пути больше нет (снесён 26.08.2026)")
    # Адрес не печатаем — в нём пароль.
    log.info("реестр документов: база (строка на документ)")
    _store = (ключ, SqlDocumentStore(url))
    return _store[1]


def reset_store() -> None:
    """Забыть хранилище. Только для тестов и смены настроек — не боевой путь."""
    global _store
    _store = None
