# Поля `done.result`, которые дальше дренажа не едут НИКОМУ.
#
#   table_markdown — таблица станции. Её рисует бэкенд, своим кодом и по
#     раскладке роли (решение владельца 14.08: «формат таблицы как у finengine,
#     у каждой роли свой»). Станционная нужна только самой станции — в чат она
#     уехать не может, а в сводке весит 10–30 КБ и попадает в промпт;
#   xlsx_path — путь в ФС КОНТЕЙНЕРА станции. С бэкенда он не читается, и
#     обещать по нему файл значит обещать несуществующее.
_STATION_ONLY = ("table_markdown", "xlsx_path")

# Поля, которые АДРЕСАТУ нужны, а СВОДКЕ — категорически нет (#244).
#
# Сводка уезжает в шину состояния прогона (#160), а оттуда — в промпт
# следующего хода. Отчёт анализа весит десятки килобайт: положи его туда, и
# каждый следующий ход начнётся с пересылки прошлого разбора в модель. Ровно за
# это `table_markdown` попал в `_STATION_ONLY`; разница в том, что отчёт
# адресату НУЖЕН — из него собирается карточка. Значит не «выбросить», а
# «развести»: тяжёлое едет в `result`, лёгкое остаётся в `summary`.
# `stages` — посекундный разрез прогона (Б7, 19.08). Адресату он нужен: из него
# пишется журнал, по которому меряют стадии. Сводке — категорически нет: она
# уезжает в промпт следующего хода, и модель начала бы пересказывать пользователю
# секунды, которые ему не показывают.
_HEAVY_FOR_SUMMARY = ("report_markdown", "stages")

# Во сколько раз абсолютный потолок жизни прогона больше окна молчания.
# Окно молчания у нас щедрое (двадцать минут), поэтому тройка даёт час — этого
# хватает самому тяжёлому отчёту и не даёт сбежавшей комнате держать подписку
# бесконечно.
# Отрезок, которым сток пересматривает окно молчания. Нужен только тому, кто
# передал `quiet_after_turn`: ответ этого колбэка меняется по ходу ожидания.
_RECHECK_SEC = 5.0
_HARD_STOP_FACTOR = 3.0

# Сколько знаков отказа станции доносим до адресата.
_ERR_TAIL = 1200


def error_tail(text: str, limit: int = _ERR_TAIL) -> str:
    """Хвост сообщения об отказе, а НЕ голова.

    ЗАЧЕМ (09.08.2026, куплено часом разбора живого прогона). Резали `[:300]` —
    с головы. У питоновского traceback полезное в ПОСЛЕДНЕЙ строке: тип и текст
    исключения; первые сотни знаков — это «Traceback (most recent call last)» и
    пути к файлам. В тот же день лаунчер станции начал печатать отпечаток
    исполняемого файла (#181), встал первой строкой и добил остаток бюджета: в
    сообщении осталось четыре бесполезные строки, а настоящая причина
    (`ModuleNotFoundError: No module named 'yaml'`) не доехала вовсе.

    ⚠️ ПЕРЕЕХАЛО СЮДА ИЗ `station_driver` вместе со сносом монолитов (#166).
    Драйвер был единственным местом, где отказ станции проходил через наш код;
    теперь это сток прогона — он же единственный приёмник события `error` с
    пути по навыкам.
    """
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    return "…" + text[-limit:]


@dataclass(frozen=True)
class StationRun:
    """Прогон, доехавший до терминального события, — одним объектом.

    ПОЧЕМУ НЕ ПРОСТО СВОДКА, как было до К8b. Адресату ХОДА нужны сами строки:
    из них бэкенд собирает и роль-раскладку рабочей области, и markdown чата, и
    книгу Excel. Сводка станции для этого не годится — в ней только счётчики.

    `summary` — ЛЁГКАЯ часть итога: счётчики, имена, ячейка. Уезжает в шину и в
    промпты. `result` — тот же итог ПЛЮС тяжёлые поля (отчёт анализа): только
    адресату, в промпт не попадает никогда.
    """

    summary: dict
    doc_id: str
    metrics: list[dict] = field(default_factory=list)
    segment_rows: list[dict] = field(default_factory=list)
    group_rows: list[dict] = field(default_factory=list)
    result: dict = field(default_factory=dict)


async def _call_destination(what: str, nonce: str, fn: Callable | None, *args) -> None:
    """Позвать адресата так, чтобы он не унёс с собой дренаж.

    ЗАЧЕМ ИЗОЛЯЦИЯ. У дренажа есть обязанности ПОСЛЕ доклада: вернуть
    управление, чтобы вызывающий снял регистрацию очереди. Исключение из
    адресата, пролетев наружу, оставило бы очередь нонса зарегистрированной на
    всё время жизни прогона, а следующая ошибка того же адресата выглядела бы
    новым дефектом.

    Адресат бывает и синхронным (история сессии), и асинхронным (ход: там
    сборка книги и запись в «Источники»). Ждём только то, что действительно
    ждётся, — иначе корутина адресата тихо не исполнилась бы вовсе.

    ⚠️ ЭТО ПОСЛЕДНЯЯ СЕТЬ, и она ловит ВСЁ — включая сломанный файл реестра, на
    который смотрит сторож `tests/test_registry_external_dir.py`. Разница
    принципиальная: сторож бьёт по тихой ПОДМЕНЕ (поймали и посчитали по
    другому реестру), а здесь подмены нет — есть громкая запись со стеком и
    непоставленный результат. Молчаливо успешным прогон отсюда не выйдет.
    Сторож этого места не видит: адресат приходит переменной, а не именем.
    """
    if fn is None:
        return
    try:
        res = fn(*args)
        if inspect.isawaitable(res):
            await res
    except Exception:  # noqa: BLE001 — адресат не смеет уронить дренаж
        log.exception("station sink: адресат %s упал, nonce=%s", what, nonce)


def _abandon(
    *,
    nonce: str,
    owner_id: int | None,
    reason: str,
    started_at: float,
    company_name: str,
    metrics: list[dict],
    seg_rows: list[dict],
    grp_rows: list[dict],
) -> StationRun:
    """Прогон замолчал: пометить отказ В ШИНЕ, В ЖУРНАЛЕ и В ХРАНИЛИЩЕ.

    ЗАЧЕМ ВТОРОЕ (найдено на прогоне владельца по Совкомбанку 15.08). Комната
    отдала все 110 показателей и затихла; терминального события не пришло,
    дренаж закрылся по простою — и записи в журнале не появилось. На экране
    таблица при этом БЫЛА: строки рисует `on_event` по мере поступления, а
    журнал пишется только из терминального события. Владелец видел результат,
    а разобрать прогон было нечем — ни бенчмарком, ни глазами.

    ЗАЧЕМ ТРЕТЬЕ (#276, Д2). Точка приёма закрывает строку прогона только по
    событиям `done`/`error`. Молчаливый конец не событие — его НЕТ ни в одной
    пачке, — поэтому строка навсегда оставалась `running`, а `/runs/by-doc`
    отбирает по `finished_at > 0` и не отдавал её никогда. То есть ровно тот
    класс потери, ради которого хранилище и заводилось, мимо хранилища и
    проходил.

    Шина, журнал и хранилище отвечают на РАЗНЫЕ вопросы: шина — «можно ли
    считать данные готовыми прямо сейчас» (нельзя), журнал — «что вообще
    происходило», хранилище — «что показать, когда вкладку откроют заново».
    Поэтому три отметки, а не одна.

    ВОЗВРАЩАЕТ СОБРАННОЕ, а не `None`. Строки прогона к этому моменту лежат
    здесь в памяти — сегодня их было 133 (110 показателей и 23 сегментных по
    Банку «Санкт-Петербург», 19.08). Раньше они выбрасывались, и в базу от
    полностью удавшегося извлечения уезжали ОДНИ СЧЁТЧИКИ. Отдаём их наружу,
    чтобы адресат положил на сервер то, что человек и хотел увидеть.
    """
    doc_id = grounding_bus.worker_doc(nonce) or ""
    grounding_bus.run_failed(owner_id, doc_id, reason, source="worker")
    # Ленивый импорт: `extract_result` тянет форматтер, Excel и реестр, а сток
    # грузится на старте бэкенда. Это третья из трёх разрешённых причин —
    # тяжесть модуля (правило 3.1).
    from finengine.skills import extract_result
    extract_result.log_aborted_run(
        doc_id=doc_id,
        company_name=company_name, user_id=owner_id, started_at=started_at,
        metrics=metrics, segment_rows=seg_rows, group_rows=grp_rows,
        reason=reason)
    # Счётчики, а не строки: строк у стока полный список, но класть их в
    # `payload` значило бы завести ВОСЬМОЕ место с теми же числами (#144). Чем
    # кончилось — вопрос к хранилищу, сами числа — к таблице прогона.
    stored = runs.finish_best_effort(
        nonce, status=runs.STATUS_FAILED, error=reason, doc_id=doc_id,
        finished_at=int(_time.time()),
        payload={"company_name": company_name,
                 "metrics_extracted": len(metrics),
                 "segments_count": len(seg_rows),
                 "group_count": len(grp_rows)})
    if not stored and runs.is_enabled():
        # Строки нет (путь воркера нонс не взводит) либо хранилище отказало —
        # причина тогда уже записана стеком внутри. Не угадываем какая: та же
        # фраза, что в точке приёма, чтобы обе потери искались одним grep.
        log.warning("исход прогона не сохранён: нонс=%s, статус=молчание — строки "
                    "прогона нет (взвода не было?) либо хранилище отказало", nonce)
    # Сводки у оборванного прогона НЕТ и быть не может: её приносит терминал.
    # Кладём то немногое, что знаем сами, и НЕ выдумываем ячейку с ролью —
    # раскладку по ним всё равно не собрать, а угаданная роль соврала бы про
    # состав таблицы.
    return StationRun(
        summary={"company_name": company_name, "aborted_reason": reason},
        doc_id=doc_id, metrics=metrics, segment_rows=seg_rows,
        group_rows=grp_rows, result={})


async def drain(
    *,
    nonce: str,
    queue: Any,
    owner_id: int | None,
    timeout: float = WORKER_LIFETIME_SEC,
    on_event: Callable[[dict], Any] | None = None,
    on_done: Callable[[StationRun], Any],
    on_failed: Callable[[str], Any],
    on_abandoned: Callable[[StationRun], Any] | None = None,
    quiet_after_turn: Callable[[bool], float | None] | None = None,
) -> None:
    """Слушать очередь нонса до терминального события и доложить адресату.

    `on_event(ev)` — событие прогона по мере поступления (`start`, `metric`,
    `status`, `plan_step`). Ходу оно нужно живым: таблица в рабочей области
    наполняется строка за строкой, и копить их до конца значило бы показывать
    пользователю пустой экран все полторы-три минуты прогона. Воркеру не нужно
    ничего — он молчит до итога, и там этот адресат просто не задан.

    `on_done(run)` — прогон завершился, `run` несёт сводку И строки.
    `on_failed(message)` — прогон явно сообщил об ошибке.
    `on_abandoned(run)` — прогон ЗАМОЛЧАЛ, не сказав ничего. Отдельный адресат,
    а не `on_failed`: тот пишет красный чип в чат («станция сообщила об
    ошибке»), а здесь станция не сообщала ничего — и сваливать их в один
    значило бы врать про то, что произошло. `run` несёт собранные строки: их
    некуда деть, кроме как показать, — 19.08 на Банке «Санкт-Петербург» их
    было 133 при полностью удавшемся извлечении.

    `quiet_after_turn()` — во сколько секунд СЖАТЬ окно молчания, когда ждать
    больше нечего; `None` — не сжимать. Спрашиваем колбэком, а не флагом:
    ответ меняется ПО ХОДУ прослушивания (ход кончается позже, чем сток
    запустился), и снятое при старте значение всегда врало бы.

    ЗАЧЕМ (21.08.2026). Окно молчания — 20 минут, и это верно, пока ход идёт:
    комната считает молча, и обрывать её нельзя. Но КОНЧИВШИЙСЯ ход ничего
    больше не пришлёт: терминал либо уже в пути (секунды), либо не придёт
    никогда. Двадцать минут ожидания в этом случае — чистая потеря, и именно
    её заплатил 19.08 Банк «Санкт-Петербург»: извлечение отработало, ход
    оборвался, и сток досидел дедлайн, прежде чем кто-либо об этом узнал.

    Любой из четырёх адресатов может быть и синхронным, и асинхронным.

    Документ берём ТОЛЬКО по факту: нонс связывается с `doc_id`, когда комната
    забирает текст. Не знаем — не пишем ничего: неверная привязка в ходу с
    несколькими документами хуже дубля.
    """
    loop = asyncio.get_event_loop()
    # 🔴 ДЕДЛАЙН СЧИТАЕТ МОЛЧАНИЕ, А НЕ СРОК ЖИЗНИ (19.08.2026, прогон Нестле).
    #
    # Здесь стояло `deadline = loop.time() + timeout` — двадцать минут ОТ ВЗВОДА
    # КАНАЛА, и это хоронило живые прогоны. Замер: канал взведён в 14:14:54,
    # первое событие станции пришло в 14:20:31 — пять с половиной минут ушло на
    # доставку полки, распознавание и распаковку, то есть на саму работу
    # осталось четырнадцать с половиной. Сжатие отчёта Нестле (476 КБ текста)
    # шло шестнадцать минут; в 14:34:54 дренаж объявил прогон мёртвым, а процесс
    # в комнате в это время работал. Всё, что он потом извлёк, приехало в
    # закрытую очередь.
    #
    # Правильная мера жизни — МОЛЧАНИЕ: пока события идут, прогон жив, сколько
    # бы он ни длился. Каждое событие отодвигает дедлайн.
    #
    # ⚠️ АБСОЛЮТНЫЙ ПОТОЛОК ОСТАЁТСЯ, и это не перестраховка: сбежавшая комната,
    # шлющая события бесконечно, иначе держала бы подписку вечно. Потолок втрое
    # больше окна молчания — щедро для работы и строго для аварии.
    started = loop.time()
    deadline = started + timeout
    last_event_at = started
    hard_stop = started + timeout * _HARD_STOP_FACTOR
    # Начало прослушивания — оно же начало прогона для журнала оборванных.
    # Точное `channel.started_at` есть только у ходового пути, а у воркера
    # адресата нет вовсе; протаскивать его сюда ради поля «сколько длилось»
    # значило бы менять сигнатуру обоим ради одной цифры.
    started_at = _time.time()
    metrics: list[dict] = []
    seg_rows: list[dict] = []
    grp_rows: list[dict] = []
    company_name = ""
    seen_any = False

    while True:
        # Окно молчания сжимается, когда ход кончился: ждать больше нечего.
        # Считаем от ПОСЛЕДНЕГО события, а не от «сейчас», иначе сжатие
        # обнулило бы уже отсиженное ожидание и сработало бы мгновенно.
        # Колбэку отдаём признак «что-то уже приехало»: решение о сжатии
        # окна принимает вызывающий, но данных для него у него нет —
        # строки копятся ЗДЕСЬ.
        short = (quiet_after_turn(bool(metrics or seg_rows or grp_rows))
                 if quiet_after_turn is not None else None)
        if short is not None:
            deadline = min(deadline, last_event_at + float(short))
        capped = min(deadline, hard_stop)
        left = capped - loop.time()
        # ⚠️ ЖДЁМ КОРОТКИМИ ОТРЕЗКАМИ, А НЕ ОДНИМ ДЛИННЫМ. Ответ
        # `quiet_after_turn()` меняется ПО ХОДУ ожидания: ход кончается позже,
        # чем сток вошёл в ожидание. Уснув на двадцать минут одним куском, сток
        # узнал бы об этом через двадцать минут — то есть сжатие окна не
        # сработало бы ровно в том случае, ради которого написано: станция
        # отдала последнее событие, а ход оборвался уже после него.
        wait = left if quiet_after_turn is None else min(left, _RECHECK_SEC)
        if left <= 0:
            why = ("молчал дольше %ss" % int(timeout) if deadline <= hard_stop
                   else "работал дольше потолка %ss" % int(timeout * _HARD_STOP_FACTOR))
            log.info("bg mailbox timeout nonce=%s (спавна не было или прогон %s)",
                     nonce, why)
            if seen_any:
                # Комната подавала признаки жизни и замолчала. Это НЕ «готово»:
                # помечаем отказ, чтобы агент мог извлечь сам.
                await _call_destination("on_abandoned", nonce, on_abandoned, _abandon(
                    nonce=nonce, owner_id=owner_id, started_at=started_at,
                    reason="фоновый воркер замолчал, не отдав результат",
                    company_name=company_name, metrics=metrics,
                    seg_rows=seg_rows, grp_rows=grp_rows))
            return
        try:
            ev = await asyncio.wait_for(queue.get(), timeout=wait)
        except asyncio.TimeoutError:
            if wait < left:
                continue          # это был отрезок проверки, а не конец окна
            log.info("bg mailbox idle nonce=%s — закрываю", nonce)
            if seen_any:
                await _call_destination("on_abandoned", nonce, on_abandoned, _abandon(
                    nonce=nonce, owner_id=owner_id, started_at=started_at,
                    reason="фоновый воркер затих, не отдав результат",
                    company_name=company_name, metrics=metrics,
                    seg_rows=seg_rows, grp_rows=grp_rows))
            return
        # Событие пришло — прогон жив, окно молчания начинается заново.
        # Отодвигаем ДО разбора события: даже нераспознанное тело доказывает,
        # что комната работает.
        last_event_at = loop.time()
        deadline = last_event_at + timeout
        if not isinstance(ev, dict):
            continue
        company_name = company_name or str(ev.get("company_name") or "")
        if not seen_any:
            # Первый признак жизни прогона — с него и «идёт». Раньше отметить
            # нечего: нонсов взводится пул, а комнат может не быть ни одной.
            seen_any = True
            grounding_bus.run_started(owner_id, grounding_bus.worker_doc(nonce),
                                      source="worker")
        kind = ev.get("type")
        if kind == "start" and (metrics or seg_rows or grp_rows):
            # 🔴 ВТОРОЕ ИЗВЛЕЧЕНИЕ НА ТОМ ЖЕ НОНСЕ НАЧИНАЕТ ТАБЛИЦУ ЗАНОВО.
            #
            # ЖИВОЙ ПРОГОН ВЛАДЕЛЬЦА 40981f96 (24.08.2026): на экране 88 строк
            # при 68 уникальных — двадцать показателей ровно ПО ДВА РАЗА,
            # строки 0–19 и 20–39 совпадают до значения. Модель запустила
            # извлечение дважды; оба раза с `--no-final`, поэтому терминала
            # между ними не было, дренаж не закрывался — и строки обоих
            # прогонов легли в один список.
            #
            # `start` движок отдаёт РОВНО ОДИН РАЗ на прогон и ДО первой строки
            # (`two_stage_extractor`, событие с шапкой периодов). Значит второй
            # `start` — это граница: предыдущая таблица кончилась.
            #
            # ⚠️ Я УЖЕ ПИСАЛ ЭТУ ПРАВКУ 22.08 И ОТКАТИЛ ЕЁ КАК ГИПОТЕТИЧЕСКУЮ:
            # рассудил, что дренаж закрывается на первом `done` и второй `start`
            # до него не дойдёт. Рассуждение верное для случая, когда извлечение
            # само ставит терминал, — но у нас его ставит РАСЧЁТ, в самом конце
            # цепочки. Между двумя извлечениями терминала нет. Это цена
            # отката по рассуждению вместо замера.
            #
            # Дубль остаётся дефектом и считается отдельно
            # (`grounding_bus.duplicate_runs`); здесь чиним другое — чтобы экран
            # показывал таблицу ОДНОГО прогона, а не сумму попыток.
            log.warning("новое извлечение на нонсе %s — экран начинается заново "
                        "(было строк: %d, сегментных: %d)",
                        nonce[:8], len(metrics), len(seg_rows) + len(grp_rows))
            metrics.clear()
            seg_rows.clear()
            grp_rows.clear()
        if kind == "metric":
            # ВТОРАЯ ОСЬ ПЕРИОДА — ЗДЕСЬ, ДО ВСЕХ ПОТРЕБИТЕЛЕЙ (#205, 19.08.2026).
            # У промежуточного отчёта баланс сравнивается с концом прошлого года,
            # а ОПУ — с тем же кварталом год назад. Движок спрашивает
            # сравнительное значение ОДНИМ периодом на прогон, и балансовая
            # строка честно отвечает `None`: на РСХБ так вышло у 92 строк из 110.
            #
            # Правим РОВНО ЗДЕСЬ, потому что дальше этот же объект строки
            # расходится по всем потребителям: живому событию на экран, списку
            # прогона (а из него — раскладке роли, книге Excel и сохранённому
            # экрану) и журналу. Любое другое место — это второй экземпляр
            # правила либо половина потребителей без него.
            from finengine.skills import extract_result as _res
            _res.fill_row_comparative(ev)
            dim = ev.get("dimension")
            (grp_rows if dim == "consolidated_group" else seg_rows if dim else metrics).append(ev)
            await _call_destination("on_event", nonce, on_event, ev)
            continue
        if kind == "done":
            raw = {k: v for k, v in (ev.get("result") or {}).items()
                   if k not in _STATION_ONLY}
            summary = {k: v for k, v in raw.items() if k not in _HEAVY_FOR_SUMMARY}
            run = StationRun(summary=summary, doc_id=grounding_bus.worker_doc(nonce) or "",
                             metrics=metrics, segment_rows=seg_rows, group_rows=grp_rows,
                             result=raw)
            # #160: тот же факт — И адресату (для следующих ходов), И статусом
            # (для ИДУЩЕГО хода). Сначала статус: он дешёвый, синхронный и
            # никуда не ходит, а доклад пишет на диск и в сеть.
            grounding_bus.run_finished(owner_id, run.doc_id,
                                       source="worker", summary=summary)
            await _call_destination("on_done", nonce, on_done, run)
            log.info("bg mailbox done nonce=%s doc=%s company=%s metrics=%s сегментов=%s",
                     nonce, (run.doc_id or "?")[:8], summary.get("company_name"),
                     len(metrics), len(seg_rows))
            return
        if kind == "error":
            message = error_tail(str(ev.get("message") or "")) or "прогон станции не удался"
            grounding_bus.run_failed(owner_id, grounding_bus.worker_doc(nonce),
                                     message, source="worker")
            await _call_destination("on_failed", nonce, on_failed, message)
            return
        # start/status/plan_step — транзит: итог из них не собирается, но ход
        # рисует по ним шапку таблицы и строку прогресса.
        await _call_destination("on_event", nonce, on_event, ev)
