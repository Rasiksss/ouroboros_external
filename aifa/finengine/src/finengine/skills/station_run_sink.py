"""Слушатель прогона станции: дренаж нонс-очереди до терминального события.

ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ (#190, коммит К2). Это тело жило в
`orchestrator/agent.py::_bg_extract_mailbox` и умело докладывать РОВНО В ОДНО
место — в историю сессии, блоком `[Tool result: background_extract]`. Такой
доклад годится фоновому воркеру: его результат нужен СЛЕДУЮЩЕМУ ходу модели.

Когда комнату станции начнёт поднимать гейтвей (К8), тот же дренаж понадобится
для комнаты ХОДА, а там доклад совсем другой: результат нужен ИДУЩЕМУ ходу и
уходит пользователю в браузер через `run_orchestrator.emit_to_run`. Один и тот
же цикл, два адресата — значит адресат становится аргументом, а цикл переезжает
сюда, чтобы не появиться второй копией.

ГРАНИЦА. Здесь ТОЛЬКО чтение очереди и решение «прогон идёт / кончился / упал».
Наружу вынесены два разных решения:

  * КУДА ДОКЛАДЫВАТЬ — `on_event`, `on_done` и `on_failed`. Сам дренаж не знает
    ни про сессию, ни про ран хода;
  * КТО ВЛАДЕЕТ ОЧЕРЕДЬЮ — регистрация и снятие регистрации нонса
    (`api/station_progress_ingest`) остаются у вызывающего. Иначе модуль слоя
    skills импортировал бы слой api, а это направление зависимостей наоборот
    (`docs/rules/architecture.md` 1.1).

ЧТО СОБИРАЕТ ДРЕНАЖ, А ЧТО ДЕЛАЕТ АДРЕСАТ (изменено в К8b). Дренаж копит СТРОКИ
прогона и отдаёт их адресату целиком (`StationRun`). Раньше он ещё и собирал
Excel — но книга у двух адресатов РАЗНАЯ: воркеру нужна плоская выгрузка всех
периодов, ходу — роль-форматная книга из общего рецепта
(`extract_result.finalize_extraction`). Собирать её здесь значило бы либо
сохранить ход дважды, либо развести форматы. Поэтому книга — забота адресата, а
здесь остаются только строки, из которых её собирают.

ШИНА СОСТОЯНИЯ ПРОГОНА остаётся ЗДЕСЬ и адресатом не параметризуется:
`run_started`/`run_finished`/`run_failed` — это не доклад, а сторож дубля
(#160). Он один на всех адресатов, и вынести его наружу значит однажды забыть
позвать из второго места. Замер, которым он оплачен: 02.08 ящик знал про 94
показателя в 18:17:19, агент запустил движок заново в 18:20:59 и сжёг 253,5 с.

⚠️ ШИНА ДАННЫХ (заземление анализа) — НЕ ЗДЕСЬ. Её наполняет рецепт
пост-обработки, то есть адресат ХОДА. Адресат ВОРКЕРА её не наполняет и сегодня:
так было до переезда, и менять это заодно с #190 нельзя — проверить живым ходом
воркерный путь сейчас нечем. Разрыв назван вслух, чтобы не выглядеть решением.

⚠️ МОЛЧАНИЕ — НЕ УСПЕХ. Из трёх способов кончиться два (истёкшее время жизни и
затихшая очередь) НЕ докладывают адресату вовсе — они помечают прогон упавшим
в шине и пишут строку в журнал (`_abandon`). Доклад уходит лишь на явном
событии. Так было и до переезда; разница важна, потому что «ничего не пришло»
и «пришла ошибка» ведут к разным действиям агента.

Запись в журнал добавлена 15.08 по прогону владельца: комната отдала все 110
показателей и затихла, на экране таблица была, а в журнале — ничего. Молчание
перестало быть невидимым, но успехом от этого не стало.
"""
