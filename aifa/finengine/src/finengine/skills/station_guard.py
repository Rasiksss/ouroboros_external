from __future__ import annotations

import os
import sys
import threading
import time


def _read(path: str) -> str:
    with open(path, "rb") as f:
        return f.read().decode("utf-8", "replace")


def _ancestors(proc_root: str, pid: int) -> set[int]:
    """Родительская цепочка pid — её процессы не считаются дублями: внешний
    `bash -lc "… extract.py …"` несёт маркер в своей же командной строке."""
    seen: set[int] = set()
    cur = pid
    for _ in range(64):
        try:
            stat = _read(os.path.join(proc_root, str(cur), "stat"))
            ppid = int(stat[stat.rindex(")") + 1:].split()[1])
        except (OSError, ValueError, IndexError):
            break
        if ppid <= 0 or ppid in seen:
            break
        seen.add(ppid)
        cur = ppid
    return seen


def _blind(marker: str, why: str) -> None:
    """Записать слепоту стража в диагностику — МОЛЧА для stderr.

    🔴 stderr ЧИТАЕТ МОДЕЛЬ, и это решает всё. Первая версия писала туда
    предупреждение — модель приняла его за отказ прогона и пересказала
    пользователю («Ошибка: скрипт пытается читать /proc»). Вторая версия
    падала с трассой на `listdir` — модель пошла ПАТЧИТЬ ЭТОТ ФАЙЛ вместо
    работы («нужно пропатчить station_guard.py»). Оба раза наша внутренняя
    кухня становилась заботой пользователя.

    Слепота стража — наша забота. Файл рядом с прогоном, stderr чистый.
    """
    try:
        with open(".station-guard.diag", "a", encoding="utf-8") as f:
            f.write(f"{marker}: {why} — проверка дубля не работает\n")
    except OSError:
        pass


"""Замок с отметкой времени: единственный признак, видимый ИЗНУТРИ песочницы."""
_STALE_SEC = 90.0
_TOUCH_SEC = 20.0


def _lock_path(marker: str) -> str:
    """Свой замок на каждый скрипт: извлечение и анализ идут рядом законно, и
    общий файл они бы отнимали друг у друга, обнуляя защиту обоим."""
    slug = "".join(c if c.isalnum() else "-" for c in marker.lower()).strip("-")
    return f".aifa-{slug}.lock"


def _lock_owner(marker: str) -> str:
    """pid хозяина, если отметка свежая; «?» — свежая, но pid не разобран;
    пусто — замок ничей."""
    path = _lock_path(marker)
    try:
        age = time.time() - os.stat(path).st_mtime
        body = _read(path)
    except OSError:
        return ""
    if age > _STALE_SEC:
        return ""  # хозяин молчит дольше срока — считаем мёртвым, комнату не запираем
    for word in body.split():
        if word.isdigit():
            return word
    return "?"


def _touch_lock(path: str) -> None:
    while True:
        time.sleep(_TOUCH_SEC)
        try:
            os.utime(path, None)
        except OSError:
            return  # замок унесли — обновлять нечего, спорить не с кем


def _hold_lock(marker: str) -> None:
    """Занять замок и обновлять отметку, пока процесс жив.

    Поток демонический: процесс кончился — отметка перестала обновляться, и
    через `_STALE_SEC` замок сам освобождается. Ни снимать, ни убирать за
    собой в `finally` не нужно — а значит, аварийный конец (SIGKILL, падение
    комнаты) не оставляет запертой двери.
    """
    path = _lock_path(marker)
    try:
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"{marker}\npid {os.getpid()}\n")
    except OSError:
        return  # писать некуда — на такой ФС и дубля не удержать, молчим
    threading.Thread(target=_touch_lock, args=(path,), daemon=True).start()


def _refuse(marker: str, pid: str) -> None:
    """Отказ обязан нести ГОТОВУЮ команду: «kill <pid>», а не «заверши старый».

    Совет без pid модель выполнить не может — а не выполнив, она делает то
    единственное, что умеет: запускает ещё одну копию.
    """
    err = sys.stderr
    # pid «?» — замок свеж, но кем занят, не разобрать: тогда честно про ожидание.
    how = f"сначала заверши старый: kill {pid}" if pid.isdigit() else "дождись его завершения"
    print(f"[{marker}] 🔴 ОТКАЗ: этот скрипт УЖЕ РАБОТАЕТ в комнате (pid {pid}).", file=err)
    print(f"[{marker}]    Вторая копия не ускорит, а ЛОМАЕТ ПЕРВУЮ: обе делят одну", file=err)
    print(f"[{marker}]    квоту модели, вызовы затягиваются и таблица выходит пустой.", file=err)
    # 🔴 ЗДЕСЬ СТОЯЛ СОВЕТ, КОТОРЫЙ В ЭТОЙ КОМНАТЕ НЕВЫПОЛНИМ (22.08.2026).
    #
    # Было: «дождись результата (poll/log; строка-сердцебиение идёт ~раз в
    # минуту — пока она есть, процесс жив)». Сердцебиение действительно идёт и
    # действительно флашится — но `process poll` в комнате отдаёт НАКОПЛЕННЫЙ
    # лог одним куском НА ВЫХОДЕ процесса. Замер живого хода по Северстали:
    # четыре опроса подряд, `idleMs` растёт 156→234 с, «(no new output)», а в
    # 13:27:46 приезжает всё сразу, включая четыре строки сердцебиения (t+00:45,
    # 01:25, 02:45, 03:25), которых модель до того не видела НИ ОДНОЙ.
    #
    # Совет «проверь, идёт ли сердцебиение» в такой комнате не просто бесполезен
    # — он ВРЕДЕН: модель проверяет, не находит и делает вывод «процесс мёртв».
    # Ровно это и случилось: она перезапустила работавший прогон, потом ещё раз,
    # потом полезла снимать замок. Говорим правду про молчание.
    print(f"[{marker}]    Молчание опроса — НЕ признак смерти: комната отдаёт лог", file=err)
    print(f"[{marker}]    целиком в конце, и до самого конца poll честно скажет", file=err)
    print(f"[{marker}]    «(no new output)», сколько бы ни росло idleMs. Прогресс", file=err)
    print(f"[{marker}]    пользователь видит на своём экране, ты — нет. Перезапуск", file=err)
    print(f"[{marker}]    нужен НАСТОЯЩИЙ — {how}", file=err)
    sys.exit(5)


def refuse_if_duplicate(marker: str, *, proc_root: str = "/proc") -> None:
    """Выйти кодом 5, если такой же скрипт уже работает в этом же cwd.

    `marker` — хвост пути скрипта («aifa-extract/scripts/extract.py»): он один
    и у полки, и у запечённой копии, и у самодельной обёртки.

    Два признака подряд: живые процессы (неподделываемо, но в песочнице
    недоступно) и замок с отметкой (виден всегда, но его можно стереть). Ни
    один не закрывает вопрос в одиночку — вместе закрывают.
    """
    if not os.path.isdir(proc_root):
        return  # вне Linux (машина разработчика) комнаты нет — запрещать нечего

    pid_s = _duplicate_by_proc(marker, proc_root)
    if pid_s:
        _refuse(marker, pid_s)
    owner = _lock_owner(marker)
    if owner:
        _refuse(marker, owner)
    _hold_lock(marker)


def _duplicate_by_proc(marker: str, proc_root: str) -> str:
    """pid дубля по /proc; пусто — либо чисто, либо страж слеп (см. `_blind`)."""
    me = os.getpid()
    my_cwd = os.path.realpath(os.getcwd())

    # 🔴 СЛЕПОТА В ПЕСОЧНИЦЕ — ГОВОРИМ ВСЛУХ (17.08.2026, прогон 9f0afd6e).
    # `ws-sandbox` подменяет /proc так, что процесс не видит НИ СОСЕДЕЙ, НИ
    # СЕБЯ: каталог есть, записей ноль. Первая версия стража честно перебирала
    # пустой список, никого не находила и молча пропускала — то есть на стенде
    # два извлечения шли рядом, а в логе не было ни отказа, ни жалобы. Молчащая
    # проверка хуже отсутствующей: она создаёт ложную уверенность, что дубль
    # закрыт. Проверяем видимость СЕБЯ — это единственный надёжный признак
    # работоспособности; не видим себя, значит не увидим и дубль.
    if not os.path.isdir(os.path.join(proc_root, str(me))):
        # 🔴 МОЛЧА, И ЭТО ОСОЗНАННО (17.08, второй заход). Сначала здесь стояло
        # громкое предупреждение в stderr — и вышло хуже: stderr читает МОДЕЛЬ,
        # она приняла его за отказ и пересказала пользователю «Ошибка: скрипт
        # пытается читать /proc, но в sandbox /proc недоступен». Пользователь
        # увидел нашу внутреннюю кухню вместо работы.
        #
        # Слепота стража — наша забота, а не пользователя. Пишем её в
        # диагностический файл рядом с прогоном; stderr остаётся чистым.
        _blind(marker, f"/proc не показывает pid {me}")
        return ""

    skip = _ancestors(proc_root, me) | {me}
    # 🔴 ПЕРЕЧИСЛЕНИЕ /proc — ТОЖЕ СЛЕПОТА, А НЕ КРУШЕНИЕ (17.08, прогон ВТБ).
    # Проверка «вижу ли себя» выше пропускает случай, когда /proc/<self> есть, а
    # listdir на корне запрещён: песочница отдаёт отказ доступа. Тогда скрипт
    # падал С ТРАССОЙ — и модель, увидев её, шла ПАТЧИТЬ ЭТОТ ФАЙЛ вместо
    # работы («нужно пропатчить station_guard.py — в sandbox нет доступа к
    # /proc»). Страж, из-за которого чинят стража, хуже отсутствующего.
    try:
        pids = os.listdir(proc_root)
    except OSError as exc:
        _blind(marker, f"listdir({proc_root}) отказал: {exc}")
        return ""
    for pid_s in pids:
        if not pid_s.isdigit() or int(pid_s) in skip:
            continue
        base = os.path.join(proc_root, pid_s)
        try:
            cmd = _read(os.path.join(base, "cmdline")).replace("\0", " ")
            cwd = os.path.realpath(os.readlink(os.path.join(base, "cwd")))
        except OSError:
            continue  # исчез между listdir и чтением
        if marker in cmd and cwd == my_cwd:
            return pid_s
    return ""


def start_heartbeat(label: str, quiet_after: float = 40.0):
    """Строка жизни в stderr, когда движок молчит дольше `quiet_after` секунд.

    Возвращает `mark()` — вызывающий дёргает её на каждом событии движка, и
    сердцебиение печатается только в настоящую тишину, не поверх прогресса.
    Поток демонический: конец процесса — конец сердцебиения, снимать нечего.
    """
    t0 = time.monotonic()
    state = {"last": t0}

    def _beat() -> None:
        while True:
            time.sleep(5)
            now = time.monotonic()
            if now - state["last"] < quiet_after:
                continue
            mm, ss = divmod(int(now - t0), 60)
            print(f"[{label}] работаю, t+{mm:02d}:{ss:02d} — тишина сейчас это долгий "
                  f"вызов модели (стадия сжатия/извлечения), НЕ зависание",
                  file=sys.stderr, flush=True)
            state["last"] = now

    threading.Thread(target=_beat, daemon=True).start()

    def mark() -> None:
        state["last"] = time.monotonic()

    return mark
