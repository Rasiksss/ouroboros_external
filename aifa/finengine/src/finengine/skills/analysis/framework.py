_STANDARD_LABEL = {"ifrs": "МСФО (IFRS)", "us_gaap": "US GAAP", "ind_as": "Ind AS"}

# Заголовок раздела внешнего контекста. Держится КОНСТАНТОЙ, потому что по нему
# читатель отделяет выверенное от найденного, а карточка на фронте рисует его
# отдельным блоком с пометкой «не из отчётности».
EXTERNAL_SECTION_TITLE = "Контекст извне"


def external_block(facts: list, m: md.Methodology | None = None) -> str:
    """Блок промпта с внешними фактами (#159). Фактов нет — блока нет.

    ⚠️ ПОЧЕМУ БЛОК ПОЯВЛЯЕТСЯ ТОЛЬКО ВМЕСТЕ С ФАКТАМИ. Постоянный раздел в
    каркасе означал бы, что при пустом срезе модели велено написать «Контекст
    извне», а взять его неоткуда — и она напишет по памяти. Память модели
    датирована обучением, ссылки у неё нет, и получился бы ровно тот домысел с
    видом факта, против которого весь раздел и заводится. Нет среза — нет и
    заголовка.

    Факты приходят собранными КОДОМ (`analysis/external.py`), каждый с
    источником и датой. Модели остаётся изложение — не добыча.
    """
    from finengine.skills.analysis import external as _ext
    if not facts:
        return ""
    mm = m or md.base()
    # Имя раздела подставляется из КОНСТАНТЫ, а не пишется в тексте методики
    # второй раз: то же имя читает разбор ответа (`parse.py`), и две копии
    # разъехались бы при первом переименовании.
    rules = mm.text_of("prompt.external.rules").replace(
        "{{EXTERNAL_SECTION_TITLE}}", EXTERNAL_SECTION_TITLE)
    return (
        mm.text_of("prompt.external.intro")
        + f"{_ext.format_for_prompt(facts)}\n"
        + rules
    )

# ── Язык ИЗЛОЖЕНИЯ ────────────────────────────────────────────────────────
# Язык отчёта и язык ответа — РАЗНЫЕ величины. Классификатор отдаёт язык
# документа: он выбирает ЯЧЕЙКУ реестра и остаётся метаданными карточки.
# Язык ответа зависит только от того, на каком языке работает пользователь, и
# задаётся ЗДЕСЬ — в одном месте на все пути вызова (инлайн-тул и станционный
# скилл). Раньше каждый путь решал сам, и станционный (боевой) отдавал язык
# документа: английский отчёт → английский разбор.
_ANSWER_LANG_ENV = "FE_ANALYSIS_LANG"
_DEFAULT_ANSWER_LANG = "ru"
_LANG_INSTR = {
    "ru": (
        "ЯЗЫК ОТВЕТА — РУССКИЙ. Это жёсткое требование и оно НЕ зависит от "
        "языка отчёта: весь анализ, заголовки разделов, выводы и подписи к "
        "таблицам пиши ПО-РУССКИ, даже если отчёт на английском или любом "
        "другом языке. Названия статей отчётности переводи на русский; "
        "названия компаний, юрлиц и тикеры оставляй как в отчёте."
    ),
    "en": (
        "LANGUAGE OF THE ANSWER IS ENGLISH — write the whole analysis in "
        "English regardless of the language of the report itself."
    ),
}


def answer_language() -> str:
    """Язык ИЗЛОЖЕНИЯ анализа — единственный источник истины.

    По умолчанию русский (интерфейс русскоязычный). `FE_ANALYSIS_LANG` —
    переключатель на весь стенд, если понадобится другой язык ответа.
    """
    lang = (os.environ.get(_ANSWER_LANG_ENV) or "").strip().lower()
    return lang if lang in _LANG_INSTR else _DEFAULT_ANSWER_LANG


def build_prompt(
    *,
    company_name: str,
    company_type: str,
    standard: str,
    depth: str,
    ocr_text: str,
    metrics_table: str = "",
    capital_facts: str = "",
    methodology: md.Methodology | None = None,
    available_enums: set[str] | None = None,
    external_facts: list | None = None,
    lens: tuple[str, ...] = (),
) -> str:
    """Собрать документо-ориентированный промпт под (ячейка × глубина).

    `methodology` — эффективная методика (база + правки пользователя). Не передали
    — берётся базовая, та, что поставляется с продуктом.

    `available_enums` — что реально посчитано кодом в этом прогоне. Определения
    коэффициентов заявлены словами «посчитаны в таблице заземления»; для тех,
    которых в таблице нет, эта фраза — неправда (#151). Не передали — блок
    собирается целиком, как раньше.

    `external_facts` — внешний срез (`analysis/external.py:ExternalFact`),
    собранный КОДОМ до анализа: сам составитель в сеть не ходит (#159). Пусто —
    раздела «Контекст извне» в отчёте не будет вовсе.

    `lens` — призмы, которые подключил ход (кредитная, риск-, факторная,
    план-факт; канон §3 и §8). Полный анализ ПЕРЕИСПОЛЬЗУЕТ их куски, а не
    пишет свои: правила призмы дописываются к аналитической глубине ветки,
    разделы — в каркас перед выводами. Пусто — промпт побайтно тот же, что был
    до появления механизма.
    """
    m = methodology or md.base()
    ct_key = "bank" if company_type == "bank" else "non_financial"
    std = _STANDARD_LABEL.get((standard or "").lower(), "МСФО (IFRS)")
    lang = _LANG_INSTR[answer_language()]
    kind = "банка" if company_type == "bank" else "компании"
    text = analysis_pack(ocr_text or "", TEXT_WINDOW.get(depth, TEXT_WINDOW["quick"]))
    # Проминентно поднимаем ноту достаточности капитала в НАЧАЛО промпта (bank):
    # иначе в quick модель не докапывается до неё в большом отчёте и верит раннему
    # дисклеймеру → ложное «нет данных». Числа модель читает сама из этой ноты.
    cap = capital_notes_text(ocr_text or "") if ct_key == "bank" else ""

    frame = md.framework_block(m, company_type, depth, lens)
    depth_note = m.text_of(
        "prompt.depth.quick" if depth == "quick" else "prompt.depth.full")

    # ⚠️ ЗДЕСЬ ЖИЛО ПРОТИВОРЕЧИЕ. Раньше последняя фраза звучала так: «Показатели,
    # которых в таблице нет, считай по отчёту сам и помечай „расчётный“». Это прямая
    # лицензия на арифметику в голове модели — рядом с числами, посчитанными Python.
    # Сверить их между собой нечем, и по одному отчёту таблица говорила одно, а
    # вердикт другое. Недостающие коэффициенты (быстрая ликвидность, оборотный
    # капитал, конверсия EBITDA→OCF, банковский ROA и декомпозиция NIM) заведены в
    # реестр расчётов формулами — то есть теперь они ПРИЕЗЖАЮТ в таблице, и
    # считать составителю больше нечего.
    #
    # ⚠️ Почему здесь НЕ сказано «вызови fe_calc»: составитель анализа — это ОДИН
    # вызов модели без инструментов (`run.py` → `llm.complete_with_usage`, tools не
    # передаются). Отправлять его к калькулятору значило бы вписать в промпт
    # вежливую ложь: дотянуться он не сможет и, скорее всего, посчитает сам.
    # Калькулятор доступен ОРКЕСТРАТОРУ в чате — туда пользователь и приходит с
    # «а посчитай ещё вот это».
    # Три элемента методики вокруг ОДНОЙ подстановки — самой таблицы заземления.
    # Заголовок и правила правит методолог; таблица приезжает из прогона.
    # ССЫЛКА НА СТРАНИЦУ (#157) стоит ЗДЕСЬ, внутри блока таблицы, и только
    # вместе с ней: без таблицы брать номера неоткуда, и просьба «указывай
    # страницу» превратилась бы в приглашение их выдумывать.
    # БЕЗУСЛОВНО (#238). Блок стоял под `if metrics_table.strip()`, и это была
    # третья дыра заземления: пустая таблица молча снимала запрет арифметики,
    # оставляя в промпте только разрешение «все числа бери из текста отчёта».
    # Сегодня пустой таблицы быть не может — `run.run` отказывает раньше, — но
    # условие тут держать нельзя всё равно: оно снимало ПРАВИЛО по состоянию
    # ДАННЫХ, то есть ровно там, где ошибка не видна ни в логе, ни в выдаче.
    if not metrics_table.strip():
        raise ValueError("промпт анализа без таблицы заземления не собирается")
    helper = (
        m.text_of("prompt.grounding.intro")
        + f"{metrics_table}\n"
        + m.text_of("prompt.grounding.rules")
        + m.text_of("prompt.page_source")
    )

    cf = (capital_facts or "").strip()
    if cf and cf.upper() != "НЕТ":
        # Чистые нормативы, извлечённые фокусным вызовом — подаём фактом (надёжнее
        # 27К сырой ноты, которую модель в quick игнорит).
        cap_block = m.text_of("prompt.capital.facts") + f"{cf}\n\n"
    elif cap.strip() and not cf:
        cap_block = m.text_of("prompt.capital.note") + f"{cap}\n\n"
    else:
        cap_block = ""
    return (
        f"Ты — опытный финансовый аналитик. Перед тобой финансовая отчётность {kind} "
        f"по стандарту {std}. {depth_note}\n\n"
        + cap_block
        # Четыре правила — из методики; пятое (язык изложения) приклеивается
        # здесь, потому что это настройка стенда, а не методическое правило.
        + m.text_of("prompt.hard_rules")
        + f"• {lang}\n"
        + "\n" + md.comparability_block(m)
        + "\n" + md.analytical_block(m, company_type, available_enums, lens)
        + f"\nКАРКАС РАЗДЕЛОВ (соблюдай порядок и состав):\n{frame}\n"
        # Сразу за каркасом: раздел «Контекст извне» — ДОБАВКА к нему, и стоять
        # правило должно там, где перечислен состав разделов, а не абзацем выше
        # среди правил про числа. Ниже (в helper) идёт запрет на арифметику, и
        # соседство намеренное: внешние сведения — не материал для расчётов.
        # Методику передаём явно: правила обращения с внешними фактами —
        # такой же элемент, и правка пользователя обязана до них доехать.
        + external_block(external_facts or [], m)
        + helper
        + f"\n=== ТЕКСТ ОТЧЁТА ===\n{text}\n"
        # Контракт выдачи — ПОСЛЕ текста отчёта, и это не стиль, а расчёт: текст
        # тут до сотни тысяч знаков, и требование к последней строке ответа,
        # поставленное до него, теряется. Само требование — элемент методики:
        # уровень на обложке обязан быть выводом аналитика, а не пересчётом кода
        # по словам в ячейках таблицы (решение владельца 09.08).
        + m.text_of("prompt.output.contract")
    )
