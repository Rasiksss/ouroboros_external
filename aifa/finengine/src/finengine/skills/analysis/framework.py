_RISK_MARKERS = (
    "ожидаемые кредитные убытки", "движение резерва", "оценочного резерва под",
    "по стадиям", "credit risk", "expected credit loss", "loss allowance",
)

# ── Оговорка о непрерывности деятельности ──────────────────────────────────
# ЗАЧЕМ (#157-C). `_DROP_MARKERS` выбрасывал страницы аудиторского заключения
# как boilerplate — и вместе с ними пропадало ЕДИНСТВЕННОЕ место, где аудитор
# говорит о риске существования компании. У Мечела мнение немодифицированное,
# но отдельным разделом выделена существенная неопределённость в отношении
# непрерывности деятельности: анализ этих страниц не видел вовсе и показывал
# компанию чистой. Это хуже, чем отсутствие раздела: молчание читается как «всё
# в порядке».
#
# Маркеры целиком НЕ сняты намеренно: аудиторское заключение вместе с разделом
# об ответственности руководства — это десятки тысяч знаков на каждый отчёт, и
# бюджет пакета они съедают у примечаний, где лежат числа. Поэтому со страниц-
# исключений спасаем ровно те, где ЕСТЬ фраза.
#
# ОДИН УРОВЕНЬ ТОЧНОСТИ — и это ИСПРАВЛЕНИЕ прежнего решения. Сначала здесь
# было два: широкие фразы решали, ЧИТАТЬ ли страницу, узкая коллокация — какой
# ставить уровень риска. Замер по 35 текстовым PDF репозитория показал цену
# широкого списка: на 15 документах он вытаскивал в БЕЗБЮДЖЕТНЫЙ тир обычные
# разделы «Ответственность аудитора / Ответственность руководства» — там по МСА
# всегда есть и «продолжать непрерывно свою деятельность», и «существенная
# неопределённость в связи с событиями», — при том что оговорки в этих отчётах
# НЕТ ни одной. На синтетическом отчёте с настоящим текстом ответственности
# пакет раздулся до 28,7 тыс. знаков при бюджете 10 тыс., и примечание с
# ЧИСЛАМИ из него вылетело. Ошибка «в плюс» стоила не одну лишнюю страницу, а
# вытеснение того, ради чего пакет и собирают.
#
# Теперь и «читать» и «уровень риска» решает ОДНА проверка — узкая коллокация
# из МСА 570 БЕЗ отрицания вокруг. Варианты предлога перечислены явно: аудиторы
# пишут «в отношении», «связанная с» и «в связи с», и это разница формулировки,
# а не смысла. Переносы строк от OCR снимает `_flat`, поэтому «широкий» список
# ради них больше не нужен.
_GC_SECTION_MARKERS = (
    "существенная неопределенность в отношении непрерывности деятельности",
    "существенной неопределенности в отношении непрерывности деятельности",
    "существенная неопределенность, связанная с непрерывностью деятельности",
    "существенной неопределенности, связанной с непрерывностью деятельности",
    "существенная неопределенность в связи с непрерывностью деятельности",
    "существенной неопределенности в связи с непрерывностью деятельности",
    "material uncertainty related to going concern",
    "material uncertainty relating to going concern",
    "material uncertainty regarding going concern",
)
# ⚠️ ОТРИЦАНИЯ. Узкой коллокации МАЛО: чистое заключение произносит ТУ ЖЕ фразу,
# чтобы сказать обратное. Проверено на «Монополия 2024.pdf» из нашего же
# бенчмарк-набора — единственном из 35 текстовых PDF репозитория, где детектор
# вообще срабатывал, и ВСЕ три вхождения там отрицания:
#   «…ключевого вопроса аудита ОТСУТСТВИЕ существенной неопределенности…»
#   «…существенная неопределенность … группы ОТСУТСТВУЕТ»
#   «…руководство считает, что ОТСУТСТВУЕТ существенная неопределенность…»
# На обложке чистой компании появлялся «ИТОГОВЫЙ РИСК-ПРОФИЛЬ: КРИТИЧЕСКИЙ» с
# обоснованием, утверждающим прямо противоположное написанному аудитором.
# Отрицание ищем ВОКРУГ вхождения — и слева, и справа: русский язык ставит его
# по обе стороны («отсутствует X» и «X отсутствует»).
_GC_NEGATIONS = (
    "отсутств", "не выявл", "не установл", "не обнаруж", "не имеется",
    "не существует", "нет существенной", "no material uncertainty",
    "did not identify", "have not identified", "does not exist",
)
# Окно подобрано по длине придаточного, а не «на глаз»: в найденных примерах
# отрицание отстоит от коллокации на 10–60 знаков. Шире — начнём цеплять
# отрицание из соседнего предложения и потеряем НАСТОЯЩУЮ оговорку, а это
# ошибка в опасную сторону.
_GC_NEG_WINDOW = 90


def _flat(s: str) -> str:
    """Строка для поиска ФРАЗ: регистр, «ё» и переносы строк решать не должны.

    OCR рвёт фразу переводом строки ровно посередине («существенная\\nнеопре-
    делённость»), и буквальный поиск подстроки в такой странице не находит
    ничего — то есть проверка молча превращается в «оговорки нет».
    """
    return re.sub(r"\s+", " ", (s or "").lower().replace("ё", "е"))


def going_concern_pages(ocr_text: str) -> list[int]:
    """Страницы, где аудитор выделил ОТДЕЛЬНЫМ разделом существенную
    неопределённость в отношении непрерывности деятельности.

    Это единственный машинно-проверяемый признак «под вопросом само
    существование компании», и уровень риска карточки опирается на него, а не
    на мнение модели: завтра по тому же отчёту получится ровно тот же ответ.
    Узкие маркеры — см. комментарий выше.
    """
    text = ocr_text or ""
    nums = re.findall(r"(?m)^===PAGE\s+(\d+)===\s*$", text)
    if not nums:
        return []
    parts = re.split(r"(?m)^===PAGE\s+\d+===\s*$", text)
    return [int(num) for num, body in zip(nums, parts[1:])
            if _gc_asserted(_flat(body))]


def _gc_asserted(flat_body: str) -> bool:
    """Есть ли на странице УТВЕРЖДЕНИЕ об оговорке, а не её отрицание.

    Считаем ПОВХОЖДЕНИЮ, а не по странице целиком: заключение вправе сначала
    процитировать стандарт («если существенная неопределённость есть, аудитор
    обязан…»), а потом сказать, что здесь её нет, — и наоборот. Достаточно
    одного НЕотрицаемого вхождения.
    """
    for marker in _GC_SECTION_MARKERS:
        start = 0
        while (i := flat_body.find(marker, start)) != -1:
            around = flat_body[max(0, i - _GC_NEG_WINDOW):
                               i + len(marker) + _GC_NEG_WINDOW]
            if not any(n in around for n in _GC_NEGATIONS):
                return True
            start = i + len(marker)
    return False


def analysis_pack(ocr_text: str, budget: int) -> str:
    """Собрать компактный аналитический пакет из пагинированного OCR: формы —
    целиком и в приоритете, затем КЛЮЧЕВЫЕ примечания (сначала капитал, затем
    кредитный риск/ECL), затем прочие до бюджета, boilerplate (аудит/
    ответственность/содержание) выкинуть. Так анализ не зависит от размера
    документа (нет таймаута на больших годовых) и не теряет критичные ноты в
    хвосте большого отчёта.
    """
    text = ocr_text or ""
    # ⚠️ ГЛАВНОЕ ПРАВИЛО (09.08.2026, решение владельца). Пока отчёт ВЛЕЗАЕТ,
    # не выбрасываем и не переставляем НИЧЕГО — отдаём как есть.
    #
    # Раньше служебные страницы (аудиторское заключение, ответственность
    # руководства, оглавление) выкидывались ВСЕГДА, а страницы переставлялись по
    # тирам — независимо от того, был ли перерасход. Возражение владельца по
    # существу: это решение КОДА о том, что в документе важно, принятое по
    # словам в первых 400 знаках страницы. Пока места хватает, у такого решения
    # нет ни повода, ни способа проверить себя — а цена ошибки в нём высокая
    # (выброшенная страница для модели просто не существует).
    #
    # Теперь приоритизация — аварийный режим, а не режим по умолчанию, и
    # включается только тогда, когда без неё часть текста всё равно потерялась
    # бы. Тогда у выбрасывания появляется хотя бы честное обоснование.
    if len(text) <= budget:
        return text
    parts = re.split(r"(?m)^===PAGE\s+\d+===\s*$", text)
    nums = re.findall(r"(?m)^===PAGE\s+(\d+)===\s*$", text)
    if not nums:  # непагинированный текст — просто отдаём голову
        return text[:budget]
    pages = list(zip(nums, parts[1:]))  # (номер, тело)
    # ⚠️ ТИРА «ОГОВОРКА АУДИТОРА» ЗДЕСЬ БОЛЬШЕ НЕТ (снято 09.08.2026 по прямому
    # указанию владельца). Он существовал ради того, чтобы страница с оговоркой
    # о непрерывности деятельности гарантированно доехала до модели: по ней
    # код-правило ставило «Критический» уровень риска. Правила больше нет —
    # уровень называет аналитик сам, — а значит подъём именно этой страницы над
    # всеми прочими превратился в предпочтение кода без основания.
    # Уровень риска — предмет отдельного навыка (#158).
    statements, cap_notes, risk_notes, other_notes = [], [], [], []
    for num, body in pages:
        head = body[:400].lower()
        block = f"===PAGE {num}===\n{body.strip()}"
        if any(m in head for m in _DROP_MARKERS):
            continue
        lb = body.lower()
        if any(m in head for m in _STATEMENT_MARKERS):
            statements.append(block)
        elif any(m in lb for m in _CAPITAL_MARKERS):
            cap_notes.append(block)  # достаточность капитала — вперёд всех нот
        elif any(m in lb for m in _RISK_MARKERS):
            risk_notes.append(block)  # кредитный риск/ECL — вторым тиром
        else:
            other_notes.append(block)
    out, used = [], 0
    # Формы держим всегда: они компактны и это ядро отчётности.
    for block in statements:
        out.append(block)
        used += len(block)
    for block in cap_notes + risk_notes + other_notes:  # капитал → риск → прочее
        if used >= budget:
            out.append("\n[…примечания усечены по объёму пакета…]")
            break
        out.append(block)
        used += len(block)
    return "\n\n".join(out)


def capital_notes_text(ocr_text: str, limit: int = 30_000) -> str:
    """Страницы ноты достаточности капитала (по _CAPITAL_MARKERS) — для
    ПРОМИНЕНТНОЙ подачи в начало промпта. В большом отчёте модель (особенно в
    quick) не докапывается до этой ноты в середине и верит раннему дисклеймеру
    «не публикуется» → ложное «нет данных». Маркеры детектят страницу-ноту, а
    числа модель читает сама (никаких регэкспов значений). Bank-специфично."""
    text = ocr_text or ""
    nums = re.findall(r"(?m)^===PAGE\s+(\d+)===\s*$", text)
    if not nums:
        return ""
    parts = re.split(r"(?m)^===PAGE\s+\d+===\s*$", text)
    out, used = [], 0
    for num, body in zip(nums, parts[1:]):
        if any(m in body[:400].lower() for m in _DROP_MARKERS):
            continue  # пропускаем оглавление/аудиторское — там только упоминание ноты
        if any(m in body.lower() for m in _CAPITAL_MARKERS):
            out.append(f"===PAGE {num}===\n{body.strip()}")
            used += len(body)
            if used >= limit:
                break
    return "\n\n".join(out)


