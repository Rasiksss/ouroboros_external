"""Разбор markdown-вывода анализа в структуру для карточки (report_structured).

Модель пишет markdown по КАРКАСУ (framework) — здесь мы парсим его в JSON-контракт
карточки. Так структура получается БЕЗ принуждения модели к JSON (не рискуем
качеством рассуждения), а фронт рендерит красивую карточку + «копировать в Excel».

Контракт:
  {company, period, verdict, kpi:[{name,value,prev,delta,flag,why}],
   sections:[{title,body}], strengths:[str], watch:[str], conclusions:[str], footnote}

Парсер ТОЛЕРАНТНЫЙ: не нашёл раздел — оставляет пусто; фронт всегда может показать
исходный markdown как фолбэк.
"""
from __future__ import annotations

import logging
import re


log = logging.getLogger(__name__)

_HEADER = re.compile(r"(?m)^\s*#{1,4}\s*(?:\d+[.)]\s*)?(.+?)\s*$")


def _norm(s: str) -> str:
    return re.sub(r"[^а-яёa-z0-9]", "", (s or "").lower())


# Заголовок раздела внешнего контекста — берём У КАРКАСА, чтобы переименование
# правилось в одном месте, а не расходилось между тем, что просит промпт, и тем,
# что ловит разбор.
def _external_key() -> str:
    from finengine.skills.analysis.framework import EXTERNAL_SECTION_TITLE
    return _norm(EXTERNAL_SECTION_TITLE)


def _split_sections(md: str) -> list[tuple[str, str]]:
    """[(title, body)] по markdown-заголовкам #..####. Текст до первого заголовка
    (обычно «# Финансовый анализ — X») отбрасывается."""
    heads = list(_HEADER.finditer(md))
    out: list[tuple[str, str]] = []
    for i, h in enumerate(heads):
        title = h.group(1).strip()
        start = h.end()
        end = heads[i + 1].start() if i + 1 < len(heads) else len(md)
        body = md[start:end].strip()
        out.append((title, body))
    return out


def _flag_from(text: str) -> tuple[str, str]:
    """Из ячейки «Δ%/оценка» вида «+4,6% / **Норма** (причина)» → (flag, why).

    Слова-статусы приходят из неприкосновенного правила `common.rule.flags`:
    менять их запрещено ровно потому, что здесь по ним красится карточка.
    Английские синонимы — для `FE_ANALYSIS_LANG=en`.

    ПОРЯДОК ПРОВЕРОК — не косметика, каждая пара разбиралась отдельно:
    • «критический» ПЕРЕД «риском»: строка «критический риск» — это верхняя
      ступень, а не обычный риск;
    • «норма» ПЕРЕД «позитивным»: «норма» — статусное слово из словаря, а
      «позитивн-» часто попадает в пояснение («+18% / **Норма** (позитивная
      динамика)»). Из двух возможных ошибок эта дешевле: сильный показатель
      покажется просто здоровым, а не наоборот — здоровый сильным.
    ГДЕ ИЩЕМ СТАТУС. Только ДО пояснения в скобках. Статусное слово стоит в
    ячейке само («… / **Норма** (рост в пределах отрасли)»), а в скобках живёт
    человеческая речь — и в ней те же корни встречаются с обратным смыслом.
    Проверено прогоном разбора: «**Норма** (рост некритичный)»,
    «**Внимание** (снижение, пока не критично)» и «**Позитивный** (критичных
    отклонений нет)» — все три давали `crit`, а одного `crit` хватает, чтобы
    весь отчёт стал критическим на обложке. Раньше цена такой ошибки была одна
    пилюля в таблице, теперь — заголовок всей карточки.
    """
    m = re.search(r"\(([^)]+)\)\s*$", text.strip())
    why = m.group(1).strip() if m else ""
    low = (text[:m.start()] if m else text).lower()
    flag = "na"
    # «не критично», «некритичный» — отрицание, а не верхняя ступень.
    if re.search(r"(?<!не)(?<!не )критич|(?<!non-)(?<!not )critical", low):
        flag = "crit"
    elif re.search(r"\bриск\b|\brisk\b", low):
        flag = "risk"
    elif re.search(r"вниман|attention|watch|caution", low):
        flag = "warn"
    elif re.search(r"норм|\bok\b|normal|healthy", low):
        flag = "ok"
    elif re.search(r"позитивн|positive", low):
        flag = "good"
    elif re.search(r"нет\s*данных|не\s*раскры|no\s*data|not\s*disclosed|\bn/?a\b", low):
        flag = "na"
    return flag, why


def _parse_kpi(body: str) -> list[dict]:
    """Парсим markdown-таблицу показателей. Ждём 4 колонки:
    показатель | текущий | предыдущий | Δ%/оценка(+флаг). Толерантно к 3 колонкам."""
    rows: list[dict] = []
    for line in body.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 2:
            continue
        if set(cells[0]) <= {"-", ":", " "}:
            continue  # разделитель |---|
        name = re.sub(r"\*\*", "", cells[0]).strip()
        if not name or _norm(name) in {"показатель", "показатели", "metric", "indicator"}:
            continue  # заголовок таблицы
        value = cells[1] if len(cells) > 1 else ""
        prev = cells[2] if len(cells) > 2 else ""
        last = cells[-1] if len(cells) > 2 else (cells[1] if len(cells) > 1 else "")
        # delta = числовая часть последней ячейки до «/» или до слова-флага
        delta = re.split(r"[/|]", last)[0].strip()
        flag, why = _flag_from(last)
        rows.append({"name": name, "value": value.strip(), "prev": prev.strip(),
                     "delta": delta, "flag": flag, "why": why})
    return rows


_TWO_PART = re.compile(
    r"^(сильные сторон\w*|strengths?"
    r"|зоны внимани\w*|watch\s*points?|areas? of (?:attention|concern))"
    r"\s*[:—-]?\s*(.*)$", re.IGNORECASE)
_STRENGTH_HEAD = re.compile(r"^(сильн|strength)", re.IGNORECASE)


def _parse_two_part(body: str) -> tuple[list[str], list[str]]:
    """Итог: «Сильные стороны» / «Зоны внимания» → два списка. Метка может быть
    отдельной строкой-заголовком ИЛИ на одной строке с текстом («• **Сильные
    стороны:** …») — во втором случае берём текст после метки как пункт."""
    strengths, watch = [], []
    cur = None
    for raw in body.splitlines():
        clean = re.sub(r"\*\*", "", re.sub(r"^\s*[•\-\*\d.)]+\s*", "", raw.strip())).strip()
        if not clean:
            continue
        m = _TWO_PART.match(clean)
        if m:
            cur = strengths if _STRENGTH_HEAD.match(m.group(1)) else watch
            rest = m.group(2).strip()
            if rest:
                cur.append(rest)
            continue
        if cur is not None:
            cur.append(clean)
    return strengths, watch


def _parse_list(body: str) -> list[str]:
    """Выводы: нумерованный/маркированный список → пункты."""
    items = []
    for line in body.splitlines():
        s = line.strip()
        if re.match(r"^\s*(?:\d+[.)]|[•\-\*])\s+", s):
            items.append(re.sub(r"^\s*(?:\d+[.)]|[•\-\*])\s+", "", s).strip())
    return items


# Пять слов закрытого словаря статусов (`common.rule.flags`) → четыре уровня
# карточки. «Позитивный» и «норма» дают один уровень: обложка различает не
# оттенки здоровья, а нужно ли читать дальше.
