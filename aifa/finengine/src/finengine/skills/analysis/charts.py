"""Спецификации графиков карточки анализа — ДАННЫЕ, а не картинка (#157).

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. В эталонном отчёте владельца есть инфографика, у нас её
не было вовсе. Но главное здесь не «нарисовать», а «не соврать»: в самом эталоне
EBITDA в HTML — 41 150, а в PDF того же прогона — 32 393, расхождение 27% между
двумя артефактами ОДНОГО расчёта. Так бывает ровно тогда, когда картинка считает
своё, а таблица — своё. Поэтому:

  • здесь НЕТ отрисовки. Функции чистые: «показатели прогона → спецификация»
    (данные, единица, подписи, источник). SVG строит фронт из этих чисел
    элементами React — ни строкой разметки отсюда;
  • здесь НЕТ собственной арифметики по отчёту. Значения читаются из ТАБЛИЦЫ
    ЗАЗЕМЛЕНИЯ этого прогона — тем же редьюсером `calc.dataset_from_metrics`,
    которым их читает калькулятор коэффициентов. Второго способа «достать
    число из прогона» быть не должно: он и есть механизм расхождения;
  • масштаб оси НЕ задаётся константой. Единица берётся из поля `unit` самих
    данных: у одного отчёта млн ₽, у другого тыс., у третьего доллары.
    Ошибка здесь превращает график в ложь, не показав ни одной неверной цифры,
    поэтому единицы всех входов сверяются, а безымянная единица — отказ.

ОТКАЗ С ПРИЧИНОЙ, А НЕ МОЛЧАНИЕ. Каждая функция возвращает пару
`(спецификация | None, причина)`. Не построили — причина называется словами и
уходит в лог вызывающего. Молча отсутствующий график неотличим от «у компании
всё ровно», а это и есть тихий отказ, запрещённый правилами продукта.
"""
from __future__ import annotations

import logging
import re

from finengine.skills.calc import dataset_from_metrics

log = logging.getLogger(__name__)

# ── Водопад «от операционного потока к свободному» ───────────────────────────
#
# Почему именно он первым: это самый содержательный график эталона («бизнес не
# окупает собственный долг»), и все его входы у нас уже извлекаются реестром
# ячейки — выдумывать под него ничего не нужно.
_OCF = "NET_OPERATING_CASH_FLOW"
_CAPEX = "CAPEX"
_FCF = "FREE_CASH_FLOW"
_INTEREST = "INTEREST_PAID"
_LEASE = "PRINCIPAL_REPAYMENT_OF_LEASE_LIABILITIES"

_WATERFALL_INPUTS = (_OCF, _CAPEX, _FCF, _INTEREST, _LEASE)

# ОТТОКИ. Реестр помечает эти показатели `formula_default_abs_behavior=true`, и
# калькулятор берёт от них модуль перед подстановкой в формулу: в отчётах они
# встречаются и со знаком, и без. Водопад обязан считать ровно так же — иначе
# столбик «минус капзатраты» разойдётся со «свободным потоком» из таблицы. Что
# соглашение выбрано верно, доказывает не этот список, а сверка ниже.
_OUTFLOWS = (_CAPEX, _INTEREST, _LEASE)

# Допуск сверки «свободный поток из таблицы» ↔ «операционный поток − капзатраты».
# Оба числа приходят из одного прогона одного калькулятора, поэтому обязаны
# совпадать до округления; 0,5% — запас на округление движка, а не на разные
# трактовки. Всё, что больше, — это уже расхождение эталона на 27%, и рисовать
# такой график нельзя.
_RECONCILE_REL_TOL = 0.005


def _close(a: float, b: float) -> bool:
    return abs(a - b) <= max(1e-6, _RECONCILE_REL_TOL * max(abs(a), abs(b)))


# Масштаб денежной единицы. Ключ — ВЕЛИЧИНА, а не строка: «млн руб» и
# «млн. руб.» — одно и то же, и путь их формирования разный только внутри нас
# (извлечённые получают канонический ярлык, рассчитанные — сырой из отчёта).
# Валюту в ключ не берём: отчёт по одной компании ведётся в одной валюте, а
# смешать рубли с долларами внутри ОДНОГО водопада отчёт не даст.
_UNIT_SCALES: tuple[tuple[tuple[str, ...], int], ...] = (
    (("миллиард", "млрд", "billion", "bn"), 1_000_000_000),
    (("миллион", "млн", "million", "mln", "mn"), 1_000_000),
    (("тысяч", "тыс", "thousand", "'000"), 1_000),
)


def unit_scale(unit: str) -> int | None:
    """Масштаб единицы или None — «не узнал».

    Отдельная функция, а не сравнение строк на месте: единица приходит из
    отчёта, и её написание — вопрос вёрстки («млн руб.», «в миллионах рублей»,
    «млн ₽»), а не смысла. Проверяются ПРЕФИКСЫ слов, поэтому падежи
    («в миллионах») попадают тем же правилом.

    None вместо «1» намеренно: незнакомая единица должна привести к ОТКАЗУ с
    названной причиной, а не к молчаливому предположению, что это рубли.
    """
    low = re.sub(r"[.,]", " ", (unit or "").lower().replace("ё", "е"))
    if not low.strip():
        return None
    for words, scale in _UNIT_SCALES:
        if any(w in low for w in words):
            return scale
    if re.search(r"\bруб|\brub\b|₽|\bдолл|\busd\b|\beur\b|€|\$", low):
        return 1  # единицы валюты без масштаба
    return None


def _name(table: dict, enum: str) -> str:
    """Имя показателя из прогона — читателю показываем то, что он видит в
    таблице, а не машинный enum."""
    return str((table.get(enum) or {}).get("name_ru") or enum)


def _fmt(v: float) -> str:
    """Число в причине отказа — так, как его прочитает человек, а не `repr`."""
    return f"{v:,.0f}".replace(",", " ") if abs(v) >= 1000 else f"{v:.2f}"


def waterfall_ocf_to_fcf(metrics: list[dict]) -> tuple[dict | None, str]:
    """«Операционный поток → −капзатраты → свободный поток → −проценты →
    −погашение аренды → остаток». Возвращает `(спецификация, "")` либо
    `(None, причина)`.

    ГЛАВНОЕ ЗДЕСЬ — СВЕРКА. Точка «свободный поток» НЕ считается сложением
    столбиков: она читается из таблицы заземления, где её посчитал код по
    формуле реестра (`FREE_CASH_FLOW = NET_OPERATING_CASH_FLOW − CAPEX`), и
    затем сверяется с суммой показанных столбиков. Разошлось — графика нет и
    названа причина. Именно этот отказ отделяет нас от эталона, у которого одно
    и то же число в двух его собственных артефактах отличается на 27%.

    Последний столбик («остаток») — единственная величина, которой в реестре
    нет: это алгебраическая сумма УЖЕ ЗАЗЕМЛЁННЫХ столбиков, посчитанная кодом,
    и подписана она отдельным именем. Назвать её «свободным потоком» было бы
    вторым числом под уже занятым названием — тем самым дефектом.
    """
    table = dataset_from_metrics(metrics or [])
    value: dict[str, float] = {}
    missing: list[str] = []
    for enum in _WATERFALL_INPUTS:
        main = (table.get(enum) or {}).get("main")
        if main is None:
            missing.append(enum)
        else:
            value[enum] = float(main)
    if missing:
        # «Нет данных» ≠ «ноль»: подставить сюда ноль значило бы нарисовать
        # компанию без аренды там, где мы просто не нашли строку.
        return None, "в таблице заземления нет показателей: " + ", ".join(missing)

    # ЕДИНИЦА — ИЗ ДАННЫХ. Реестр единицу не хранит вовсе (её определяет отчёт),
    # поэтому она приходит с каждым показателем прогона. Разные единицы в одном
    # водопаде — сложение тысяч с миллионами: числа верные, картинка лживая.
    units = {enum: str((table.get(enum) or {}).get("unit") or "").strip()
             for enum in _WATERFALL_INPUTS}
    # ПУСТАЯ ЕДИНИЦА ХОТЯ БЫ У ОДНОГО ВХОДА — ОТКАЗ. Раньше пустые молча
    # отбрасывались (`{u for u in units.values() if u}`), и вход без единицы
    # наследовал масштаб соседей: проверено — один показатель без единицы среди
    # «тыс. руб.» давал ПОСТРОЕННЫЙ график с чужим ярлыком. Это ровно та ловушка,
    # ради которой единица берётся из данных: график лжёт, не соврав ни одним
    # числом. Отказ здесь дешевле: нет графика — читатель смотрит таблицу.
    blank = [e for e, u in units.items() if not u]
    if blank:
        return None, ("не указана единица измерения у " + ", ".join(blank)
                      + " — масштаб оси взять неоткуда")
    # СРАВНИВАЕМ ПО СМЫСЛУ, А НЕ ПО СТРОКЕ. На боевом пути извлечённые
    # показатели получают КАНОНИЧЕСКИЙ ярлык («млн. руб.»), а рассчитанные —
    # сырой из отчёта («млн руб»): две ветки, одна величина. Строковое
    # сравнение отбивало КАЖДЫЙ живой прогон, и знал об этом только log.info —
    # то есть график не появлялся никогда, а выглядело это как «не сделано».
    scales = {enum: unit_scale(u) for enum, u in units.items()}
    if len({s for s in scales.values()}) > 1:
        return None, ("единицы измерения расходятся: "
                      + "; ".join(f"{e} — «{u}»" for e, u in units.items()))
    if next(iter(scales.values())) is None:
        return None, ("единица измерения не распознана: "
                      + "; ".join(f"{e} — «{u}»" for e, u in units.items()))
    unit = units[_OCF]

    ocf, fcf = value[_OCF], value[_FCF]
    outflow = {enum: abs(value[enum]) for enum in _OUTFLOWS}
    expected = ocf - outflow[_CAPEX]
    if not _close(fcf, expected):
        # ⚠️ ЧЬЯ ВИНА. Расхождение бывает двух происхождений, и валить их в одну
        # формулировку нельзя: читатель по ней решает, чему не верить.
        #   • у ПОКАЗАТЕЛЯ два прочтения внутри нас (#163: enum заведён и
        #     извлекаемым, и расчётным, движок эмитит два события) — виноваты мы,
        #     и говорить «отчёт не сходится» тут значит клеветать на отчётность;
        #   • иначе числа пришли из отчёта такими — тогда вопрос к отчёту.
        # Признак первого — след, оставленный редьюсером таблицы заземления.
        ours = [e for e in (_OCF, _CAPEX, _FCF) if (table.get(e) or {}).get("conflict")]
        if ours:
            return None, (
                "график не построен по НАШЕЙ причине, а не из-за отчёта: "
                + ", ".join(_name(table, e) for e in ours)
                + " пришли двумя разными числами (показатель заведён и "
                "извлекаемым, и расчётным — задача #163). Числа в таблице верны, "
                "сверить их между собой нечем."
            )
        return None, (
            f"свободный поток в таблице ({_fmt(fcf)} {unit}) не сходится с "
            f"«операционный поток − капзатраты» ({_fmt(expected)} {unit}) — "
            f"график показал бы третье число"
        )

    def _label(enum: str) -> str:
        # Подпись — имя показателя ИЗ ПРОГОНА, а не литерал: реестр ячейки
        # переводится (ifrs_nf_en), и зашитая здесь русская строка подписала бы
        # английский отчёт по-русски.
        return str((table.get(enum) or {}).get("name_ru") or enum)

    rest = fcf - outflow[_INTEREST] - outflow[_LEASE]
    points = [
        {"label": _label(_OCF), "value": ocf, "kind": "start"},
        {"label": _label(_CAPEX), "value": -outflow[_CAPEX], "kind": "delta"},
        {"label": _label(_FCF), "value": fcf, "kind": "total"},
        {"label": _label(_INTEREST), "value": -outflow[_INTEREST], "kind": "delta"},
        {"label": _label(_LEASE), "value": -outflow[_LEASE], "kind": "delta"},
        {"label": "Остаток после процентов и аренды", "value": rest, "kind": "total"},
    ]
    return {
        "kind": "waterfall",
        "title": "От операционного потока к свободному",
        "unit": unit,
        "points": points,
        "note": ("Отрицательный остаток означает, что операционного потока не "
                 "хватает на инвестиции и обслуживание долга одновременно."),
        "source": ("таблица заземления прогона: значения извлечены из отчёта, "
                   "свободный поток посчитан кодом по формуле реестра"),
    }, ""


# График → отрасли, к которым он применим. Пусто в наборе = «ко всем».
#
# ЗАЧЕМ ЭТО ПОЯВИЛОСЬ (прогон Банка «Санкт-Петербург», 15.08). Водопад
# «операционный поток → капзатраты → свободный поток» заведён под НЕФИНАНСОВУЮ
# компанию: в банковском реестре нет ни `NET_OPERATING_CASH_FLOW`, ни `CAPEX`,
# ни `FREE_CASH_FLOW`. Строить его для банка нечем В ПРИНЦИПЕ — и каждый
# банковский прогон давал два WARNING «обещанного в отчёте нет»: один от
# карточки, второй от листа Excel.
#
# Уровень WARNING здесь заведён намеренно (см. ниже): отказ построить график —
# это «обещали и не дали». Но на банке никто ничего не обещал, и наше же
# правило гласит: сторож, который кричит на исправном, хуже отсутствующего —
# его начинают пролистывать, и настоящий отказ проезжает вместе с ложным.
_APPLIES_TO: dict = {
    "waterfall_ocf_to_fcf": ("non_financial",),
}


def build_charts(metrics: list[dict], company_type: str = "") -> list[dict]:
    """Все графики, которые получилось построить по показателям прогона.

    Единственная точка входа для боевого пути (карточка анализа) и для листа
    «Данные графиков» в Excel — чтобы карточка и книга рисовались по ОДНОЙ
    спецификации, а не по двум похожим.

    `company_type` — отрасль прогона. Не передали (старый вызов) — строим всё,
    как раньше: молча пропустить график страшнее лишнего предупреждения.
    """
    charts: list[dict] = []
    for build in (waterfall_ocf_to_fcf,):
        applies = _APPLIES_TO.get(build.__name__) or ()
        if company_type and applies and company_type not in applies:
            # НЕ WARNING: график к этой отрасли не относится, обещаний не было.
            log.info("charts: %s не строим — он про %s, а прогон по «%s»",
                     build.__name__, "/".join(applies), company_type)
            continue
        spec, reason = build(metrics)
        if spec is None:
            # WARNING, а не INFO. Отказ построить график — это не рядовой шаг
            # работы, а «обещанного в отчёте нет», и до этой правки он тонул в
            # info-потоке: график не появлялся НИ РАЗУ на боевом пути, а
            # выглядело это снаружи как «ещё не сделали». Уровень — минимальная
            # цена того, чтобы такое расхождение заметили за день, а не за
            # состязательную проверку.
            log.warning("charts: %s не построен — %s", build.__name__, reason)
            continue
        charts.append(spec)
    return charts
