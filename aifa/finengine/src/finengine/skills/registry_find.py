"""Мост между словами человека и именами показателей в реестре (Ш13).

ЗАЧЕМ. Сценарий владельца §5.2 — «извлеки выручку, чистую прибыль, EBITDA и
активы, посчитай рентабельность активов и Cost/Income» — сегодня НЕВЫРАЗИМ. У
`fe_extract_metrics` нет аргумента «список показателей»: ближайшее, что есть, —
роль из шести фиксированных наборов. Новый набор = правка `roles/layouts.json`,
то есть НОВЫЙ КОД под каждый запрос пользователя. Это прямо нарушает критерий
приёмки §12: любой запрос финансового домена обрабатывается БЕЗ нового кода.

Прежде чем принимать список показателей, его надо уметь ПОЛУЧИТЬ. Модель не
обязана знать наши enum'ы (`SALES_REVENUE`, `NET_INCOME`), а пользователь тем
более: он говорит «выручка», «чистая прибыль», «EBITDA». Здесь и живёт перевод.

ПОЧЕМУ ДЕТЕРМИНИРОВАННО, А НЕ МОДЕЛЬЮ. Сопоставление имени показателя — это
справочник, а не суждение. Модель на нём ошибается тихо: вернёт похожий enum,
движок его послушно извлечёт, и пользователь получит не тот показатель, о
котором спрашивал, без единого признака подмены. Здесь же промах виден: список
пуст, и об этом говорится вслух.

ЧЕСТНЫЙ ПУСТОЙ ОТВЕТ — часть контракта. Не нашли — так и пишем; выдумывать
ближайшее по звучанию нельзя.
"""
from __future__ import annotations

import re
import unicodedata
from typing import Any

# Порядок = приоритет. Точное попадание в enum сильнее совпадения в описании:
# «EBITDA» обязана находить EBITDA, а не «EBITDA маржа» и не всё, где это слово
# упомянуто в пояснении.
_EXACT_ENUM = 100
_EXACT_NAME = 90
_EXACT_ALIAS = 80
_PREFIX_NAME = 60
# Все слова запроса нашлись, но не подряд и в другом порядке. Ровно так и
# выглядят живые запросы: «долг/EBITDA» против «Отношение общего долга к
# EBITDA». Непрерывная подстрока такое не ловит вовсе, и до этого уровня
# ходовой запрос аналитика просто не находился.
_ALL_TOKENS = 50
_SUBSTR_NAME = 40
_SUBSTR_ALIAS = 30
# Имя реестра ЦЕЛИКОМ содержится в просьбе — человек сказал то же самое, но
# многословнее: «итого краткосрочные активы» про «Краткосрочные активы».
# Слабее прямых совпадений и слабее `_ALL_TOKENS` намеренно: лишние слова в
# просьбе всё-таки могут указывать на соседний показатель, поэтому уровень
# участвует в отборе последним из содержательных.
_NAME_INSIDE_QUERY = 20
_SUBSTR_DESC = 10

_WORD_RE = re.compile(r"[^\w]+", re.UNICODE)

# Слова-итоги: в названии строки отчётности они означают «сумма по разделу» и
# показатель от соседнего НЕ отличают. Только их разрешено оставить непокрытыми
# в `_fits_inside_query` — уточнение вроде «краткосрочные» оставить нельзя,
# иначе «итого краткосрочные активы» находит «Итого активы». Список короткий и
# закрытый намеренно: каждое слово здесь — разрешение на неточность.
_FILLER = frozenset({"итого", "всего", "совокупный", "совокупные", "совокупная",
                     "суммарный", "суммарные", "суммарная", "общий", "общие", "общая"})


def _norm(s: str) -> str:
    """Свести к сравнимому виду: регистр, ё/е, пунктуация, кратные пробелы.

    ё→е намеренно: в отчётах и в речи пользователя одно и то же слово пишется
    и так и так («заёмные»/«заемные»), и различать их здесь — терять попадания.
    """
    s = unicodedata.normalize("NFKC", str(s or "")).casefold().replace("ё", "е")
    return _WORD_RE.sub(" ", s).strip()


def _score(query: str, row: dict) -> float:
    """Насколько строка реестра отвечает на запрос. 0 = не отвечает.

    ДВЕ ВЕЩИ, БЕЗ КОТОРЫХ ОН ВРЁТ (обе найдены на живом запросе «активы»):

    1. СИНОНИМЫ РАВНОПРАВНЫ ИМЕНАМ. Сначала премия за начало строки давалась
       только `name_ru`, и «активы» находило «Активы в форме права пользования»
       вместо «Итого активы»: у второго нужное слово стоит в СИНОНИМЕ («Активы
       всего»), а синонимам премии не полагалось. Реестр писали люди, и главное
       слово нередко живёт именно в синониме.

    2. ПОКРЫТИЕ РАЗРЫВАЕТ НИЧЬЮ. Когда две строки совпали одинаково, ближе та,
       чьё имя КОРОЧЕ: чем меньше лишнего вокруг запроса, тем общее показатель.
       «активы» покрывает «итого активы» наполовину и «активы в форме права
       пользования» — на пятую часть. Прибавка меньше шага между уровнями,
       поэтому ничью она разрывает, а порядок уровней сломать не может.
    """
    q = _norm(query)
    if not q:
        return 0.0
    enum = _norm(row.get("enum"))
    if q == enum or q == enum.replace("_", " "):
        return _EXACT_ENUM
    names = [n for n in (_norm(row.get("name_ru")), _norm(row.get("name_en"))) if n]
    aliases = [a for a in (_norm(x) for x in
                           (list(row.get("aliases_ru") or [])
                            + list(row.get("aliases_en") or []))) if a]
    if q in names:
        return _EXACT_NAME
    if q in aliases:
        return _EXACT_ALIAS

    def _same_word(a: str, b: str) -> bool:
        """Одно ли это слово с точностью до падежа и числа.

        Было только `b.startswith(a)` — совпадение по НАЧАЛУ и ТОЛЬКО в одну
        сторону. Русский падеж режет иначе: «приобретения основных средств» не
        находило «Приобретение основных средств», потому что ни одно из двух не
        начало другого — они расходятся на последней букве («приобретени|я» /
        «приобретени|е»). Живой прогон 22.08: показатель не опознан, не извлечён
        и молча пропал из просьбы.

        Общий корень + близкая длина. Длина здесь и есть тормоз: «капитал» и
        «капитальные» делят семь букв, но отличаются на четыре — это разные
        слова, и склеивать их нельзя.
        """
        if a == b:
            return True
        if len(a) < 4 or len(b) < 4 or abs(len(a) - len(b)) > 3:
            return False
        общее = 0
        for x, y in zip(a, b):
            if x != y:
                break
            общее += 1
        return общее >= 5

    def _tokens_all_in(hay: str) -> bool:
        """Все слова запроса есть в строке — в любом порядке и с разрывами.

        Короткие слова (предлоги, союзы) сравниваем целиком: по двум буквам
        совпадёт что угодно.
        """
        hay_t = hay.split()
        for qt in q.split():
            if not any(ht == qt or (len(qt) >= 4 and (ht.startswith(qt) or _same_word(qt, ht)))
                       for ht in hay_t):
                return False
        return True

    def _fits_inside_query(hay: str) -> bool:
        """Имя реестра целиком уложилось в просьбу человека.

        Обратное направление к `_tokens_all_in`: там просьба должна найтись в
        имени, здесь имя — в просьбе. «Итого краткосрочные активы» не находило
        `TOTAL_CURRENT_ASSETS` ни одним уровнем, хотя его синоним —
        «Краткосрочные активы», то есть буквально подмножество сказанного.
        Лишнее слово в просьбе делало запрос ХУЖЕ, чем неточный: чем точнее
        человек формулирует, тем меньше шансов быть понятым.

        🔴 И РОВНО ЗДЕСЬ ЭТОТ УРОВЕНЬ ЛЕГКО СТАНОВИТСЯ ВРЕДНЕЕ ОТСУТСТВИЯ. В
        первой редакции условие было «имя ⊆ просьба», и «итого краткосрочные
        активы» находило `TOTAL_ASSETS` («Итого активы» тоже подмножество!) —
        то есть молча возвращало ДРУГОЙ показатель. Молчаливая подмена — худший
        из возможных исходов: движок послушно извлечёт не то, и признака
        подмены не будет ни одного.

        Поэтому непокрытыми могут остаться ТОЛЬКО слова-итоги. Уточнение
        («краткосрочные», «долгосрочные», «чистый») непокрытым остаться не
        может: оно и есть то, чем один показатель отличается от соседнего.
        """
        hay_t = hay.split()
        if len(hay_t) < 2:
            return False  # «активы» уложатся в любую просьбу и утащат отбор
        q_t = q.split()
        covered = set()
        for ht in hay_t:
            попал = [qt for qt in q_t if ht == qt or _same_word(ht, qt)]
            if not попал:
                return False
            covered.update(попал)
        return all(qt in covered or qt in _FILLER for qt in q_t)

    best, hit = 0, ""
    for n in names:
        if n.startswith(q) and _PREFIX_NAME > best:
            best, hit = _PREFIX_NAME, n
        elif _tokens_all_in(n) and _ALL_TOKENS > best:
            best, hit = _ALL_TOKENS, n
        elif q in n and _SUBSTR_NAME > best:
            best, hit = _SUBSTR_NAME, n
    for a in aliases:
        # Синоним, начинающийся с запроса, — тот же вес, что у имени: иначе
        # «Итого активы» проигрывает «Активам в форме права пользования».
        lvl = _PREFIX_NAME if a.startswith(q) else (_SUBSTR_ALIAS if q in a else 0)
        if lvl > best:
            best, hit = lvl, a
    if not best:
        for n in names + aliases:
            if _fits_inside_query(n) and _NAME_INSIDE_QUERY > best:
                best, hit = _NAME_INSIDE_QUERY, n
    if not best:
        desc = _norm(row.get("description"))
        if q in desc:
            best, hit = _SUBSTR_DESC, desc
    if not best:
        return 0.0
    return best + 9.0 * (len(q) / max(len(hit), 1))


def _row_out(row: dict, kind: str, *, also: str = "") -> dict:
    """Ответ модели: имя + чем оно отличается от соседних + как искать в отчёте.

    `hint` и `description` кладём НЕ для красоты: именно они не дают спутать
    «операционные расходы» с себестоимостью, а «прибыль» — с прибылью до
    налогов. Модель, выбирая из трёх похожих, читает их.
    """
    out = {
        "enum": row.get("enum"),
        "name_ru": row.get("name_ru"),
        "name_en": row.get("name_en"),
        "kind": kind,
        "aliases": list(row.get("aliases_ru") or []) + list(row.get("aliases_en") or []),
        "description": row.get("description") or "",
        "hint": row.get("hint") or "",
        "period_type": row.get("period_type") or "",
    }
    if row.get("formula"):
        out["formula"] = row["formula"]
    if also:
        out["ambiguous"] = also
    return {k: v for k, v in out.items() if v not in ("", [], None)}


def find_metrics(queries: list[str], profile_id: str, *, limit: int = 5) -> dict[str, Any]:
    """Слова пользователя → показатели реестра ячейки.

    ⚠️ ИМЯ НЕ СЛУЧАЙНО ДЛИННОЕ. Сначала функция звалась `find`, и сторож
    #153 (он строит цепочку вызовов реестра ПО ИМЕНАМ) немедленно покраснел:
    `find` совпадает со строковым методом `.find()`, которого в коде десятки, —
    и весь граф «кто трогает реестр» разошёлся по всему проекту. Общее имя у
    функции, ведущей к реестру, ломает чужую проверку. Не переименовывать
    обратно.

    Возвращает `{"matches": {слово: [строки]}, "not_found": [слова]}`.
    `not_found` — не досадная мелочь, а главный выход: по нему видно, что
    пользователь попросил показатель, которого в ячейке нет вовсе, и сказать
    ему об этом надо прямо, а не подсунуть похожий.
    """
    from finengine.skills.metric_schema import registry_for_profile

    reg = registry_for_profile(profile_id)
    extractable = list(reg["extractable"])
    # Расчётные приходят кортежами (enum, name_ru, formula, deps) — приводим к
    # той же форме, чтобы поиск не знал о двух представлениях.
    calculated = [
        {"enum": c[0], "name_ru": c[1], "formula": c[2], "name_en": "",
         "aliases_ru": [], "aliases_en": [], "description": "", "hint": ""}
        for c in reg["calculated"]
    ]

    # #163: один и тот же enum бывает заведён И извлекаемым, И расчётным (6 штук
    # в 7 ячейках из 8). Это открытый вопрос владельца, и тонкий тул делает его
    # ЗАМЕТНЕЕ, а не безопаснее: на «извлеки EBITDA» и «посчитай EBITDA» выйдут
    # разные числа под одним именем. Пока решения нет — показываем оба варианта
    # и говорим об этом вслух, а не выбираем молча.
    calc_enums = {str(c["enum"]) for c in calculated}
    both = {str(r["enum"]) for r in extractable} & calc_enums

    matches: dict[str, list[dict]] = {}
    not_found: list[str] = []
    for q in queries:
        scored: list[tuple[int, dict, str]] = []
        for row in extractable:
            s = _score(q, row)
            if s:
                scored.append((s, row, "extractable"))
        for row in calculated:
            s = _score(q, row)
            if s:
                scored.append((s, row, "calculated"))
        if not scored:
            not_found.append(q)
            continue
        scored.sort(key=lambda t: (-t[0], str(t[1].get("enum"))))
        matches[q] = [
            {
                **_row_out(row, kind,
                           also=("этот показатель заведён и извлекаемым, и расчётным — "
                                 "числа могут разойтись (#163)"
                                 if str(row.get("enum")) in both else "")),
                "match_score": _s,
            }
            for _s, row, kind in scored[:limit]
        ]
    return {
        "profile_id": profile_id,
        "matches": matches,
        "not_found": not_found,
        "note": (
            "Показателей с такими названиями в реестре этой ячейки нет: "
            + ", ".join(not_found)
            + ". Не подбирай похожий по звучанию — скажи пользователю прямо, "
              "что показателя нет, и предложи ближайший по СМЫСЛУ, если он есть."
        ) if not_found else "",
    }
