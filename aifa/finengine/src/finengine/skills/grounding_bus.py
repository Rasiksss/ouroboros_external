"""Станционная шина: bounded ephemeral transport для одного прогона (Срез 13.5.4).

ЧТО ОСТАЛОСЬ И ПОЧЕМУ. Durable financial/run truth (`EvidenceBundleV2`, typed
`ReportOutput`/`FormOutput`, `RunPassport`) живёт в `Case`/`PlanRun`/artifacts
через `CaseRuntime`; этот модуль их не хранит и не выбирает routing. Из
исходной шины (#121, «один прогон движка кормит и таблицу, и анализ») удалена
ПУБЛИКАЦИЯ ПОКАЗАТЕЛЕЙ (`announce`/`publish`/`fail`/`take`/`metrics_of`/
`cell_of`): в canonical production route `analyze.py`/`extract.py` каждый идут
своим `execute_production_goal` над одной и той же `EvidenceBundleV2` внутри
графа — второй прогон движка, ради экономии которого шина была заведена,
здесь не запускается вовсе, а заземлять не через что. Единственный
production-вызыватель публикации (`extract_result.publish_grounding`, через
недостижимое тело `station_turn._finish_run`) удалён тем же срезом.

ЧТО ОСТАЁТСЯ И ПОЧЕМУ ЭТО ВСЁ ЕЩЁ TRANSPORT, А НЕ STATE. Два жильца:

1. Явный СТАТУС фонового прогона (#160): «идёт»/«завершено»/«не получилось».
   Это не данные прогона (те живут в `Case`/`store/runs.py`), а сторож дубля —
   диагностика, не участвующая ни в чьём routing-решении. Без него агент
   выводил статус из молчания и переизвлекал уже извлечённое (замер Мечела:
   253,5 секунды сожжённого повтора).
2. Связь «нонс воркера → документ» (`bind_worker_doc`/`worker_doc`) — то, какой
   физический документ читает ЗАПЕЧАТАННАЯ комната под этим нонсом. Это
   nonce/file-delivery routing (тот же класс, что `internal_docs.py`'s
   `register_nonce_docs`), не второй источник document identity: canonical
   typed-результат несёт свой `document_id` независимо, а эта связь нужна
   ТОЛЬКО тем читателям, которым результата ещё не видно (сторож дубля,
   упавший/замолчавший прогон — см. `station_run_sink._abandon`).

Оба жильца — короткоживущая память об ОДНОМ ходе, привязанная к владельцу и
документу; ни один не переживает `_MEMORY_TTL_SEC` и не хранит финансовые
факты.
"""
from __future__ import annotations

import logging
import time

log = logging.getLogger(__name__)

# Потолок жизни фонового воркера — таймаут релея/ящика в оркестраторе. Живёт
# ЗДЕСЬ, а не в `agent.py`, чтобы у числа был один хозяин: `agent.py` берёт его
# отсюда как значение по умолчанию, и разъехаться они уже не могут.
WORKER_LIFETIME_SEC = 1200.0

# Сколько живёт ПАМЯТЬ о прогоне: связь «нонс воркера → документ» и запись
# состояния. Память обязана ПЕРЕЖИТЬ охраняемый процесс, иначе сторож молча
# выключается ровно на длинных прогонах — то есть ровно на тех, ради которых
# извлечение и уносят в фон. Арифметика дыры (найдена проверкой ветки #160):
# связь ставится в момент выдачи текста, воркер после этого работает до
# `WORKER_LIFETIME_SEC`, плюс доставка текста и спавн. При равном TTL связь
# протухала раньше воркера, `worker_doc` возвращал "", `run_finished` уходил в
# no-op, `run_status` отдавал None — и главный агент запускал движок ВТОРОЙ
# раз, как в замере Мечела. Двойной запас: ошибиться в эту сторону дёшево
# (лишняя запись в памяти), в обратную — 253 секунды и вторая цена прогона.
_MEMORY_TTL_SEC = WORKER_LIFETIME_SEC * 2


# ─────────────────────────────────────────────────────────────────────────────
# Явный статус фонового извлечения (#160): «идёт» / «завершено» / «не получилось»
# ─────────────────────────────────────────────────────────────────────────────
#
# ДЕФЕКТ, который это закрывает (прогон Мечела 02.08, цифры настоящие). Почтовый
# ящик воркера знал в 18:17:19,836 и про 94 показателя, и про сохранённый Excel
# на 15 802 байта. Главный агент этого НЕ узнал и в 18:20:59 запустил движок
# ЗАНОВО: 253,5 секунды работы, те же 94 показателя, и на выходе ни файла, ни
# карточки — около 30% всего прогона впустую. Причина не в промпте: статус
# фонового прогона агент выводил из МОЛЧАНИЯ, а молчание неотличимо от
# «не получилось».
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ СЛОТОВ ВЫШЕ. Слот — про ДАННЫЕ: кто в него заглянул, тот
# ЖДЁТ показателей до таймаута. Статус — про сам ФАКТ прогона, и ждать по нему
# нельзя: воркер (#84) показатели в шину не кладёт, и живи статус в том же
# слоте, `take()` анализа честно висел бы минуты ради данных, которых там
# никогда не будет.
#
# ИНВАРИАНТ, который тут важнее удобства. Молчание не читается как «не
# получилось», но и «получилось» по умолчанию НЕ предполагается: записи нет —
# сторож молчит, извлечение идёт как раньше. Иначе агент замолчал бы там, где
# извлечение ДЕЙСТВИТЕЛЬНО не состоялось, а это хуже дубля.
#
# ГОРИЗОНТ — ОДИН ХОД. Запись заводит сам прогон, а стирает её начало
# СЛЕДУЮЩЕГО хода (`run_forget`). Без этого «извлеки заново» следующим
# сообщением молча вернуло бы прошлый результат: дубль стоит времени, а подмена
# чисел стоит доверия ко всем числам сразу.

# (owner_id, doc_id) → {"state", "source", "summary", "message", "ts"}
_runs: dict[tuple[int, str], dict] = {}

# Нонс воркера → (doc_id, время записи). Заполняется по ФАКТУ выдачи текста.
_worker_docs: dict[str, tuple[str, float]] = {}


def _run_key(owner_id: int | None, doc_id: str) -> tuple[int, str]:
    return (int(owner_id or 0), doc_id)


def _runs_gc() -> None:
    now = time.monotonic()
    for key in [k for k, r in _runs.items() if now - r["ts"] > _MEMORY_TTL_SEC]:
        _runs.pop(key, None)
    for n in [n for n, (_, ts) in _worker_docs.items() if now - ts > _MEMORY_TTL_SEC]:
        _worker_docs.pop(n, None)
    # Счётчик повторов чистим ВМЕСТЕ с прогоном, которого он касается: иначе он
    # растёт вечно и переживает сам предмет счёта. Держать дольше незачем —
    # история дублей нужна внутри рабочего окна, а не навсегда.
    for key in [k for k in _dup_runs if k not in _runs]:
        _dup_runs.pop(key, None)


# Счётчик повторов по документу. Держим отдельно от `_runs`: тот живёт по
# состоянию прогона и обнуляется вместе с ним, а нам нужна ИСТОРИЯ — сколько раз
# по этому документу вообще начинали заново.
_dup_runs: dict[tuple, int] = {}


def duplicate_runs(owner_id: int | None, doc_id: str) -> int:
    """Сколько повторных запусков по этому документу уже случилось.

    Читатель для журнала и для сторожей. Пока порога нет, число говорит само:
    ноль — дубля не было, больше нуля — было столько раз.
    """
    return _dup_runs.get(_run_key(owner_id, doc_id), 0)


def run_started(owner_id: int | None, doc_id: str, *, source: str) -> None:
    """Прогон подал ПЕРВЫЙ признак жизни (пришло первое его событие).

    Именно первое событие, а не заказ прогона: диспетчер (#116) запускает
    извлечение тем же тулом `fe_extract_metrics`, и запись «идёт», поставленная
    до старта, заблокировала бы его собственный вызов.

    Терминальное состояние не понижаем: события после `done` (запоздавший
    хвост релея) не должны воскрешать «идёт» и снова прятать готовый результат.
    """
    if not doc_id:
        return
    _runs_gc()
    key = _run_key(owner_id, doc_id)
    prev = _runs.get(key)
    if prev is not None and prev["state"] in ("done", "failed"):
        return
    # 🔴 ВТОРОЙ ПРОГОН ПО ТОМУ ЖЕ ДОКУМЕНТУ — ГОВОРИМ ГРОМКО (#160).
    #
    # Пишущая половина сторожа дубля жила с 18.08, а ЧИТАТЕЛЕЙ у `run_status` не
    # было НИ ОДНОГО: запись велась в пустоту. Цена дубля измерена — 253,5
    # секунды сожжённого повтора на Мечеле, и узнать о нём было неоткуда.
    #
    # ⚠️ ГОВОРИМ, А НЕ ОТКАЗЫВАЕМ, И ЭТО РЕШЕНИЕ, А НЕ ПОЛУМЕРА. Отказать
    # вслепую значит однажды убить ЗАКОННЫЙ повтор — перезапуск после сбоя,
    # второй ход по тому же отчёту с другим составом показателей. Порог
    # «сколько повторов ненорма» назначать не на чем, пока их никто не считал;
    # тот же порядок мы приняли для сорвавшихся батчей: сначала запись, потом
    # наблюдение, потом правило.
    if prev is not None and prev["state"] == "running":
        _dup_runs[key] = _dup_runs.get(key, 0) + 1
        log.warning(
            "ДУБЛЬ ПРОГОНА: документ %s уже считается (%s), пришёл второй (%s) — "
            "повтор по этому документу №%d. Цена одного дубля измерена: 253 с",
            doc_id, prev.get("source") or "?", source, _dup_runs[key])
    _runs[key] = {"state": "running", "source": source, "summary": {},
                  "message": "", "ts": time.monotonic()}


def run_finished(owner_id: int | None, doc_id: str, *, source: str, summary: dict) -> None:
    """Прогон ЗАВЕРШЁН, результат доставлен пользователю (таблица + Excel).

    `summary` — то же, что уходит в историю сессии блоком `background_extract`:
    компания, число показателей, период, file_id Excel. Из неё агент отвечает
    на «а что там с извлечением», не запуская движок второй раз.
    """
    if not doc_id:
        return
    _runs_gc()
    _runs[_run_key(owner_id, doc_id)] = {
        "state": "done", "source": source, "summary": dict(summary or {}),
        "message": "", "ts": time.monotonic()}
    log.info("grounding_bus: прогон завершён doc=%s (%s) — повтор не нужен",
             doc_id[:8], source)


def run_failed(owner_id: int | None, doc_id: str, message: str, *, source: str) -> None:
    """Прогон НЕ состоялся. Записывается так же явно, как успех: без этого
    отличить «упал» от «ещё идёт» можно было бы только по молчанию — и агент
    либо ждал бы несуществующего результата, либо дублировал бы живой."""
    if not doc_id:
        return
    _runs_gc()
    _runs[_run_key(owner_id, doc_id)] = {
        "state": "failed", "source": source, "summary": {},
        "message": message or "фоновое извлечение не состоялось",
        "ts": time.monotonic()}


def run_status(owner_id: int | None, doc_id: str) -> dict | None:
    """Статус фонового прогона по документу или None — «система не знает».

    None и `failed` для вызывающего означают одно и то же: работай как раньше.
    Разведены они не для кода, а для человека в логах и в ответе агента.
    """
    if not doc_id:
        return None
    _runs_gc()
    rec = _runs.get(_run_key(owner_id, doc_id))
    if rec is None:
        return None
    return {**rec, "age_sec": round(time.monotonic() - rec["ts"], 1)}


def run_forget(owner_id: int | None, doc_id: str) -> None:
    """Забыть прогон. Зовётся в НАЧАЛЕ хода по документам сессии: сторож живёт
    ровно один ход, иначе «извлеки заново» вернуло бы прошлый результат."""
    if doc_id:
        _runs.pop(_run_key(owner_id, doc_id), None)


def run_forget_finished(owner_id: int | None) -> None:
    """Забыть ЗАВЕРШЁННЫЕ прогоны владельца — тоже в начале его хода.

    `run_forget` чистит по составу сессии, а состав меняется: документ выпадает
    из набора проекта, и его запись «готово» остаётся висеть. Дальше явный
    «извлеки вот этот» получает молчаливый отказ — и чем дольше живёт память
    (а она теперь живёт дольше воркера), тем дольше этот отказ.

    Чистим ТОЛЬКО терминальные записи. Живой прогон (`running`) не трогаем ни
    при каких условиях: он и есть то, ради чего сторож заведён, и цена ошибки
    здесь несимметрична — лишняя чистка стоит повторного извлечения, лишняя
    осторожность не стоит ничего.
    """
    oid = int(owner_id or 0)
    for key in [k for k, r in _runs.items()
                if k[0] == oid and r.get("state") != "running"]:
        _runs.pop(key, None)


def bind_worker_doc(nonce: str, doc_id: str) -> None:
    """Связать нонс воркера с документом — по ФАКТУ, а не по догадке.

    Зовётся из выдачи текста (`/internal/doc-text`): воркер сам называет пару
    (нонс, doc_id), когда забирает OCR-текст в свою комнату, — это первый и
    единственный момент, когда бэк узнаёт, ЧТО именно считает комната.
    Догадываться по составу сессии нельзя: в ходу с несколькими документами
    промах связал бы результат с ЧУЖИМ документом, и агент отчитался бы числами
    другой компании — молча и уверенно.

    ПОСЛЕДНЯЯ ПРИВЯЗКА ПОБЕЖДАЕТ, НО ПЕРЕЕЗД СЛЫШНО (Б8.3, редакция 20.08.2026).
    Здесь стояло безусловное присваивание — и второй документ под тем же нонсом
    затирал первый БЕЗ ЕДИНОГО СЛОВА. Молчание и было дефектом: инвариант «один
    нонс — один документ» держался соглашением, а его нарушения не видел никто.

    ПЕРЕЕЗД САМ ПО СЕБЕ НЕ АВАРИЯ, И ОТКАЗЫВАТЬ В НЁМ НЕЛЬЗЯ. Все три читателя
    берут связь ЛЕНИВО, в момент своего события: шапка таблицы на экране
    (`station_turn._start_body`), `doc_id` строки прогона
    (`station_run_sink.drain`) и сторож дубля (`run_started`/`run_finished`).
    Значит для ПОСЛЕДОВАТЕЛЬНЫХ прогонов одного хода (документ A отработал,
    следом пошёл B) перезапись как раз ПРАВА: события B обязаны читаться как B.
    Первая редакция правки отклоняла вторую привязку — и приписывала прогон B
    документу A, то есть делала ровно ту ошибку атрибуции, от которой защищала.
    Опасен ПАРАЛЛЕЛЬНЫЙ случай: два прогона на одном нонсе одновременно
    перемешают итоги. Разводить их — работа `station_turn` (нонс на документ,
    Б8.4), и вид мультидока владельцем ещё не выбран; до тех пор здесь стоит
    громкость, а не отказ.

    Предупреждение несёт ОБА документа: по журналу должно быть видно не только
    что нонс переехал, но и откуда куда.
    """
    if nonce and doc_id:
        _runs_gc()
        bound = _worker_docs.get(nonce)
        if bound is not None and bound[0] != doc_id:
            log.warning(
                "нонс %s переехал с документа %s на %s — побеждает последняя "
                "привязка. Для последовательных прогонов одного хода это "
                "штатно; для параллельных итоги перемешаются (нонс на документ "
                "— Б8.4)", nonce, bound[0], doc_id,
            )
        _worker_docs[nonce] = (doc_id, time.monotonic())


def worker_doc(nonce: str) -> str:
    """Документ нонса или "" — «не знаю». Пустое значит ровно «статус не
    записывать», а не «взять первый попавшийся документ сессии»."""
    if not nonce:
        return ""
    ent = _worker_docs.get(nonce)
    if ent is None:
        return ""
    doc_id, ts = ent
    if time.monotonic() - ts > _MEMORY_TTL_SEC:
        _worker_docs.pop(nonce, None)
        return ""
    return doc_id
