"""Метакарта документа: что это, о ком, за какой период и сколько его.

ЗАЧЕМ (#189, формулировка владельца 09.08.2026): «карта метаинформации — тип
документа, число символов, строк, описание — что есть в документе и зачем он
нужен. И модель сама должна выбирать, что открывать».

Сегодня агент знает про документ только имя файла. Отсюда два наблюдаемых
следствия: он открывает не тот документ, когда их несколько, и запускает
извлечение полного реестра по пресс-релизу, где реестра нет и быть не может.

КОГДА СНИМАЕТСЯ. Один раз при приёме — после того, как документ приведён к
тексту, и до всякой работы с ним («сначала текст, потом классификация», решение
владельца). Не на каждом прогоне заново: классификация — свойство документа, а
не действие анализа.

ГРАНИЦА КОД↔МОДЕЛЬ (решение владельца 09.08, docs/REQUEST_HANDLING.md §0)
проходит прямо посередине этого модуля, и это не случайность:
  • `measure()` — КОД. Знаки, строки, страницы, есть ли разметка страниц. Всё
    это СЧИТАЕТСЯ, а не оценивается, и код здесь точнее модели;
  • `describe()` — МОДЕЛЬ. Тип документа, эмитент, его альтернативные имена,
    период, короткое описание. Всё это РЕШЕНИЯ по тексту, и код их принимать не
    должен: список ключевых слов «пресс-релиз / отчётность» — ровно тот
    код-классификатор, который владелец отменил.

ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Ячейки (стандарт × тип компании × язык): её считает
`detect_profile` внутри извлечения, и переносить сюда её надо вместе с образцом
от команды FinEngine, а не своим проектом (#189). Пока карта отвечает на вопрос
«что это и стоит ли открывать», а не «по каким правилам считать».

ПРО ТЕКСТ ЗАПРОСА. Он пока константа в этом модуле, и это временно: когда типов
документов станет больше трёх-четырёх, его место — в правимом текстовом файле
рядом с методикой, а не в программе. Записано в #189.
"""
from __future__ import annotations

import json
import logging
import re

log = logging.getLogger(__name__)

# Разметку страниц ставит OCR: «===PAGE 12===». По ней анализ даёт ссылки вида
# «PDF стр. 42», и её отсутствие — важный факт: ссылаться будет не на что.
_PAGE_MARK = re.compile(r"(?m)^===PAGE\s+(\d+)===")

# Сколько текста показываем модели. Тип, эмитент и период видны в начале
# документа; гнать в запрос сотню тысяч знаков ради этого незачем.
_HEAD = 12_000

_ASK = """Перед тобой НАЧАЛО документа. Определи по нему четыре вещи и опиши документ одной фразой.

Ответь ТОЛЬКО JSON-объектом, без пояснений вокруг:
{"doc_kind": "...", "issuer": "...", "issuer_aliases": ["..."], "period": "...", "summary": "..."}

doc_kind — одно из: отчётность | пресс-релиз | презентация | транскрипт | таблица | прочее.
issuer — компания или банк, о котором документ. Не нашёл — пустая строка.
issuer_aliases — другие написания того же имени, встреченные в тексте (латиница, сокращение, юр. форма). Нет — пустой список.
period — период документа как он назван в тексте: «2024», «1П 2025», «3кв 2024». Не нашёл — пустая строка.
summary — одна фраза: что в документе есть и для чего он может пригодиться.

Ничего не выдумывай: чего в тексте нет — оставляй пустым.

=== НАЧАЛО ДОКУМЕНТА ===
"""

_KINDS = ("отчётность", "пресс-релиз", "презентация", "транскрипт", "таблица", "прочее")


def measure(text: str) -> dict:
    """Счётные свойства текста. Только код — здесь нечего решать."""
    text = text or ""
    pages = [int(m.group(1)) for m in _PAGE_MARK.finditer(text)]
    return {
        "chars": len(text),
        "lines": text.count("\n") + 1 if text else 0,
        "pages_marked": max(pages) if pages else 0,
        "has_page_markers": bool(pages),
    }


def _clean(raw: str) -> dict:
    """Ответ модели → поля карты. Разбор, а не досочинение."""
    body = raw.strip()
    if "```" in body:                      # модель обернула в блок кода
        body = body.split("```")[1].lstrip("json").strip()
    data = json.loads(body)
    if not isinstance(data, dict):
        raise ValueError(f"ожидался объект, пришло {type(data).__name__}")
    kind = str(data.get("doc_kind") or "").strip().lower()
    aliases = data.get("issuer_aliases") or []
    return {
        # Вид вне словаря НЕ подгоняем к ближайшему: подгонка — это решение,
        # а мы бы приняли его кодом. Пусть будет «прочее» и видно, что вид не понят.
        "doc_kind": kind if kind in _KINDS else "прочее",
        "doc_kind_raw": kind,
        "issuer": str(data.get("issuer") or "").strip(),
        "issuer_aliases": [str(a).strip() for a in aliases if str(a).strip()][:8],
        "period": str(data.get("period") or "").strip(),
        "summary": str(data.get("summary") or "").strip(),
    }


async def describe(text: str, *, model_id: str | None = None) -> dict:
    """Что это за документ — по решению МОДЕЛИ, одним обращением.

    Не получилось — возвращаем пустую карту с причиной. Пустое поле честнее
    угаданного: агент увидит, что вид неизвестен, и спросит или откроет сам.
    """
    from finengine.llm import openrouter as _or  # noqa: PLC0415 — тяжёлый импорт
    head = (text or "")[:_HEAD]
    if not head.strip():
        return {"error": "текст документа пуст"}
    try:
        raw = await _or.complete(_ASK + head, model=model_id)
        return _clean(raw)
    except Exception as exc:  # noqa: BLE001 — карта не смеет ронять приём документа
        log.exception("метакарта: описание не получено")
        return {"error": f"{type(exc).__name__}: {exc}"}


async def build(text: str, *, model_id: str | None = None) -> dict:
    """Полная карта: счётное — кодом, определяемое — моделью.

    Замеры кладутся ВСЕГДА, даже когда модель не ответила: объём и наличие
    разметки страниц — самостоятельно полезные факты, и терять их из-за
    неудачного обращения к модели незачем.
    """
    card = measure(text)
    card.update(await describe(text, model_id=model_id))
    return card


def as_line(card: dict, *, filename: str) -> str:
    """Карта одной строкой — в таком виде она попадает модели в глаза."""
    if not card:
        return f"- {filename} (карта не снята)"
    parts = [p for p in (card.get("doc_kind"), card.get("issuer"), card.get("period")) if p]
    size = f"{card.get('chars', 0)} знаков"
    if card.get("pages_marked"):
        size += f", стр. 1–{card['pages_marked']}"
    head = f"- {filename} — {', '.join(parts)}" if parts else f"- {filename}"
    tail = f" ({size})"
    summary = card.get("summary")
    return head + tail + (f": {summary}" if summary else "")
