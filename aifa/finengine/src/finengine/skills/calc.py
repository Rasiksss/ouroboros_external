"""Калькулятор агента: любой расчёт — формулой в коде, а не в уме модели (#122).

ЗАЧЕМ. Реестровые коэффициенты (47 в ячейке) считает Python. Всё, чего в реестре
нет — отраслевые метрики, оборачиваемость в днях, «очищенная прибыль без разовой
продажи» — модель до сих пор считала В УМЕ, а промпт лишь просил пометить такие
числа словом «расчётный». Это ровно та стохастика, из-за которой в вердикте по
ИКС-5 долг/EBITDA оказался посчитан на глаз при готовой формуле рядом.

АДРЕСАЦИЯ — «набор.показатель@период», а не просто «показатель». Разница в один
уровень, но заложить её надо СРАЗУ: следом идут сравнение с прошлым Excel
пользователя, план-факт и прогнозы, и там без имени набора не обойтись. Добавлять
это измерение потом — переписывать всех потребителей.

    NET_INCOME                     показатель текущего набора, основной период
    NET_INCOME@"6M 2025"           он же за конкретный период
    doc.NET_INCOME                 явно из набора документа

ОТКУДА ЗНАЧЕНИЯ. Пересчитывать документ ради одной формулы недопустимо (это
минуты и деньги), поэтому берём уже посчитанное, в порядке свежести:
  1) шина заземления (#121) — прогон этого же хода, те же числа, что пользователь
     видит в таблице и вердикте: расчёт обязан быть с ними согласован;
  2) журнал прогонов извлечения — последний прогон по этому документу.
Ничего нет — честно говорим, что считать не из чего, а не выдумываем.

ИСПОЛНЕНИЕ. Тем же вычислителем, что и реестровые формулы: разбор в дерево,
белый список узлов, никакого eval. Формула от пользователя и формула из git
проходят один путь — второй реализации арифметики быть не должно.
"""
from __future__ import annotations

import logging
import re

log = logging.getLogger(__name__)

# Токен адресации: [набор.]ПОКАЗАТЕЛЬ[@период]. Период — в кавычках, если внутри
# пробелы («6M 2025»), иначе можно голым словом.
_TOKEN_RE = re.compile(
    r"(?:(?P<ds>[a-z][a-z0-9_]*)\.)?"
    r"(?P<enum>[A-Z][A-Z0-9_]{2,})"
    r"(?:@(?:\"(?P<qperiod>[^\"]+)\"|(?P<period>[^\s()+\-*/,]+)))?"
)


class CalcError(ValueError):
    """Считать нечем или формула неверна — говорим прямо, а не молчим."""


def _norm_period(p: str) -> str:
    return (p or "").strip().strip('"').lower()


def dataset_from_metrics(metrics: list[dict]) -> dict:
    """Свести события движка в набор: enum → {период → значение} + справка.

    Значения периодов держим отдельно от «основного»: пользователь вправе
    спросить и «за 2024», и просто «за отчётный период».
    """
    by_enum: dict[str, dict] = {}
    for m in metrics or []:
        enum = str(m.get("enum") or "").strip().upper()
        if not enum or m.get("dimension"):
            continue  # сегментные и групповые строки — не тот же набор
        slot = by_enum.setdefault(enum, {"periods": {}, "main": None, "page": m.get("page"),
                                         "name_ru": m.get("name_ru") or enum,
                                         "unit": m.get("unit")})
        for pv in (m.get("period_values") or []):
            val = pv.get("value")
            if val is None:
                continue
            slot["periods"][_norm_period(str(pv.get("period") or ""))] = float(val)
        cur = m.get("value_current")
        if cur is not None:
            # ⚠️ ДВА ЧИСЛА ПОД ОДНИМ ИМЕНЕМ (#163). Одиннадцать показателей в
            # реестре заведены И извлекаемыми, И расчётными — 35 пар «ячейка +
            # показатель» в девяти ячейках из десяти (снято прогоном 20.08.2026;
            # состав держит `tests/test_registry_no_silent_duplicates.py`, там
            # же и поимённый список). Стоявшие здесь «шесть показателей, семь
            # ячеек из восьми» — счёт эпохи восьми ячеек, устаревший дважды.
            # Движок эмитит на такой показатель ДВА события, и
            # здесь второе молча затирало первое: в таблице оказывалось
            # расчётное, а свой FREE_CASH_FLOW движок считал по извлечённому.
            # Проверено исполнением: CAPEX уезжал 100 000 при FCF, посчитанном
            # от 85 000.
            #
            # Правило приоритета — вопрос МЕТОДИКИ, а не кода («что компания
            # раскрыла» против «что сопоставимо между компаниями»), и решает его
            # владелец (#163). До решения поведение НЕ меняем — меняем только
            # молчание: расхождение обязано быть слышно. Совпало до копейки —
            # молчим, это ровно тот случай, когда дубль безвреден.
            prev = slot["main"]
            if prev is not None and float(cur) != prev:
                log.warning(
                    "#163 два числа под одним именем: %s было %s, стало %s — "
                    "в таблицу заземления попадёт последнее, а производные могли "
                    "считаться от первого",
                    enum, prev, float(cur),
                )
                slot.setdefault("conflict", []).append(prev)
            slot["main"] = float(cur)
        elif slot["main"] is None and slot["periods"]:
            # Основного нет — берём первый доступный, но НЕ выдумываем период.
            slot["main"] = next(iter(slot["periods"].values()))
    return by_enum
