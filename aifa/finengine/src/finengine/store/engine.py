"""Один вход для всех подключений к базе — и одно место, где живёт контур.

🔴 ЗАЧЕМ ОДИН ВХОД. Схема контура стоит у ПОДКЛЮЧЕНИЯ (`search_path`), а не у
таблиц, потому что одни и те же определения таблиц обязаны работать на обоих
движках: `MetaData(schema="dev")` на SQLite падает с
`OperationalError: unknown database dev`.

⚠️ SQLite на стенде не используется ни одним хранилищем — все девять на
Postgres. Но он остался в трёх живых ролях: откат (пусто в настройке = файл),
источник переездных скриптов (`migrate_*` читают старые `.db`) и подложка
тестов. Уберутся все три — схему можно будет перенести в `MetaData`, и этот
модуль станет не нужен.

Пока не убрались, следствие такое: любой движок, собранный мимо этого модуля,
пишет в `public`, пока приложение читает `dev`. Расхождение молчит — обе
стороны работают, просто с разными данными. Сторож
`test_every_engine_goes_through_one_door` держит это правило.

Пусто в `FINENGINE_PG_SCHEMA` = как было (`public`), и тогда модуль ничего не
делает — обычный `create_engine`. Момент переезда выбирает владелец.

⚠️ СХЕМУ МЫ НЕ ЗАВОДИМ ИСПОДТИШКА. `движок()` не подключается к базе — иначе
импорт модуля начал бы зависеть от того, поднят ли Postgres. Схему заводит
отдельный осознанный шаг: `python -m finengine.store.ensure_schema`. Не завели —
первый же запрос скажет об этом вслух, а не отработает мимо данных.
"""
from __future__ import annotations

import re
from typing import Any

from sqlalchemy import create_engine as _create_engine
from sqlalchemy.engine import Engine

from finengine import config

# Имя схемы в SQL параметром не передать — только подстановкой. Значит сузить
# набор символов обязано МЫ, а не драйвер (docs/rules/security.md).
_ИМЯ = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,62}$")


def схема() -> str:
    """Схема контура. Пусто = как было, общий `public`.

    🔴 ЧИТАЕМ ЧЕРЕЗ МОДУЛЬ, А НЕ ЧЕРЕЗ ССЫЛКУ, СВЯЗАННУЮ НА ИМПОРТЕ. В прогоне
    всего набора `finengine/config.py` исполняется ВТОРОЙ раз, и в
    `finengine.config.settings` оказывается НОВЫЙ объект; модуль, взявший
    `from finengine.config import settings` при загрузке, держит старый. Правка
    настройки тогда видна одному и не видна другому.

    Для схемы контура цена этого — не мелочь: движок молча собирается без
    `search_path` и пишет в `public`, пока приложение читает свою схему. Ровно
    так сторож в тестовом прогоне увидел 185 боевых документов стенда вместо
    своего одного — и дописал к ним свой.

    Здесь читается ТЕКУЩЕЕ значение атрибута модуля. Кто бы ни подменил
    `settings`, мы видим то же, что видит подменивший.
    """
    return (config.settings.pg_schema or "").strip()


def это_постгрес(url: str) -> bool:
    return url.strip().startswith("postgresql")


def проверить_имя(имя: str) -> str:
    if not _ИМЯ.match(имя):
        raise ValueError(
            f"недопустимое имя схемы контура: {имя!r} — только буквы, цифры и "
            "подчёркивание, начиная с буквы")
    return имя


def движок(url: str, **kwargs: Any) -> Engine:
    """Движок к базе. На Postgres со схемой контура — с её `search_path`."""
    имя = схема()
    if not (имя and это_постгрес(url)):
        return _create_engine(url, **kwargs)
    проверить_имя(имя)
    # Копия, а не правка чужого словаря: вызывающий мог передать свой connect_args.
    связь = dict(kwargs.pop("connect_args", None) or {})
    связь["options"] = f"-csearch_path={имя}"
    return _create_engine(url, connect_args=связь, **kwargs)
