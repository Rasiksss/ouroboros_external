"""Личная методика пользователя — в ЗАПЕЧАТАННУЮ комнату станции (#123).

ЧТО ЧИНИТ. Пользователь правит методику словами, тул `fe_methodology` кладёт
правку в его личный слой (`skills/analysis/personal.py`), агент отвечает
«записал» — и на этом всё кончалось. Разбор идёт в комнате станции; у комнаты
нет ни сети, ни диска бэкенда, а команду разбора собирает МОДЕЛЬ, которая про
личный слой не знает и знать не должна. Правка не применялась НИ В ОДНОМ
прогоне, и молча: отчёт выглядел удавшимся, просто считан был по базе.

КАК. Тем же каналом, что и текст документа (`internal_docs.py`): комната пишет
записку в `.model-rpc`, демон `station-bridge` (сеть есть у него, не у комнаты)
ходит сюда и кладёт ответ файлом в рабочую папку комнаты.

ПРАВО — ПО НОНСУ, А НЕ ПО uid ИЗ ЗАПИСКИ. Записку пишет комната, а комната —
недоверенная сторона: назови она чужой uid, мы бы отдали чужую методику. Нонс
хода выдаёт бэкенд и он же знает, чей это ход (`station_turn.arm`), поэтому uid
в записке нет вовсе — его неоткуда взять и нечем подделать. Секрет тот же, что
у doc-text и релея прогресса: внутренний gateway-токен, маршрут только по
внутренней docker-сети.

РАЗОВАЯ ПРАВКА СЪЕДАЕТСЯ РОВНО ОДНИМ ХОДОМ. `personal.deltas_for_run` вынимает
«в этот раз» из памяти безвозвратно, а обёртка в комнате идемпотентна: её
перезапуск не должен получить методику БЕЗ разовой правки — это был бы тихий
разбор по другим правилам. Поэтому выданное запоминается за нонсом: повторный
заказ ТЕМ ЖЕ ходом отдаёт то же самое, следующий ход — уже без неё. Ход, который
за методикой не сходил вовсе, разовую правку не тратит: она доживает до
ближайшего анализа или до своего TTL.

🔴 А ХОД, КОТОРЫЙ СХОДИЛ И УПАЛ, ЕЁ ТРАТИТ — И ЭТО НАЗВАНО ЗДЕСЬ, А НЕ ОБОЙДЕНО
МОЛЧАНИЕМ. Выдача безвозвратна: комната забрала правку, разбор не состоялся,
правки больше нет ни у кого. Семантика («терять в редком случае» против
«применить дважды») — вопрос владельцу, он открыт. Пока он открыт, потеря
обязана быть ГРОМКОЙ: `_spent_one_shot` помнит, что выдача унесла разовую
правку, а `station_turn` на конце канала говорит об этом пользователю словами.
Молчаливая потеря неотличима от «правка не сработала» — худший вид отказа.

ЭТА ЖЕ ЗАПИСЬ — ИСТОЧНИК ПАСПОРТА, НО НЕ ЕДИНСТВЕННЫЙ ЕГО ВХОД. Выдача
доказывает, что правки УШЛИ из бэкенда, и не доказывает, что они ДОЕХАЛИ до
разбора: между ними демон, который может быть старой выкладки. Поэтому паспорт
складывается из двух фактов — выдачи (здесь) и подтверждения станции
(`plan_step` с `methodology_changes`), см. `station_turn._methodology_of_run`.
Выводить методику заново (`personal.effective`) нельзя ни при каком раскладе:
вывод соврал бы в обе стороны — назвал бы личной методику прогона, который её
не заказывал, и потерял бы разовую правку, которой в личном слое уже нет.

In-process реестр (как скоуп документов и шина прогресса) — один uvicorn-процесс,
задокументировано; переезд в общее хранилище идёт вместе с ними.
"""
from __future__ import annotations

import os

from fastapi import APIRouter, Header, HTTPException

router = APIRouter()

# Три реестра хода живут в ОБЩЕМ кэше, а не в памяти процесса
# (architecture.md 3.2, 🔴 MUST): владелец нонса, уже выданные правки и признак
# «разовая правка израсходована». На двух репликах взвод канала шёл бы у одной,
# а выдача методики у другой — и комната получала бы отказ «чужой нонс», хотя
# ход её собственный.
#
# Тот же TTL, что у скоупа документов: это один и тот же ход и одна комната.
_TTL_SEC = 1800.0
_ВЛАДЕЛЕЦ = "methowner:"
_ВЫДАНО = "methserved:"
_РАЗОВАЯ = "methspent:"


def _кэш():
    from finengine.store.cache import get_cache  # noqa: PLC0415

    return get_cache()


def register_nonce_owner(nonce: str, owner_id: int) -> None:
    """Вызывается на взводе канала хода (`station_turn.arm`): чей это нонс.

    ⚠️ Срок ведёт КЭШ, а не `time.monotonic` здесь: монотонные часы у каждой
    реплики свои, и общий срок по ним не считается. Просроченное подметает сам
    кэш, поэтому попутная чистка отсюда ушла.
    """
    if nonce and owner_id:
        _кэш().set(f"{_ВЛАДЕЛЕЦ}{nonce}", int(owner_id), _TTL_SEC)


def _owner_of(nonce: str) -> int:
    return int(_кэш().get(f"{_ВЛАДЕЛЕЦ}{nonce}") or 0)


def reset() -> None:
    """Забыть все реестры хода. Для тестов — чтобы не лезли во внутренности.

    🔴 ЗАЧЕМ ПУБЛИЧНО. Тесты чистили три словаря модуля напрямую и упали разом,
    как только хранилище сменилось. Просить «начни с чистого листа» они вправе;
    знать, чем этот лист сделан, — нет.
    """
    кэш = _кэш()
    for приставка in (_ВЛАДЕЛЕЦ, _ВЫДАНО, _РАЗОВАЯ):
        for k in кэш.keys(приставка):
            кэш.delete(k)


def set_served(nonce: str, deltas: list[dict]) -> None:
    """Подставить «уже выданные ходу правки». Для тестов.

    Настоящий роут кладёт их сам (`methodology`), но часть сторожей проверяет
    ПАСПОРТ прогона и обходится без обращения к роуту: там разовая правка
    реально израсходовалась бы, а проверяется не она.
    """
    _кэш().set(f"{_ВЫДАНО}{nonce}", list(deltas), _TTL_SEC)


def expire_nonce(nonce: str) -> None:
    """Состарить нонс: ключ мёртв, как после получаса.

    Тоже для тестов. Раньше срок правили руками в кортеже словаря; теперь его
    ведёт кэш, и «состарить» значит удалить — снаружи это неотличимо.
    """
    _кэш().delete(f"{_ВЛАДЕЛЕЦ}{nonce}")


def served_for_turn(owner_id: int, *nonces: str) -> tuple[list[dict], bool]:
    """Что уехало в комнату ЭТОГО хода и унесло ли это разовую правку.

    ПОЧЕМУ НОНСОВ НЕСКОЛЬКО. Владелец регистрируется на КАЖДОМ виде канала
    (`station_turn.arm`), и это намеренно: «этот нонс методику не получит» стало
    бы сюрпризом при первом же новом навыке. Обратная сторона — комната вольна
    назвать нонс ИЗВЛЕЧЕНИЯ того же хода: роут правки отдаст, а паспорт, ищущий
    по нонсу РАЗБОРА, скажет «базовая». Ход один, нонса два — спрашивать надо
    про оба, иначе паспорт молчит именно тогда, когда правки уехали.

    ВЛАДЕЛЕЦ СВЕРЯЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ. Нонсы сюда приходят ВЫВЕДЕННЫМИ из
    ключа хода (`run_nonce_of`/`analysis_nonce_of`), а вывод — не доказательство
    принадлежности. Без сверки перебор чужих нонсов отдал бы в паспорт чужие
    правки, то есть ровно то, от чего роут защищён проверкой права.
    """
    owner = int(owner_id or 0)
    if not owner:
        return [], False
    кэш = _кэш()
    for nonce in nonces:
        выдано = кэш.get(f"{_ВЫДАНО}{nonce}") if nonce else None
        if nonce and _owner_of(nonce) == owner and выдано:
            return list(выдано), bool(кэш.get(f"{_РАЗОВАЯ}{nonce}"))
    return [], False


def _token() -> str:
    # Тот же внутренний секрет, что у doc-text и station-progress ingest.
    return os.environ.get("FINENGINE_OPENCLAW_GATEWAY_TOKEN", "").strip()


@router.get("/internal/methodology")
async def methodology(nonce: str = "", authorization: str = Header(default="")) -> dict:
    # Проверка секрета живёт в ОДНОМ месте (`api/internal_auth`): копия здесь
    # была четвёртой, и правило в четырёх местах — тот же класс дефекта, что
    # двойные enum'ы. Оно же закрывает пустой секрет при поднятой строгости.
    from finengine.api.internal_auth import require_gateway_token  # noqa: PLC0415

    require_gateway_token(authorization)
    nonce = nonce.strip()
    owner = _owner_of(nonce)
    if not owner:
        raise HTTPException(status_code=403, detail="unknown nonce")
    кэш = _кэш()
    уже = кэш.get(f"{_ВЫДАНО}{nonce}")
    if уже is not None:
        return {"deltas": уже}
    from finengine.skills.analysis import personal  # noqa: PLC0415

    # Спрашиваем ДО выдачи: `deltas_for_run` разовую правку съедает, и после
    # него отличить «была разовая» от «были только сохранённые» уже нечем.
    one_shot = bool(personal.one_shot_pending(owner))
    deltas = personal.deltas_for_run(owner)
    кэш.set(f"{_ВЫДАНО}{nonce}", deltas, _TTL_SEC)
    if one_shot:
        кэш.set(f"{_РАЗОВАЯ}{nonce}", True, _TTL_SEC)
    return {"deltas": deltas}
