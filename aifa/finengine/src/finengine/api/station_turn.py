def _emit(channel: TurnChannel, item: object) -> None:
    """Событие прогресса — на экран, ТЕМ ЖЕ конвертером, что у инлайн-петли.

    `_progress_events` переводит внутренний словарь тула
    (`{"metric_row": …}`) в событие фронта (`{"type": "metric_row", …}`). Без
    перевода станция шлёт `{"type": "metric"}`, а фронт ждёт `metric_row` — и
    таблица в рабочей области остаётся пустой при полностью успешном прогоне.

    ⚠️ ГРОМКО. Мост прогресса в `internal_tools._ProgressBridge` глушит свои
    отказы в `log.debug`, и по логам «на экране пусто» было неотличимо от «всё
    хорошо». Здесь тот же отказ — предупреждение с текстом.
    """
    from finengine.llm.openclaw import _progress_events
    from finengine.skills import run_orchestrator

    run_id = channel.run_id
    if not run_id:
        log.warning("station turn: рана нет, событие потеряно, nonce=%s", channel.nonce[:8])
        return
    try:
        for event in _progress_events(item, _TOOL_NAME):
            if not run_orchestrator.emit_to_run(run_id, event):
                # `False` — АНОМАЛИЯ, а не правило маршрутизации: ход кончился
                # раньше, чем прогон, а маршрут выбирается по `turn_over`.
                log.warning("station turn: ран %s не принял %s, nonce=%s",
                            run_id[:8], event.get("type"), channel.nonce[:8])
    except Exception:  # noqa: BLE001 — экран не смеет ронять прогон
        log.exception("station turn: событие не отправлено, nonce=%s", channel.nonce)


