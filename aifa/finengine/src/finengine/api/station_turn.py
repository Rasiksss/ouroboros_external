# 216 секунд. Окно в минуту истекло, сток объявил прогон замолчавшим, снял
# подписку — и все дальнейшие события (75 строк, потом 52) приехали в пустоту:
#
#   прогресс станции некуда доставить: нонс=e606e6ce…, событий=75 —
#   подписчика нет
#
# Продолжение хода при этом не спасло: строк на тот момент не было ни одной, а
# без них продолжать нечем (`_may_continue`). Пользователь увидел готовую
# таблицу в рабочей области и НИ ОДНОГО слова в чате.
#
# ОШИБКА БЫЛА В ПОСЫЛКЕ, А НЕ В ЧИСЛЕ. «Кончившийся ход больше ничего не
# пришлёт» — верно про МОДЕЛЬ и неверно про СТАНЦИЮ: комната живёт своей
# жизнью и присылает события минутами позже. Окно молчания защищает работу
# станции, а не ход.
#
# Поэтому окно обязано быть ШИРЕ самого долгого ЗАКОННОГО молчания. Самое
# долгое измерено: 216 секунд первой стадии (замер 20.08, Северсталь). Берём с
# запасом — и всё равно вчетверо быстрее прежних 1200 секунд.
_QUIET_AFTER_TURN_SEC = 420.0


def continuations_used(gw_key: str) -> int:
    """Сколько раз ход этого ключа уже продолжали. Для сторожей и диагностики."""
    return _continuations.get(gw_key or "", 0)


def _may_report_back(channel: TurnChannel, run: Any) -> bool:
    """Продолжать ли ход ПОСЛЕ УДАЧНОГО прогона, кончившегося позже хода.

    ДЕФЕКТ, ЗАМЕЧЕННЫЙ ВЛАДЕЛЬЦЕМ 22.08 НА ЖИВОМ ПРОГОНЕ. Извлечение по
    Северстали отработало полностью (`done`, 60 показателей, Excel собран), а
    ход кончился на минуте — и в чате не появилось НИ ОДНОГО СЛОВА. Результат
    ушёл в историю сессии, чтобы СЛЕДУЮЩИЙ ход его пересказал; но следующего
    хода может не быть никогда, а пользователь смотрит на готовую таблицу и
    молчащий чат.

    Толкатель для этого уже построен — он ловил только `on_abandoned`. Удачно
    кончившийся прогон в него не попадал, хотя молчание там ровно то же.

    Условия те же, что у продолжения замолчавшего: ход кончился, путь
    гейтвейный, петля жива, потолок не исчерпан. Пустого прогона здесь не
    бывает — сюда приходят только удавшиеся.
    """
    if not channel.gw_key or not channel.turn_over or not _loop_is_running():
        return False
    return continuations_used(channel.gw_key) < _MAX_CONTINUATIONS


def _report_back_prompt(run: Any) -> str:
    """Работа кончилась — доложи. Маршрут по-прежнему не диктуем."""
    rows = len(getattr(run, "metrics", []) or [])
    return (
        f"Работа в станции ЗАКОНЧИЛАСЬ УДАЧНО: строк {rows}, таблица собрана и "
        "показана пользователю в рабочей области.\n\n"
        "Ход оборвался раньше, чем ты успел ответить, поэтому пользователь "
        "видит таблицу и НИ ОДНОГО твоего слова. Ты по-прежнему в этом ходе.\n\n"
        "🔴 НИЧЕГО НЕ ПЕРЕЗАПУСКАЙ: работа уже сделана, повтор удвоит время и "
        "деньги.\n"
        "Посмотри СВОЙ план: осталось незакрытое — доделай; всё закрыто — "
        "ответь пользователю по существу того, что он просил."
    )


def _may_continue(channel: TurnChannel, run: Any) -> bool:
    """Продолжать ли ход. Четыре условия, каждое обязательно.

    ⚠️ ПУСТОЙ ПРОГОН НЕ ПРОДОЛЖАЕМ. Строк нет — станции нечего доложить модели,
    и продолжение свелось бы к «попробуй ещё раз» вслепую. Это не толкатель, а
    повтор наугад; такой прогон закрывается честным отказом.
    """
    if not channel.gw_key:
        return False              # не гейтвейный путь — продолжать нечего
    if not channel.turn_over:
        return False              # ход ещё идёт, модель сама доведёт
    if not getattr(run, "metrics", None):
        return False              # станция ничего не отдала
    if not _loop_is_running():
        return False              # отдать продолжение некуда — остаётся сеть
    return continuations_used(channel.gw_key) < _MAX_CONTINUATIONS


def _continuation_prompt(channel: TurnChannel, run: Any) -> str:
    """Что модель прочитает, вернувшись в петлю.

    Говорим ровно три вещи, и каждая куплена ошибкой:
      · ЧТО УЖЕ СДЕЛАНО и с каким числом строк — иначе модель перезапустит
        извлечение и удвоит счёт (#160, 253 секунды сожжённого дубля);
      · ЧТО ХОД НЕ ЗАКОНЧЕН — иначе она допишет ответ текстом вместо работы;
      · ЧТО РЕШАЕТ ОНА — по СВОЕМУ плану.

    🔴 СЛЕДУЮЩИЙ ШАГ ЗДЕСЬ НЕ НАЗЫВАЕТСЯ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Первая
    редакция подсказывала «обычно это расчёт коэффициентов» — то есть зашивала
    сюда наш конвейер. Ровно от этого владелец отказался 21.08: «ты пытаешься
    захардкодить все пайплайны… тебе придётся кучу таких дорожек спроектировать,
    в этом же нету смысла». Толкатель обязан будить агента, а не диктовать ему
    маршрут: план он объявил сам, у него же и спрашивает. Пользователь мог
    просить только таблицу — тогда верный следующий шаг это ответить, а не
    считать коэффициенты.
    """
    rows = len(getattr(run, "metrics", []) or [])
    step = channel.running_step
    where = (f"Он стоял на шаге №{int(step) + 1} твоего плана."
             if step is not None else "")
    return (
        f"Команда в станции ОТРАБОТАЛА: строк {rows}, таблица собрана и уже "
        f"показана пользователю. {where}\n\n"
        "Ход при этом оборвался раньше работы — результат ты не забрал и "
        "план не довёл. Ты по-прежнему в этом ходе, продолжай с этого места.\n\n"
        "🔴 УЖЕ ОТРАБОТАВШЕЕ НЕ ПЕРЕЗАПУСКАЙ: повтор удвоит работу, время и "
        "деньги, а результат уже есть.\n"
        "Посмотри СВОЙ план и реши сам, что осталось. Осталась работа — сделай "
        "её и дождись возврата команды. Не осталось — ответь пользователю по "
        "существу того, что он просил."
    )


def _loop_is_running() -> bool:
    """Есть ли петля, в которую можно отдать продолжение.

    ⚠️ ИСКЛЮЧЕНИЕ ЗДЕСЬ ЗАКОННО, хотя правило запрещает `try/except` в обычном
    потоке: «петли нет» — это не ветка логики, а отсутствие среды, и другого
    способа спросить об этом стандартная библиотека не даёт. Цена молчаливого
    падения высока: исключение в адресате стока уронило бы запись исхода, то
    есть потеряло бы прогон целиком — ровно то, от чего этот код и написан.
    """
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        return False
    return True


def _continue_turn(channel: TurnChannel, run: Any, *, finished: bool = False) -> None:
    """Вернуть агента в петлю новым ходом на ТОМ ЖЕ ключе сессии.

    Тот же ключ — тот же разговор: модель видит собственный план и уже
    запущенные команды, а не начинает с чистого листа.

    Канал взводим ЗАНОВО на тот же нонс: продолжение снова пойдёт в станцию
    (расчёт — это `exec`), и без подписки его события и терминал улетели бы в
    пустоту ровно так же, как в исходном дефекте.
    """
    from finengine.llm import openclaw as _gw

    _continuations[channel.gw_key] = continuations_used(channel.gw_key) + 1
    attempt = _continuations[channel.gw_key]
    log.warning(
        "station turn: %s (строк %d) — продолжаю в петле, попытка %d из %d, nonce=%s",
        "работа кончилась после хода" if finished else "ход замолчал при готовой таблице",
        len(run.metrics or []), attempt, _MAX_CONTINUATIONS, channel.nonce[:8])

    arm(nonce=channel.nonce, gw_key=channel.gw_key, doc_ids=[run.doc_id or ""],
        owner_id=channel.owner_id, project_id=channel.project_id,
        cell=channel.run_cell, kind=channel.kind)

    async def _go() -> None:
        # 🔴 ОТВЕТ ПРОДОЛЖЕНИЯ СОХРАНЯЕМ, А НЕ ВЫБРАСЫВАЕМ (23.08.2026).
        #
        # Здесь стояло `async for _ in …: pass` с объяснением «текст на экран не
        # едет: SSE пользователя закрыт вместе с ходом, результат он увидит из
        # сохранённого исхода». Первая половина верна, вторая — нет: в
        # сохранённом исходе лежит ТАБЛИЦА, а не слова модели. Живой прогон
        # владельца 23.08: толкатель вернул агента в петлю, агент за минуту
        # написал полный разбор по пяти коэффициентам — и текст остался ТОЛЬКО
        # в логе гейтвея. Человек десять минут смотрел в молчащий чат.
        #
        # Кладём ответ в серверную сессию обычным сообщением ассистента: её
        # отдаёт `/chat/history`, по ней фронт восстанавливает тред, и её же
        # читает следующий ход. Своего канала на закрытый SSE мы не изобретаем.
        куски: list[str] = []
        async for ev in _gw.stream_events(
            prompt=(_report_back_prompt(run) if finished
                    else _continuation_prompt(channel, run)),
            gateway_session_key=channel.gw_key,
        ):
            if ev.get("type") == "text_delta" and ev.get("text"):
                куски.append(str(ev["text"]))
        _remember_answer(channel, "".join(куски))

    asyncio.create_task(_go())


def _remember_answer(channel: TurnChannel, text: str) -> None:
    """Ответ продолжения — в серверную сессию, как обычный ход модели.

    Не `add_tool_output`, которым кладётся итог прогона: тот в ленту не едет
    вовсе (`/chat/history` отдаёт только `user`/`assistant`/`tool_call`), он для
    следующего хода. Здесь же речь ровно о словах, адресованных ЧЕЛОВЕКУ.
    """
    text = (text or "").strip()
    if not text:
        log.warning("station turn: продолжение не дало текста, nonce=%s", channel.nonce[:8])
        return
    if not channel.session_id:
        log.error("station turn: ответ продолжения некуда положить — сессии нет, nonce=%s",
                  channel.nonce[:8])
        return
    try:
        from finengine.api.main import get_agent
        from finengine.orchestrator.agent import _save_session

        session = get_agent().get_or_create_session(
            channel.session_id, auth_user_id=channel.owner_id)
        session.add("assistant", text)
        _save_session(session)
        channel.delivered.append("answer")
        log.info("station turn: ответ продолжения сохранён (%d знаков), nonce=%s",
                 len(text), channel.nonce[:8])
    except Exception:  # noqa: BLE001 — доклад не смеет уронить продолжение
        log.exception("station turn: ответ продолжения не записан, nonce=%s", channel.nonce)


def _remember_partial(channel: TurnChannel, run: Any) -> None:
    """Прогон замолчал — сохранить то, что успел собрать (#276, находка 19.08).

    ЗАМЕР, КОТОРЫЙ ЭТО ОПЛАТИЛ. Прогон по Банку «Санкт-Петербург» (нонс
    `4155b31e…`): станция отдала 110 показателей и 23 сегментные строки за
    пятнадцать минут, `metrics.json` на 121 917 байт записан в комнате — и
    терминала не прислала. Модель запустила извлечение с `--no-final` и
    закончила ход, не запустив расчёт, который по эстафете и ставит терминал.
    Сток прождал дедлайн и закрыл прогон отказом.

    До этой правки в базу от полностью удавшегося извлечения уезжали ЧЕТЫРЕ
    ЧИСЛА-СЧЁТЧИКА, а 133 строки, лежавшие у стока в памяти, выбрасывались.
    Теперь они доезжают до сервера, и человек видит таблицу вместо пустоты.

    ЛЕЧЕНИЕ РЯДОМ, И ОНО ПРОБУЕТСЯ ПЕРВЫМ (21.08.2026). Строки приехали, а
    терминала нет — значит агент уснул на середине плана, и его надо ВЕРНУТЬ В
    ПЕТЛЮ, а не хоронить ход (`_may_continue` / `_continue_turn`). Сеть остаётся
    для случаев, когда продолжать нечем: строк нет, ход ещё идёт, путь не
    гейтвейный или потолок продолжений исчерпан.
    """
    if _may_continue(channel, run):
        _remember_screen(channel, run, done=None, status=runs.STATUS_RUNNING)
        _continue_turn(channel, run)
        return
    _remember_screen(channel, run, done=None, status=runs.STATUS_FAILED)


def _is_canonical_station_result(run: Any) -> bool:
    result = getattr(run, "result", {}) or {}
    return bool(
        result.get("schema_version") == "1.0"
        and (
            result.get("form_output") or result.get("report_output")
            or result.get("extracted_metric") or result.get("calculated_metric")
            or result.get("monitor_result") or result.get("period_change_report")
            or result.get("file_artifact")
        )
    )


def _canonical_role_plan(output: dict, passport: dict) -> Any:
    """`RolePlan` for the role/cell the graph actually resolved — display-only.

    Built from `FormOutput.role` + `RunPassport.classification`, never from a
    second narrowing decision: `out.form` already narrowed `FormOutput.rows`
    to `requested_concepts` (`skills/atoms/out_form.py`), so this listener
    trusts `rows` as-is. `build_role_plan`/`role_not_applied`/`role_notice`
    only answer "does a display layout exist for this role×cell" — a lookup
    against `roles/layouts.json`, not a second source of extracted facts.
    """
    from finengine.roles import scope as _scope

    role = str(output.get("role") or "")
    if not role:
        return None
    classification = passport.get("classification") or {}
    return _scope.build_role_plan(
        role, str(classification.get("company_type") or ""),
        str(classification.get("profile_id") or ""))


def _canonical_summary_text(output_type: str, output: dict) -> str:
    """"Итог читается одним способом" (#НОВАТЭК 31.08) — on the typed result.

    Same invariant `station-skills/aifa-extract/scripts/extract.py` prints to
    its own stdout for the sub-agent worker reading `exec`'s result: a words
    summary BEFORE any table, naming values found vs. requested, and a loud
    warning when found is under half of requested. Built once here for the
    chat-facing canon text.
    """
    if output_type != "FormOutput":
        return ""
    rows = output.get("rows") or []
    total = len(rows)
    if not total:
        return ""
    found = sum(1 for row in rows if row.get("status") == "supported")
    text = f"Извлечено ЗНАЧЕНИЙ: {found} из {total} запрошенных показателей."
    if found / total < 0.5:
        text += (
            "\n⚠️ Скажи пользователю ПРЯМО: найдено меньше половины "
            "запрошенного."
        )
    return text


def _methodology_personal(run_metadata: dict) -> bool | None:
    """Личная методика применилась или базовая — по `methodology_version`.

    `OutputRunMetadata.methodology_version` (`contracts/results.py:66`) уже
    везёт отпечаток правил КАЖДОГО typed-результата; сравниваем его с
    отпечатком базовой методики тем же `versioning.methodology_fingerprint`,
    которым его посчитал станционный `analyze.py`. `None` — отпечатка нет
    (старый прогон/сбой), а не «базовая»: молчать за неизвестное нельзя.
    """
    from finengine.skills import versioning as _ver

    version = run_metadata.get("methodology_version")
    if not version or version == "unversioned":
        return None
    base_sha = _ver.methodology_fingerprint(None)["effective_sha256"]
    return str(version) != base_sha


def _canonical_journal(channel: TurnChannel, result: dict, output: dict) -> None:
    """Журнал прогонов обязан называть ПУТЬ (`aifa_station`) и документ.

    Минимальная запись: canonical `FormOutput`/`ReportOutput` не несёт
    company_name/period на верхнем уровне, как нёс плоский список показателей
    старого движка — их не домысливаем, а честно оставляем пустыми полями
    того же журнала, а не заводим второй.
    """
    from finengine.skills import run_logger

    passport = result.get("run_passport") or {}
    entity = passport.get("entity") or {}
    try:
        run_logger.log_run(
            doc_id=str(result.get("document_id") or channel.run_id or ""),
            filename="", arch="aifa_station", model_id=None,
            company_type=str((passport.get("classification") or {}).get("company_type") or ""),
            company_name=str(entity.get("canonical_name") or ""),
            period_current="", period_prev="",
            user_id=int(channel.owner_id or 0) or None,
            started_at=channel.started_at, metrics=[],
            diag={"output_type": str(output.get("output_type") or "")},
        )
    except Exception:  # noqa: BLE001 — журнал не смеет ронять прогон
        log.exception("station turn: canonical прогон не записан в журнал, nonce=%s",
                      channel.nonce[:8])


def _stream_canonical(channel: TurnChannel, output_type: str, output: dict, *,
                      role_notice: str, file_artifact: dict | None) -> None:
    """Готовый typed-результат — пользователю: слова в чат, кнопка Excel."""
    from finengine.api import internal_tools
    from finengine.skills import run_orchestrator
    from finengine.skills.result_events import source_file_id

    run_id = channel.run_id
    pieces = []
    summary = _canonical_summary_text(output_type, output)
    if summary:
        pieces.append(summary)
    if role_notice:
        pieces.append(role_notice)
    text = "\n\n".join(pieces)
    if text:
        run_orchestrator.emit_to_run(run_id, {"type": "text_delta", "text": text})
        internal_tools.mark_verbatim(channel.gw_key, text)
        channel.delivered.append("canon")
    if file_artifact:
        run_orchestrator.emit_to_run(run_id, {
            "type": "file", "kind": "excel",
            "file_id": source_file_id(str(file_artifact.get("object_store_location") or "")),
            "filename": str(file_artifact.get("filename") or ""),
        })
        channel.delivered.append("file")


def _finish_canonical_station_result(channel: TurnChannel, run: Any) -> None:
    """Единственный слушатель typed-результата: экран, канон, журнал, методика.

    Один проход по готовому `FormOutput`/`ReportOutput` + `OutputRunMetadata` —
    ровно дух Среза 13.5.4 (`23f-1`): не эмулирует старый словарь событий
    (`start`/`metric`/`plan_step`) поверх нового движка и не пересчитывает
    состав/числа заново. `rows`/`sections` — то, что граф уже решил показать;
    здесь только "показать то, что дали", не второй решатель.
    """
    from finengine.roles import scope as _scope
    from finengine.skills import extract_result

    result = run.result or {}
    output = (
        result.get("report_output") or result.get("form_output")
        or result.get("extracted_metric") or result.get("calculated_metric")
        or result.get("monitor_result") or result.get("period_change_report")
        or result.get("file_artifact") or {}
    )
    output_type = str(output.get("output_type") or "")
    passport = result.get("run_passport") or {}
    run_metadata = output.get("run_metadata") or {}
    doc_id = run.doc_id or str(result.get("document_id") or "")

    channel.saw_life = True
    # "outcome" — generic completion marker (kept alongside the specific
    # output_type) so callers that only know "the finish landed, whatever it
    # produced" (tests' polling loops included) have one stable name to watch.
    channel.delivered.append("outcome")
    channel.delivered.append(output_type or "typed_result")

    if channel.kind == KIND_ANALYZE:
        # Предупреждение о непроехавших правках, если оно есть, обязано уйти
        # ДО отчёта (иначе его прочтут после отчёта, то есть никогда) —
        # поэтому зовём здесь явно, а не полагаемся только на безусловный
        # вызов из `finally` слушателя (`_methodology_told` не даёт сказать
        # дважды). `methodology_result_personal` — только СЫРОЕ утверждение
        # результата; `_methodology_verdict` сам объединит его с
        # `served_for_turn`, прежде чем поверить.
        channel.methodology_result_personal = _methodology_personal(run_metadata)
        _methodology_verdict(channel)

    plan = _canonical_role_plan(output, passport)
    role_not_applied = bool(plan and _scope.role_not_applied(plan))
    role_notice = (
        _scope.role_notice(plan, plan.company_type, str(
            (passport.get("classification") or {}).get("profile_id") or ""))
        if plan else ""
    )

    screen = {"schema_version": "1.0", "output_type": output_type, "result": output}
    runs.save_best_effort(runs.RunOutcome(
        nonce=channel.nonce, kind=channel.kind, status=runs.STATUS_RUNNING,
        user_id=int(channel.owner_id or 0), project_id=channel.project_id,
        session_id=channel.session_id, run_id=channel.run_id,
        doc_id=doc_id or None, screen=screen))

    terminal_id = str(
        output.get("output_id") or output.get("metric_id")
        or output.get("result_id") or output.get("artifact_id") or ""
    )
    payload = {
        "schema_version": "1.0",
        "case_id": str(result.get("case_id") or ""),
        "document_version": str(result.get("document_version") or ""),
        "output_type": output_type,
        "output_id": terminal_id,
        "role_not_applied": role_not_applied,
        "role_notice": role_notice,
    }

    if output_type == "FormOutput":
        refusal = extract_result.form_refusal_reason(output)
        if refusal:
            runs.finish_best_effort(channel.nonce, status=runs.STATUS_FAILED,
                                    error=refusal, doc_id=doc_id,
                                    finished_at=int(time.time()), payload=payload)
            _report_failed(channel, refusal)
            return

    runs.finish_best_effort(channel.nonce, status=runs.STATUS_DONE, doc_id=doc_id,
                            finished_at=int(time.time()), payload=payload)
    _canonical_journal(channel, result, output)

    if channel.turn_over:
        _report_to_history(channel, {"status": "завершено", **payload})
        return

    _stream_canonical(channel, output_type, output, role_notice=role_notice,
                      file_artifact=result.get("file_artifact"))


async def _finish_run(channel: TurnChannel, run: Any) -> None:
    """Прогон кончился: собрать всё, что видит пользователь, и отдать ходу."""
    if _is_canonical_station_result(run):
        _finish_canonical_station_result(channel, run)
        return
    _report_failed(channel, "legacy station extraction result rejected after Slice 13.5 cutover")


def _methodology_verdict(channel: TurnChannel) -> Any:
    """По каким правилам считал ЭТОТ прогон. Возвращает методику или `None`.

    И ГОВОРИТ ПОЛЬЗОВАТЕЛЮ, ЕСЛИ ПРАВКИ ПРОПАЛИ, — ровно один раз на канал.
    Вопрос закрывается здесь целиком, потому что ответ «по базовой» и слова
    «ваши правки не доехали» — это один и тот же вывод из одних и тех же двух
    фактов. Разведи их по двум функциям — и однажды паспорт скажет «базовая»
    молча, ровно как говорил до 21.08.

    Концов у канала три (готовый разбор, явный отказ, молчание с отменой), и
    какой случится — заранее неизвестно; зовётся поэтому безусловно из
    `finally` слушателя. `channel.methodology_applied` канонический путь
    выставляет РАНЬШЕ — синхронно внутри `_finish_canonical_station_result`,
    до того как `finally` вообще запустится, — поэтому порядок «предупреждение
    ПЕРЕД отчётом» держится сам собой: `finally` идёт уже после того, как
    отчёт(если он есть) отдан пользователю.

    ДВА ФАКТА, А НЕ ОДИН, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Выдача (`internal_methodology`)
    доказывает, что правки УШЛИ из бэкенда; `methodology_result_personal`
    (`OutputRunMetadata.methodology_version` типизированного результата,
    сравненный с отпечатком базовой) — что они ДОЕХАЛИ и реально применились.
    Между этими двумя фактами лежит демон station-bridge, который деплоится
    ОТДЕЛЬНО от полки и бэкенда: на старой его выкладке записка комнаты не
    разбирается вовсе, обёртка ждёт двадцать секунд и уходит считать по
    базовой. Паспорт по одной только выдаче назвал бы такой отчёт личным —
    воспроизведено состязательной проверкой 21.08 (дельта сохранена, роут
    вызван, файл в комнату не попал, `personal is True`). Обратная сторона
    той же монеты (закрыто Срезом 13.5.4): типизированный результат САМ ПО
    СЕБЕ тоже не доказательство — он может заявлять «личная», а
    `served_for_turn` для ЭТОГО владельца может не найти ничего (чужие
    правки, выданные на чужом нонсе), и тогда доверять нечему.

    ПОЧЕМУ ГЛАВНЫМ ВЗЯТО ПОДТВЕРЖДЕНИЕ, А НЕ ВЫДАЧА. Оно едет тем же нонс-каналом
    и в том же файле, что и терминальное событие разбора, и РАНЬШЕ него. Значит
    «результат доехал, подтверждение потерялось» — это порванный поток, а на
    порванном потоке паспорта не будет вовсе: `_finish_analysis` зовётся из
    `done`. Ошибиться эта пара может только в сторону «базовая», а именно
    обратная ошибка («личная», когда считали по базовой) и есть чинимый дефект.

    МОЛЧАТЬ О ПРОПАЖЕ НЕЛЬЗЯ. Разовая правка при выдаче израсходована
    безвозвратно (`internal_methodology`), и человек, уверенный, что посчитали по
    его правилам, не узнает об этом ниоткуда. Семантика («терять» против
    «применить дважды») — открытый вопрос владельцу; пока он открыт, потеря
    обязана быть громкой.
    """
    from finengine.api import internal_methodology as _meth
    from finengine.skills.analysis import methodology as _md

    told = channel.methodology_told
    channel.methodology_told = True
    if channel.kind != KIND_ANALYZE:
        return None
    # ОБА НОНСА ХОДА, а не только свой: комната вольна назвать нонс извлечения
    # того же хода, и выдача ляжет под ним (см. `served_for_turn`). Выводим их
    # из ключа хода — второго источника у них нет.
    run_nonce = run_nonce_of(channel.gw_key)
    served, one_shot = _meth.served_for_turn(
        channel.owner_id, channel.nonce, run_nonce, analysis_nonce_of(run_nonce))
    if not served:
        return None
    if channel.methodology_result_personal:
        # Оба факта сошлись: ЭТОМУ владельцу что-то выдавалось, И
        # типизированный результат заявляет применённую методику, отличную от
        # базовой. `methodology_applied` — наблюдаемый след для тестов/логов,
        # не отдельный источник истины.
        channel.methodology_applied = len(served)
        return _md.apply(served, strict=False)
    if not told:
        # Формулировка одна на все три конца канала, поэтому говорит о том, что
        # верно в каждом: правки не применялись. «Посчитано по базовой» было бы
        # неправдой там, где разбор оборвался и не посчитал ничего.
        lost = (f"⚠️ Личные правки методики ({len(served)}) до разбора не доехали — "
                f"в этом ходе ваша методика НЕ применялась.")
        if one_shot:
            lost += (" Разовая правка «в этот раз» при этом израсходована — "
                     "если она нужна, повторите её.")
        _tell(channel, lost)
    return None


def _tell(channel: TurnChannel, text: str) -> None:
    """Сказать пользователю СЛОВАМИ — в чат, а если хода уже нет, в историю.

    Не `_emit`: события прогресса эфемерны (нота уезжает бегущей строкой
    размышления), и предупреждение о потерянной правке не переживёт в них даже
    следующий шаг плана. Маршрут выбирается так же, как у самого отчёта.
    """
    from finengine.skills import run_orchestrator

    log.warning("station turn: nonce=%s — %s", channel.nonce[:8], text)
    if channel.turn_over or not channel.run_id:
        _report_to_history(channel, {"status": "предупреждение", "message": text})
        return
    run_orchestrator.emit_to_run(channel.run_id, {"type": "text_delta", "text": text + "\n\n"})


async def _finish_analysis(channel: TurnChannel, run: Any) -> None:
    """Разбор кончился: собрать карточку и отдать ходу (#244, шаг 2).

    ЗЕРКАЛО `_finish_run`, а не его ветка — общая точка входа для обоих видов
    остаётся `_finish_canonical_station_result`: единственный слушатель
    typed-результата, не второй решатель под другим именем.

    ⚠️ Срез 13.5.4: сборка карточки ЧЕРЕЗ `skills/analysis_result.
    finalize_analysis` (пересказ текста разбора в структуру) здесь больше не
    происходит — канонический граф уже вернул готовый typed `ReportOutput`,
    пересобирать его из markdown значило бы завести второй числовой путь.
    Паспорт (личная методика или базовая) считается из `OutputRunMetadata.
    methodology_version` тем же проходом (`_methodology_personal`), не из
    отдельного вызова `personal.effective`.

    ⚠️ ЧЕГО У ЭТОГО ПУТИ НЕТ — И ЭТО НАЗВАНО ВСЛУХ, А НЕ ПОДМЕНЕНО ПУСТОТОЙ:
    ВНЕШНЕГО КОНТЕКСТА. Станция запечатана, сходить за новостями из комнаты
    нельзя, а собрать их заранее некому — модель решает сама. Разрыв остаётся
    предметом отдельной работы; выдавать его за «так и задумано» нельзя.
    """
    if _is_canonical_station_result(run):
        _finish_canonical_station_result(channel, run)
        return
    _report_failed(channel, "legacy station analysis result rejected after Slice 13.5 cutover")


# Вид прогона → адресат его результата. Таблицей, а не развилкой внутри стока:
# добавить третий вид (расчёт, сверка) должно быть строкой здесь, а не правкой
# чужой функции.
_FINISHERS = {
    KIND_EXTRACT: _finish_run,
    KIND_ANALYZE: _finish_analysis,
}


def _report_failed(channel: TurnChannel, message: str) -> None:
    """Явный отказ прогона. Молчание сюда НЕ попадает — см. station_run_sink."""
    text = message or "извлечение в станции не удалось"
    log.error("station turn: отказ прогона nonce=%s: %s", channel.nonce[:8], text)
    if channel.turn_over:
        _report_to_history(channel, {"status": "ошибка", "message": text})
        return
    _emit(channel, {"extract_error": text})


def _report_to_history(channel: TurnChannel, payload: dict) -> None:
    """Итог в ИСТОРИЮ СЕССИИ: экрана уже нет, но следующий ход её прочтёт.

    Это второй адресат, а не запасной: прогон длиннее хода — нормальный исход,
    а не сбой. Молча выбросить результат было бы худшим из вариантов: время и
    деньги потрачены, а сказать о них некому.
    """
    import json

    if not channel.session_id:
        log.error("station turn: итог некуда положить — сессии нет, nonce=%s (%s)",
                  channel.nonce[:8], payload.get("status"))
        return
    try:
        from finengine.api.main import get_agent

        session = get_agent().get_or_create_session(
            channel.session_id, auth_user_id=channel.owner_id)
        session.add_tool_output(
            "background_extract", payload.get("status") != "ошибка",
            json.dumps(payload, ensure_ascii=False, default=str))
        from finengine.orchestrator.agent import _save_session

        _save_session(session)
        channel.delivered.append("history")
    except Exception:  # noqa: BLE001
        log.exception("station turn: итог не записан в историю, nonce=%s", channel.nonce)
