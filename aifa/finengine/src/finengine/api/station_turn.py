            # молчание после конца хода НЕ отличает мёртвый прогон от живого.
            # Отличает другое — ПРИШЛО ЛИ ХОТЬ ЧТО-НИБУДЬ. Строки идут, значит
            # комната работает и хвост её работы законно тихий: ждём полное
