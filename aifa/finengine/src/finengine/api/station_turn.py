def _relay_event(channel: TurnChannel, event: dict) -> None:
    """Живой прогон на экран: шапка таблицы и строки по мере извлечения.

    Копить строки до конца нельзя: прогон идёт полторы-три минуты, и всё это
    время пользователь смотрел бы на пустую рабочую область.
    """
    channel.saw_life = True
    kind = event.get("type")
    if kind in {"typed_result", "typed_error", "node_run", "plan_graph"}:
        # `plan_graph` (Срез 29, Этап 7) — тот же принцип, что у остальных
        # трёх: уже готовая публичная форма события, конвертер прогресса
        # текстовые версии не переживёт.
        # Canonical events already have the public SSE/journal shape.  Sending
        # them through the legacy progress converter would stringify the
        # contract and force the UI to recover structure from prose.
        if not channel.turn_over and channel.run_id:
            from finengine.skills import run_orchestrator

            run_orchestrator.emit_to_run(channel.run_id, event)
        return
    if kind == "start":
        # ⚠️ ЗАПОМИНАЕМ ДО ПРОВЕРКИ «ход кончился», и это не перестраховка.
        # Интересный случай ровно один: вкладку закрыли, ход кончился, прогон
        # доработал в одиночестве. Поставь эту строку ниже — и шапка не
        # сохранится именно в том случае, ради которого хранилище заводилось.
        channel.screen_start = _start_body(channel, event)
    if event.get("methodology_changes") is not None:
        # ПОДТВЕРЖДЕНИЕ ПРИМЕНЕНИЯ — ТОЖЕ ДО ПРОВЕРКИ «ход кончился», и по той
        # же причине: паспорт собирается в `_finish_analysis`, который на
        # отцепленном прогоне работает уже ПОСЛЕ конца хода. Пропусти его
        # здесь — и разбор, честно посчитанный по личной методике, получит
        # паспорт «базовая» ровно в том случае, когда прогон пережил ход.
        channel.methodology_applied = int(event.get("methodology_changes") or 0)
    if channel.turn_over:
        # Ход кончился — рисовать некуда. Итог всё равно доедет: он уходит в
        # историю сессии, и следующий ход его подхватит.
        return

    # План и его отметки — ОБОИМ видам. У анализа это вообще единственный живой
    # признак: строк он не эмитит, и без плана рабочая область молчала бы все
    # 1–4 минуты разбора, неотличимо от зависшего прогона.
    #
    # ⚠️ ИМЕНА ПОЛЕЙ ПЕРЕВОДИМ. Станция шлёт `{"type": "plan", "steps": […]}` и
    # `{"type": "plan_step", "index": …}`, а конвертер экрана ждёт `{"plan": […]}`
    # и `{"step": …}` (`openclaw._progress_events`). Отдай как есть — и остров
    # «Прогресс» промолчит при полностью успешном прогоне, ровно как молчала
    # таблица, пока не перевели `metric` → `metric_row`.
    if kind == "plan":
        _emit(channel, {"plan": list(event.get("steps") or [])})
        return
    if kind == "plan_step":
        index = int(event.get("index") or 0)
        status = str(event.get("status") or "")
        channel.running_step = index if status == "running" else None
        item = {"step": index, "status": status}
        if event.get("note"):
            item["note"] = str(event["note"])
        _emit(channel, item)
        return
    if kind == "status":
        # СТАДИИ ДВИЖКА — ЕДИНСТВЕННОЕ, ЧТО ШЕВЕЛИТСЯ В ДОЛГОМ ИЗВЛЕЧЕНИИ
        # (жалоба владельца 19.08, п.6: «история статусов не обновляется —
        # пять минут на экране ничего не менялось»). Сжатие контекста идёт
        # 3–4 минуты и шлёт про себя ровно одно событие; оно доезжало до
        # бэкенда и тут же выбрасывалось — обработчика у `status` не было.
        #
        # 🔴 ДО 30.08.2026 ЗДЕСЬ СТОЯЛО МОЛЧАНИЕ, И Я ЖЕ ЕГО ОБЕСТОЧИЛ.
        #
        # Было: «остров прогресса умеет показывать заметку под ИДУЩИМ шагом,
        # туда и цепляем; шага не знаем — молчим, подпись без места хуже
        # отсутствия подписи». Это было верно, пока план объявлял шаг 0 порядка
        # работ `aifa-extract` (`_runner/plan.py`) — идущий шаг был ВСЕГДА.
        #
        # 29.08 план уехал из тела навыка к ядровому `update_plan`, а тот модель
        # зовёт не каждый ход. Идущего шага не стало — и стадии движка начали
        # молча выбрасываться. Владелец увидел это первым же прогоном: в станции
        # четыре минуты работал `extract.py`, в журнале лежал status «Извлекаем
        # показатели», а на экране — «нет активного плана» и ни строки движения.
        # Отличить работу от поломки было нечем.
        #
        # МЕСТО У ПОДПИСИ ЕСТЬ, и оно было всё это время: строка без ключа
        # `step` уходит в `tool_progress` (`_progress_events`, запасная ветка),
        # тот ложится в `thinking` реплики, а `v2/page.tsx` рисует `thinking`
        # отдельным идущим шагом острова. Один и тот же текст закрывает обе
        # просьбы владельца — и «на каком шаге прогон», и «размышления в чате».
        note = _STAGE_NOTE.get(str(event.get("stage") or ""),
                               str(event.get("message") or "")).strip()
        if not note:
            return
        if channel.running_step is not None:
            # План объявлен — заметка идёт ПОД идущим шагом, как и раньше:
            # так она стоит на своём месте в чек-листе, а не рядом с ним.
            _emit(channel, {"step": channel.running_step,
                            "status": "running", "note": note})
        else:
            _emit(channel, note)
        return
    if kind == "start":
        _emit(channel, {"extract_start": channel.screen_start})
    elif kind == "metric" and not event.get("dimension"):
        _emit(channel, {"metric_row": _row_body(event)})


def _remember_screen(channel: TurnChannel, run: Any, *,
                     done: dict | None, status: str) -> None:
    """Собранный экран — в строку прогона, чтобы пережить закрытую вкладку (#276).

    ЧТО ИМЕННО КЛАДЁМ И ПОЧЕМУ ИМЕННО ЭТО. Три события, из которых браузер
    складывает карточку извлечения: шапка (`extract_start`), строки
    (`metric_row`) и итог (`extract_done` с раскладкой роли). Не «похожие
    поля», а ТЕ ЖЕ тела, собранные теми же `_start_body`/`_row_body`/
    `outcome.extract_done`, — иначе после перезагрузки страницы таблица
    оказалась бы ТРЕТЬЕЙ редакцией того же прогона (Д5 в разборе #276), и
    расхождение никто бы не заметил: обе выглядят правдоподобно.

    ⚠️ ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЧИСЛА ПРОГОНА ОСЕДАЮТ НА СЕРВЕРЕ так, как их
    видел человек. Точка приёма (`station_progress_ingest`) записывает только
    сводку станции со счётчиками: строки приезжают событиями `metric` раньше
    терминала и туда не попадают вовсе.

    `done=None` — ПРОГОН ОБОРВАЛСЯ. Итога у него нет и взяться ему неоткуда:
    раскладку роли собирает `finalize_extraction` по сводке из терминала,
    которого не было. Кладём шапку и строки — плоскую таблицу фронт из них
    соберёт, а роль-формат честно отсутствует. Пустой словарь вместо `None`
    был бы враньём: он читается как «итог есть, в нём ничего».

    Зовётся ДО ветки «ход кончился»: интересный случай — именно тот, где ходу
    результат уже некуда отдать.
    """
    if not run.metrics:
        # Показывать нечего. Пустой экран в базе хуже отсутствующего: он
        # означал бы «прогон прошёл и не нашёл ни строки». Сюда попадает и
        # канал анализа — он строк не эмитит вовсе.
        return
    screen = {
        "start": channel.screen_start,
        "rows": [_row_body(m) for m in run.metrics],
        "done": done,
    }
    runs.save_best_effort(runs.RunOutcome(
        nonce=channel.nonce, kind=channel.kind, status=status,
        user_id=int(channel.owner_id or 0), project_id=channel.project_id,
        session_id=channel.session_id, run_id=channel.run_id,
        doc_id=run.doc_id or None, screen=screen,
        finished_at=int(time.time())))


