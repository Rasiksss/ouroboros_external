"""Внутренний секрет станции: одна проверка на все внутренние роуты.

ЗАЧЕМ ОДИН МОДУЛЬ. Проверка была скопирована в каждый роут строкой
`if tok and authorization != f"Bearer {tok}"`, и копий стало три (доставка
текста документа, приём прогресса, исполнение fe-тулов), а с личной методикой
станет четыре. Правило в четырёх местах — тот же класс дефекта, что стоил нам
двойных enum'ов, приведения к году и подписи единицы: заведено в одном, молча
не действует в остальных.

ЧТО ЧИНИТСЯ. `if tok and ...` означает, что ПУСТОЙ секрет отключает проверку
ЦЕЛИКОМ, а не ослабляет её. Роуты видны снаружи: `deploy/Caddyfile` проксирует
`/api/*` на бэкенд, то есть `https://<домен>/api/internal/...` достижим из
интернета. Сегодня дверь закрыта вторым рубежом — разовым нонсом хода (32 hex,
живёт 30 минут, владелец сверяется), — но замок при этом снят.

ПОЧЕМУ НЕ «ВСЕГДА ЖЁСТКО». Тем же секретом ходят демон станции и плагин
гейтвея. Отказ при пустом секрете кладёт ЛЮБОЙ прогон станции, а не только один
роут. Локальный запуск без `.env` и часть тестов сегодня работают именно на
пустом секрете. Поэтому строгость включается флагом, а не по умолчанию:

    FINENGINE_ENFORCE_INTERNAL_AUTH=1   ← поднят в compose dev и прода

При поднятом флаге пустой секрет даёт 503 на КАЖДЫЙ внутренний запрос и громкую
строку в лог при старте. Это не крэш-луп: контейнер поднимается и внятно
объясняет, чего ему не хватает, вместо того чтобы тихо пускать всех.

⚠️ 503, А НЕ 401. Пустой секрет — это НАША ошибка развёртывания, а не чужая
попытка войти. 401 послал бы демона переспрашивать с тем же результатом.
"""
from __future__ import annotations

import logging
import os

from fastapi import HTTPException

log = logging.getLogger(__name__)

_TOKEN_ENV = "FINENGINE_OPENCLAW_GATEWAY_TOKEN"
_ENFORCE_ENV = "FINENGINE_ENFORCE_INTERNAL_AUTH"


def gateway_token() -> str:
    """Внутренний секрет: один на бэкенд, демон станции и плагин гейтвея."""
    return os.environ.get(_TOKEN_ENV, "").strip()


def enforced() -> bool:
    """Требовать ли непустой секрет. Поднимается в compose dev и прода."""
    return os.environ.get(_ENFORCE_ENV, "").strip().lower() in ("1", "true", "yes", "on")


def require_gateway_token(authorization: str) -> None:
    """Пустить или отказать. Единственная реализация правила.

    Пусто и строгость выключена — пускаем (локальный запуск, тесты).
    Пусто и строгость включена — 503: развёртывание неполное.
    Секрет есть — сверяем дословно.
    """
    tok = gateway_token()
    if not tok:
        if enforced():
            raise HTTPException(
                status_code=503,
                detail=(f"{_TOKEN_ENV} не задан, а {_ENFORCE_ENV} поднят — "
                        "внутренние роуты закрыты до появления секрета"))
        return
    if authorization != f"Bearer {tok}":
        raise HTTPException(status_code=401, detail="bad token")


def warn_if_unconfigured() -> None:
    """Сказать при старте, а не на первом запросе пользователя."""
    if gateway_token():
        return
    if enforced():
        log.error(
            "%s не задан при поднятом %s — внутренние роуты (текст документа, "
            "приём прогресса, вызов fe-тулов) будут отвечать 503, то есть любой "
            "прогон станции не поедет", _TOKEN_ENV, _ENFORCE_ENV)
    else:
        log.warning(
            "%s не задан и %s не поднят — проверка внутренних роутов ОТКЛЮЧЕНА. "
            "Допустимо только на закрытом контуре и в тестах", _TOKEN_ENV, _ENFORCE_ENV)
