"""Кэш ПЕРВОЙ СТАДИИ извлечения: один отчёт читается моделью один раз.

ЦЕНА, КОТОРУЮ ЭТО СНИМАЕТ (замер 20.08.2026). Прогон Северстали — 318 секунд,
из них **216 на первой стадии**: модель читает отчёт целиком и отбирает
таблицы, где искать каждый показатель. Для ОДНОГО И ТОГО ЖЕ документа при том
же составе показателей ответ каждый раз один и тот же. Повторный прогон
становится втрое быстрее; первый — нет, ему всё равно надо прочитать.

Решение владельца 21.08: «давай делать кэш разумеется нужен».

## Почему хранит бэкенд, а не комната

Комната станции живёт ~18 минут и умирает вместе со всем содержимым — держать
кэш там значит не иметь кэша вовсе. Комната запечатана (seccomp рубит сокеты),
поэтому ходит сюда тем же путём, что за текстом документа: записка демону.

## Ключ — ОТПЕЧАТОК ПРОМПТА, а не документа

Соблазн ключевать по `doc_id` велик и неверен: у одного документа промпт первой
стадии РАЗНЫЙ при разном составе показателей, разной ячейке и после любой нашей
правки правил. Ключ по документу отдал бы вчерашний ответ на сегодняшний
вопрос — и молча, потому что оба выглядят правдоподобно.

Отпечаток промпта закрывает всё это разом: изменилась ячейка, состав, текст
правил или сам отчёт — изменился промпт, значит другой ключ. Отдельной «версии
схемы» не нужно, она уже внутри.

## Чего здесь НЕТ намеренно

**Кэша неудач.** Кладём только разобранный ответ. Иначе переспрос батча,
ради которого написан `_run_stage2_batch`, получал бы из кэша тот же мусор, и
все три попытки стали бы одной.

**Владельца в ключе.** Отпечаток промпта несёт ТЕКСТ ОТЧЁТА целиком: совпал
отпечаток — значит у спрашивающего ровно тот же документ, и отдавать ему нечего
такого, чего он не имеет. Ключ по владельцу отнял бы дедупликацию (тот же отчёт,
загруженный дважды, читался бы дважды) и ничего бы не защитил. Пропуск при этом
обязателен: отвечаем только живому ходу, а не случайному прохожему.

In-process хранилище (как скоуп документов и шина прогресса) — один
uvicorn-процесс, задокументировано; переезд в общее хранилище идёт вместе с ними.
"""
from __future__ import annotations


from fastapi import APIRouter, Header, HTTPException
from pydantic import BaseModel

router = APIRouter()

# Час жизни: отчёт обрабатывают несколькими ходами подряд (извлекли → посчитали →
# разобрали), и все они попадают в окно. Сутки держать незачем — правки правил
# выходят чаще, а память не резиновая.
_TTL_SEC = 3600.0
# Потолок записей: сжатие крупного отчёта — сотни килобайт. Двадцать штук это
# единицы мегабайт, и этого хватает на рабочий день одного пользователя.
_MAX_ENTRIES = 20

# отпечаток → полезная нагрузка. Живёт в ОБЩЕМ кэше, а не в памяти процесса
# (architecture.md 3.2, 🔴 MUST): здесь был словарь уровня модуля, и на двух
# репликах сжатие, положенное одной, второй не досталось бы — крупный отчёт
# сжимался бы заново, то есть кэш работал бы вполсилы и незаметно.
_ПРИСТАВКА = "compress:"


def _кэш():
    from finengine.store.cache import get_cache  # noqa: PLC0415

    return get_cache()


def _подрезать() -> None:
    """Держать не больше `_MAX_ENTRIES` записей: свежий отчёт нужнее вчерашнего.

    ⚠️ ПОРЯДОК ВЫБРОСА ТЕПЕРЬ ПО КЛЮЧУ, А НЕ ПО СРОКУ. Прежняя версия
    выбрасывала запись с наименьшим сроком, то есть самую старую. В общем кэше
    срок ведёт сам Redis и снаружи он не виден; выбрасываем произвольную из
    лишних. Разница безобидна — записи живут час и различаются минутами, а
    потолок нужен от разрастания, не от возраста. Сказано вслух, потому что
    поведение изменилось, пусть и незначимо.
    """
    ключи = _кэш().keys(_ПРИСТАВКА)
    for k in ключи[_MAX_ENTRIES:]:
        _кэш().delete(k)


def _live(nonce: str) -> bool:
    """Живой ли ход. Реестр нонсов общий с выдачей текста документа."""
    from finengine.api import internal_docs

    return internal_docs.nonce_is_live(nonce)


def _require_token(authorization: str) -> None:
    from finengine.api.internal_auth import require_gateway_token

    require_gateway_token(authorization)


class _Put(BaseModel):
    nonce: str = ""
    fingerprint: str = ""
    payload: str = ""


@router.get("/internal/compression-cache")
async def read(nonce: str = "", fingerprint: str = "",
               authorization: str = Header(default="")) -> dict:
    """Отдать сжатие по отпечатку. Промах — не ошибка, а `{"hit": false}`."""
    _require_token(authorization)
    if not _live(nonce):
        raise HTTPException(status_code=403, detail="unknown nonce")
    if not fingerprint.strip():
        raise HTTPException(status_code=400, detail="no fingerprint")
    нагрузка = _кэш().get(f"{_ПРИСТАВКА}{fingerprint.strip()}")
    if нагрузка is None:
        return {"hit": False}
    return {"hit": True, "payload": нагрузка}


@router.post("/internal/compression-cache")
async def write(body: _Put, authorization: str = Header(default="")) -> dict:
    """Запомнить сжатие. Кладёт ТОЛЬКО тот, кто его успешно разобрал."""
    _require_token(authorization)
    if not _live(body.nonce or ""):
        raise HTTPException(status_code=403, detail="unknown nonce")
    fingerprint = (body.fingerprint or "").strip()
    if not fingerprint or not (body.payload or "").strip():
        raise HTTPException(status_code=400, detail="no fingerprint or payload")
    _кэш().set(f"{_ПРИСТАВКА}{fingerprint}", body.payload, _TTL_SEC)
    _подрезать()
    return {"stored": True, "entries": entries()}


def entries() -> int:
    """Сколько записей лежит. Для сторожей и диагностики."""
    return len(_кэш().keys(_ПРИСТАВКА))


def clear() -> None:
    """Опустошить. Для тестов — иначе записи текут между ними."""
    кэш = _кэш()
    for k in кэш.keys(_ПРИСТАВКА):
        кэш.delete(k)
