"""Внешний срез для разбора: новости и макро собирает БЭКЕНД, а не комната.

ДЕФЕКТ, КОТОРЫЙ ЭТО ЗАКРЫВАЕТ (первый эшелон, п.2). Сборщик
`skills/analysis/external.py` написан, выверен и снабжён собственным правилом
приёмки (`_accept`: факт без ссылки или без даты строкой не становится) — но
вызывающих у него на живом пути НОЛЬ. `api/station_turn` передавал
`external_rows=[]` жёстко, раздел «Контекст извне» не появлялся никогда, и
**пустота читалась как «снаружи тихо»**. Это худший вид молчания: отсутствие
ответа неотличимо от ответа «ничего не происходило».

## Почему собирает бэкенд, а не станция

Комната запечатана — seccomp рубит сокеты, наружу можно только через мост, и
единственное, что мост умеет, — позвать модель. Попросить составителя анализа
«загляни в новости» физически нельзя: он дотянуться не сможет и, скорее всего,
напишет по памяти. Память модели датирована обучением, ссылки у неё нет — и
получился бы ровно тот домысел с видом факта, против которого раздел заводится.

## Почему просит КОМНАТА, а не бэкенд шлёт сам

Сбору нужны имя компании и период — их знает КЛАССИФИКАЦИЯ, то есть первый шаг
работы в комнате. Собери бэкенд заранее, на взводе хода, — он не знал бы, по
какой компании искать, и либо промахнулся бы, либо потратил поиск впустую.

## Тумблер пользователя — здесь, а не в комнате

`external.collect` сам спрашивает `user_allowed_web_search()`: выключенный
«Поиск в интернете» означает пустой срез, и это ШТАТНЫЙ исход. Пустой список —
не ошибка: раздела просто не будет, а не появится пустой заголовок.
"""
from __future__ import annotations

import logging

from fastapi import APIRouter, Header, HTTPException

log = logging.getLogger(__name__)
router = APIRouter()

# Сколько ждать поиск. Дольше — и разбор стоит на месте ради украшения: сам
# анализ без внешнего среза выходит полным, просто без одного раздела.
_BUDGET_SEC = 25.0


@router.get("/internal/external-context")
async def external_context(nonce: str = "", company: str = "", period: str = "",
                           language: str = "ru",
                           authorization: str = Header(default="")) -> dict:
    """Собрать внешний срез по компании и периоду. Пусто — штатный исход."""
    import asyncio

    from finengine.api.internal_auth import require_gateway_token
    from finengine.api.internal_docs import nonce_is_live
    from finengine.skills.analysis import external as _ext

    require_gateway_token(authorization)
    if not nonce_is_live(nonce):
        raise HTTPException(status_code=403, detail="unknown nonce")
    if not company.strip():
        # Компания не названа — искать нечего, и это не ошибка: классификация
        # могла не найти имя (квартальник без титульного листа).
        return {"external": [], "note": "компания не названа"}
    try:
        facts = await asyncio.wait_for(
            _ext.collect(company_name=company.strip(), period=period.strip(),
                         language=(language or "ru").strip()),
            timeout=_BUDGET_SEC)
    except TimeoutError:
        # ⚠️ ПУСТО, А НЕ ОТКАЗ. Внешний срез — дополнение к разбору, а не его
        # условие: уронить анализ из-за медленного поисковика значит поменять
        # главное на второстепенное.
        log.info("внешний контекст: поиск не уложился в %.0f с — отдаю пусто", _BUDGET_SEC)
        return {"external": [], "note": "поиск не успел"}
    # ⚠️ КЛЮЧ `external`, А НЕ `rows`: его ждёт потребитель, написанный раньше
    # этого роута (`aifa-analyze/scripts/analyze.py`, разбор флага `--external`).
    # Назови я поле по-своему — завёл бы два имени одного контракта, и файл
    # доехал бы в комнату, чтобы быть молча прочитанным как пустой.
    return {"external": _ext.to_rows(facts)}
