"""Отказ «нет базиса» обязан назвать ВЫХОД, а не только причину.

ЗАЧЕМ ЭТОТ ФАЙЛ. До 09.08.2026 анализ ждал таблицу извлечения ограниченное
время и, не дождавшись, шёл дальше: станция «заземлялась сама», то есть модель
брала числа прямо из текста отчёта.

Живой случай, на котором это вскрылось (прогон по Лукойлу 09.08): извлечение
упало на шаге «собрать показатели (77 шт.)», анализ пошёл дальше и отработал
7 минут. В таблице не оказалось НИ ОДНОГО денежного потока — в логе осталось
«charts: в таблице нет NET_OPERATING_CASH_FLOW, CAPEX, FREE_CASH_FLOW,
INTEREST_PAID…». Всё, что отчёт сказал про денежные потоки, модель взяла из
текста сама, и отличить это в выдаче было нельзя.

Требование владельца дословно: «любой анализ должен опираться на точно
извлечённые финансовые показатели и корректно рассчитанные коэффициенты.
Поэтому любому анализу в качестве пререквизитов необходимо использовать
результат извлечения и расчёта коэффициентов».

🔴 ПОЛОВИНА «АНАЛИЗ НЕ ИДЁТ» ОТСЮДА УБРАНА 20.08.2026 — не потому, что
перестала быть важной, а потому что её сторожит ЗЕЛЁНЫЙ
`test_analysis_page_links.py::test_without_grounding_the_analysis_does_not_
start`: он ловит тот же отказ на его нынешнем месте (`analysis/run.py:52`,
`pytest.raises(ValueError, match="без таблицы показателей")`). Здешняя копия
ходила через `tools._h_fe_analyze`, снесённый коммитом aa13cb1, и падала на
`AttributeError`, не добравшись до предмета.

ОСТАЛОСЬ ТО, ЧЕГО НЕ СТОРОЖИТ НИКТО: отказ без выхода — тупик. Это НЕЗАКРЫТЫЙ
дефект, а не сломанная обвязка, поэтому тест переселён на живую дверь и помечен
`xfail(strict=True)`: как только отказу приделают выход, пометка покраснеет и
потребует снятия.
"""
from __future__ import annotations

import asyncio

import pytest

from finengine.skills.analysis import run as analysis_run


@pytest.mark.xfail(
    strict=True,
    reason="ждёт первого эшелона (SESSION_STATE.md): analysis/run.py:52 поднимает голое ValueError "
           "без what_to_do — пользователю не сказано, чем снять отказ",
)
def test_refusal_says_what_to_do():
    """Отказ без выхода — тупик: пользователю некуда идти.

    ПОЧЕМУ НЕ `fe_extract_metrics`, как было в прошлой редакции: тула с таким
    именем нет (`grep` по `src/finengine/llm/tools.py` — ноль вхождений), а
    посылать человека в снесённую дверь хуже, чем не посылать никуда. Выход
    сегодня — навык `aifa-extract`, поэтому его и требуем.
    """
    with pytest.raises(ValueError) as caught:
        asyncio.run(analysis_run.run(
            company_name="ЛУКОЙЛ", company_type="non_financial",
            ocr_text="===PAGE 1===\nОтчет о финансовом положении\nИтого активы 100\n",
            metrics=[],
        ))

    # Отказ читает ЧЕЛОВЕК, а не только лог: причина у голого ValueError есть,
    # выхода нет — ровно это и требуется дописать.
    said = str(caught.value)
    assert "aifa-extract" in said, (
        f"в отказе не сказано, чем его снять: {said}")
