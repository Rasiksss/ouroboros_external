def _assemble(report_md: str) -> dict:
    """Точное зеркало сборки report_structured из tools.py:1750-1754."""
    return parse_report(
        report_md, company="Банк «Пример»", period="",
        company_type="bank", standard="МСФО", language="ru",
    )


def _capital_rows(structured: dict) -> list[dict]:
    """KPI-строки о достаточности капитала — локальный признак по имени.

    Раньше здесь вызывался продакшн-предикат `_is_capital_kpi_name`, но он жил
    только ради впечатывания капитала и снят вместе с ним (#73).
    """
    return [r for r in structured["kpi"]
            if "достаточность капитала" in (r.get("name") or "").lower()]


# ────────────────────────── Ассерт (1): все ключи контракта ──────────────────────────


def test_contract_has_all_declared_keys():
    structured = _assemble(BANK_REPORT_MD)
    assert set(structured.keys()) == CONTRACT_KEYS
    # Мета-поля прокидываются как передал вызывающий (period="" — как в tools.py).
    assert structured["company"] == "Банк «Пример»"
    assert structured["company_type"] == "bank"
    assert structured["standard"] == "МСФО"
    assert structured["language"] == "ru"
    assert structured["period"] == ""


def test_key_containers_have_expected_types():
    structured = _assemble(BANK_REPORT_MD)
    for key in ("company", "period", "company_type", "standard", "language",
                "verdict", "footnote"):
        assert isinstance(structured[key], str)
    for key in ("kpi", "sections", "strengths", "watch", "conclusions"):
        assert isinstance(structured[key], list)


# ────────────────────────── Ассерт (2): форма каждого KPI ──────────────────────────


def test_sections_have_title_and_body_shape():
    structured = _assemble(BANK_REPORT_MD)
    for sec in structured["sections"]:
        assert set(sec.keys()) == {"title", "body"}
        assert isinstance(sec["title"], str)
        assert isinstance(sec["body"], str)
        assert sec["title"], "у раздела должен быть заголовок"
    # H1-заголовок документа («Финансовый анализ — …») не попадает в разделы.
    titles = [s["title"] for s in structured["sections"]]
    assert not any(t.lower().startswith("финансовый анализ") for t in titles)

