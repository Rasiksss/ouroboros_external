"""Юнит-тесты чистых функций сборки аналитического пакета.

Покрывают ТОЛЬКО детерминированную re/строковую логику
`finengine.skills.analysis.framework`:
  • `analysis_pack` — приоритизация форм/нот и обрезка по бюджету;
  • `capital_notes_text` — выборка страниц ноты достаточности капитала.

LLM здесь не задействован (обе функции работают на regex + срезах строк),
поэтому тесты полностью офлайн и детерминированы.

⚠️ ГЛАВНОЕ ПРАВИЛО С 09.08.2026 (решение владельца). Приоритизация и выброс
служебных страниц — АВАРИЙНЫЙ режим, а не режим по умолчанию: пока отчёт
влезает в бюджет, `analysis_pack` возвращает текст КАК ЕСТЬ. Возражение
владельца по существу: выбрасывать страницы по словам в первых 400 знаках —
это решение КОДА о том, что в документе важно, и пока места хватает, у него нет
ни повода, ни способа проверить себя, а цена ошибки высока (выброшенная
страница для модели просто не существует).

Поэтому проверки приоритизации ниже гоняются на бюджете, СПЕЦИАЛЬНО меньшем
документа. Само правило защищает `test_under_budget_nothing_is_touched`.
"""
from __future__ import annotations

from finengine.skills.analysis.framework import analysis_pack, capital_notes_text

# Маркер обрыва, который analysis_pack дописывает при превышении бюджета пакета.
TRUNC_MARKER = "[…примечания усечены по объёму пакета…]"


def _page_lines(text: str) -> list[str]:
    """Только строки-разделители страниц — удобно сверять ПОРЯДОК блоков."""
    return [ln for ln in text.splitlines() if ln.startswith("===PAGE")]


# ─────────────────────────── analysis_pack ───────────────────────────


def test_non_paginated_returns_head_sliced_to_budget() -> None:
    """Нет ни одного ===PAGE N=== → отдаём голову текста, срезанную до бюджета."""
    text = "просто сплошной текст отчёта без разметки страниц " * 50
    assert analysis_pack(text, budget=40) == text[:40]
    # Бюджет больше длины — текст не режется.
    assert analysis_pack("коротко", budget=10_000) == "коротко"


def test_under_budget_nothing_is_touched() -> None:
    """ГЛАВНОЕ ПРАВИЛО: влезает — отдаём как есть.

    Ни выброса служебных страниц, ни перестановки, ни даже нормализации
    пробелов. Пока места хватает, у кода нет основания решать за методолога и
    за модель, что в документе важно.

    ПРОВЕРКА СТОРОЖА ОТКАТОМ: убрать ранний возврат из `analysis_pack` — тест
    обязан покраснеть (страница аудитора исчезнет, порядок изменится).
    """
    doc = "\n".join([
        "===PAGE 1===", "Прочее примечание про запасы.",
        "===PAGE 2===", "Заключение независимого аудитора. Мы провели аудит.",
        "===PAGE 3===", "Отчёт о финансовом положении. Активы 100.",
    ])
    out = analysis_pack(doc, budget=10_000)
    assert out == doc, "текст под бюджетом изменён — код решил за нас, что важно"
    assert _page_lines(out) == ["===PAGE 1===", "===PAGE 2===", "===PAGE 3==="]


def test_statements_held_and_come_first() -> None:
    """Форма (_STATEMENT_MARKERS в первых 400 символах) держится всегда и идёт
    ПЕРВОЙ, даже если в документе стоит после прочих страниц."""
    doc = "\n".join([
        "===PAGE 1===",
        "Прочее примечание про запасы и дебиторскую задолженность.",
        "===PAGE 2===",
        "Консолидированный отчёт о финансовом положении на 31 декабря. Активы 100.",
    ])
    out = analysis_pack(doc, budget=len(doc) - 1)  # аварийный режим
    # Форма (стр. 2) поднята вперёд прочей ноты (стр. 1).
    assert _page_lines(out) == ["===PAGE 2===", "===PAGE 1==="]
    assert "о финансовом положении" in out
    assert "запасы" in out  # прочая нота тоже вошла (бюджет большой)


def test_capital_note_sorted_before_risk_and_other() -> None:
    """Регресс бага Сбера (нота Н1.0 на стр. 152/167 в ХВОСТЕ отчёта):
    капитал (_CAPITAL_MARKERS) должен идти ПЕРЕД кредитным риском/ECL
    (_RISK_MARKERS) и ПЕРЕД прочими нотами. Маркеры капитала/риска ищутся по
    ВСЕМУ телу страницы, поэтому нота в конце документа не теряется."""
    doc = "\n".join([
        "===PAGE 1===", "Отчёт о финансовом положении. Активы и обязательства.",
        "===PAGE 2===", "Прочее примечание про запасы.",
        "===PAGE 3===", "Движение резерва по стадиям, ожидаемые кредитные убытки.",
        "===PAGE 4===", "Примечание 39. Коэффициент достаточности капитала, Н1.0 = 12,5%.",
    ])
    out = analysis_pack(doc, budget=len(doc) - 1)  # аварийный режим
    # Порядок: форма → капитал (хвост!) → кредитный риск → прочее.
    assert _page_lines(out) == [
        "===PAGE 1===",  # форма
        "===PAGE 4===",  # капитал (стр. в хвосте, но вперёд остальных нот)
        "===PAGE 3===",  # кредитный риск / ECL
        "===PAGE 2===",  # прочее
    ]


def test_boilerplate_dropped_by_first_400_chars() -> None:
    """Boilerplate (_DROP_MARKERS: аудиторское/содержание/ответственность)
    выкидывается по первым 400 символам страницы; drop-маркер ГЛУБЖЕ 400
    символов страницу НЕ выбрасывает."""
    filler = "текст " * 80  # ~480 символов — уводим маркер за границу head(400)
    doc = "\n".join([
        "===PAGE 1===", "Отчёт о финансовом положении. Активы.",
        "===PAGE 2===", "Заключение независимого аудитора. Мы провели аудит SENT_DROP.",
        "===PAGE 3===", f"{filler}аудиторское SENT_KEEP",
    ])
    out = analysis_pack(doc, budget=len(doc) - 1)  # аварийный режим
    pages = _page_lines(out)
    assert "===PAGE 2===" not in pages  # аудиторская страница выброшена по head
    assert "SENT_DROP" not in out
    assert "===PAGE 3===" in pages      # маркер после 400 символов — страница цела
    assert "SENT_KEEP" in out


def test_budget_overflow_truncates_notes_but_keeps_statements() -> None:
    """При превышении бюджета: формы НЕ режутся (добавляются безусловно),
    примечания обрываются, в хвост дописывается TRUNC_MARKER."""
    stmt_body = "Отчёт о финансовом положении. Итого активы 100."
    doc = "\n".join([
        "===PAGE 1===", stmt_body,
        "===PAGE 2===", "Первое прочее примечание AAA.",
        "===PAGE 3===", "Второе прочее примечание BBB.",
    ])
    # Бюджет = длина блока-формы + 1: первое примечание влезает, второе — уже нет.
    stmt_block = f"===PAGE 1===\n{stmt_body.strip()}"
    out = analysis_pack(doc, budget=len(stmt_block) + 1)
    assert stmt_body in out          # форма целиком (не срезана)
    assert "AAA" in out              # первое примечание успело войти
    assert "BBB" not in out          # второе обрезано по бюджету
    assert TRUNC_MARKER in out


def test_budget_overflow_marker_absent_when_everything_fits() -> None:
    """Контроль: когда всё влезает в бюджет, маркера обрыва быть не должно."""
    doc = "===PAGE 1===\nОтчёт о финансовом положении.\n===PAGE 2===\nПрочая нота.\n"
    out = analysis_pack(doc, budget=10_000)
    assert TRUNC_MARKER not in out


# ─────────────────────────── capital_notes_text ───────────────────────────


def test_capital_notes_selects_only_capital_pages() -> None:
    """Возвращаются только страницы с _CAPITAL_MARKERS (по всему телу);
    прочие страницы отсекаются."""
    doc = "\n".join([
        "===PAGE 1===", "Отчёт о финансовом положении. Активы.",
        "===PAGE 2===", "Прочее примечание про запасы.",
        "===PAGE 3===", "Коэффициент достаточности капитала Н1.0 = 12,5%.",
    ])
    out = capital_notes_text(doc)
    assert _page_lines(out) == ["===PAGE 3==="]
    assert "Н1.0" in out


def test_capital_notes_skips_table_of_contents_mention() -> None:
    """Оглавление/аудиторское (_DROP_MARKERS в head) пропускается, даже если там
    лишь УПОМИНАНИЕ ноты капитала — берётся фактическая страница-нота."""
    doc = "\n".join([
        "===PAGE 1===",
        "Содержание. Примечание 39 Коэффициент достаточности капитала Н1.0 ..... 152",
        "===PAGE 2===",
        "Коэффициент достаточности капитала Н1.0 = 12,5% (фактическая нота).",
    ])
    out = capital_notes_text(doc)
    assert _page_lines(out) == ["===PAGE 2==="]


def test_capital_notes_stops_at_limit() -> None:
    """Накопив >= limit символов, выборка останавливается (не тянет весь хвост)."""
    big = "достаточности капитала " * 50  # одна страница уже перекрывает limit
    doc = f"===PAGE 1===\n{big}\n===PAGE 2===\n{big}\n"
    out = capital_notes_text(doc, limit=100)
    assert _page_lines(out) == ["===PAGE 1==="]


def test_capital_notes_empty_when_not_paginated() -> None:
    """Непагинированный текст → пустая строка (нечего проминентно поднимать)."""
    assert capital_notes_text("сплошной текст про достаточности капитала") == ""
    assert capital_notes_text("") == ""
