"""Числа отчётности даёт извлечение, а не глаз модели.

ПРОИСШЕСТВИЕ 20.08.2026, 16:18 (Северсталь). Пользователь попросил восемь
показателей и четыре коэффициента. Агент ответил ВЕРНЫМИ числами — и ни разу
не запустил извлечение: ни таблицы, ни Excel, ни страницы-источника,
`extract = not_started`.

ЦЕПОЧКА ВОССТАНОВЛЕНА ПО ТРАССЕ ЯДРА, а не по догадке. Тул `exec` у модели БЫЛ
(список тулов собранного контекста: exec, read, write, edit, apply_patch,
sessions_spawn, …), тело навыка с точной командой — тоже. Модель рассуждала так:

    «Давай я прочитаю весь документ через инструмент… Но read_source вернул
     пустой массив sources… Попробую через exec с curl. Нет, подожди. У меня
     есть полный текст документа в контексте».

То есть три звена, и каждое чинится отдельно:
  1. `list_sources` вернул голый `[]`. «Источники» и ДОКУМЕНТЫ — разные
     хранилища, приложенный отчёт лежит во втором, и этот тул его не покажет
     НИКОГДА. Пустой массив модель прочитала как «читать нечем»;
  2. текст документа лежал у неё в контексте, а оговорка «не отвечай по этому
     обрезку» висела ВНУТРИ пометки об обрезке (то есть только у длинных
     документов) и была советом, а не запретом с названной заменой;
  3. `fe_calc` прямо приглашал: «числа, названные в разговоре, передавай в
     values{} — тогда доступа к отчёту не требуется вовсе». 🔴 ЗВЕНО ЗАКРЫТО
     НАСОВСЕМ 29.08.2026: тул снят целиком — он считал формулы В ПРОЦЕССЕ
     БЭКЕНДА, а исполняться должно в станции. Два сторожа на него (описание
     и пометка `unverified`) сняты вместе с предметом; звенья 1 и 2 ниже.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ: все три звена сразу. Порознь каждое лечится обходом.

🔵 РЕВИЗИЯ 21.08.2026 — СТОРОЖА ПЕРЕПИСАНЫ НА ИСПОЛНЕНИЕ. До неё пять из шести
читали ИСХОДНИК (`inspect.getsource`) и искали в нём подстроки. Мутация,
прогнанная 21.08: признак `unverified` считается и НЕ кладётся в ответ
(`if False and unverified:`), `_h_list_sources` снова отдаёт голый `[]` при
живом тексте объяснения ниже по функции, запрет снова стоит только у
обрезанного документа — ВСЕ ШЕСТЬ остались зелёными. То есть сторожа стерегли
буквы, а не поведение, и три звена происшествия 20.08 можно было вернуть, не
покраснев. Теперь хендлеры и сборка контекста ЗОВУТСЯ, и проверяется выдача;
та же мутация теперь красит по тесту на звено.

Снят `test_the_guard_is_not_vacuous`: его первый ассерт (`json.loads(
json.dumps(...))`) — тавтология стандартной библиотеки, которую не сломает ни
одна правка продукта, а второй (`"fe_calc" in T.REGISTRY`) краснеет ровно
вместе с `test_the_calculator_does_not_invite_bypassing_the_report` — проверено
удалением тула из реестра.
"""
from __future__ import annotations

import asyncio
import json
from pathlib import Path

import pytest

from finengine.config import settings
from finengine.llm import tools as T
from finengine.models.document import DocumentMeta
from finengine.orchestrator import agent as A


def _call(handler, args: dict, ctx) -> dict:
    return json.loads(asyncio.run(handler(args, ctx)))


@pytest.fixture
def ctx(tmp_path, monkeypatch):
    """Пустой namespace пользователя: ни источников, ни прогонов."""
    monkeypatch.setattr(settings, "data_dir", Path(tmp_path))
    return T.ToolContext(user_id=7, project_id="p")


def test_an_empty_source_list_says_where_reports_live(ctx):
    """Голый `[]` — то, что модель 20.08 прочитала как «читать документ нечем».

    Проверяются ОБЕ ветки: пустая обязана объяснить, где лежит отчёт, непустая
    — остаться обычным списком, иначе объяснение сломает штатный ответ.
    """
    пусто = _call(T._h_list_sources, {}, ctx)
    assert isinstance(пусто, dict), (
        "пустой список источников снова уходит голым массивом — модель "
        "прочитает его как «читать документ нечем» и пойдёт читать глазами")
    assert пусто["sources"] == []
    assert "ДОКУМЕНТАХ" in пусто["note"], (
        "в объяснении не сказано, где на самом деле лежит приложенный отчёт")
    assert "извлечение" in пусто["note"], (
        "запрет без замены: не названо, чем брать числа вместо глаза")

    # Кладём источник тем же способом, что и боевой путь, — через хранилище.
    # До переезда тест писал файл сам (`_sources_dir(...)/f1.meta.json`), то
    # есть знал раскладку на диске; после смены хранилища такой тест сломался
    # бы, ничего не поймав по существу.
    from finengine.skills import sources as _sources
    from finengine.store import blobs as _blobs
    _blobs.get_blob_store().put(
        f"{_sources._префикс(7, 'p')}f1.meta.json",
        json.dumps({"file_id": "f1", "filename": "справка.pdf",
                    "content_type": "application/pdf", "size": 10,
                    "uploaded_at": 1.0, "text_status": "ok"}).encode("utf-8"))
    непусто = _call(T._h_list_sources, {}, ctx)
    assert isinstance(непусто, list) and непусто[0]["file_id"] == "f1", (
        "непустой список перестал быть массивом — объяснение испортило "
        "нормальный ответ")


@pytest.mark.parametrize("длина", [200, 60_000], ids=["короткий", "обрезанный"])
def test_every_document_carries_the_prohibition_not_only_the_truncated_one(
        длина, tmp_path, monkeypatch):
    """Запрет стоит у КАЖДОГО документа и ДО его текста.

    До 20.08 оговорка висела внутри пометки об обрезке — у короткого документа
    её не было вовсе, и именно короткий обрезок Северстали модель прочитала
    глазами. Поэтому короткий случай здесь не «ещё один», а главный.
    """
    doc_id = "doc-1"
    text = "===PAGE 1===\nВыручка 100\n" + "x" * длина
    (tmp_path / f"{doc_id}.txt").write_text(text, encoding="utf-8")
    meta = DocumentMeta(doc_id=doc_id, filename="severstal.pdf",
                        company_name="Северсталь")

    class _Index:
        def get_document(self, did):
            return meta if did == doc_id else None

    monkeypatch.setattr(A, "get_store", _Index)
    monkeypatch.setattr(settings, "docs_dir", Path(tmp_path))

    context, _ = A._build_context("посчитай ROE", [doc_id])
    assert "ДЛЯ ФАКТОВ И ЦИТАТ" in context, (
        "пропал заголовок предупреждения: без него запрет теряется в середине "
        "текста документа и читается как примечание")
    assert "ЗАПРЕЩЕНО" in context, (
        "у документа в контексте нет запрета читать числа глазами")
    assert "извлечение" in context, (
        "запрет есть, а замены нет: голый запрет модель обойдёт, ей нужно "
        "сказать, ЧЕМ взять числа вместо глаза")
    assert context.index("ЗАПРЕЩЕНО") < context.index("Выручка 100"), (
        "запрет стоит ПОСЛЕ текста — к числам модель дойдёт раньше, чем к нему")
