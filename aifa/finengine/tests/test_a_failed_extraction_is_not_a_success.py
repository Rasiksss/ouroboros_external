"""Полностью провалившееся извлечение обязано выйти ОТКАЗОМ, а не кодом 0.

ДЕФЕКТ, РАДИ КОТОРОГО ЭТОТ ФАЙЛ (найден разбором красной базы 20.08.2026).
Батч второй стадии, не прошедший разбор JSON, попадает в
`two_stage_extractor.failed_batches`: движок эмитит статус «не удалось
восстановить батчей: N» и идёт дальше с пустым разбором. Цикл выдачи при этом
идёт по ВСЕМ запрошенным показателям и отдаёт строку на каждый — со значениями
`None` и `found: False`.

Сторож станционного скрипта проверял НЕПУСТОТУ списка строк
(`if not metrics:`), а список непуст всегда. Поэтому прогон, не разобравший
ничего, выходил с `metrics_found: 0, metrics_total: 122` и КОДОМ ВОЗВРАТА 0.

Цена ровно та, что записана в теле навыка: «Упала — это ненулевой КОД
ВОЗВРАТА, а не строчка в stderr». По этому правилу модель ОБЯЗАНА была
прочитать полный провал как успех и доложить человеку пустую таблицу как
результат прогона.

ЧТО ЗДЕСЬ ЗАКРЕПЛЕНО И ЧТО СОЗНАТЕЛЬНО НЕ ЗАКРЕПЛЕНО. Безусловный случай один:
разобрано НОЛЬ значений. Порог для ЧАСТИЧНОГО провала (провалилась половина
батчей — отказ это или нет) здесь НЕ проверяется и в коде не заведён: это
решение владельца, а не побочный эффект правки. Третий тест держит границу с
той стороны — одно разобранное значение отказом быть не должно.

УЗКИЙ ПРОГОН СТАЛ ОТКАЗОМ — ЭТО СЛЕДСТВИЕ, И ОНО ЗАКРЕПЛЕНО, А НЕ ЗАБЫТО.
`--metrics "чистый долг"` по отчёту, где чистого долга нет, даёт одну строку с
`found: False` — то есть ноль разобранных значений, то есть отказ по тому же
безусловному правилу. Человек получит «извлечение провалилось» вместо «не
нашлось». Пятый тест держит СЕГОДНЯШНЕЕ поведение, чтобы оно не поменялось
молча ни в ту, ни в другую сторону; развилка «мы сломались» ↔ «в отчёте нет»
вынесена владельцу отдельным вопросом и кодом не выдумывается.

ПРОВЕРКА СТОРОЖА ОТКАТОМ (каждая мутация обязана покрасить свой тест):
  * `refusal_reason` возвращает "" всегда → первые два теста;
  * `refusal_reason` считает отказом любой непустой `stage2_invalid_batches`
    (то есть выдуманный порог частичного провала) → третий тест;
  * вернуть в `station-skills/aifa-extract/scripts/extract.py` проверку
    `if not metrics:` вместо вызова `refusal_reason` → четвёртый тест;
  * там же ослабить условие до `if refusal and len(metrics) == 0:` — то есть
    вернуть исходный мёртвый сторож под другим именем → четвёртый тест
    (подстрочная редакция этой проверки на такой мутации ЗЕЛЕНЕЛА);
  * `refusal_reason` молчит на выдаче из одной строки → пятый тест.
"""
from __future__ import annotations

import ast
import io
import tokenize
from pathlib import Path

from finengine.skills.extract_result import refusal_reason

ROOT = Path(__file__).resolve().parents[1]
STATION_EXTRACT = ROOT / "station-skills" / "aifa-extract" / "scripts" / "extract.py"


def _code_only(path: Path) -> str:
    """Исходник БЕЗ комментариев и строковых литералов, одной строкой токенов.

    Сторож не смеет зеленеть от объяснительной записки: слова «refusal_reason»
    в комментарии достаточно, чтобы подстрочная проверка прошла на коде, где
    вызова нет.

    Переводы строк и отступы схлопнуты в один пробел сознательно: предмет
    проверки — ПОСЛЕДОВАТЕЛЬНОСТЬ вызова, а она обязана держаться независимо
    от того, как разложена по строкам.
    """
    kept: list[str] = []
    for token in tokenize.generate_tokens(io.StringIO(
            path.read_text(encoding="utf-8")).readline):
        if token.type in (tokenize.COMMENT, tokenize.STRING):
            continue
        kept.append(token.string)
    return " ".join(" ".join(kept).split())


def _row(enum: str, *, found: bool) -> dict:
    """Строка выдачи движка ровно той формы, что уходит станционному скрипту."""
    value = 1000.0 if found else None
    return {
        "type": "metric", "enum": enum, "name_ru": enum, "found": found,
        "value_current": value, "value_prev": None,
        "period_values": [{"period": "FY 2024", "value": value, "unit": "млн руб."}],
    }


def test_all_batches_failed_is_a_refusal():
    """Все батчи второй стадии не разобраны — это отказ, и он назван словами."""
    metrics = [_row(f"M{i}", found=False) for i in range(122)]
    diag = {"stage2_batch_count": 25,
            "stage2_invalid_batches": [{"batch_no": n, "error": "invalid_json"}
                                       for n in range(1, 26)]}

    reason = refusal_reason(metrics, diag)

    assert reason, (
        "122 строки без единого значения и 25 провалившихся батчей из 25 — "
        "прогон объявлен успешным; модель доложит человеку пустую таблицу"
    )
    assert "25" in reason, f"причина не называет масштаб провала: {reason!r}"


def test_zero_parsed_without_batch_diagnostics_is_still_a_refusal():
    """Схема без батчей (полноконтекстная) — тот же безусловный случай.

    Диагностики `stage2_*` у неё нет вовсе, и опираться на её отсутствие
    значило бы оставить половину движков без сторожа.
    """
    metrics = [_row(f"M{i}", found=False) for i in range(40)]

    assert refusal_reason(metrics, None), (
        "ни одного значения на 40 строк, а прогон засчитан успешным"
    )
    assert refusal_reason([], {}), "пустая выдача — тем более отказ"


def test_one_parsed_value_is_not_a_refusal():
    """ГРАНИЦА С ДРУГОЙ СТОРОНЫ: частичный провал сторож НЕ объявляет отказом.

    Порог «провалилась половина батчей» — решение владельца. Пока его нет,
    прогон с одним разобранным значением обязан дойти до человека: выбросить
    его молча было бы второй потерей поверх первой.
    """
    metrics = [_row("REVENUE", found=True)] + [_row(f"M{i}", found=False)
                                               for i in range(121)]
    diag = {"stage2_batch_count": 25,
            "stage2_invalid_batches": [{"batch_no": n, "error": "invalid_json"}
                                       for n in range(1, 25)]}

    assert refusal_reason(metrics, diag) == "", (
        "24 провалившихся батча из 25 объявлены отказом — порог частичного "
        "провала выдуман кодом вместо владельца"
    )


def test_a_narrow_run_over_an_absent_metric_is_a_refusal_today():
    """ПОБОЧНОЕ СЛЕДСТВИЕ ПРАВКИ, НАЗВАННОЕ ВСЛУХ И ЗАКРЕПЛЁННОЕ.

    Человек говорит «найди чистый долг», модель обязана позвать навык с
    `--metrics` (`station-skills/aifa-extract/SKILL.md:88`), состав сужается до
    названного — и если в отчёте его нет, выдача это одна строка с
    `found: False`. Ноль разобранных значений, значит по безусловному правилу
    отказ и ненулевой код возврата: человек услышит «извлечение провалилось»
    вместо «в отчёте такого показателя нет».

    ОТЛИЧИТЬ ОДНО ОТ ДРУГОГО ТЕХНИЧЕСКИ МОЖНО: в станционном скрипте рядом
    лежит `requested`, а сюда уже приходит `diag`. НЕ СДЕЛАНО СОЗНАТЕЛЬНО —
    это выбор владельца между «молчаливая пустая таблица» и «громкий отказ», а
    не побочный эффект правки. Пока выбора нет, тест держит сегодняшнее
    поведение: поменяться оно должно решением, а не случайно.
    """
    reason = refusal_reason([_row("NET_DEBT", found=False)], None)

    assert reason, (
        "узкий прогон по отсутствующему показателю перестал быть отказом — "
        "поведение поменялось без решения владельца (см. owner_question)"
    )


def test_the_station_guard_asks_the_core_and_exits_nonzero():
    """Боевой путь: скрипт станции спрашивает ЯДРО и выходит ненулевым кодом.

    Проверяется по AST, а не по токенам исходника: единственный способ увидеть
    код возврата станционного скрипта из теста — прогнать в комнате настоящее
    извлечение, а его тут нет и быть не может.

    ⚠️ Срез 13.5.4: диагностика двухстадийного движка (`stage2_*`, `_diag`)
    канонической станции больше не видна — она внутренняя для graph atoms
    `read.value`/`locate`. Ядро, которое здесь спрашивают, —
    `extract_result.form_refusal_reason(form)`: тот же безусловный порог
    («ноль найденных — отказ, любое ненулевое — нет»), перенесённый на
    `FormOutput.rows`, не выдуманный заново.

    ПРЕДМЕТ ПРОВЕРКИ — ЦЕПОЧКА, А НЕ НАЛИЧИЕ СЛОВ. Ответ ядра обязан попасть в
    условие БЕЗ добавок (иначе поверх ядра встаёт второй, местный решатель), а
    тело условия обязано дойти до `return 4` не разветвляясь. AST устойчив к
    форматированию ИСХОДНИКА (в отличие от точного текста токенов) и всё ещё
    ловит мутацию из 20.08: `if refusal:` → `if refusal and ...:` меняет узел
    `test` условия с простого имени на `BoolOp` — проверка ниже это отличает.

    ⚠️ ВТОРОЕ МЕСТО ЭТОТ СТОРОЖ НЕ ДЕРЖИТ, И ЭТО НАЗВАНО, А НЕ ЗАМОЛЧАНО.
    Та же мёртвая проверка `if not metrics:` стоит в `finengine/skills/spec/
    steps.py` — втором исполнителе, которого сегодня не зовёт ни один `run.sh`.
    Починить её нельзя, не сломав `test_skill_spec_runner.py`: его заглушка
    модели отвечает в формате, который двухстадийный движок не разбирает, так
    что прогон там извлекает НОЛЬ значений и зеленеет ровно потому, что
    мёртвый сторож его пропускает. Это отдельная работа (чинить надо заглушку),
    и она вынесена в отчёт.
    """
    tree = ast.parse(STATION_EXTRACT.read_text(encoding="utf-8"))
    run_fn = next(n for n in ast.walk(tree)
                 if isinstance(n, ast.FunctionDef) and n.name == "_run")
    code = _code_only(STATION_EXTRACT)
    assert "if not metrics" not in code, (
        "вернулась проверка-пустышка: список строк непуст всегда, потому что "
        "движок отдаёт строку на каждый запрошенный показатель"
    )

    assign = next(
        (n for n in ast.walk(run_fn)
         if isinstance(n, ast.Assign)
         and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name)
         and n.targets[0].id == "refusal"
         and isinstance(n.value, ast.Call)
         and isinstance(n.value.func, ast.Name)
         and n.value.func.id == "form_refusal_reason"),
        None,
    )
    assert assign is not None, (
        "станционный скрипт не спрашивает ядро (extract_result."
        "form_refusal_reason) об отказе на пустом извлечении — значит "
        "объявляет исход сам, вторым решателем"
    )

    idx = run_fn.body.index(assign)
    guard = run_fn.body[idx + 1]
    assert isinstance(guard, ast.If) and isinstance(guard.test, ast.Name) and guard.test.id == "refusal", (
        "ответ ядра не уходит в условие ПРЯМО И ЦЕЛИКОМ следующей же строкой. "
        "Либо между присвоением и веткой появился код, либо к условию "
        "приписана добавка — а любая добавка возвращает исходный дефект: "
        "отказ найден, но не объявлен"
    )
    returns = [n for n in guard.body if isinstance(n, ast.Return)]
    assert returns and isinstance(returns[-1].value, ast.Constant) and returns[-1].value.value == 4, (
        "отказ найден, но код возврата не 4 — тело навыка учит модель читать "
        "такой прогон как успех"
    )
    assert not any(isinstance(n, ast.If) for n in guard.body), (
        "внутри ветки отказа появилась развилка — выход из процесса стал "
        "условным, хотя условие уже принято"
    )
