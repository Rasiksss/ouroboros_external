"""Апостроф в числе — разделитель разрядов, а не мусор.

🔴 ПРОГОН ВЛАДЕЛЬЦА ПО НОВАТЭКУ 30.08.2026: 6 показателей из 122.

Выглядело как провал извлечения, а движок отработал безупречно. В событии
`metric` по выручке лежало:

    "value_current": null,
    "period_values": [{"period": "FY 2021", "value": null,
                       "source_text": "1'156'724"}]

Модель НАШЛА число и нашла верно. Разбор в float его не взял — в этом отчёте
разделитель тысяч апостроф, а `_parse_verbatim_value` знал только пробел и
запятую. Так печатают по швейцарской типографской традиции, и у НОВАТЭКа так
ВЕСЬ отчёт: значит все основные формы вышли пустыми.

Выжили ровно шесть строк — те, где апострофа не было: `144.23` (прибыль на
акцию), `393` (уставный капитал), `-804` (НМА), `221 000` (с ПРОБЕЛОМ).

⚠️ ЧЕМ ЭТО БЫЛО ОПАСНО. «Движок не нашёл» и «нашёл и не смог прочитать» дают
на экране ОДИН И ТОТ ЖЕ прочерк. Диагноз в таблице говорил «искали, в отчёте
НЕТ» — то есть уводил в сторону: переизвлечение не помогло бы никогда.

ПОБОЧНОЕ. Разбор ПЕРИОДОВ про апостроф знал давно (`periods.py` снимает `'` и
`’`), разбор ЧИСЕЛ — нет. Со строки 78 апостроф снимался только по КРАЯМ
ячейки. Две половины одного файла знали про формат разное.

⚠️ Я И САМ НА ЭТОМ СПОТКНУЛСЯ в тот же день: искал `1 135 206` с пробелами по
распознанному тексту, не нашёл и объявил владельцу «чисел в тексте нет». Текст
был в порядке. Искать надо в том виде, в каком число НАПЕЧАТАНО.
"""
from __future__ import annotations

import pytest

from finengine.skills.bulk_extractor.value_parsing import _parse_verbatim_value as разобрать

# Настоящие ячейки из отчёта ПАО «НОВАТЭК» за 2021 год, страницы 10 и 11.
НОВАТЭК = [
    ("1'156'724", 1_156_724.0),   # выручка
    ("711'812", 711_812.0),       # выручка прошлого года
    ("2'457'664", 2_457_664.0),   # итого активы
    ("1'911'469", 1_911_469.0),   # итого капитал
    ("(33'293)", -33_293.0),      # выкупленные акции: скобки = минус
    ("451'621", 451_621.0),       # прибыль
    ("870'541", 870_541.0),       # основные средства
]


@pytest.mark.parametrize(("ячейка", "ждём"), НОВАТЭК)
def test_apostrophe_grouping_is_read(ячейка, ждём):
    got = разобрать(ячейка)
    assert got == ждём, (
        f"«{ячейка}» разобрано как {got!r}, а это {ждём}. Пустое значение при "
        "найденном source_text выглядит на экране как «в отчёте нет» — и "
        "переизвлечение такой прочерк не чинит"
    )


# Апостроф бывает не только прямой: в тексте из OCR встречается типографский.
@pytest.mark.parametrize("ячейка", ["1’156’724", "1ʼ156ʼ724"])
def test_typographic_apostrophes_too(ячейка):
    assert разобрать(ячейка) == 1_156_724.0, (
        "типографский апостроф не распознан — а OCR отдаёт именно такой, "
        "когда в PDF стоит не ASCII-кавычка"
    )


# ── ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: правка не должна была сломать прежние формы ─────
ПРЕЖНИЕ = [
    ("1 156 724", 1_156_724.0),   # пробел — русская группировка
    ("1,156,724", 1_156_724.0),   # запятая — американская группировка
    ("1,234.56", 1_234.56),       # американская: запятая тысячи, точка дробь
    ("144,23", 144.23),           # русская дробная запятая
    ("0,1612", 0.1612),           # доля, ведущий ноль
    ("144.23", 144.23),
    ("-804", -804.0),
    ("(465)", -465.0),
    ("—", None),                  # прочерк — «нет данных», а не ноль
    ("н/д", None),
]


@pytest.mark.parametrize(("ячейка", "ждём"), ПРЕЖНИЕ)
def test_the_old_shapes_still_read(ячейка, ждём):
    assert разобрать(ячейка) == ждём, (
        f"«{ячейка}» перестало разбираться как {ждём}: правка про апостроф "
        "задела разбор запятых и точек"
    )
