"""Первый уровень: нарезка на таблицы и паспорт — код без суждений (#250).

ЗАЧЕМ ЭТОТ ФАЙЛ. Требование владельца: извлечение становится двухуровневым —
сначала поиск и ранжирование таблиц, потом извлечение из отобранных. Здесь
проверены первые два шага (`docs/EXTRACTION_V2_DESIGN.md`, 6.1 и 6.2): они
детерминированные, и вся их ценность в том, что они НЕ РЕШАЮТ ЗА МОДЕЛЬ.

ГЛАВНОЕ, ЧТО СТЕРЕЖЁТ ЭТОТ ФАЙЛ, — отсутствие арифметики смысла. У механики,
из которой взята нарезка, есть продолжение: `_flush_group_table_block` в
`bulk_extractor.py` даёт блоку оценку по ключевым словам (+3/+5/+7, порог 7) и
сортирует по ней. Эта арифметика СНОСИТСЯ по решению проекта: отбор таблиц —
решение по смыслу, его принимает модель, читая паспорта. Вернуть сюда вес или
ключевое слово значит вернуть вторую методику отбора рядом с моделью.

ПРОВЕРКА СТОРОЖА ОТКАТОМ: добавить в `tables.py` любую сортировку блоков по
«полезности» — покраснеет `test_blocks_keep_document_order`. Отсеять блок по
числу строк или по доле цифр — покраснеет `test_nothing_is_dropped_by_a_threshold`.

ЧЕГО НЕ ЛОВИТ (ревизия 21.08.2026). Десять тестов из одиннадцати ЗАПУСКАЮТ
`split_tables`/`passport`; одиннадцатый — `test_the_module_carries_no_scoring`
— читает исходник и ищет слова (`score`, `weight`, `sorted(`). Отбор, названный
иначе (`rank`, `pick`, `_useful`) или вынесенный в соседний модуль, он
пропустит. Оставлен как «О» — это сторож ОТСУТСТВИЯ снесённой арифметики, и
исполнить отсутствие нечем. Замер 21.08 показал, что он не лишний: мутация
`return tuple(sorted(blocks, key=...))` покрасила ТОЛЬКО его — поведенческий
`test_blocks_keep_document_order` остался зелёным, потому что id раздаются до
сортировки.
"""
from __future__ import annotations

from finengine.skills.extraction.tables import (
    Passport,
    passport,
    passports,
    split_tables,
)

# Кусок отчёта в том виде, в каком его отдаёт наше распознавание: маркеры
# страниц, подпись и единицы над таблицей, шапка периодов, метки строк.
REPORT = """===PAGE 46===
Прочая проза, которая таблицей не является и в блок попасть не должна.

===PAGE 47===
Примечание 14. Кредиты и займы
(в миллионах российских рублей)
| | 31 декабря 2024 | 31 декабря 2023 |
| Долгосрочные кредиты банков | 124 500 | 98 300 |
| Облигационные займы | 45 000 | 45 000 |
| Итого | 169 500 | 143 300 |

Ниже идёт пояснительный абзац, он таблицу закрывает.

| Краткосрочная часть | 12 000 | 9 500 |
===PAGE 48===
| Этот блок начинается сразу после маркера страницы | 1 | 2 |
"""


def test_page_marker_closes_a_block():
    """Таблица не продолжается через границу страницы.

    Иначе в один блок склеятся хвост одной формы и шапка другой, и модель
    получит паспорт несуществующей таблицы.
    """
    blocks = split_tables(REPORT)
    pages = [b.page for b in blocks]
    assert pages == [47, 47, 48], f"страницы блоков разъехались: {pages}"
    assert blocks[-1].rows == 1


def test_a_text_line_closes_a_block():
    """Строка без `|` закрывает блок: между таблицами бывает проза."""
    blocks = split_tables(REPORT)
    assert len(blocks) == 3
    assert blocks[0].rows == 4, "первая таблица потеряла или набрала строк"
    assert "Краткосрочная часть" in blocks[1].text


def test_blocks_keep_document_order():
    """Порядок — как в документе. Никакой сортировки «по полезности».

    Ранжирование делает модель ярлыками high/medium/low на шаге 6.3; порядок
    появления в документе — лишь тай-брейк при равенстве. Отсортируй мы здесь —
    получилась бы вторая, скрытая методика отбора.
    """
    blocks = split_tables(REPORT)
    assert [b.id for b in blocks] == [1, 2, 3]
    assert blocks[0].page <= blocks[2].page


def test_nothing_is_dropped_by_a_threshold():
    """Блок из ОДНОЙ строки доживает до паспорта.

    Любой порог («меньше трёх строк — не таблица», «мало цифр — не форма») это
    решение по смыслу. Одна строка вполне может быть той самой раскрытой
    величиной, которую ищут.
    """
    blocks = split_tables("===PAGE 5===\n| Гарантии выданные | 4 300 |")
    assert len(blocks) == 1
    assert blocks[0].rows == 1


def test_context_above_the_block_is_captured():
    """Подпись и единицы над таблицей — часть паспорта, а не потеря."""
    p = passports(REPORT)[0]
    assert p.title_lines == ("Примечание 14. Кредиты и займы",)
    assert p.unit_lines == ("(в миллионах российских рублей)",)


def test_passport_has_the_header_and_the_labels():
    """Паспорт несёт шапку периодов и метки строк — по ним модель и решает."""
    p = passports(REPORT)[0]
    assert p.header_row == "| | 31 декабря 2024 | 31 декабря 2023 |"
    assert p.labels == ("Долгосрочные кредиты банков", "Облигационные займы", "Итого")
    assert p.page == 47 and p.rows == 4


def test_passports_are_a_fraction_of_the_report():
    """В экономии весь смысл первого уровня — и мерить её надо на ОТЧЁТЕ.

    ⚠️ ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ТЕСТА МЕРИЛА НЕ ТО и покраснела по делу: на
    таблице в четыре строки паспорт (280 б) ДЛИННЕЕ самой таблицы (162 б) —
    заголовок, единицы, шапка и метки это почти вся такая таблица плюс
    накладные расходы структуры. И это нормально: экономии на игрушечной
    таблице нет и быть не может.

    Экономия появляется там, где она заявлена: таблица в тридцать строк едет в
    модель паспортом на десяток меток. Сегодня туда уходит ВЕСЬ отчёт, да ещё
    по числу шардов раз, — вот с чем сравнение осмысленно.
    """
    rows = "\n".join(f"| Строка раскрытия номер {i} | {i * 1000} | {i * 900} |"
                     for i in range(1, 32))
    report = ("===PAGE 47===\nПримечание 14. Кредиты и займы\n"
              "(в миллионах российских рублей)\n"
              "| | 31 декабря 2024 | 31 декабря 2023 |\n" + rows)

    block = split_tables(report)[0]
    p = passport(block)
    assert block.rows == 32, "тест построил не ту таблицу"
    size = len(str(p.as_dict()))
    assert size < block.chars / 2, (
        f"паспорт {size} б против таблицы {block.chars} б — экономии нет, "
        "первый уровень не окупается")
    # Меток ровно столько, сколько влезает в паспорт: остальные строки модели
    # для решения «есть ли тут этот показатель» не нужны.
    assert len(p.labels) == 12


def test_a_table_without_a_header_row_is_still_a_table():
    """Шапки нет — паспорт всё равно собирается, а не отказывает.

    Выдумывать шапку нельзя: модель разберётся по меткам. Пустая строка шапки —
    честный ответ «её тут не напечатали».
    """
    p = passports("===PAGE 1===\n| Выручка | 604 401 | 552 271 |")[0]
    assert p.header_row == ""
    assert p.labels == ("Выручка",)


def test_a_document_without_tables_yields_nothing():
    """Ни одного `|` — блоков нет, и это не отказ.

    Что делать дальше (единицей станет страница) решает вызывающий: подставить
    страницы здесь значило бы выдать за таблицу то, что ею не является.
    """
    assert split_tables("===PAGE 1===\nСплошная проза без таблиц.\n") == ()
    assert passports("") == ()


def test_the_module_carries_no_scoring():
    """🔴 В модуле нет ни весов, ни ключевых слов отбора.

    Именно эту арифметику (+3/+5/+7, порог 7) проект велит СНЕСТИ, а не
    перенести. Сторож смотрит на исходник, потому что вернуть её можно тихо —
    одной сортировкой, и ни один поведенческий тест этого не заметит.
    """
    from pathlib import Path
    src = Path(__file__).resolve().parents[1] / "src/finengine/skills/extraction/tables.py"
    code = "\n".join(
        ln for ln in src.read_text(encoding="utf-8").split("\n")
        if not ln.lstrip().startswith("#")
    ).split('"""')
    # Чётные куски — код, нечётные — докстринги: веса ищем только в коде.
    body = "".join(code[::2])
    for banned in ("score", "weight", "relevan", "sort(", "sorted("):
        assert banned not in body.lower(), (
            f"в коде появилось «{banned}» — похоже на отбор по смыслу. "
            "Его принимает модель по паспортам, а не этот модуль.")


def test_passport_survives_a_round_trip_as_plain_data():
    """Паспорт уезжает в промпт словарём — значит должен быть простыми типами."""
    p = passports(REPORT)[0]
    d = p.as_dict()
    assert isinstance(d["labels"], list) and isinstance(d["title_lines"], list)
    assert set(d) == set(Passport.__dataclass_fields__)
