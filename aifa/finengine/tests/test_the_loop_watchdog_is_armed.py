"""Ватчдог событийной петли ПОДКЛЮЧЁН, а не только определён (Р17).

🔴 НЕДОВОЗ 31.08.2026, мой собственный. Ватчдог `_loop_lag_watchdog` был
написан, снабжён докстрингом «наблюдательный код, потому и без отдельного
стража» — и НЕ ВЫЗВАН НИ РАЗУ: определение попало в коммит, вызов нет. Обрыв
владельца в тот же день прошёл без единой строки замера, и «ватчдог молчит»
читалось как «петля чиста», хотя ватчдога не существовало.

Урок дословно тот же, что у правила «сторож без отката не сторож»:
наблюдательный код без проверки подключения неотличим от ненаписанного.
Проверяется двумя утверждениями: вызов стоит в warmup (петля каждого воркера
заводит свой замер), и рядом есть строка о заведении — молчащий лог обязан
отличаться от незаведённого сторожа.

Текстовая проверка сознательно: поднимать всё приложение ради одной строки
несоразмерно, а мутация «убрать await» краснит её (проверено 31.08.2026).
"""
from __future__ import annotations

import re
from pathlib import Path

MAIN = Path(__file__).resolve().parents[1] / "src" / "finengine" / "api" / "main.py"


def _warmup_body() -> str:
    src = MAIN.read_text(encoding="utf-8")
    m = re.search(r"async def warmup\(\).*?(?=\n@app\.|\nasync def |\ndef )",
                  src, flags=re.S)
    assert m, "warmup() в main.py не найден — стартовый хук переехал, перенеси сторож"
    return m.group(0)


def test_the_watchdog_is_called_at_startup():
    body = _warmup_body()
    # В начале строки, а не «где-то в тексте»: первый вариант проверки был
    # подстрокой и оставался зелёным на ЗАКОММЕНТИРОВАННОМ вызове — поймано
    # отрицательным контролем в день написания.
    assert re.search(r"^\s*await _loop_lag_watchdog\(\)", body, flags=re.M), (
        "warmup() не заводит ватчдог петли: определение без вызова уже "
        "случалось, и обрыв Р17 прошёл без замера. Верни "
        "`await _loop_lag_watchdog()` в startup")


def test_the_arming_is_logged():
    body = _warmup_body()
    assert "ватчдог событийной петли заведён" in body, (
        "строки о заведении нет — молчание ватчдога снова будет неотличимо "
        "от его отсутствия")
