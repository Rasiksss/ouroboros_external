"""Прошлый период находится, даже если подписан по ДРУГОЙ оси (#205).

ЗАЧЕМ ЭТОТ ФАЙЛ. Прогон владельца 15.08 по годовому отчёту Черкизово: колонка
за 2020 год пустая. Замер по журналу стенда (4 прогона, 502 строки) показал,
что пустота НЕ случайна и распадается ровно на две половины:

    Абрау-Дюрсо (годовой)   поток  12 с прошлым / 31 без  ← ломается поток
                            запас  27 с прошлым /  0 без
    Детский мир (полугодие) поток  33 с прошлым /  9 без
                            запас   0 с прошлым / 30 без  ← ломается запас
    Ак Барс банк (полугодие) поток  7 / 9 ;  запас 0 / 38  ← ломается запас

ПРИЧИНА. У отчёта ДВЕ ОСИ периода, и обе законны:
  * ЗАПАС (`point`, баланс) живёт ДАТОЙ: «31.12.2020»;
  * ПОТОК (`duration`, ОПУ) живёт ОТРЕЗКОМ: «FY 2020», «6M 2024».
`normalize_metric_period` это знает и подписывает значение по оси показателя —
правильно. А `period_current`/`period_prev` у прогона ОДНИ на всех, и попадают
они на одну ось: у годового отчёта распознаётся «31.12.2020» (дата), у
промежуточного — отрезок. Дальше `_value_for_period` сверяла подписи БУКВАЛЬНО,
и показатели противоположной оси не находили СВОЁ ЖЕ значение.

Отсюда зеркальность замера: у годового отчёта пусто у потока, у промежуточного
— у запаса. Это ОДИН дефект, а не два.

ПОЧЕМУ ТЕКУЩИЙ ПЕРИОД ЭТО ПРЯТАЛ. У `value_current` есть запасной ход
`_first_value` — не нашли по подписи, берём первое значение. Оно почти всегда
и есть текущая колонка, поэтому промах молчал. У `value_prev` такого хода нет
и быть не должно: «первое попавшееся» вместо прошлого года — это выдуманное
число. Дефект вылезал только на прошлом периоде.

ЧТО ПОЧИНЕНО. `_value_for_period` сверяет ДАТОЙ ОКОНЧАНИЯ периода
(`_period_end_key`), когда буквальная подпись не совпала. Своего понятия при
этом не заведено: `_period_end_key` уже жил в этом файле ровно за этим —
«matching duration rows to point rows» — но применялся только в расчётах
(`_with_point_values_for_duration_calculations`), а до выдачи значений не
доехал. Тот же приём уже был применён ТРЕТИЙ раз отдельно —
`_normalize_group_period_label` схлопывает `FY YYYY` в `31.12.YYYY` для строк
группы. Три места об одном и том же.

⚠️ ЧЕГО ЭТОТ ФАЙЛ НЕ ЧИНИТ. У промежуточного отчёта период прогона —
ГОЛЫЙ ГОД («2025»), который нормализуется в конец года и даёт `31.12.2025`
вместо `30.06.2025`. Из-за этого поток полугодия («6M 2024») с прошлым годом
(«FY 2024») не совпадёт и по дате окончания — и не должен: это РАЗНЫЕ отрезки.
Тот дефект отдельный, он про выбор периода прогона, и держится он тестом
`test_interim_flow_is_not_glued_to_the_year` ниже — как граница починки.

ПРОВЕРКА СТОРОЖА ОТКАТОМ: вернуть в `_value_for_period` сверку только по
`normalize_period_label` — красными обязаны стать оба теста «оси».
"""
from __future__ import annotations

from finengine.skills.bulk_extractor import _coerce_period_values, _value_for_period


def _values(enum: str, raw: dict, current: str, prev: str) -> list[dict]:
    period_values, _unit = _coerce_period_values(
        {"values": raw, "unit_text": "млн руб."},
        enum=enum,
        period_current=current,
        period_prev=prev,
    )
    return period_values


def test_annual_flow_metric_finds_its_previous_year():
    """ГЛАВНОЕ, случай Черкизово: годовой отчёт, период прогона — ДАТА.

    Выручка подписана отрезком («FY 2020»), период прогона — датой баланса
    («31.12.2020»). До починки здесь было None, и колонка 2020 пустела.
    """
    pv = _values(
        "SALES_REVENUE",
        {"Год, закончившийся 31 декабря 2021 г.": "180 000",
         "Год, закончившийся 31 декабря 2020 г.": "128 000"},
        current="31.12.2021", prev="31.12.2020",
    )
    assert [p["period"] for p in pv] == ["FY 2021", "FY 2020"], (
        f"движок подписал поток не отрезком: {[p['period'] for p in pv]}"
    )
    assert _value_for_period(pv, "31.12.2020") == 128000.0, (
        "поток не нашёл свой прошлый год по периоду прогона-дате — "
        "это и есть пустая колонка 2020 у Черкизово"
    )
    assert _value_for_period(pv, "31.12.2021") == 180000.0


def test_interim_stock_metric_finds_its_previous_year():
    """Зеркало: промежуточный отчёт, период прогона — ОТРЕЗОК.

    Активы подписаны датой («31.12.2024»), период прогона — годом («2024» →
    «FY 2024»). До починки у банков так терялись ВСЕ 38 балансовых строк.
    """
    pv = _values(
        "TOTAL_ASSETS",
        {"30 июня 2025 г.": "800 000", "31 декабря 2024 г.": "750 000"},
        current="2025", prev="2024",
    )
    assert [p["period"] for p in pv] == ["30.06.2025", "31.12.2024"]
    assert _value_for_period(pv, "2024") == 750000.0, (
        "запас не нашёл свой прошлый год по периоду прогона-отрезку — "
        "так у банков пустел ВЕСЬ баланс"
    )


def test_interim_flow_is_not_glued_to_the_year():
    """ГРАНИЦА ПОЧИНКИ: полугодие ≠ год, и склеивать их нельзя.

    Прошлый период промежуточного прогона приезжает голым годом («2024» →
    «FY 2024»), а сравнительный поток полугодия — это «6M 2024». Отрезки
    РАЗНЫЕ, и дата окончания у них разная (31.12 против 30.06), поэтому
    починка их не сводит. Останется пусто — и это честно: чинить надо выбор
    периода прогона, а не сверку.
    """
    pv = _values(
        "SALES_REVENUE",
        {"6 месяцев, закончившихся 30 июня 2025 г.": "60 000",
         "6 месяцев, закончившихся 30 июня 2024 г.": "55 000"},
        current="2025", prev="2024",
    )
    assert [p["period"] for p in pv] == ["6M 2025", "6M 2024"]
    assert _value_for_period(pv, "2024") is None, (
        "полугодие подставилось вместо года — движок соврал бы сравнением"
    )


def test_exact_label_still_wins_over_the_end_date():
    """Точная подпись главнее даты окончания — иначе починка перепутает колонки.

    Если в записях есть И «FY 2024», И «31.12.2024» (модель вернула обе формы),
    спрошенное буквально обязано вернуть именно своё значение.
    """
    pv = [
        {"period": "FY 2024", "value": 111.0},
        {"period": "31.12.2024", "value": 222.0},
    ]
    assert _value_for_period(pv, "FY 2024") == 111.0
    assert _value_for_period(pv, "31.12.2024") == 222.0


def test_absent_period_stays_absent():
    """Ничего не выдумываем: чего нет — того нет."""
    pv = [{"period": "FY 2024", "value": 111.0}]
    assert _value_for_period(pv, "31.12.2022") is None
