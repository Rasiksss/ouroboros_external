"""Выкатка не умирает от собственного отчёта о коммитах.

ЦЕНА, ЗАПЛАЧЕННАЯ 20.08.2026. Ночная выкатка сорока семи коммитов оборвалась
на коде 141 (SIGPIPE) — ПОСЛЕ `git pull` на VPS и ДО пересборки образа.
Репозиторий стенда обновился, контейнеры остались вчерашними: состояние, в
котором «выкатил» и «работает старое» неотличимы по логу выкатки, потому что
лог обрывается на середине без единого слова об отказе.

ПРИЧИНА. Удалённая часть скрипта идёт под `set -euo pipefail`, а список
приехавших коммитов печатался так:

    git --no-pager log --oneline "$BEFORE..$AFTER" | head -10 | sed …

`head` закрывает трубу на десятой строке, `git` получает SIGPIPE, конвейер
возвращает 141, `set -e` роняет весь скрипт. Дефект спал полтора месяца:
выкатки были по три-четыре коммита, и `head` дочитывал вывод до конца.

⚠️ ПЕРЕПИСАН 21.08.2026 (ревизия набора). До этого дня здесь стояло ТРИ
текстовых сторожа: «в удалённом блоке нет слова `head`», «ограничение `-n N`
на месте» и самопроверка разбора. Они охраняли НАПИСАНИЕ, а не поведение.
Замер 21.08: тот же дефект, записанный без слова `head` —

    git --no-pager log --oneline "$BEFORE..$AFTER" | sed -n "1,10p;10q" | sed …

— даёт под `pipefail` ровно те же 141, и все три сторожа оставались зелёными
(проверено: `bash -o pipefail -c 'yes | sed -n "1,10p;10q"'` → 141).

Теперь команда ИСПОЛНЯЕТСЯ: `git` подменяется шимом, который печатает пять
тысяч строк (заведомо больше буфера трубы). Ранняя смерть потребителя ловится
кодом возврата, снятое ограничение — числом напечатанных строк. Прежняя пара
поводов покрыта одним прогоном, и любым написанием, а не одним.

ЧЕГО СТОРОЖ НЕ ЛОВИТ: он гоняет ОДНУ команду удалённого блока — ту, что
печатает список коммитов. Остальной блок (docker, systemctl, штамп версии) не
исполняется вовсе, и SIGPIPE, заведённый в другой его строке, здесь не виден.
"""
from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

SHIP = Path(__file__).resolve().parents[1] / "deploy" / "skill-hub" / "ship.sh"

# Шим `git`: печатает столько строк, сколько просит `-n N`, а без `-n` — пять
# тысяч. 5000 × ~50 б заведомо больше буфера трубы (64 КБ), поэтому потребитель,
# закрывающий трубу досрочно, гарантированно даёт SIGPIPE — на macOS тоже.
_GIT_SHIM = """#!/bin/sh
n=5000
prev=""
for a in "$@"; do [ "$prev" = "-n" ] && n="$a"; prev="$a"; done
i=1
while [ "$i" -le "$n" ]; do
  echo "abc1234 коммит номер $i, достаточно длинная строка сообщения"
  i=$((i + 1))
done
"""


def _remote_block() -> str:
    """Часть скрипта, исполняемая НА СТЕНДЕ через `bash -s`, без комментариев.

    Именно у неё свой `set -euo pipefail`, и именно её обрыв оставляет стенд
    с новым git и старыми контейнерами.
    """
    body = SHIP.read_text(encoding="utf-8")
    start = body.index("<<'REMOTE'")
    block = body[start:body.index("\nREMOTE", start)]
    assert "set -euo pipefail" in block and "git pull --ff-only" in block, (
        "разбор ship.sh перестал находить удалённый блок — проверка смотрит "
        "не туда и зеленеет на чём угодно")
    return re.sub(r"^\s*#.*$", "", block, flags=re.M)


def _commit_list_command() -> str:
    """Единственная команда блока, печатающая список приехавших коммитов."""
    found = [ln.strip() for ln in _remote_block().splitlines()
             if re.match(r"git\b.*\blog\b", ln.strip())]
    assert len(found) == 1, (
        f"в удалённом блоке команд `git log` стало {len(found)}: {found}. "
        "Сторож гоняет одну — разберитесь, какая печатает список коммитов")
    return found[0]


def test_the_commit_list_survives_a_long_history(tmp_path):
    """Команда переживает выкатку в пять тысяч коммитов и остаётся короткой.

    Два повода одним прогоном: код возврата ловит SIGPIPE (потребитель закрыл
    трубу раньше времени), число строк — снятое ограничение.
    """
    shim = tmp_path / "git"
    shim.write_text(_GIT_SHIM, encoding="utf-8")
    shim.chmod(0o755)

    run = subprocess.run(
        [shutil.which("bash") or "/bin/bash", "-euo", "pipefail",
         "-c", _commit_list_command()],
        env={"PATH": f"{tmp_path}:/usr/bin:/bin",
             "BEFORE": "aaaaaaa", "AFTER": "bbbbbbb"},
        capture_output=True, text=True, timeout=120,
    )

    assert run.returncode == 0, (
        f"список коммитов вернул код {run.returncode} на длинной истории. "
        "141 — это SIGPIPE: потребитель конвейера закрывает трубу раньше, чем "
        "`git` допишет вывод, а под `pipefail` это роняет ВСЮ выкатку — "
        "с обновлённым git на стенде и вчерашними контейнерами. "
        f"stderr: {run.stderr[-500:]}")

    printed = len(run.stdout.splitlines())
    assert printed <= 50, (
        f"в лог выкатки уехало {printed} строк — ограничение снято. Убрав "
        "`| head`, нельзя убрать и `-n N`: иначе получим лог на всю историю")
