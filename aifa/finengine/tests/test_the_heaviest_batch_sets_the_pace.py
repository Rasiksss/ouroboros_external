def test_the_run_says_out_loud_when_the_weights_are_all_equal(monkeypatch):
    """Вырождение меры обязано быть ВИДНО в исходе прогона, а не только в коде.

    ЦЕНА МОЛЧАНИЯ. Равные веса — законный случай, и раскладка тогда побайтово
    равна `spread` (`test_equal_weights_degenerate_to_prior_division`). Но мера
    вырождается и там, где этого никто не ждёт: улике не обязательно быть
    markdown-таблицей — `_extract_tables_from_ocr_payload` берёт любое тело
    длиннее 60 символов, — и на плоской распознанной таблице
    `_widest_row_columns` даёт ноль у ВСЕХ улик. Настройка при этом стоит на
    `balanced`, замер показывает прежнюю неровность, и отличить «балансировка
    не помогла» от «балансировки не было» нечем.

    Громкой ошибкой это не сделано намеренно (в отличие от `weights=None`):
    падать на плоско распознанном отчёте значило бы отказывать ему в
    извлечении. Поэтому — число в диагностике, и обе стороны проверяются
    настоящим прогоном:
    * улики у всех показателей одинаковые (харнесс даёт каждому по одной
      цитате) — разброс ноль, признак поднят;
    * улики у половины — разброс ненулевой, признак снят.
    """
    from tests.test_the_batch_pace_has_something_to_pace import _run_two_stage

    uneven = _run_two_stage(monkeypatch)
    assert uneven.diag["stage2_batch_count"] > 1, "делить было нечего — проверять нечего"
    assert uneven.diag["stage2_batch_weight_spread"] > 0.0, (
        "улики у показателей разные, а разброс весов нулевой — признак вырождения "
        "поднят всегда, то есть не значит ничего")
    assert uneven.diag["stage2_batch_weights_degenerate"] is False

    # Вторая сторона — мера, которая показатели различить не смогла. Здесь она
    # подменена нарочно: настоящий путь к этому — плоская OCR-таблица без
    # markdown-пайпов (`test_a_flat_table_collapses_the_measure`), а через
    # харнесс такую не подать, он строит таблицы из размеченного текста.
    monkeypatch.setattr(ts, "_prompt_card_weights", lambda *a, **kw: {})
    flat = _run_two_stage(monkeypatch)
    assert flat.diag["stage2_batch_weight_spread"] == 0.0, (
        f"разброс {flat.diag['stage2_batch_weight_spread']} при мере, не давшей "
        "ни одного веса — считается что-то помимо неё")
    assert flat.diag["stage2_batch_weights_degenerate"] is True, (
        "веса схлопнулись, а исход прогона об этом молчит: замер не отличит "
        "«балансировка не помогла» от «балансировки не было»")


def test_a_flat_table_collapses_the_measure():
    """Улика без markdown-пайпов делает меру слепой — и это не гипотеза.

    `_extract_tables_from_ocr_payload` берёт в улики любое тело длиннее 60
    символов, пайпов не требует. На таком теле `_widest_row_columns` даёт ноль,
    веса становятся одинаковыми у всех показателей, и `balanced` возвращает
    ровно то же деление, что `spread`, — молча. Здесь проверяется и причина
    (веса равны), и следствие (раскладка та же), чтобы правка, которая уберёт
    первое, не оставила второе без объяснения.
    """
    flat = "Наименование показателя  2025  2024\nИтого активы  1 234 567  1 098 765\n" * 4
    assert len(flat) >= 60, "тело короче порога улики — проверяется не тот случай"
    tables = {f"T{idx:03d}": ts.ReportTable(f"T{idx:03d}", idx, "Плоская", flat)
              for idx in (1, 5, 9)}
    weights = _weights_for({"A": ["T001"], "B": ["T005"], "C": ["T009"]}, tables)
    assert set(weights.values()) == {1.0}, (
        f"на плоской улике веса различимы: {weights} — сторож проверяет не тот случай")
    assert ts._weight_spread(list(weights), weights) == 0.0
    items = sorted(weights)
    assert ts._batch_items(items, 2, strategy="balanced", weights=weights) == \
        ts._batch_items(items, 2, strategy="spread"), (
        "веса равны, а раскладка отличается от прежней — тогда вырождение не "
        "полное и признак в диагностике описывает не то")


