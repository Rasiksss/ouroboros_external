def _makespan(loads: list[float], jobs: int) -> float:
    """Списочный планировщик: `gather` пускает все батчи, семафор даёт `jobs` мест.

    Место берётся ВНУТРИ корутины батча и освобождается сразу по её концу, так
    что следующий по очереди занимает его немедленно. Никаких «кругов», в
    которых все ждут пикового батча, здесь нет — и вся ошибка прежнего ожидания
    была ровно в том, что круги предполагались.
    """
    free = [0.0] * jobs
    end = 0.0
    for load in loads:
        seat = min(range(jobs), key=lambda idx: free[idx])
        free[seat] += load
        end = max(end, free[seat])
    return end


