def test_a_misspelled_strategy_is_refused_before_the_run():
    """Опечатка в ручке обязана падать при чтении настройки, а не на делении.

    ЦЕНА ДЕФЕКТА. Ручка отката — единственное, чем владелец возвращает прежнее
    деление, и набирает он её руками на стенде. Свободной строкой `=balnced`
    принималось молча: `Settings()` пропускал значение, движок доходил до
    первой стадии, сжимал документ — минуты и токены, — и только на делении
    получал `ValueError: Unknown batch strategy`. Перечисление ловит опечатку
    до первого вызова модели.

    Все три известных деления обязаны при этом читаться: сузь перечисление до
    двух — и `contiguous`, которым режется путь без размера батча, перестанет
    набираться с той же внезапностью.
    """
    for good in ("balanced", "spread", "contiguous"):
        assert Settings(FINENGINE_EXTRACT_BATCH_STRATEGY=good).extract_batch_strategy == good
    for typo in ("balnced", "Balanced", "", "spread "):
        try:
            Settings(FINENGINE_EXTRACT_BATCH_STRATEGY=typo)
        except ValidationError:
            continue
        raise AssertionError(f"настройка приняла {typo!r} — опечатка вскроется после сжатия")


