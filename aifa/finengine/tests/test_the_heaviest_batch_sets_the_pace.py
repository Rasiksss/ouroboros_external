def test_balancing_narrows_the_gap():
    """Разброс между самым тяжёлым и самым лёгким батчом обязан упасть.

    ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ВСТРОЕН В САМ СТОРОЖ: сравниваем не с числом из
    отчёта, а с прежним делением, посчитанным здесь же. Верни `_balanced_batches`
    раскладку `spread` — и обе стороны сравнения станут равны, строгое
    неравенство покраснеет.
    """
    balanced, by_order, weights = _both_ways()
    assert len(balanced) == len(by_order) > 1, "батчей стало разное число — сравнивать нечего"
    gap_balanced = max(_loads(balanced, weights)) - min(_loads(balanced, weights))
    gap_by_order = max(_loads(by_order, weights)) - min(_loads(by_order, weights))
    assert gap_balanced < gap_by_order, (
        f"разброс батчей {gap_balanced:.0f} против {gap_by_order:.0f} при делении "
        "по порядку реестра — балансировка не работает")


