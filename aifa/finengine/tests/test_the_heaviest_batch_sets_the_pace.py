def test_the_weight_survives_a_padded_enum():
    """Пробел в enum'е реестра не обязан ронять вес в пол.

    🔴 ЭТО ПОВЕДЕНИЕ, А НЕ НАЛИЧИЕ КЛЮЧА, и разница здесь стоила отдельной
    проверки. `test_the_weight_finds_its_metric_when_the_enum_has_a_space`
    требует только `item in weights` — и остаётся зелёным, когда вес схлопнут:
    ключ на месте (`_prompt_card_weights` кладёт его под `.strip().upper()`), а
    улики `_evidence_for_metric` искала по СЫРОМУ enum'у, тогда как полезная
    нагрузка сжатия ключуется нормализованно (`_normalize_compression_payload`).
    Прогон 21.08 до правки: чистый `TOTAL_ASSETS` → 3,0, `" TOTAL_ASSETS "` →
    1,0, `"total_assets"` → 1,0.

    Второй assert — отрицательный контроль на пустое сравнение: не будь у
    чистого enum'а веса выше пола, равенство выполнялось бы само собой.
    """
    tables = {"T001": ts.ReportTable("T001", 12, "Отчёт о финансовом положении", _TALL_NARROW_TABLE)}
    compression = {"metrics": {"TOTAL_ASSETS": {"tables": [{"table_id": "T001"}], "quotes": []}}}
    clean = ts._prompt_card_weights([{"enum": "TOTAL_ASSETS"}], compression, tables)
    assert clean["TOTAL_ASSETS"] > 1.0, (
        f"улика чистого enum'а не нашлась: {clean} — сравнивать не с чем")
    for padded in (" TOTAL_ASSETS ", "total_assets", "Total_Assets\n"):
        weights = ts._prompt_card_weights([{"enum": padded}], compression, tables)
        assert weights == clean, (
            f"enum {padded!r} дал вес {weights} вместо {clean}: улики ищутся по "
            "сырому ключу, а вес кладётся по нормализованному — показатель стал "
            "невесомым молча")


def test_the_measured_input_is_the_retired_weight():
    """Замеренный ВХОД батча — это снятая мера, а не соседняя с ней величина.

    ЗАЧЕМ ЭТОТ СТОРОЖ ВООБЩЕ ЕСТЬ. Вся замена меры держится на одном выводе:
    прежняя мера равняла вход, вход выровнялся в 1,1 раза, а время осталось
    двенадцатикратным — значит равняли не то. Вывод верен ровно настолько,
    насколько «вход батча» и «сумма длин карточек» — одно и то же число.
    Разрастись постоянная часть промпта (правила, шаблон ответа, охранный
    блок) до половины входа — и наблюдённая ровность входа перестала бы
    что-либо говорить о прежней мере: она могла бы означать просто крупную
    константу, а неровность карточек — прятаться в оставшейся половине.

    Здесь это меряется, а не предполагается: промпт собирается БЕЗ единого
    показателя, и его длина обязана остаться малой долей измеренного входа.
    Порог 20 процентов взят с запасом вдвое к наблюдённым девяти.

    ⚠️ Замер владельца даёт вход в ТОКЕНАХ (18 275…20 346), а здесь считаются
    символы. Переводить одно в другое честно нельзя без токенизатора, поэтому
    сравнение идёт по НИЖНЕЙ оценке: 3,5 символа на токен — курс для латиницы,
    которой постоянная часть и написана целиком. Для кириллических карточек
    курс ниже, то есть настоящая доля постоянной части ещё меньше расчётной.
    """
    profile = f2.prompt_profile_for_cell("ifrs_nf_ru")
    fixed = f2.build_extraction_prompt(
        profile,
        target_enums=[],
        metric_blocks_json="[]",
        schema_lines=[],
        split_request=False,
        company_type="non_financial",
    )
    smallest_measured_input_chars = 18275 * 3.5
    share = len(fixed) / smallest_measured_input_chars
    assert share < 0.20, (
        f"постоянная часть промпта — {len(fixed)} символов, {share:.0%} от самого "
        "лёгкого замеренного входа. При такой доле ровность входа перестаёт быть "
        "показанием о прежней мере, и вывод, ради которого мера снята, повисает")


def test_the_weight_finds_its_metric_when_the_enum_has_a_space(monkeypatch):
    """Ключ веса и ключ состава батча нормализуются ОДИНАКОВО.

    ЦЕНА ДЕФЕКТА — молчаливая, и это худший её вид. Состав батчей набирается
    ключами `metric_by_enum`, а веса `_prompt_card_weights` кладёт под
    `.strip().upper()`. Разойдись нормализации — `weights.get(name, 0.0)` вернёт
    ноль, показатель с пробелом в enum'е станет невесомым, и раскладка тихо
    поедет: тяжёлая карточка сядет туда, где по мере пусто. Ни одного красного
    теста, ни строки в диагностике — только неровность, которую автор правки
    как раз и убирал.

    Сегодня все 711 enum'ов реестра чисты, поэтому пробел здесь ставится
    НАРОЧНО: сторож обязан ловить расхождение до того, как его принесёт первая
    же правка per-cell файла реестра.

    ⚠️ ЧЕГО ЭТОТ СТОРОЖ НЕ ПРОВЕРЯЕТ, И ЭТО ВАЖНЕЕ ТОГО, ЧТО ПРОВЕРЯЕТ. Он
    требует лишь НАЛИЧИЯ ключа в мере (`item in weights`) — и остаётся зелёным,
    когда ключ есть, а вес схлопнут в пол. Ровно так и было до 21.08: улики
    искались по сырому enum'у, а ключ веса клался нормализованным, и
    `" TOTAL_ASSETS "` весил 1,0 против 3,0 у чистого. Достижимость улик
    проверяет `test_the_weight_survives_a_padded_enum`; здесь проверяется
    только нормализация ключей, и снимать это разделение нельзя.
    """
    import tests.test_the_batch_pace_has_something_to_pace as pace

    real_registry = pace.registry_for_profile

    def _registry_with_a_padded_enum(profile_id: str) -> dict:
        registry = dict(real_registry(profile_id))
        metrics = [dict(metric) for metric in registry["extractable"]]
        metrics[0]["enum"] = f" {metrics[0]['enum']} "
        registry["extractable"] = metrics
        return registry

    seen: list[tuple[list[str], dict[str, float]]] = []
    real_split = ts._batch_items

    def _spy(items, batch_size, *, strategy="spread", weights=None):  # noqa: ANN001
        seen.append((list(items), dict(weights or {})))
        return real_split(items, batch_size, strategy=strategy, weights=weights)

    monkeypatch.setattr(pace, "registry_for_profile", _registry_with_a_padded_enum)
    monkeypatch.setattr(ts, "_batch_items", _spy)
    # Улики первой стадии называются ЧИСТЫМ enum'ом: модель их так и вернёт, а
    # оставь мы имя с пробелом — показатель отсеялся бы как безулиочный и до
    # деления не дошёл вовсе, оставив сторож зелёным на пустом месте.
    pace._run_two_stage(
        monkeypatch,
        evidence_enums={
            str(metric["enum"]).strip().upper()
            for metric in real_registry("ifrs_nf_ru")["extractable"]
        },
    )

    assert seen, "деление состава не вызывалось — проверять нечего"
    for items, weights in seen:
        weightless = [item for item in items if item not in weights]
        assert not weightless, (
            f"у показателей {weightless[:3]} нет веса: ключ состава и ключ меры "
            "нормализованы по-разному, раскладка считает их невесомыми")


