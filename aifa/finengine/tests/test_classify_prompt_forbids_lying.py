"""Промпт классификатора запрещает четыре вида вранья (18.08.2026).

РАЗБОР ЖИВОГО ВЫПУСКА ПРОДА ОТ 17.08. Классификатор — единственная модельная
стадия дайджеста, и все четыре дефекта выпуска пришли из неё:

  * «Block (Square) ⭐: Трейдеры оценивают вероятность провала сделки Paramount
    и WBD» — в источнике (CNBC) Block не упомянут вообще; «ВТБ ⭐: Индекс
    Мосбиржи снизился на 2,02%» — вечерняя сводка рынка, ВТБ там одна строка
    в перечислении. Чужие новости встали под заголовки компаний.
  * «Brent выросла до $91,21» (у Ъ — внутридневной максимум) и «Brent $89,31»
    (у Ведомостей — на 19:00 мск) в ОДНОМ выпуске. Оба числа верны, но пересказ
    выбросил временные привязки — осталось голое противоречие.
  * «Nvidia инвестирует $105 млрд» рядом с «Nvidia предоставит гарантию на
    $105 млрд» — подмена финансовой модальности: инвестиция, гарантия и кредит
    — разные обязательства, а формулировка источника была усилена.
  * Те же две строки про Nvidia стояли СОСЕДНИМИ пунктами как два события —
    дубль одного факта из разных источников не был схлопнут, хотя
    classify_batch видит весь батч одним промптом.

По решению владельца «Граница код↔модель» все четыре правила живут в ПРОМПТЕ
(_SYSTEM), а не код-эвристиками — тест держит якоря правил в тексте промпта.
Отрицательный контроль: правки откатывались временно — каждый тест краснел.

Пятый тест добавлен третьим заходом: правка дефекта (г) сама внесла дефект —
порядок предпочтения «агентство, официальный сайт» гасил первоисточник.

Механизм дубля проверен по коду: is_relevant=false у дубля безопасен —
select_long_list, _count_coverage и _render_regulators_box фильтруют по
is_relevant, счётчики шапки считают событие один раз, marks и error-контроль
pipeline не затронуты, строка в digest_items сохраняется для разбора.

🔴 РЕВИЗИЯ 21.08: ГДЕ БЕРЁТСЯ ТЕКСТ. Раньше файл импортировал константу
`_SYSTEM` и искал якоря в НЕЙ. Это охраняло содержимое переменной, а не то,
что уходит модели: перенести правила в `user_msg`, послать `system=""` или
собрать системное сообщение из другого куска — константа не меняется, все шесть
тестов зелёные, а классификатор врёт ровно так же, как 17.08. Теперь батч
гоняется живьём с заглушкой вместо модели, и якоря ищутся в СИСТЕМНОМ
СООБЩЕНИИ, которое `classify_batch` реально отправил. Вместе с этим снят
`test_rules_live_in_system_prompt_not_in_user_message`: он искал `system=_SYSTEM`
в `inspect.getsource(classify_batch)` — теперь то же свойство проверяет сам
факт перехвата, якорь найден в аргументе `system`, а не в написании вызова.

⚠️ ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ. Он доводит правила ДО МОДЕЛИ и на этом
останавливается. Послушается ли модель — тест сказать не может; это видно
только на живом выпуске, как 17.08 и вышло.
"""
from __future__ import annotations

import asyncio
from datetime import datetime, timezone

import pytest

from finengine.skills.news import classify
from finengine.skills.news.models import NewsItem


def _item() -> NewsItem:
    return NewsItem(
        source="РБК", source_id="rbc", source_type="tier1", region="RU",
        source_weight=0.8, title="t", snippet="s", url="https://rbc.ru/1",
        published_at=datetime.now(timezone.utc), raw_hash="h1",
    )


@pytest.fixture(scope="module")
def shipped_system() -> str:
    """Системное сообщение, которое `classify_batch` РЕАЛЬНО отправил модели."""
    sent: dict = {}

    async def _fake(**kw):
        sent.update(kw)
        return "[]", {"in": 0, "out": 0, "cached": 0, "model": "stub"}

    from finengine.llm import openrouter as llm

    orig = llm.complete_with_usage
    llm.complete_with_usage = _fake
    try:
        asyncio.run(classify.classify_batch([_item()]))
    finally:
        llm.complete_with_usage = orig

    system = sent.get("system") or ""
    assert system, (
        "classify_batch не послал системное сообщение — правила выпуска до "
        f"модели не доехали вовсе, ушло только: {sorted(sent)}")
    return system


def test_company_is_assigned_only_when_news_is_about_it(shipped_system: str):
    """Дефект (а): упоминание в перечислении/рыночной сводке — не основание
    ставить новость под компанию."""
    assert "ТОЛЬКО если новость О ней" in shipped_system, (
        "правило «компания — герой новости» ушло из промпта: сводка Мосбиржи "
        "снова встанет под «ВТБ ⭐»")
    assert "НЕ основание" in shipped_system, (
        "промпт не запрещает присваивать компанию по упоминанию в перечислении")


def test_prices_keep_their_time_anchor(shipped_system: str):
    """Дефект (б): «Brent $91,21» и «Brent $89,31» в одном выпуске верны ТОЛЬКО
    вместе со своими привязками — «внутридневной максимум» и «на 19:00 мск»."""
    assert "временную привязку" in shipped_system, (
        "правило про привязку цен ушло: два верных числа снова станут "
        "противоречием")
    for anchor in ("внутридневной", "на закрытие", "на 19:00 мск"):
        assert anchor in shipped_system, (
            f"пример привязки «{anchor}» пропал — модели не на что опереться")


def test_financial_modality_is_not_reworded(shipped_system: str):
    """Дефект (в): «инвестирует» / «предоставит гарантию» / «выдаст кредит» —
    разные обязательства; формулировку источника нельзя подменять и усиливать."""
    assert "не подменяй и не усиливай" in shipped_system, (
        "запрет подмены модальности ушёл: гарантия снова станет инвестицией")
    for word in ("«инвестирует»", "«предоставит гарантию»", "«выдаст кредит»"):
        assert word in shipped_system, (
            f"перечисление модальностей потеряло {word} — правило без примеров "
            "не работает")


def test_duplicate_event_is_collapsed_to_primary_source(shipped_system: str):
    """Дефект (г): одно событие из разных источников схлопывается в один пункт;
    у остальных is_relevant=false — и это правило сильнее «ВСЕГДА true»
    (regulator, e-disclosure), иначе дубль решения ЦБ не схлопнуть."""
    assert "ОДНОМ событии" in shipped_system, (
        "правило дубля ушло: Nvidia снова выйдет двумя соседними пунктами")
    assert "первичный источник" in shipped_system, (
        "нет предпочтения первичного источника — при расхождении формулировок "
        "выживет случайная")
    assert "остальным is_relevant=false" in shipped_system, (
        "механизм гашения дубля ушёл из промпта")
    assert "дубль сильнее правил" in shipped_system, (
        "правила «is_relevant=true ВСЕГДА» перебивают дедуп — дубль решения "
        "регулятора не схлопнется")


def test_duplicate_prefers_official_feed_over_agency_retelling(shipped_system: str):
    """Дефект правки дефекта (г): порядок предпочтения «агентство, официальный
    сайт» ставил АГЕНТСТВО ПЕРЕД первоисточником. Модель гасила копию с ленты
    ЦБ и оставляла пересказ Интерфакса; блок «🏛️ Регуляторы» фильтрует по
    (is_relevant and category=='regulator'), пунктов не оставалось — и выпуск
    печатал «Свежих публикаций за 7 дней нет», хотя событие стояло в Long list.
    Тот же класс лжи о самом себе, который правило дубля и закрывало."""
    assert shipped_system.index("официальный сайт") < shipped_system.index("агентство"), (
        "в правиле ДУБЛЯ агентство снова стоит перед официальным сайтом — "
        "пересказ переживёт первоисточник, и блок регуляторов опустеет")
    assert "Гасится ПЕРЕСКАЗ" in shipped_system, (
        "нет указания, ЧТО именно гасить: модель снова погасит первоисточник")
    assert "с ленты самого регулятора гасить нельзя" in shipped_system, (
        "ушла оговорка про ленту регулятора — дедуп снова обнулит блок "
        "регуляторов при живом событии")
