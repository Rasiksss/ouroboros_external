"""Итог извлечения читается ОДНИМ способом — числом найденных ЗНАЧЕНИЙ.

🔴 ПРОИСШЕСТВИЕ 31.08.2026, прогон владельца по НОВАТЭКу. Движок нашёл 6
значений из 122 запрошенных показателей. Агент доложил:

    «извлечено 122 показателя за оба периода (2021 и 2020).
     Таблица уже в рабочей области.»

Человек прочитал это как успех и пошёл смотреть таблицу, где стояли 122
прочерка. Про то, что значений шесть, ему не сказали ни словом.

ПРИЧИНА НЕ В МОДЕЛИ. Ей отдавали markdown-таблицу и JSON — и всё. Числа
`metrics_found` и `metrics_total` лежали внутри json рядом, и какое из них
«извлечено», модель решала сама. Она посчитала СТРОКИ таблицы.

Пересказ чисел — не работа модели: если итог можно прочитать двумя способами,
виноват тот, кто так его написал. Поэтому сводка теперь идёт СЛОВАМИ и первой
строкой, до таблицы.

⚠️ ЧТО ЭТОТ СТОРОЖ НЕ ЛОВИТ. Он проверяет, что мы СКАЗАЛИ однозначно, а не что
модель послушалась. Исполнить приказ в наборе тестов нечем: тело навыка — это
инструкция, и её выполнение проверяется живым прогоном. Тут стережётся ровно
то, что от нас зависит.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

СКРИПТ = (Path(__file__).resolve().parents[1]
          / "station-skills" / "aifa-extract" / "scripts" / "extract.py")


def _исходник() -> str:
    return СКРИПТ.read_text(encoding="utf-8")


def _summary_fn() -> str:
    """Тело `_summary_line` — предмет всех четырёх проверок ниже."""
    src = _исходник()
    return src[src.find("def _summary_line("):src.find("\ndef _run(")]


def test_the_summary_is_printed_before_the_table():
    """Сводка идёт ДО таблицы: модель читает stdout сверху вниз.

    Поставь её после — и первым, что модель увидит, снова будут строки
    таблицы, а не число найденных значений.
    """
    src = _исходник()
    сводка = src.find("print(_summary_line(form))")
    таблица = src.find("print(_render_form(form))")
    assert сводка > 0, "печать сводки словами в stdout пропала"
    assert таблица > 0, "печать таблицы из stdout исчезла"
    assert сводка < таблица, (
        "сводка печатается ПОСЛЕ таблицы — модель прочитает сначала строки "
        "таблицы и снова назовёт их извлечёнными"
    )


def test_the_summary_names_values_not_rows():
    """В тексте сводки обязано стоять слово ЗНАЧЕНИЙ, а не «показателей».

    Разница не косметическая: строк в таблице столько же, сколько запрошено, и
    именно это число агент выдал за результат. Числитель обязан считать
    НАЙДЕННЫЕ значения (`FormRow.status == "supported"`), а не строки таблицы.
    """
    fn = _summary_fn()
    assert "Извлечено ЗНАЧЕНИЙ" in fn, "сводка не называет извлечённое ЗНАЧЕНИЯМИ"
    assert 'row.status == "supported"' in fn, (
        "числитель считает не найденные значения, а что-то ещё — снова "
        "двусмысленно"
    )


def test_both_numbers_reach_the_line():
    """Найдено И запрошено — оба в одной фразе, иначе снова две трактовки."""
    fn = _summary_fn()
    assert "{found}" in fn and "{total}" in fn, (
        "в сводку попадает только одно число: «извлечено N» без «из скольких» "
        "читается как полный успех"
    )


def test_a_thin_result_says_so_out_loud():
    """Меньше половины — отдельная громкая строка, а не тихая доля в процентах."""
    fn = _summary_fn()
    assert re.search(r"found\s*/\s*total\s*<\s*0\.5", fn), (
        "порог «меньше половины» исчез — заметная неполнота снова пройдёт "
        "тихо"
    )
    assert "⚠️" in fn and "ПРЯМО" in fn, (
        "предупреждение перестало требовать сказать пользователю прямо"
    )


@pytest.mark.parametrize(("найдено", "всего", "ждём_предупреждение"),
                         [(6, 122, True), (60, 122, True), (61, 122, False),
                          (122, 122, False)])
def test_the_threshold_behaves_as_written(найдено, всего, ждём_предупреждение):
    """Порог считается от долей, а не от числа: 6/122 и 60/122 — оба «мало»."""
    доля = 100.0 * найдено / всего
    assert (доля < 50) is ждём_предупреждение, (
        f"{найдено} из {всего} = {доля:.0f} % — порог сработал не так, как "
        "описан в скрипте"
    )
