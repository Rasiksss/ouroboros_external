"""Тело навыка — промпт, а не журнал происшествий.

🔴 ЗАЧЕМ (решение владельца 25.08.2026). Тела навыков превратились в растущую
кучу предупреждений, каждое куплено ОДНИМ инцидентом на ОДНОМ отчёте: «так
владелец получил пустую клетку», «потеряны 110 показателей по Банку
Санкт-Петербург», «97,1 вместо 24,2», «#253, четыре прогона подряд». Владелец
назвал это переобучением под один кейс — и он прав дважды:

  1. модель читает это КАЖДЫЙ ХОД. История чужого инцидента ей ничего не
     говорит: ей нужно правило и формат, а не то, кто и когда на нём погорел;
  2. потолок чтения (150 строк) при этом никуда не делся, и каждое новое
     предупреждение вытесняло что-то полезное. За два дня такой размен сделан
     трижды.

ГДЕ ЭТОМУ МЕСТО. Причина правки живёт в коммите, в комментарии у кода и в
`references/` рядом с навыком — там её прочитает человек, который правит. В
теле остаётся то, что нужно ИСПОЛНИТЕЛЮ: что делать, в каком формате, чего
нельзя.

⚠️ ЧТО ЭТОТ СТОРОЖ МОЖЕТ И ЧЕГО НЕТ. Он ловит ФОРМУ — даты, номера задач, имена
компаний из наших прогонов. Он не отличит хорошее правило от плохого и не
помешает написать многословно. Это грубый фильтр против конкретного рецидива,
а не судья качества.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1] / "station-skills"
ТЕЛА = sorted(КОРЕНЬ.glob("*/SKILL.md"))

# Следы конкретного случая. Каждый шаблон — то, что уже приходилось вычищать.
СЛЕДЫ = [
    (re.compile(r"\b\d{2}\.\d{2}(\.\d{4})?\b"), "дата инцидента"),
    (re.compile(r"#\d{2,4}\b"), "номер задачи"),
    (re.compile(r"владельц\w*|владелец", re.I), "упоминание владельца"),
    (re.compile(r"Северсталь|Санкт-Петербург|Совкомбанк|Мегафон|Дойчбанк", re.I),
     "имя компании из наших прогонов"),
    (re.compile(r"\bКуплено\b", re.I), "формула «куплено инцидентом»"),
]


def test_skill_bodies_exist() -> None:
    """Предпосылка: без неё остальные тесты зелены на пустом месте."""
    assert len(ТЕЛА) >= 3, f"тел навыков найдено {len(ТЕЛА)} — проверять нечего"


@pytest.mark.parametrize("тело", ТЕЛА, ids=lambda p: p.parent.name)
def test_a_skill_body_carries_rules_not_incidents(тело: Path) -> None:
    """Ни дат, ни номеров задач, ни имён компаний — это память, не инструкция."""
    текст = тело.read_text(encoding="utf-8")
    находки: list[str] = []
    for шаблон, что in СЛЕДЫ:
        for m in шаблон.finditer(текст):
            строка = текст[: m.start()].count("\n") + 1
            находки.append(f"{тело.parent.name}/SKILL.md:{строка} — {что}: «{m.group(0)}»")
    assert not находки, (
        "в тело навыка вернулась память об инциденте. Правило оставь, историю "
        "унеси в коммит, комментарий у кода или references/ рядом:\n  "
        + "\n  ".join(находки)
    )
