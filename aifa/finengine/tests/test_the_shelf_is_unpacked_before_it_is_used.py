"""Ни один навык не трогает `.shelf/` раньше, чем распакует полку.

🔴 КУПЛЕНО ПОТЕРЯННЫМ ПРОГОНОМ 26.08.2026 (Nordea). Плагин кладёт в комнату
АРХИВ `.shelf.zip`; каталога `.shelf/` не существует, пока его не распакуют.
А в `aifa-extract/SKILL.md` распаковка стояла ШАГОМ 2, тогда как шаг 0 — самая
первая команда хода — уже звал `.shelf/aifa_station_skills/_runner/plan.py`.

На свежей комнате эта команда не могла отработать никогда. Что было видно в
логе гейтвея:

    shelf delivered to …-64d720d9… (1483313 bytes)
    read failed: Sandbox FS error (ENOENT): .shelf/…/extract_run.sh
    ⚠️ `find files named "extract_run.sh" in .shelf/` failed
    run ended with stopReason=stop

Модель дважды попыталась добраться до скрипта, не нашла — и закончила ход
текстом «Запускаю извлечение показателей… запускаю», не запустив ничего.
Пользователь увидел уверенный ответ, панель извлечения осталась пустой, а в
базе прогон записан `not_started`. Отказа не было НИ ОДНОГО.

⚠️ ЭТО СТОРОЖ НА ПОРЯДОК, А НЕ НА ФОРМУЛИРОВКУ. Тела навыков переписываются
постоянно, и проверять в них слова — заведомо мёртвый труд (решение владельца
25.08). Здесь проверяется отношение «раньше/позже» между двумя КОМАНДАМИ:
распаковка обязана стоять до первого обращения к распакованному. Переписать
текст вокруг можно как угодно.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

НАВЫКИ = sorted((Path(__file__).resolve().parents[1] / "station-skills").glob("*/SKILL.md"))

# Команда — то, что модель ИСПОЛНЯЕТ: обратные кавычки с вызовом оболочки или
# питона. Описательные упоминания пути (в прозе, в примерах grep) командами не
# считаются: они ничего не запускают и порядок не нарушают.
_КОМАНДА = re.compile(r"`([^`]*(?:python3|bash|sh) [^`]*)`")
_РАСПАКОВКА = re.compile(r"zipfile\s+-e\s+\.shelf\.zip")


def _команды(текст: str) -> list[str]:
    """Все исполняемые команды тела навыка, по порядку появления."""
    return [m.group(1) for m in _КОМАНДА.finditer(текст)]


def test_there_are_skills_to_check():
    """Сторож без предмета — не сторож: пустой список молча зеленел бы."""
    assert len(НАВЫКИ) >= 3, f"навыков найдено {len(НАВЫКИ)} — проверять нечего"


@pytest.mark.parametrize("навык", НАВЫКИ, ids=lambda p: p.parent.name)
def test_the_bodies_do_not_unpack_anymore(навык):
    """Р19 (решение владельца 31.08.2026): распаковку делает ПЛАГИН при
    доставке полки — шаг снят с модели. Значит в телах команды распаковки
    быть не должно: вернётся — модель снова потратит ход на то, что уже
    сделано за неё, а два владельца одного шага рано или поздно разойдутся.
    """
    команды = _команды(навык.read_text(encoding="utf-8"))
    распаковки = [c for c in команды if _РАСПАКОВКА.search(c)]
    assert not распаковки, (
        f"{навык.parent.name}: в теле снова команда распаковки полки — её "
        f"делает плагин при доставке (Р19): {распаковки[0][:80]!r}")


def test_the_plugin_unpacks_after_delivery():
    """Полку распаковывает плагин — сразу за заливкой архива в комнату.

    Прежний предмет этого файла («распаковка в теле стоит раньше первого
    `.shelf/`») умер вместе с шагом: теперь порядок держится в одном месте —
    `uploadShelf` плагина, и здесь проверяется, что распаковка оттуда не
    исчезла. Исчезнет — каждая свежая комната встретит команды навыков
    голым архивом, и это снова будет выглядеть как Nordea 26.08 (см. шапку).
    """
    плагин = (Path(__file__).resolve().parents[1]
              / "deploy" / "workstation-ext" / "index.ts").read_text(encoding="utf-8")
    тело = плагин.split("async function uploadShelf", 1)[1].split("\nasync function ", 1)[0]
    assert "zipfile" in тело and ".shelf.zip" in тело, (
        "uploadShelf больше не распаковывает полку — свежие комнаты получат "
        "голый архив, а шага распаковки в телах навыков нет (Р19)")


def test_the_rescue_command_lives_in_the_constitution():
    """Спасательный люк: если доставка споткнулась, модель обязана знать, чем
    распаковать самой. Команда живёт в конституции комнаты — одна на всех."""
    tools = (Path(__file__).resolve().parents[1]
             / "agent-workspace" / "bootstrap" / "TOOLS.md").read_text(encoding="utf-8")
    assert _РАСПАКОВКА.search(tools), (
        "в TOOLS.md нет спасательной команды распаковки — при споткнувшейся "
        "доставке модель упрётся в ENOENT без объяснения, чем себя спасти")


# ─────────── путь из инструкции обязан существовать в полке ───────────


def _пути_полки(текст: str) -> set[tuple[str, bool]]:
    """Все пути `.shelf/...` из тела навыка: (путь, обрезан ли на шаблоне).

    `catalogue/_index_<ячейка>.md` — не путь, а ФОРМА пути: захват регекспа
    останавливается на `<`, и буквально такого файла в полке нет. Пропускать
    форму молча нельзя — переименуют файлы, и тело будет слать модель в
    ENOENT при зелёном стороже. Поэтому форма помечается и проверяется как
    ПРЕФИКС: хоть один файл полки обязан с него начинаться.
    """
    return {(m.group(0), текст[m.end():m.end() + 1] == "<")
            for m in re.finditer(r"\.shelf/[A-Za-z0-9_./-]+", текст)
            if not m.group(0).endswith("/")}


@pytest.mark.parametrize("навык", НАВЫКИ, ids=lambda p: p.parent.name)
def test_every_path_the_skill_names_exists_in_the_shelf(навык):
    """🔴 ЧТО НАВЫК ВЕЛИТ ЗАПУСТИТЬ — ТО В ПОЛКЕ И ЛЕЖИТ.

    Вторая половина того же урока: порядок команд можно починить, а файла всё
    равно может не оказаться. Для модели это неотличимо — тот же ENOENT, тот же
    тихий конец хода. Здесь полка СОБИРАЕТСЯ по-настоящему и в ней ищется
    ровно тот путь, что записан в теле навыка.

    Мутация: переименовать `extract_run.sh` в теле навыка — тест краснеет.

    ⚠️ Шаблоны (`<ячейка>`, `<doc_id>`) пропускаем: это не путь, а форма пути,
    и проверять его существование нечем.
    """
    import io
    import zipfile

    from finengine.skills import station_driver

    station_driver._shelf_cache = None
    полка = set(zipfile.ZipFile(io.BytesIO(station_driver._build_shelf())).namelist())

    пропали = []
    for путь, форма in sorted(_пути_полки(навык.read_text(encoding="utf-8"))):
        if "<" in путь or ">" in путь:
            continue
        ключ = путь[len(".shelf/"):]
        if not ключ:
            continue
        if форма:
            # Форма пути: буквального файла нет по построению, но префикс
            # обязан разрешаться — иначе тело зовёт несуществующее семейство.
            if not any(k.startswith(ключ) for k in полка):
                пропали.append(путь + "<…>")
            continue
        if ключ not in полка and not any(k.startswith(ключ + "/") for k in полка):
            пропали.append(путь)

    assert not пропали, (
        f"{навык.parent.name}: тело навыка велит модели обратиться к путям, "
        f"которых в полке НЕТ: {пропали}. В комнате это ENOENT, и модель "
        "закончит ход, ничего не запустив.")
