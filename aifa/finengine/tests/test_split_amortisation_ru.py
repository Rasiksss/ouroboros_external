"""Разнесённая амортизация русских отчётов узнаётся реестром (17.08.2026).

ЗАЧЕМ. Замер Мегафона Q2 2025 против разметки Finengine: 25 пропусков, среди
них `DEPRECIATION_AMORTIZATION`. Причина не в модели и не в тексте — данные в
отчёте ЕСТЬ, но разнесены на две строки:

    Амортизация основных средств и АФПП        32 642
    Амортизация нематериальных активов          5 978

а реестр знал только слитную формулировку «Амортизация основных средств и
нематериальных активов», которой в русском отчёте не бывает.

⚠️ ВТОРАЯ ЛОВУШКА, из-за которой мало было просто дописать синонимы. Прежняя
подсказка заканчивалась «Не путай с ROU amortization» — верно для англоязычной
раскладки, где ROU-амортизация идёт своей строкой. В русской раскладке АФПП
(активы в форме права пользования) СИДИТ ВНУТРИ строки основных средств, и
буквальное следование предупреждению уводит модель от правильной строки.
Поэтому подсказка теперь разделяет два случая явно.
"""
from __future__ import annotations

import pytest

from finengine.skills.metric_schema import registry_for_profile

RU_CELLS = ["ifrs_nf_ru", "rsbu_nf_ru"]

# Формулировки из живых отчётов, а не придуманные: Мегафон Q2 2025.
REPORT_WORDINGS = [
    "Амортизация основных средств и АФПП",
    "Амортизация основных средств и активов в форме права пользования",
    "Амортизация нематериальных активов",
]

# 🔴 ЯЧЕЙКИ РАЗВЕДЕНЫ СОЗНАТЕЛЬНО, И ЭТО НЕ НЕДОДЕЛКА.
# Замер сделан на Мегафоне — это МСФО, ячейка `ifrs_nf_ru`: там АФПП сидит
# внутри строки основных средств, и разметка ждёт сумму ВМЕСТЕ с ним. Для
# `rsbu_nf_ru` такого замера нет, а её подсказка (пришла из FinEngine) прямо
# велит право пользования исключать. Переносить туда вывод по чужому стандарту
# «за компанию» — это менять методику без данных; РСБУ получает только
# опознание двух строк и правило суммы, её собственное правило по ППА цело.
IFRS_ONLY_WORDINGS = REPORT_WORDINGS[:2]


def _da(cell: str) -> dict:
    for m in registry_for_profile(cell)["extractable"]:
        if m["enum"] == "DEPRECIATION_AMORTIZATION":
            return m
    pytest.fail(f"{cell}: показателя DEPRECIATION_AMORTIZATION нет в реестре")


@pytest.mark.parametrize("cell,wording", [
    *[("ifrs_nf_ru", w) for w in REPORT_WORDINGS],
    # РСБУ узнаёт разнесённые строки, но не формулировки АФПП из МСФО.
    ("rsbu_nf_ru", "Амортизация нематериальных активов"),
    ("rsbu_nf_ru", "Амортизация основных средств"),
])
def test_report_wording_is_a_known_alias(cell, wording):
    """Каждая формулировка из живого отчёта обязана быть синонимом.

    Проверяем ВХОЖДЕНИЕ, а не равенство: в отчёте строка бывает с хвостом
    вроде «(АФПП)» или с примечанием, и точного совпадения не будет.
    """
    al = [a.casefold() for a in (_da(cell).get("aliases_ru") or [])]
    assert any(wording.casefold() in a or a in wording.casefold() for a in al), (
        f"{cell}: формулировка «{wording}» не опознаётся; синонимы: {al}")


@pytest.mark.parametrize("cell", RU_CELLS)
def test_hint_demands_summing_two_lines(cell):
    """Синонимов мало: без правила «сложи» модель возьмёт одну строку и
    занизит показатель вдвое-впятеро."""
    hint = (_da(cell).get("hint") or "")
    assert "ДВЕ СТРОКИ" in hint or "ДВЕ СТРОКИ" in hint.upper(), (
        f"{cell}: подсказка не говорит про две строки")
    assert "СУММА" in hint.upper(), f"{cell}: не сказано, что нужна сумма"


def test_hint_does_not_send_the_model_away_from_rou_in_russian_layout():
    """Отрицательный контроль на прежнюю формулировку: предупреждение про ROU
    обязано быть ОГРАНИЧЕНО англоязычной раскладкой, иначе оно вредит.

    Только для `ifrs_nf_ru` — см. IFRS_ONLY_WORDINGS выше: у РСБУ исключение
    права пользования это её собственное правило, отменять его нашим замером
    по МСФО нельзя."""
    cell = "ifrs_nf_ru"
    hint = _da(cell).get("hint") or ""
    if "ROU" in hint:
        assert "англоязычн" in hint, (
            f"{cell}: предупреждение про ROU не ограничено англоязычными "
            f"отчётами — в русской раскладке АФПП внутри строки ОС, и оно "
            f"уводит модель от верной строки")


@pytest.mark.parametrize("cell", RU_CELLS)
def test_english_aliases_survived(cell):
    """Правка русских формулировок не имеет права выбить прежние: двуязычные
    отчёты по МСФО печатают обе (та же ошибка, что ловит #147)."""
    al = _da(cell).get("aliases_ru") or []
    assert any("нематериальных активов" in a and "основных средств" in a for a in al), (
        f"{cell}: слитная формулировка потерялась при добавлении разнесённых")
