"""«На 1 января Y» = «31.12.(Y−1)»: входящий остаток капитала (17.08.2026).

ОТКУДА. Замер Мегафона Q2 2025 против разметки Finengine. Сравнительная
колонка отчёта об изменениях капитала подписана «На 1 января 2025 года», и
движок так её и помечал — `01.01.2025`. Числа при этом брались ВЕРНЫЕ:
уставный капитал 526 и эмиссионный доход 12 567 совпадают с разметкой ровно.
Но разметка ждёт их периодом 2024, и в сверке они числились пропуском, а в
таблице пользователя вставали вторым значением 2025 года рядом с настоящим
остатком на 30.06.2025 — то есть один и тот же год показывал два остатка.

ПОЧЕМУ ТАК, А НЕ ИНАЧЕ. Полночь 1 января и конец 31 декабря — одна точка на
оси времени; отчётность пользуется второй записью, и сопоставлять периоды надо
по ней. Правило только для ТОЧЕЧНЫХ дат: длительность «с 1 января» — это
законное начало периода, её сдвигать нельзя (проверяется ниже).
"""
from __future__ import annotations

import pytest

from finengine.skills.periods import POINT_KIND, normalize_period_label


@pytest.mark.parametrize("raw", [
    "На 1 января 2025 года",
    "1 января 2025",
    "01.01.2025",
    "As at 1 January 2025",
])
def test_opening_balance_becomes_prior_year_close(raw):
    """Остатки капитала нормализуются с типом «точка» — так их зовёт движок.

    Без `value_kind` строка «На 1 января 2025 года» уходит в ветку
    длительности («12M 31.12.2024»): слово «года» читается как годовой период.
    Якорь там уже верный, но проверять надо ТОТ вызов, который делает движок.
    """
    assert normalize_period_label(raw, value_kind=POINT_KIND) == "31.12.2024", (
        f"«{raw}» обязан свестись к закрытию прошлого года")


def test_other_dates_are_untouched():
    """Отрицательный контроль: сдвигается ТОЛЬКО 1 января."""
    assert normalize_period_label("30 июня 2025") == "30.06.2025"
    assert normalize_period_label("31 декабря 2024") == "31.12.2024"
    assert normalize_period_label("2 января 2025") == "02.01.2025"


def test_duration_starting_january_first_is_not_shifted():
    """«За период с 1 января по 30 июня 2025» — длительность, а не остаток:
    её начало никуда не переносится, иначе полугодие станет прошлым годом."""
    got = normalize_period_label("За шесть месяцев, закончившихся 30 июня 2025")
    assert "2025" in got and "2024" not in got, f"полугодие 2025 уехало: {got}"
