"""Карточка анализа НИЧЕГО не выводит из прозы. Решение владельца 11.08.2026.

ЧТО БЫЛО. Код резал markdown отчёта по заголовкам, нормализовал строку
заголовка и искал её в словаре ролей из методики. Совпало — блок попадал в
карточку; не совпало — ИСЧЕЗАЛ молча. Тем же способом собирались KPI-таблица,
«сильные стороны», «выводы». Уровень риска на обложке выводился дважды: сначала
регуляркой по строке «ИТОГОВЫЙ УРОВЕНЬ:», затем подсчётом статусов в ячейках.

ЧЕМ ЭТО КОНЧИЛОСЬ. Прогон ФосАгро 11.08: модель не поставила заголовков вовсе,
совпадений ноль, карточка вышла пустая. На экране остался единственный график и
подпись под ним — их строит КОД по таблице извлечения, поэтому они появляются
даже когда анализа нет. Провал прочитался как результат.

ЧТО СТАЛО. Отчёт едет одним полем `report_md` и рисуется как написан. Разбора
нет — терять нечего. Уровень риска — поднавык (#158, объектив lenses/risk.md), а
не слово, которое код выискивает в тексте; карточка принимает готовый профиль
параметром и сама из текста ничего не выводит.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from finengine.skills.analysis import framework as fw  # noqa: E402
from finengine.skills.analysis.parse import parse_report  # noqa: E402

_FULL = (
    "# Финансовый анализ — Х\n\n"
    "## Резюме\n\nСостояние устойчивое.\n\n"
    "## Ключевые показатели\n\n"
    "| Показатель | 2024 | 2023 | Δ%/оценка |\n|---|---|---|---|\n"
    "| Выручка | 100 | 90 | +11% / **Критический** (обвал) |\n\n"
    "## Выводы\n\n1. Рост опережает инфляцию.\n"
)


def test_report_reaches_the_card_verbatim():
    """Текст отчёта доезжает целиком и в своём порядке."""
    card = parse_report(_FULL, company="Х")
    report = card["report_md"]

    for fragment in ("Резюме", "Состояние устойчивое",
                     "Ключевые показатели", "| Выручка | 100 | 90 |",
                     "Выводы", "Рост опережает инфляцию"):
        assert fragment in report, f"из отчёта пропало: {fragment}"
    assert report.index("Резюме") < report.index("Выводы"), "порядок разделов сбит"


def test_nothing_is_derived_from_the_text():
    """Ни разделов, ни KPI, ни вердикта, ни уровня — код их больше не выводит.

    В `_FULL` есть всё, за что цеплялся прежний разбор: заголовок «Резюме»
    (роль verdict), заголовок «Ключевые показатели» (роль kpi), таблица со
    словом «Критический» в ячейке, заголовок «Выводы». Ни одно из этого не
    должно превратиться в поле карточки.
    """
    card = parse_report(_FULL, company="Х")

    assert card["sections"] == []
    assert card["kpi"] == []
    assert card["verdict"] == ""
    assert card["conclusions"] == []
    assert card["strengths"] == [] and card["watch"] == []
    assert card["risk_profile"] is None, (
        "уровень выведен из текста — ровно то, что запрещено (#158)")


def test_the_words_итоговый_уровень_are_not_a_trigger():
    """Строка «ИТОГОВЫЙ УРОВЕНЬ: …» — обычный текст отчёта, а не команда коду.

    Регулярка по ней стояла с 09.08 и выглядела как «канал от аналитика». По
    сути это был тот же поиск ключевого слова в прозе; владелец 11.08 запретил
    прямо: «Никаких поиска слов итоговый уровень».
    """
    md = _FULL + "\nИТОГОВЫЙ УРОВЕНЬ: критический — ковенанты нарушены\n"
    card = parse_report(md, company="Х")

    assert card["risk_profile"] is None
    assert "ИТОГОВЫЙ УРОВЕНЬ" in card["report_md"], "строка потеряна из текста"


def test_explicit_profile_is_respected():
    """Готовый профиль, переданный вызывающим, карточка берёт.

    Это вход от вызывающего, а не догадка по тексту, — и это точка, через
    которую подключится объектив риска (#158).
    """
    profile = {"level": "critical", "label": "Критический", "why": ["ковенанты"]}
    card = parse_report(_FULL, company="Х", risk_profile=profile)

    assert card["risk_profile"] == profile


def test_report_without_any_heading_survives():
    """Отчёт без единого заголовка доезжает целиком.

    Ровно случай ФосАгро 11.08: прежний разбор возвращал ноль разделов, и
    карточка выходила пустой.
    """
    plain = "Компания нарастила выручку на 11%, долговая нагрузка снизилась."
    card = parse_report(plain, company="Х")

    assert card["report_md"] == plain


def test_duplicates_of_what_the_card_draws_itself_are_cut():
    """Из текста снимаются ровно два дубля — и ничего больше.

    H1 документа дублирует шапку карточки; раздел внешнего контекста от модели
    дублирует список, который карточка рисует сама — но БЕЗ ссылок и дат, и
    встаёт вплотную к выверенным числам (#159).
    """
    md = (f"# Финансовый анализ — Х\n\n## Резюме\n\nУстойчиво.\n\n"
          f"## {fw.EXTERNAL_SECTION_TITLE}\nПожар на складе.\n")
    report = parse_report(md, company="Х")["report_md"]

    assert "Финансовый анализ — Х" not in report
    assert fw.EXTERNAL_SECTION_TITLE not in report
    assert "Пожар на складе" not in report
    assert "Резюме" in report and "Устойчиво" in report
