"""Справочник ячейки назван в теле навыка — по ПУТИ, а не по формулировке.

🔴 ИЗ ЭТОГО ФАЙЛА УБРАНЫ ЧЕТЫРЕ ТЕСТА ИЗ ПЯТИ (решение владельца 25.08.2026).

Они пришпиливали ФОРМУЛИРОВКИ промпта: искали в `aifa-calc/SKILL.md` и в
конституции подстроки «НЕТ В РЕЕСТРЕ», «рядом с числом», «одно название»,
«методику молча», «Определения РЕЕСТРА не переписывай», «Своих формул не
предлагай».

Довод владельца: «мы будем менять промпты ещё тысячу раз, каждый раз
переписывать сторожей — бред». Он прав, и на этих тестах это видно прямо:
за неделю два из них переписывались вслед за переформулировками, и краснели
они не потому, что правило исчезло, а потому что его сказали иначе.

⚠️ ЧЕГО ЭТИ ТЕСТЫ НЕ ДЕЛАЛИ, ХОТЯ ИХ ИМЕНА ОБЕЩАЛИ. Ни один не смотрел на
ОТВЕТ агента. `test_one_name_means_one_value_within_a_chat` звучал как
проверка «одна величина — одно число в разговоре», а на деле открывал файл и
искал в нём фразу. Настоящей проверки этого правила нет и не было: код нигде
не сверяет два ответа между собой и не помнит, каким определением считали
раньше. Правило держится только на том, что модель его прочитает.

САМИ ПРАВИЛА ИЗ ПРОМПТА НЕ УДАЛЕНЫ — снят лишь текстовый сторож над ними.
Выкинуть правило намеренно можно и теперь, но это правка навыка, и она видна
в ревью; сломать его синонимом больше нельзя.

ОСТАЛОСЬ здесь то, что от формулировок не зависит: ПУТЬ к справочнику. Он —
контракт между телом навыка и файловой раскладкой полки: переименуют каталог
или уедет `method/catalogue/` — модель пойдёт искать реестр по памяти, а
памяти о реестре ячейки у неё нет.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CALC = ROOT / "station-skills" / "aifa-calc" / "SKILL.md"


def test_the_catalogue_path_is_named_in_the_skill():
    """«Нет в реестре» — проверенный факт, а проверить его можно только по пути.

    🔴 СЕКЦИЮ БОЛЬШЕ НЕ ФИКСИРУЕМ (27.08.2026). Сторож требовал путь именно в
    «Порядке работы». Но проверка «есть ли показатель в реестре» — это ПРАВИЛО
    («не гадай по памяти»), а не шаг запуска, и место ей в «Правилах». Держать
    её в одной секции значило пришпилить композицию текста, а предмет здесь —
    путь: переименуют каталог, и модель пойдёт искать реестр по памяти, которой
    у неё нет.
    """
    order = CALC.read_text(encoding="utf-8")
    assert "method/catalogue/" in order, (
        "в теле навыка не сказано, ГДЕ смотреть реестр. Без пути к "
        "справочнику «такого показателя нет» — догадка по памяти, а память у "
        "модели про реестр ячейки пустая: целиком она его никогда не видела")


def test_the_catalogue_path_actually_exists():
    """Путь в промпте обязан существовать на диске.

    Без этой пары первый тест сторожил бы букву: строка на месте, а каталога
    нет — и модель уходит в ENOENT ровно там, где мы обещали ей справочник.
    """
    каталог = ROOT / "station-skills" / "aifa-extract" / "method" / "catalogue"
    assert каталог.is_dir(), f"каталога справочников нет: {каталог}"
    ячейки = sorted(p.name for p in каталог.glob("*.md") if not p.name.startswith("_"))
    assert len(ячейки) >= 8, (
        f"справочников ячеек всего {len(ячейки)} ({ячейки}) — реестр неполон, "
        "и часть отчётностей окажется без описаний показателей")
