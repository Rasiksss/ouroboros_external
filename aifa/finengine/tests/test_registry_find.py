"""Мост «слова человека → имена реестра» (Ш13, тул fe_registry_find).

ПОЧЕМУ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Сценарий владельца §5.2 — «извлеки выручку,
чистую прибыль, EBITDA и активы» — невыразим, пока у тула извлечения нет
аргумента «список показателей». А чтобы список передать, его надо УМЕТЬ
ПОЛУЧИТЬ: модель не обязана знать наши enum'ы, пользователь тем более.

Поиск детерминированный НАМЕРЕННО. Сопоставление имени показателя — справочник,
а не суждение; модель ошибается на нём ТИХО: вернёт похожий enum, движок
послушно извлечёт не тот показатель, и подмену будет не по чему заметить.

Тесты писались от РЕАЛЬНЫХ формулировок и поймали два настоящих дефекта:

1. «активы» находило «Активы в форме права пользования» вместо «Итого активы»
   (премия за начало строки давалась только имени, а нужное слово у TOTAL_ASSETS
   живёт в СИНОНИМЕ «Активы всего»);
2. «долг/EBITDA» не находилось вовсе — в реестре это «Отношение общего долга к
   EBITDA»: слова те же, но в другом порядке и с разрывом, а поиск умел только
   непрерывную подстроку.

Оба — ровно та тихая подмена, ради предотвращения которой всё и делается.
"""
from __future__ import annotations

import pytest

from finengine.skills.registry_find import find_metrics

CELL = "ifrs_nf_ru"


def _top(q: str, cell: str = CELL) -> str | None:
    r = find_metrics([q], cell, limit=3)
    ms = r["matches"].get(q) or []
    return ms[0]["enum"] if ms else None


# ── что говорит аналитик ──────────────────────────────────────────────────

@pytest.mark.parametrize(("query", "expected"), [
    ("выручка", "SALES_REVENUE"),
    ("чистая прибыль", "NET_INCOME"),
    ("активы", "TOTAL_ASSETS"),
    ("рентабельность активов", "ROA"),
    ("свободный денежный поток", "FREE_CASH_FLOW"),
    ("долг/EBITDA", "RATIO_TOTAL_DEBT_EBITDA"),
    ("SALES_REVENUE", "SALES_REVENUE"),
])
def test_analyst_words_resolve_to_the_right_metric(query, expected):
    assert _top(query) == expected, (
        f"«{query}» ведёт не туда — движок извлечёт не тот показатель, и "
        f"заметить это будет негде"
    )


def test_generic_word_finds_the_general_metric_not_a_narrow_one():
    """Дефект №1 в чистом виде: короткое общее слово обязано вести к общему
    показателю, а не к первому, чьё имя с него начинается."""
    assert _top("активы") == "TOTAL_ASSETS"
    top3 = [m["enum"] for m in find_metrics(["активы"], CELL, limit=3)["matches"]["активы"]]
    assert top3[0] == "TOTAL_ASSETS", f"порядок сбит: {top3}"


def test_words_in_any_order_with_gaps():
    """Дефект №2: «долг/EBITDA» против «Отношение общего долга к EBITDA».
    Падеж («долг» → «долга») ломать поиск не должен."""
    assert _top("долг/EBITDA") == "RATIO_TOTAL_DEBT_EBITDA"
    assert _top("EBITDA долг") == "RATIO_TOTAL_DEBT_EBITDA"


# ── честный пустой ответ ──────────────────────────────────────────────────

def test_absent_metric_is_reported_absent_not_guessed():
    """Главный выход тула. Подобрать похожее по звучанию — худшее, что можно
    сделать: пользователь получит число не про то, о чём спрашивал."""
    r = find_metrics(["поголовье коров", "выручка"], CELL)
    assert r["not_found"] == ["поголовье коров"]
    assert "поголовье коров" not in r["matches"]
    assert "выручка" in r["matches"], "заодно не потеряли то, что нашлось"
    assert "не подбирай похожий" in r["note"].lower()


def test_bank_metric_is_absent_in_non_financial_cell():
    """Cost/Income — банковский показатель. В нефинансовой ячейке его НЕТ, и
    честный ответ здесь — пустой, а не ближайший по смыслу расход."""
    assert "Cost/Income" in find_metrics(["Cost/Income"], CELL)["not_found"]


# ── #163 на виду, а не под ковром ────────────────────────────────────────

def test_double_registered_metric_is_flagged_not_silently_picked():
    """Шесть показателей заведены И извлекаемыми, И расчётными (#163, решение
    владельца открыто). Тонкий тул делает это ЗАМЕТНЕЕ: на «извлеки EBITDA» и
    «посчитай EBITDA» выйдут разные числа под одним именем. Пока решения нет —
    показываем оба и говорим вслух."""
    ms = find_metrics(["EBITDA"], CELL, limit=4)["matches"]["EBITDA"]
    ebitda = [m for m in ms if m["enum"] == "EBITDA"]
    assert len(ebitda) == 2, "показан только один вариант — расхождение замаскировано"
    assert {m["kind"] for m in ebitda} == {"extractable", "calculated"}
    assert all("#163" in m.get("ambiguous", "") for m in ebitda), (
        "нет пометки о двойной прописке — модель выберет молча"
    )


# ── контракт ответа ──────────────────────────────────────────────────────

def test_answer_carries_what_disambiguates():
    """Подсказка и описание кладутся не для красоты: именно они не дают
    спутать операционные расходы с себестоимостью."""
    m = find_metrics(["выручка"], CELL)["matches"]["выручка"][0]
    assert m["enum"] and m["name_ru"] and m["kind"] == "extractable"
    assert m.get("description") or m.get("hint"), (
        "модели нечем выбрать между похожими показателями"
    )


def test_works_for_every_cell():
    """Восемь ячеек, и ни одна не должна падать: реестры у них разные."""
    from finengine.skills.metric_schema import PROFILE_IDS

    for cell in PROFILE_IDS:
        r = find_metrics(["выручка", "revenue"], cell, limit=1)
        assert isinstance(r["matches"], dict) and isinstance(r["not_found"], list)


# ── 22.08.2026: точная формулировка перестала быть наказанием ─────────────
#
# ЖИВОЙ ПРОГОН ПО СЕВЕРСТАЛИ. Модель выписала входы пяти коэффициентов —
# тринадцать имён, — и ЧЕТЫРЕ из них не опознались вовсе. Не экзотика: «итого
# краткосрочные активы», «приобретения основных средств». Показатели молча
# выпали из просьбы, и человек получил таблицу не о том, что просил.
#
# ДВЕ ПРИЧИНЫ, ОБЕ ОДНОГО РОДА — ПОИСК НАКАЗЫВАЛ ЗА ТОЧНОСТЬ:
#
#   1. сравнение слов шло ТОЛЬКО по началу и ТОЛЬКО в одну сторону. Русский
#      падеж режет иначе: «приобретения» и «Приобретение» расходятся на
#      последней букве, и ни одно не начало другого;
#   2. лишнее слово в просьбе рвало поиск целиком. «Итого краткосрочные активы»
#      не находило TOTAL_CURRENT_ASSETS, хотя его синоним — буквально
#      «Краткосрочные активы», подмножество сказанного.
#
# ⚠️ И РОВНО ЗДЕСЬ ЛЕЧЕНИЕ ЧУТЬ НЕ СТАЛО ХУЖЕ БОЛЕЗНИ. Первая редакция правила
# «имя ⊆ просьба» отдавала на «итого краткосрочные активы» TOTAL_ASSETS
# («Итого активы» — тоже подмножество!). Это МОЛЧАЛИВАЯ ПОДМЕНА, то есть худший
# исход из возможных. Поймано замером до коммита; лечится тем, что непокрытыми
# могут остаться только слова-итоги, а уточнение — никогда.
#
# ПРОВЕРКА СТОРОЖЕЙ ОТКАТОМ (мутации прогнаны 22.08.2026, каждая покраснела):
#   · `_same_word` всегда False (падежная терпимость выключена) → падает
#     «приобретения основных средств». ⚠️ Мутация «убрать `_same_word` ТОЛЬКО
#     из `_tokens_all_in`» зелёная, и это не дыра: имя тогда находится другим
#     уровнем, `_fits_inside_query`, который зовёт ту же `_same_word`. Ломать
#     надо ПРЕДМЕТ, а не одну из двух его площадок;
#   · убрать уровень `_NAME_INSIDE_QUERY` → падает «итого краткосрочные активы»;
#   · разрешить оставлять непокрытым любое слово (снять проверку `_FILLER`) →
#     падает `test_an_extra_qualifier_is_never_ignored`.

@pytest.mark.parametrize(("query", "expected"), [
    ("приобретения основных средств", "ASSET_PURCHASES"),   # падеж
    ("итого краткосрочные активы", "TOTAL_CURRENT_ASSETS"),  # лишнее «итого»
    ("итого краткосрочные обязательства", "TOTAL_CURRENT_LIABILITIES"),
    ("долгосрочное долговое финансирование", "LONG_TERM_DEBT"),  # синоним-зеркало
])
def test_a_precise_wording_is_understood(query, expected):
    assert _top(query) == expected, (
        f"«{query}» не опознано — показатель молча выпадет из просьбы человека, "
        "как выпали четыре из тринадцати 22.08 по Северстали")


def test_an_extra_qualifier_is_never_ignored():
    """«Краткосрочные» — не мусор: им один показатель отличается от другого.

    Молчаливая подмена хуже пустого ответа: движок послушно извлечёт не тот
    показатель, и признака подмены не будет ни одного.
    """
    assert _top("итого краткосрочные активы") != "TOTAL_ASSETS", (
        "уточнение «краткосрочные» проигнорировано и отдан ДРУГОЙ показатель")
    assert _top("итого долгосрочные обязательства") != "TOTAL_LIABILITIES", (
        "уточнение «долгосрочные» проигнорировано")


def test_close_but_different_words_are_not_glued():
    """«Капитал» и «капитальные» делят корень, но это разные слова."""
    assert _top("капитальные затраты") == "CAPEX"
    assert _top("собственный капитал") == "TOTAL_EQUITY"
