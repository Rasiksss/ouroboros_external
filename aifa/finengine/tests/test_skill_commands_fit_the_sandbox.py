from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / "agent-workspace" / "bootstrap" / "TOOLS.md"
SKILLS = sorted(d for d in (ROOT / "station-skills").iterdir()
                if d.is_dir() and (d / "SKILL.md").is_file())

# Команда в теле навыка — строка в обратных кавычках, в которой есть запуск.
# Не всякий инлайн-код команда: `--out-json`, `ok: true`, имена файлов тоже в
# кавычках. Отбираем по признаку запуска, иначе сторож начнёт ругаться на текст.
_RUNS = ("python3 ", "bash ", "sh ", "python -m", "python3 -m")


def _commands(body: str) -> list[str]:
    return [m for m in re.findall(r"`([^`]{6,400})`", body)
            if any(r in m for r in _RUNS)]


def test_the_constitution_says_where_the_agent_stands():
    """Модель обязана знать, что она уже в рабочей папке и что `/workspace` нет.

    Это не деталь навыка, а свойство комнаты — одно на все четыре. Пока его не
    было написано нигде, модель заполняла пробел догадкой, и догадка была
    неверной.
    """
    body = TOOLS.read_text(encoding="utf-8")
    # Пути и имя команды — контракт; формулировки «не существует» здесь больше
    # нет, она пришпиливала текст.
    assert "/workspace" in body, (
        "в конституции не назван каталог /workspace — модель снова пойдёт "
        "искать файлы там, где его нет")
    assert "cd" in body, "не сказано, что `cd` добавлять не надо"
    assert "ls -la" in body, (
        "запретили искать по абсолютным путям, но не сказали ЧЕМ смотреть. "
        "Запрет без замены модель обойдёт")
    assert "complex interpreter invocation" in body, (
        "не назван текст отказа песочницы: модель не свяжет его с правилом и "
        "будет чинить команду наугад")


@pytest.mark.parametrize("skill", SKILLS, ids=lambda d: d.name)
def test_no_skill_hands_the_model_a_command_the_sandbox_refuses(skill: Path):
    """Ни одна команда в теле навыка не составная и не по абсолютному пути."""
    body = (skill / "SKILL.md").read_text(encoding="utf-8")
    for cmd in _commands(body):
        assert not re.search(r"(^|\s)cd\s", cmd), (
            f"{skill.name}: в команде есть `cd` — песочница отобьёт составную "
            f"команду, а рабочий каталог и так верный: {cmd[:120]!r}")
        assert "&&" not in cmd, (
            f"{skill.name}: команда составная через `&&`: {cmd[:120]!r}")
        assert ";" not in cmd, (
            f"{skill.name}: команда составная через `;` — эстафету делает "
            f"обёртка, а не модель: {cmd[:120]!r}")
        assert "/workspace/" not in cmd, (
            f"{skill.name}: абсолютный путь /workspace — из exec он недостижим: "
            f"{cmd[:120]!r}")


@pytest.mark.parametrize("skill", SKILLS, ids=lambda d: d.name)
def test_python_scripts_are_called_without_an_env_prefix(skill: Path):
    """Питон-скрипты модель зовёт голой командой, нонс — флагом.

    Приставка `ПЕРЕМЕННАЯ=значение` перед `python3` сама по себе правило ядра НЕ
    нарушает — это проверено по его коду. Но она делает команду на шаг ближе к
    составной, и 19.08 модель, начав с такой формы, дописала к ней `cd … &&`.
    Форма, которую нельзя испортить, лучше формы, которую можно.

    `bash файл.sh` под это правило не подпадает: у обёрток нонс приходит флагом
    `--nonce`, а переменную они экспортируют себе сами.
    """
    body = (skill / "SKILL.md").read_text(encoding="utf-8")
    for cmd in _commands(body):
        if "python3 " not in cmd:
            continue
        assert not re.match(r"^[A-Z_][A-Z0-9_]*=", cmd.strip()), (
            f"{skill.name}: питон зовётся с приставкой-переменной, а нонс должен "
            f"приходить флагом `--nonce`: {cmd[:120]!r}")


