    cat = ROOT / "station-skills" / "aifa-extract" / "method" / "catalogue"
    cells = sorted(p.stem for p in cat.glob("*.md") if not p.stem.startswith("_"))
    assert len(cells) >= 10, f"справочник неполон: ячеек {len(cells)}"
    from finengine.skills.metric_schema import PROFILE_IDS

    reg = sorted(PROFILE_IDS)
    assert cells == reg, (
        f"справочник и реестр разошлись по составу ячеек: {set(cells) ^ set(reg)}")


