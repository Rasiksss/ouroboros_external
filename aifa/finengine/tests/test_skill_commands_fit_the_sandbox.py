def test_the_registry_catalogue_travels_to_the_model():
    """Справочник ячейки — в белом списке синхронизации воркспейса.

    Без этого «есть ли у вас такой показатель» стоит двадцатиминутного прогона
    вслепую, а модель узнаёт ответ по пустой клетке.
    """
    sync = (ROOT / "deploy" / "sync_workspace_skills.sh").read_text(encoding="utf-8")
    # ⚠️ СМОТРИМ НА КОД, А НЕ НА КОММЕНТАРИЙ. Первая редакция искала строку по
    # всему файлу и была ЗЕЛЕНОЙ при вырезанной команде: путь остался в
    # объяснении выше. Поймано отрицательным контролем — сторож охранял текст.
    body = sync.split("skill_files() {", 1)[1].split("}", 1)[0]
    assert "method/catalogue/*.md" in body, (
        "справочник не едет в воркспейс — модель снова не сможет его прочитать "
        "и будет узнавать состав реестра прогоном")
    assert "SKILL.md" in body, "из белого списка пропало само тело навыка"
    assert "scripts" not in body, (
        "в белый список синхронизации попали скрипты: справочник — данные, "
        "скрипты — код, и им место на полке, а не рядом с телом навыка")
