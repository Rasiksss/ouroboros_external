"""Сообщения модели не слипаются в одно слово.

ЖАЛОБА ВЛАДЕЛЬЦА 20.08: «агент явно криво пишет свои размышления». На экране:

    …и сразу распакую полХорошо, отчёт классифицирован — МСФО…
    …классификацию.Классификация: МСФО, нефинансовая компания…
    …Посчитаю все запрошенные показатели однимвызовом.Отлично, инструмент…

Это не модель пишет криво. Ответ хода собирается из НЕСКОЛЬКИХ сообщений
модели — одно до вызова инструмента, другое после, — и `_extract_text` клеил их
тексты подряд без единого знака между ними. Модель оборвала фразу на слове
«полку», позвала инструмент и начала новое сообщение; на экране вышло
«полХорошо».

Внутри ОДНОГО сообщения куски — поток одной фразы, их клеить подряд правильно.
Между сообщениями нужна пустая строка: это разные высказывания.

ПРОВЕРКА СТОРОЖА ОТКАТОМ: вернуть общий аккумулятор `text +=` по всем
сообщениям — первый тест обязан покраснеть на «полХорошо».
"""
from __future__ import annotations

from finengine.llm.openclaw import _extract_text


def _msg(*parts: str) -> dict:
    return {"type": "message",
            "content": [{"type": "output_text", "text": p} for p in parts]}


def test_two_messages_do_not_glue_into_one_word():
    """Ровно случай владельца: фраза оборвана вызовом инструмента."""
    resp = {"output": [_msg("и сразу распакую пол"),
                       {"type": "function_call", "name": "fe_classify_report"},
                       _msg("Хорошо, отчёт классифицирован")]}
    got = _extract_text(resp)
    assert "полХорошо" not in got, (
        f"сообщения снова склеены в одно слово: {got!r}. Пользователь читает "
        f"это как сбой агента")
    assert got == "и сразу распакую пол\n\nХорошо, отчёт классифицирован"


def test_parts_inside_one_message_stay_together():
    """Куски одного сообщения — это поток одной фразы, разрывать их нельзя."""
    assert _extract_text({"output": [_msg("Отчёт ", "классифицирован")]}) == \
        "Отчёт классифицирован"


def test_the_ready_output_text_still_wins():
    """Готовое поле ответа сильнее сборки по кускам — путь не тронут."""
    assert _extract_text({"output_text": "готовый ответ",
                          "output": [_msg("не отсюда")]}) == "готовый ответ"


def test_empty_messages_do_not_add_blank_lines():
    """Пустое сообщение не должно рождать лишний разрыв в ответе."""
    resp = {"output": [_msg("первое"), _msg("   "), _msg("второе")]}
    assert _extract_text(resp) == "первое\n\nвторое"


def test_no_output_is_an_empty_answer_not_a_crash():
    assert _extract_text({}) == ""
    assert _extract_text({"output": []}) == ""
