"""Общий базис доезжает до БОЕВОГО пути анализа (#121).

ЧТО БЫЛО. Шина заземления наполнялась диспетчером, а забор с неё стоял внутри
инлайн-ветки `_h_fe_analyze` — той, что не исполняется ни на dev, ни на проде
(`FE_ENGINE_IN_STATION=1`). Станционный анализ каждый раз заземлялся СВОИМ
прогоном движка: по одному отчёту выходило два независимых прохода, и они
расходились — замер дал 15 нестабильных показателей из 114.

Здесь защищается ровно то, что чинилось: забор стоит ДО развилки, показатели
доезжают в станцию, а станция при их наличии второго прохода не делает.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TOOLS = (REPO / "src" / "finengine" / "llm" / "tools.py").read_text(encoding="utf-8")
DRIVER = (REPO / "src" / "finengine" / "skills" / "station_driver.py").read_text(encoding="utf-8")
STATION = (REPO / "station-skills" / "aifa-analyze" / "scripts" / "analyze.py").read_text(
    encoding="utf-8")


def test_station_has_no_pass_of_its_own_at_all():
    """#238: своего прохода движка у анализа НЕТ — ни в ветке, ни в фолбэке.

    Раньше здесь стояли две проверки: «получил готовое — второй проход не
    делает» и «спросили анализ отдельно — заземляется сам». Вторая защищала
    фолбэк, который и оказался дырой: ошибка движка в нём не валила анализ
    («идём дальше без справки-таблицы»), и числа в выводах брались моделью
    прямо из текста отчёта. Отличить такой разбор в выдаче невозможно, поэтому
    ветка снята целиком, а отказ поднят в `main`.
    """
    assert "extract_stream_from_text(" not in STATION, (
        "у анализа снова свой проход движка — числа в выводах разойдутся с таблицей")
    assert "if ready_metrics" not in STATION, (
        "вернулась развилка «есть таблица / нет таблицы»: таблица теперь обязательна")


def test_station_refuses_without_the_table():
    """Отказ ГРОМКИЙ и отдельным кодом возврата, а не тихим продолжением."""
    assert '"--metrics", required=True' in STATION, "флаг таблицы снова необязателен"
    assert "SystemExit(4)" in STATION, "пустая таблица не отбивается кодом возврата"
