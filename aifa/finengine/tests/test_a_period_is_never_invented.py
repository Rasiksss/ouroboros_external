# ───────── вторая линия обороны: год обязан нести значения ─────────


def test_a_year_with_labels_but_no_values_is_not_the_run_year():
    """🔴 МЕТКА БЕЗ ЗНАЧЕНИЯ НИЧЕГО НЕ ДОКАЗЫВАЕТ.

    `pick_periods` доверяет периоду, названному движком, если год «встречается
    в показателях». На KBC движок назвал выдуманную дату `20.12.2024`, и
    проверка её ПРОПУСТИЛА: год 2024 встречался пять раз — все пять в метках
    без единого значения (дата аудиторского заключения). Таблица построилась по
    колонкам 2024/2023 и вышла пустой при 73 найденных показателях.

    Это вторая линия обороны, независимая от разбора периодов: даже когда
    движок ошибся, таблица обязана строиться по годам, где есть данные.

    Мутация: считать метки вместо значений — тест краснеет.
    """
    from finengine.skills.extract_present import pick_periods

    # ⚠️ ОБА года движка присутствуют В МЕТКАХ и оба без значений — ровно как в
    # прогоне KBC (2024 пять раз, 2023 четыре). Первая редакция теста давала
    # только 2024, и проверка отваливалась по отсутствию 2023: мутация
    # «считать метки» его не краснила.
    метрики = [
        {"enum": "AUDIT", "period_values": [
            {"period": "12M 20.12.2024", "value": None},
            {"period": "12M 20.12.2023", "value": None}]},
        *[{"enum": f"M{i}", "period_values": [
            {"period": "31.03.2026", "value": 1.0},
            {"period": "31.12.2025", "value": 2.0}]} for i in range(20)],
    ]

    assert pick_periods(метрики, ("20.12.2024", "20.12.2023")) == ("2026", "2025")
    # А когда движок называет год, в котором значения ЕСТЬ, — его и слушаем.
    assert pick_periods(метрики, ("Q1 2026", "Q1 2025")) == ("2026", "2025")


def test_a_period_that_has_not_ended_is_dropped():
    """🔴 ОТЧЁТ НЕ МОЖЕТ ОТЧИТЫВАТЬСЯ ЗА КВАРТАЛ, КОТОРЫЙ ЕЩЁ ИДЁТ.

    У KBC в разделе финансового календаря значатся будущие публикации
    («3Q2026 earnings release: 12 November 2026»), и детектор брал оттуда
    `Q3 2026` как законный период — самый поздний, значит побеждал.

    Отличать календарь от отчёта по словам («earnings release») нельзя: такое
    правило ломается на первой чужой формулировке. Здесь арифметика: мы читаем
    документ СЕЙЧАС, и период, который на данный момент не закончился, отчётным
    быть не может — данных за него не существует ни у кого.

    Мутация: убрать фильтр — тест краснеет.
    """
    from datetime import date, timedelta

    from finengine.skills.bulk_extractor.period_selection import (
        _drop_periods_ending_after_today,
    )

    через_год = date.today().year + 1
    прошлые = ["Q1 2020", "FY 2019"]

    assert _drop_periods_ending_after_today([f"Q4 {через_год}", *прошлые]) == прошлые
    assert _drop_periods_ending_after_today(прошлые) == прошлые
    # Опустошать список нельзя: остаться без периодов хуже, чем оставить лишний.
    assert _drop_periods_ending_after_today([f"Q4 {через_год}"]) == [f"Q4 {через_год}"]
    del timedelta


