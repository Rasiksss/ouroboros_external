def test_the_cover_period_wins_when_it_is_the_only_one_named():
    """🔴 СТРУКТУРНОЕ СВИДЕТЕЛЬСТВО ВМЕСТО ПРАВИЛА ПРО СЛОВА.

    У KBC в разделе финансового календаря расписание будущих публикаций
    («2Q2026 earnings release: 6 August 2026»), и `Q2 2026` побеждал как самый
    поздний из ЗАКРЫВШИХСЯ — арифметикой его не отсечь, он действительно
    кончился. Отличать расписание от отчёта по словам («earnings release»)
    нельзя: сломается на первой чужой формулировке.

    А отчёт называет свой период на обложке, и это проверяемо: у KBC первые
    полторы тысячи символов дают ровно один кандидат — `Q1 2026`.

    Мутация: снять правило обложки — тест краснеет.
    """
    from finengine.skills.bulk_extractor.period_selection import (
        _prefer_period_named_on_the_cover as по_обложке,
    )

    кандидаты = ["Q2 2026", "Q1 2026", "Q4 2025"]
    assert по_обложке(кандидаты, "KBC Group\n\nQuarterly Report\n\n1Q2026\n")[0] == "Q1 2026"


def test_the_cover_rule_stays_silent_when_it_has_no_evidence():
    """Правило нарочно узкое — три случая, когда оно НЕ вмешивается.

    Так ведут себя БСПб и Nordea: у них титул периода не называет, и порядок
    остаётся прежним. Правило, которое срабатывает всегда, было бы догадкой.
    """
    from finengine.skills.bulk_extractor.period_selection import (
        _prefer_period_named_on_the_cover as по_обложке,
    )

    кандидаты = ["Q2 2026", "Q1 2026"]
    assert по_обложке(кандидаты, "Годовой отчёт") == кандидаты, "обложка молчит"
    assert по_обложке(кандидаты, "сравнение 1Q2026 и 4Q2025") == кандидаты, "названо несколько"
    assert по_обложке(["Q2 2026", "Q4 2025"], "отчёт 1Q2026") == ["Q2 2026", "Q4 2025"], (
        "обложка назвала период, которого нет среди кандидатов — добавлять нельзя")
    assert по_обложке(["Q1 2026"], "отчёт 1Q2026") == ["Q1 2026"], "один кандидат — нечего менять"
