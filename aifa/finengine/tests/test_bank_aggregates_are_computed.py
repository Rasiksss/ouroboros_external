"""Банковские агрегаты складываются, и что выделено — не входит (решения 19.08).

ЧЬИ ЭТО РЕШЕНИЯ. Владелец разобрал четыре спорных показателя, где правило
реестра расходилось с эталонной разметкой, и вынес по каждому вердикт. Это
ДОМЕННЫЕ решения аналитика, а не выводы из кода: здесь они закреплены, чтобы
следующая правка не «починила» их обратно по красному бенчмарку.

ГЛАВНОЕ ИЗ СКАЗАННОГО ВЛАДЕЛЬЦЕМ:

  «Не очень понимаю, почему были наложены столь жёсткие ограничения на расчёты,
   многие показатели, особенно у банков, требуют вычислений. Кстати поэтому у
   нас реколл и низкий при высоком пресижне.»

Замер это подтверждает: 19.08 по банкам точность 93–96 %, полнота 81–89 %.
Подсказок семейства «нет отдельной строки → верни пусто» в реестре 69 штук.

  «Принцип такой, что там, где существует выделение в отдельную сущность —
   она сохраняет за собой самостоятельность.»

То есть: агрегат складывается ИЗ ВСЕГО, кроме того, для чего в реестре есть
свой показатель.

⚠️ ЗАКРЫТЫЕ ПЕРЕЧНИ СЛАГАЕМЫХ ВЛАДЕЛЕЦ ОТКЛОНИЛ: «если мы опустимся на подобный
уровень описания, мы потеряем агентность». Поэтому правило живёт ТЕКСТОМ в
подсказке показателя, а не формулой в коде. Промпт извлечения это понимает
буквально: агрегировать разрешено, только если это «explicitly permitted by
that metric's registry hint» (`finengine2_prompts.py`).

🔴 РАСХОЖДЕНИЕ С РАЗМЕТКОЙ, ПРИНЯТОЕ ОСОЗНАННО. По чистому процентному доходу
владелец сказал «реестр прав» — берём строку ПОСЛЕ резервов. Все 14 русских
банковских эталонов размечены ДО резервов, значит замер по этому показателю
будет показывать расхождение НАМЕРЕННО. Не «чинить» по красному бенчу.

ПРОВЕРКА СТОРОЖЕЙ ОТКАТОМ: вернуть в любую из подсказок «нет отдельной строкой
— null» вместо разрешения складывать — покраснеет свой тест.

🔴 РЕВИЗИЯ 21.08: ГДЕ ЧИТАЕТСЯ ПОДСКАЗКА. До сегодня файл читал JSON ячейки
`src/finengine/data/registry/ifrs_bank_ru.json` напрямую — то есть охранял
СОДЕРЖИМОЕ ФАЙЛА, а не то, что уходит в модель. Теперь подсказка берётся из
БЛОКА ПРОМПТА боевой (двухстадийной) схемы, собранного живьём:
`registry_for_profile` → `_merge_aliases_from_base` → `_metric_info_blocks`.
Разница не косметическая: сорвётся загрузка ячейки, слетит слияние синонимов
или сборщик перестанет печатать `Где искать:` — файл на диске не изменится, и
прежняя редакция осталась бы зелёной при пустом промпте.

⚠️ ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ. Он доводит правило ДО МОДЕЛИ и на этом
останавливается: подействует ли «СКЛАДЫВАЙ» на извлечение — тест сказать не
может, это решает модель. Полноту по агрегатам меряет бенчмарк, не набор тестов.
"""
from __future__ import annotations

import pytest

from finengine.skills.bulk_extractor import _merge_aliases_from_base
from finengine.skills.metric_schema import registry_for_profile
from finengine.skills.two_stage_extractor import _metric_info_blocks

CELL = "ifrs_bank_ru"
# Строки ячейки в том виде, в каком их получает сборщик промпта боевой схемы
# (`two_stage_extractor._assemble_registry`, ветка `registry_override`).
BY = {m["enum"]: m for m in _merge_aliases_from_base(
    registry_for_profile(CELL)["extractable"], "bank")}


def _hint(enum: str) -> str:
    """Строка «Где искать» ИЗ ПРОМПТА — то, что реально прочтёт модель."""
    assert enum in BY, f"{enum} исчез из ячейки {CELL}"
    block = _metric_info_blocks([BY[enum]])[0]
    line = next((ln for ln in block.splitlines() if ln.startswith("  Где искать: ")), "")
    assert line, f"{enum}: подсказка не доехала до блока промпта — модель её не увидит"
    return line[len("  Где искать: "):]


AGGREGATES = ["SECURITIES_ASSETS", "SECURITIES_FVPL", "DEBT_SECURITIES_ISSUED",
              "ECL_ALLOWANCE_STAGE1", "ECL_ALLOWANCE_STAGE2", "ECL_ALLOWANCE_STAGE3"]


@pytest.mark.parametrize("enum", AGGREGATES)
def test_the_hint_permits_aggregation(enum: str):
    """Складывать РАЗРЕШЕНО явно — промпт понимает только явное разрешение."""
    hint = _hint(enum)
    assert "СКЛАДЫВАЙ" in hint, (
        f"{enum}: в подсказке нет разрешения складывать. Промпт извлечения "
        f"агрегирует только по явному разрешению подсказки, и без него движок "
        f"вернёт пусто — это и есть низкая полнота при высокой точности")


@pytest.mark.parametrize("enum", AGGREGATES)
def test_the_hint_no_longer_orders_an_empty_answer(enum: str):
    """Снято «нет отдельной строкой — null»: это и душило полноту."""
    hint = _hint(enum).lower()
    for phrase in ("нет отдельной строкой - null", "не раскрыт отдельно - null",
                   "если такой категории нет отдельной строкой"):
        assert phrase not in hint, (
            f"{enum}: подсказка снова велит вернуть пусто вместо суммы: {phrase!r}")


def test_what_has_its_own_metric_stays_out_of_the_aggregate():
    """Принцип владельца: выделенное в отдельную сущность самостоятельно.

    Два проверяемых случая, оба с числами прогона РСХБ за 1 кв. 2026:
      * заложенные по репо (108 718) — свой показатель REPO_PLEDGED_SECURITIES,
        поэтому «ценные бумаги в активе» = торговые 55 773 + инвестиционные
        360 973 = 416 746, а НЕ 525 464 как в разметке;
      * субординированные обязательства (189 857) — свой показатель, поэтому
        выпущенные долговые = векселя 39 585 + облигации 114 943 = 154 528.
    """
    assert "REPO_PLEDGED_SECURITIES" in _hint("SECURITIES_ASSETS"), (
        "в подсказке не назван показатель, который НЕ входит в агрегат — "
        "движок сложит репо дважды")
    assert "REPO_PLEDGED_SECURITIES" in BY, "показатель репо исчез из ячейки"

    debt = _hint("DEBT_SECURITIES_ISSUED").lower()
    assert "субординированн" in debt and "не включай" in debt, (
        "в подсказке выпущенных долговых не сказано, что субординированный долг "
        "имеет свой показатель и в агрегат не входит")


def test_net_interest_income_follows_the_owner_not_the_markup():
    """ЧПД — строка ПОСЛЕ резервов. Решение владельца против разметки.

    ⚠️ Этот тест закрепляет ОСОЗНАННОЕ расхождение. В эталонах NET_INTEREST_INCOME
    размечен до резервов, и замер будет это показывать. Правка «по красному
    бенчу» здесь запрещена — сперва спросить владельца.
    """
    hint = _hint("NET_INTEREST_INCOME")
    assert "ПОСЛЕ резервов" in hint, (
        "подсказка снова велит брать доход ДО резервов — это отменяет решение "
        "владельца 19.08 и меняет смысл показателя на всех банках")
    block = _metric_info_blocks([BY["NET_INTEREST_INCOME"]])[0]
    aliases = next(ln for ln in block.splitlines() if "называться" in ln)
    assert "после резерв" in aliases.lower(), (
        "формы «после резервов» нет в СПИСКЕ СИНОНИМОВ ПРОМПТА — движок не "
        "узнает строку. Синоним мог остаться в реестре и быть вытеснен "
        "потолком `merge_aliases`: там его и надо искать")
