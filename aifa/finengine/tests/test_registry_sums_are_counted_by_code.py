def _class_hints() -> list[tuple[str, str, str]]:
    """Пары «ячейка + показатель» с подсказкой класса «нет строки — верни пусто»."""
    found: list[tuple[str, str, str]] = []
    for cell in PROFILE_IDS:
        for metric in registry_for_profile(cell).get("extractable", []):
            hint = metric.get("hint") or ""
            for phrase in re.split(r"(?<=[.;])\s+", hint):
                if _COUNTER.search(phrase):
                    continue
                if _EMPTY.search(phrase) and _ABSENT.search(phrase) and _LINEISH.search(phrase):
                    found.append((cell, metric["enum"], phrase.strip()))
                    break
    return found


def _formulas(cell: str) -> dict[str, str]:
    return {row[0]: row[2] for row in registry_for_profile(cell).get("calculated", [])}


def test_the_class_is_not_empty():
    """Предикат обязан кого-то находить: молчащий сторож не сторож."""
    assert len(_class_hints()) >= 40


@pytest.mark.parametrize("cell,enum,phrase", _class_hints())
def test_every_empty_hint_is_answered(cell: str, enum: str, phrase: str):
    """Либо формула считает, либо в списке записано, почему считать нельзя."""
    if enum in _formulas(cell):
        return
    reason = WITHOUT_FORMULA.get((cell, enum))
    assert reason is not None, (
        f"{cell}/{enum}: подсказка «{phrase}» запрещает модели досчитывать "
        f"величину, формулы в разделе calculated нет, и в списке "
        f"WITHOUT_FORMULA этот показатель не значится.\n"
        f"Либо заведи формулу (слагаемые есть в реестре — группа «а»), либо "
        f"впиши сюда причину, по которой её быть не должно."
    )
    group, why = reason
    assert group in ("б", "в"), f"{cell}/{enum}: группа «{group}» не из (б)/(в)"
    assert len(why) > 20, f"{cell}/{enum}: причина «{why}» ничего не объясняет"


def test_no_stale_exceptions():
    """Показателю завели формулу — строка списка обязана уйти.

    Иначе список превращается в кладбище: он молчит про новые дыры и врёт про
    старые, а читатель верит, что «эти сознательно без формулы».
    """
    stale = sorted(
        f"{cell}/{enum}" for (cell, enum) in WITHOUT_FORMULA if enum in _formulas(cell)
    )
    assert not stale, (
        f"у этих показателей формула ЕСТЬ, а в WITHOUT_FORMULA они числятся "
        f"как «сознательно без формулы»: {stale}"
    )


def test_no_exception_outside_the_class():
    """В списке нет показателей, которых предикат не находит.

    Строка без подсказки класса ничего не стережёт и только мешает читать.
    """
    inside = {(cell, enum) for cell, enum, _ in _class_hints()}
    extra = sorted(f"{cell}/{enum}" for cell, enum in WITHOUT_FORMULA if (cell, enum) not in inside)
    assert not extra, f"в WITHOUT_FORMULA есть показатели вне класса: {extra}"


# ── Группа «а»: формулы, заведённые 20.08.2026 ───────────────────────────────
#
# Пары «ячейка + показатель», у которых слагаемые лежат в реестре той же ячейки
# и сложение — чистый счёт. Проверяем не наличие строки в json, а то, что
# вычислитель по ней РЕАЛЬНО считает: формула с опечаткой в имени слагаемого
# лежит в файле так же тихо, как правильная.
#
# ⚠️ `ifrs_bank_en/SECURITIES_ASSETS` СТОЯЛ ЗДЕСЬ И СНЯТ 20.08.2026. Формулу
# завели по аналогии с русской ячейкой, а определение показателя в английской
# другое: подсказка говорит «marketable securities / short-term investments» и
# слагаемых не называет — то есть правило отбора («подсказка НАЗЫВАЕТ, из чего
# складывать») не выполнено. Счёт по разметке: 13 троек из 21 сходятся, восемь
# расходятся, и семь из восьми — в одну сторону, завышение +23…49 % у трёх
# разных банков. Одностороннее завышение — это систематика, а не шум. Состав
# английского агрегата вынесен владельцу вопросом.
NEW_FORMULAS = [
    ("ifrs_bank_ru", "SECURITIES_ASSETS",
     {"SECURITIES_FVPL": 10.0, "SECURITIES_FVOCI": 20.0, "SECURITIES_AMORTISED_COST": 5.0}, 35.0),
    ("rsbu_nf_ru", "CAPEX",
     {"COMBINED_ASSET_PURCHASES": 90.0, "ASSET_SALES_PROCEEDS": 15.0}, 75.0),
]


@pytest.mark.parametrize("cell,enum,extracted,expected", NEW_FORMULAS)
def test_new_formulas_are_computable_by_code(cell, enum, extracted, expected):
    """Слагаемые извлечены, итоговой строки нет — считает КОД, а не модель."""
    calc_defs = registry_for_profile(cell)["calculated"]
    result = _calculate_metrics(calc_defs, dict(extracted))
    assert result.get(enum) == pytest.approx(expected), (
        f"{cell}/{enum}: слагаемые {extracted} извлечены, а вычислитель вернул "
        f"{result.get(enum)!r} вместо {expected}. Показатель приедет пустым — "
        f"это ровно та дыра реколла, ради которой формула заводилась."
    )


@pytest.mark.parametrize("cell,enum,extracted,expected", NEW_FORMULAS)
def test_extracted_value_wins_over_the_formula(cell, enum, extracted, expected):
    """Строку в отчёте нашли — формула молчит, извлечённое старше расчётного.

    Здесь проверяется не приоритет строк (он живёт в `two_stage_extractor`), а
    то, что показатель остался ДВОЙНОЙ природы: извлекаемым он был и до правки.
    """
    registry = registry_for_profile(cell)
    assert enum in {m["enum"] for m in registry["extractable"]}, (
        f"{cell}/{enum}: формулу завели, а из извлекаемых показатель пропал — "
        f"тогда напечатанную в отчёте строку больше никто не прочитает."
    )
