"""Складывает КОД по формуле реестра, а не модель в уме.

ВОПРОС ВЛАДЕЛЬЦА, ИЗ КОТОРОГО ВЫРОС ЭТОТ ФАЙЛ: «Что ты хочешь складывать и
считать? через калькулятор или в уме модели?». Ответ — правило от 09.08: код
возит, хранит и СЧИТАЕТ числа; модель принимает РЕШЕНИЯ по тексту навыка.
Сложение — счёт, а не решение.

ЧТО ЗДЕСЬ СТЕРЕЖЁТСЯ. В реестре есть класс подсказок «нет отдельной строки —
верни null». Сама по себе такая подсказка ВЕРНА: она запрещает модели
досочинять величину. Но если у показателя есть слагаемые, заведённые
отдельными показателями ЭТОЙ ЖЕ ячейки, и формулы нет, — запрет превращается
в молчаливую дыру: компоненты извлечены, итог пуст. Это и есть «низкий реколл
при высоком пресижне», на который жалуется владелец.

Механизм, который закрывает дыру, уже работает: показатель, заведённый И
извлекаемым, И расчётным, берёт извлечённое значение, если строка нашлась, и
считает формулой, если нет (`_dual_nature_enums` в `two_stage_extractor`).
Поэтому подсказку снимать НЕ надо — надо дать формулу.

ПОЧЕМУ СПИСОК ИСКЛЮЧЕНИЙ ЛЕЖИТ В КОДЕ, А НЕ В КОММЕНТАРИИ. Показателей этого
класса четыре десятка, и у большинства формулы быть НЕ ДОЛЖНО: слагаемых в
реестре нет вовсе, либо вычитание дало бы двойной счёт. Разница между «ещё не
завели» и «сознательно не заводим» видна только тогда, когда второе записано
машиночитаемо. В комментарии её не отличить, и следующий агент заведёт формулу
там, где она врёт.

ПРОВЕРКА СТОРОЖА ОТКАТОМ — три мутации, все три прогнаны 20.08.2026:
* переименовать слагаемое в формуле SECURITIES_ASSETS (`ifrs_bank_ru.json`) в
  несуществующее — `test_new_formulas_are_computable_by_code` краснеет
  «Obtained: None, Expected: 35.0». Проверять НАЛИЧИЕ строки в json мало:
  формула с опечаткой лежит в файле так же тихо, как правильная;
* убрать любую строку из `WITHOUT_FORMULA` —
  `test_every_empty_hint_is_answered` называет пару поимённо;
* завести формулу показателю ИЗ списка исключений —
  `test_no_stale_exceptions` называет его поимённо.
"""
