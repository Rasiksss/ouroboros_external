"""Правила ВЫДАЧИ извлечения — по существу, а не сравнением двух путей (#154 / В3).

ЧТО ЗА ДЕФЕКТ ЗАКРЫВАЕТСЯ. Выбор периодов прогона, markdown-таблица и Excel
переехали из станционного скрипта `station-skills/aifa-extract/scripts/extract.py`
в общий модуль `finengine.skills.extract_present`, и оба пути (старый скрипт и
навык-спека) зовут теперь ОДИН И ТОТ ЖЕ код. Единственным сторожем на этот
переезд было сравнение «спека == скрипт» — сторож ОТНОСИТЕЛЬНЫЙ: сломай правило
внутри общего модуля, и обе половины сломаются ОДИНАКОВО, а сравнение останется
зелёным. Проверено руками: `pick_periods` переделали на «самый свежий год»
вместо «самого частого», `format_number` перестал ставить прочерк — весь прогон
остался зелёным. Это тот же класс промаха, что #137: тест ходит не туда, куда
ходит пользователь, и молчит на сломанном проде.

Поэтому здесь сторожа АБСОЛЮТНЫЕ: каждое правило проверяется на подобранном
входе и на граничных значениях, безо всякой второй половины для сравнения.
"""
from __future__ import annotations

import pytest

from finengine.skills.extract_present import (
    format_number,
    pick_periods,
    render_table_markdown,
    value_for_period,
)


def _metric(enum: str, pairs: list[tuple[str, object]], unit: str = "млн руб.") -> dict:
    """Показатель в том виде, в каком его отдаёт движок: значения по периодам."""
    return {
        "enum": enum,
        "name_ru": enum.lower(),
        "unit": unit,
        "period_values": [{"period": p, "value": v} for p, v in pairs],
    }


# ─────────────────────────── выбор периодов прогона ───────────────────────────

def test_main_period_is_the_most_populated_year_not_the_latest():
    """ГЛАВНОЕ правило: основной год — тот, где БОЛЬШЕ ВСЕГО значений.

    Не «самый свежий»: в отчёте всегда мелькают годы из примечаний, планов и
    сравнительных справок. Возьми мы свежесть — основным периодом прогона стал бы
    год с парой случайных чисел, и вся таблица приехала бы пустой при полном
    наборе извлечённых показателей."""
    metrics = [_metric(f"M{i}", [("31 декабря 2023", 100 + i), ("31 декабря 2022", 90 + i)])
               for i in range(10)]
    # Пара упоминаний более СВЕЖИХ лет — ровно то, чем отчёт и сбивает выбор:
    # прогноз в примечании и один показатель за незакрытый год.
    metrics.append(_metric("FUTURE_CAPEX_LIABILITIES", [("2025", 12), ("2026", 7)]))

    assert pick_periods(metrics) == ("2023", "2022")


def test_the_engine_has_the_last_word_on_periods():
    """🔴 ЖИВОЙ ДЕФЕКТ 22.08.2026: `severstal-Q1-2025.pdf`, нонс 1a5d94b5.

    Движок определил периоды верно и сказал об этом в событии `start`
    (`period_current: "Q1 2025"`, `period_prev: "Q1 2024"`). Подсчёт лет решил
    иначе, и станция собрала таблицу ПЕРЕВЁРНУТОЙ — вот её настоящая шапка из
    хранилища прогона:

        | Показатель | 2024 | 2025 | Ед. |
        | Выручка | 188 706 | 178 733 | млн. руб. |

    Числа под своими ярлыками, но текущий период встал в колонку предыдущего:
    в конверте прогона осталось `main_period: '2024', prev_period: '2025'`.
    Отсюда перевёрнутые колонки книги Excel, счёт `metrics_found` по чужому
    году и перевёрнутые периоды в сводке, уезжающей в промпт следующего хода.

    У промежуточного отчёта лет ровно поровну (баланс сравнивается с
    `31.12.2024`, ОПУ — с `Q1 2024`), и порядок решает случайность подсчёта.
    Спорить с движком тут не о чем: он единственный, кто видел титул отчёта.
    """
    метрики = [_metric("SALES_REVENUE", [("Q1 2025", 178733), ("Q1 2024", 188706)]),
               _metric("TOTAL_CURRENT_ASSETS", [("31.03.2025", 331529), ("31.12.2024", 354085)]),
               # Ряд, которым подсчёт и перевешивается: у денежных средств
               # движок отдаёт ещё и прошлогоднюю дату того же квартала.
               _metric("CASH_EQUIVALENTS", [("31.03.2025", 95866), ("31.12.2024", 128571),
                                            ("31.03.2024", 373568)])]

    assert pick_periods(метрики) == ("2024", "2025"), (
        "фикстура перестала воспроизводить живой дефект — сторож ниже "
        "проверяет пустоту")
    assert pick_periods(метрики, ("Q1 2025", "Q1 2024")) == ("2025", "2024"), (
        "слово движка не перевесило подсчёт — колонки снова уедут наоборот")


def test_a_year_the_engine_names_but_the_report_lacks_is_not_trusted():
    """Движок назвал год, которого в показателях нет — верим подсчёту.

    Это не придирка: пустой или чужой ярлык в событии сделал бы `main_year`
    годом, по которому `value_for_period` не найдёт НИ ОДНОГО значения, и
    таблица вышла бы пустой при полном наборе извлечённых показателей.
    """
    метрики = [_metric(f"M{i}", [("31 декабря 2024", 1), ("31 декабря 2023", 2)])
               for i in range(5)]
    assert pick_periods(метрики, ("FY 2019", "FY 2018")) == ("2024", "2023")
    assert pick_periods(метрики, ("", "")) == ("2024", "2023")
    assert pick_periods(метрики, None) == ("2024", "2023")


def test_previous_period_is_strictly_main_minus_one():
    """Предыдущий год — строго «основной − 1», если он в отчёте есть.

    Даже когда другой год встречается чаще: сравнение год-к-году в отчётности
    идёт с непосредственно предшествующим периодом, а не с самым населённым."""
    metrics = [_metric(f"A{i}", [("FY 2024", 10 + i)]) for i in range(10)]
    metrics += [_metric(f"B{i}", [("FY 2022", 20 + i)]) for i in range(5)]
    metrics += [_metric(f"C{i}", [("FY 2023", 30 + i)]) for i in range(2)]

    assert pick_periods(metrics) == ("2024", "2023")


def test_previous_period_falls_back_to_the_next_most_populated_year():
    """Если года «основной − 1» в отчёте нет вовсе — берём следующий по частоте:
    пустая вторая колонка хуже, чем колонка с разрывом в год."""
    metrics = [_metric(f"A{i}", [("2024", 10 + i)]) for i in range(10)]
    metrics += [_metric(f"B{i}", [("2021", 20 + i)]) for i in range(3)]

    assert pick_periods(metrics) == ("2024", "2021")


def test_no_periods_at_all_is_not_a_crash():
    """Движок мог не разобрать ни одного периода (сканы, кривой OCR). Это не
    авария: таблица соберётся на «текущий/пред.», прогон дойдёт до пользователя."""
    assert pick_periods([_metric("TOTAL_ASSETS", [])]) == ("", "")


def test_period_matches_by_year_across_engine_label_formats():
    """Периоды приезжают из движка в разных формах («FY 2024», «31.12.2024»,
    «12M 2024»). Сопоставление идёт подстрокой по году: иначе одна и та же
    таблица собиралась бы по-разному от отчёта к отчёту."""
    m = _metric("NET_INCOME", [("12M 2024", 5), ("31.12.2023", 4)])
    assert value_for_period(m, "2024") == 5
    assert value_for_period(m, "2023") == 4
    assert value_for_period(m, "2022") is None
    # Пустой период = «текущий» в терминах движка.
    assert value_for_period({"value_current": 42}, "") == 42


# ──────────────────────────── формат чисел выдачи ────────────────────────────

@pytest.mark.parametrize(
    ("value", "expected"),
    [
        # Прочерк, а не пустота: пользователь должен видеть, что показатель
        # СПРАШИВАЛИ и не нашли, а не думать, что строку забыли.
        (None, "—"),
        # 0 — найденное значение, а не отсутствие. Граница: falsy, но не None.
        (0, "0"),
        (1234567, "1 234 567"),
        (-1234, "-1 234"),
        # Целое, приехавшее float'ом, показываем без хвоста «.0».
        (1234.0, "1 234"),
        (1234.5, "1 234.5"),
        # Текстовые показатели (мнение аудитора, валюта отчётности) — как есть.
        ("с оговоркой", "с оговоркой"),
    ],
)
def test_format_number_boundaries(value, expected):
    """Разряды — ПРОБЕЛОМ (русский отчёт), пустое значение — прочерком."""
    assert format_number(value) == expected


# ───────────────────────────── таблица для чата ─────────────────────────────

def test_table_shows_dash_for_a_missing_side_and_drops_empty_rows():
    """Показатель, найденный только за один период, остаётся в таблице с
    прочерком во второй колонке; показатель, не найденный ни за один, — уходит
    (иначе таблица в чате наполовину состоит из пустых строк)."""
    metrics = [
        _metric("TOTAL_ASSETS", [("2024", 814479), ("2023", 721063)]),
        _metric("EBITDA", [("2024", 250000)]),
        _metric("GUARANTEES", []),
    ]
    md = render_table_markdown(
        metrics, name_by_enum={"TOTAL_ASSETS": "Активы", "EBITDA": "EBITDA"},
        main_period="2024", prev_period="2023",
    )
    rows = md.splitlines()

    assert rows[0] == "| Показатель | 2024 | 2023 | Ед. |"
    assert rows[2] == "| Активы | 814 479 | 721 063 | млн руб. |"
    assert rows[3] == "| EBITDA | 250 000 | — | млн руб. |"
    assert len(rows) == 4, f"строка без значений не должна попадать в таблицу:\n{md}"


def test_table_composition_follows_the_role_layout():
    """Таблица в чате — это ВЫДАЧА, её состав задаёт роль (#141), а не то,
    сколько показателей движок читал из отчёта: при `--basis-full` базис
    специально шире роли, и без фильтра пользователь роли получил бы в чат всю
    ячейку вместо своих строк."""
    metrics = [
        _metric("TOTAL_ASSETS", [("2024", 1)]),
        _metric("NET_INCOME", [("2024", 2)]),
    ]
    md = render_table_markdown(
        metrics, name_by_enum={"TOTAL_ASSETS": "Активы", "NET_INCOME": "Чистая прибыль"},
        main_period="2024", prev_period="2023", show_enums={"NET_INCOME"},
    )

    assert "Чистая прибыль" in md
    assert "Активы" not in md, "показатель вне раскладки роли уехал в чат"
