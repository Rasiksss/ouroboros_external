"""Потолок кандидатов и бюджет ответа не разъезжаются (21.08.2026).

ПОЧЕМУ ПОТОЛОК ПОДНЯТ. Сбор даёт ~800 новостей, правила оставляют ~200, а к
модели уходило 60 — остальные 140 не попадали в выпуск НИКОГДА, каким бы важным
ни было событие. Это был главный ограничитель полноты. Цена замерена по 12
прогонам: $0.00073 за кандидата, то есть 60 → $0.044, 100 → $0.073 за прогон.

🔴 ПОЧЕМУ БЮДЖЕТ СЧИТАЕТСЯ, А НЕ СТОИТ ЧИСЛОМ. `max_output` был литералом
24000, подобранным под 60 кандидатов. Подними потолок — литерал остался бы
прежним, и ответ модели обрывался бы на полуслове. Ровно этим отказом куплены
две предыдущие редакции той строки:
  * 17.08 бюджет 9000 → 29 287 знаков размышлений и НИ ОДНОГО знака ответа,
    выпуск с нулями при 942 собранных новостях;
  * 19.08 обрыв разбора на управляющем символе → «0 компаний» при 199
    отобранных.
Токены размышлений идут в тот же счёт, что и ответ, поэтому запас обязателен.

Замер на 60 кандидатах: выход 10 965–19 904 токенов, то есть 183–332 на
кандидата. Формула 350×кандидатов + 8000 покрывает верх замера с запасом:
60 → 29 000, 100 → 43 000. Модель принимает до 64 000 (проверено живым
вызовом). Неиспользованный бюджет не оплачивается.
"""
from __future__ import annotations

import inspect
import re

from finengine.config import settings
from finengine.skills.news import classify, pipeline


def _budget_for(n: int) -> int:
    """Бюджет, который код запросит на n кандидатов."""
    src = inspect.getsource(classify.classify_batch)
    m = re.search(r"max_output=([0-9]+)\s*\*\s*len\(items\)\s*\+\s*([0-9]+)", src)
    assert m, "бюджет больше не считается от числа кандидатов"
    return int(m.group(1)) * n + int(m.group(2))


def test_budget_covers_the_measured_output():
    """Отрицательный контроль: вернул `max_output=24000` литералом — краснеет
    на потолке 100, потому что 24000 меньше замеренного верха."""
    worst_per_item = 332          # верх замера по 12 прогонам
    for n in (60, 100, 150):
        assert _budget_for(n) >= worst_per_item * n, (
            f"на {n} кандидатах бюджет {_budget_for(n)} ниже замеренного "
            f"верха {worst_per_item * n} — ответ оборвётся на полуслове")


def test_budget_leaves_room_for_reasoning():
    """Токены размышлений идут в тот же счёт. Живой отказ: 29 287 знаков
    размышлений при нулевом ответе."""
    src = inspect.getsource(classify.classify_batch)
    assert "размышлен" in src, (
        "исчезло объяснение про размышления — бюджет вернут к тесному")
    assert _budget_for(0) >= 8000, "нет запаса на размышления"


def test_budget_stays_within_what_the_model_accepts():
    """Проверено живым вызовом: модель принимает до 64 000. Формула не должна
    выходить за это на разумных потолках."""
    assert _budget_for(150) <= 64000, (
        f"на 150 кандидатах бюджет {_budget_for(150)} выше принимаемого моделью")


def test_the_cap_is_a_setting_not_a_literal():
    """Потолок меняет цену прогона вдвое — владелец должен уметь дёрнуть его
    переменной окружения, без выкатки."""
    assert settings.news_top_candidates >= 60
    src = inspect.getsource(pipeline.run_daily_news_pipeline)
    assert "news_top_candidates" in src, (
        "конвейер не читает настройку — потолок снова прибит числом")
    assert "top_n_candidates: int | None" in src, (
        "явно переданное значение должно оставаться сильнее настройки")


def test_explicit_argument_still_wins():
    """Ручка тула `top_n` и CLI передают число явно — оно обязано побеждать
    настройку, иначе замеры на другом потолке станут невозможны."""
    src = inspect.getsource(pipeline.run_daily_news_pipeline)
    assert "top_n_candidates or" in src, (
        "явное значение перестало иметь приоритет над настройкой")
