"""Сторож не пришпиливает ФОРМУЛИРОВКИ промптов.

🔴 РЕШЕНИЕ ВЛАДЕЛЬЦА 25.08.2026, дословно: «мы будем менять промпты ещё 1000
раз, каждый раз переписывать сторожей придётся? Это бред, убирай эту проверку».

ЧТО БЫЛО. В наборе накопились тесты вида `assert "ДОЖДИСЬ" in body`,
`assert "3 134" in rules`, `assert "СПРАВОЧНИК" in body.upper()` — они искали
подстроки в теле навыка, в конституции и в инструкции хода. Такой тест краснеет
НЕ когда правило исчезло, а когда его сказали другими словами. За неделю два
из них переписывались вслед за переформулировками; настоящую пропажу они при
этом не ловят — правило можно выхолостить, оставив слова на месте.

ЧТО ПРОВЕРЯТЬ МОЖНО И НУЖНО:

  * КОНТРАКТ — имя флага (`--metrics`), путь (`method/catalogue/`), имя тула,
    ключ JSON, имя каталога комнаты. Переписал текст вокруг — тест молчит;
    переименовал флаг — краснеет по делу;
  * ОТРИЦАНИЕ — «в теле НЕ должно быть обещания фонового запуска». От
    переформулировки не зависит: краснеет, только если вредное впишут заново;
  * ВЫВОД КОДА — `res.stderr`, текст исключения, поле ответа. Это поведение,
    а не стиль.

⚠️ ЧТО ЭТОТ СТОРОЖ МОЖЕТ И ЧЕГО НЕТ. Он ловит ФОРМУ: положительное сравнение
русской фразы с переменной, в которой лежит текст промпта. Он не отличит
удачную проверку от неудачной и обходится переименованием переменной. Это
напоминание о договорённости, а не забор.

ЕСЛИ ПРОВЕРКА ВСЁ-ТАКИ НУЖНА — пометь строку `# pin-ok: <почему>`. Так помечены
два места, где предмет — механизм, а не формулировка: подстановка канарейки при
проверке кэша методики и разбор линз анализа, где строки приходят ИЗ ДАННЫХ.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

ТЕСТЫ = Path(__file__).resolve().parent
# Переменные, в которых по нашему коду лежит ТЕКСТ ПРОМПТА.
ТЕКСТ_ПРОМПТА = {"body", "rules", "low", "op", "tail", "frame", "тело",
                 "soul", "order", "before", "after"}
ПРОЗА = re.compile(r"[А-Яа-яЁё]{4}")


def _пришпилено() -> list[str]:
    находки: list[str] = []
    for f in sorted(ТЕСТЫ.glob("test_*.py")):
        if f.name == Path(__file__).name:
            continue
        src = f.read_text(encoding="utf-8", errors="ignore")
        if not re.search(r"SKILL\.md|SOUL\.md|method/|_OPERATING_PROCEDURE", src):
            continue
        строки = src.splitlines()
        try:
            дерево = ast.parse(src)
        except SyntaxError:
            continue
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.Assert):
                continue
            for t in ast.walk(узел):
                if not isinstance(t, ast.Compare):
                    continue
                if not (isinstance(t.left, ast.Constant) and isinstance(t.left.value, str)):
                    continue
                if not (t.ops and isinstance(t.ops[0], ast.In)):
                    continue  # отрицания разрешены
                if not ПРОЗА.search(t.left.value):
                    continue  # контрактные имена разрешены
                цель = ast.unparse(t.comparators[0])
                if re.split(r"[.\[(]", цель)[0] not in ТЕКСТ_ПРОМПТА:
                    continue  # это вывод кода, а не промпт
                строка = строки[узел.lineno - 1] if узел.lineno <= len(строки) else ""
                соседи = "\n".join(строки[max(0, узел.lineno - 3):узел.lineno + 1])
                if "pin-ok:" in строка or "pin-ok:" in соседи:
                    continue
                находки.append(
                    f"{f.name}:{узел.lineno} — «{t.left.value[:44]}» в {цель[:30]}")
    return находки


def test_no_guard_pins_a_phrase_of_a_prompt() -> None:
    """Ни один сторож не держит формулировку промпта положительным сравнением."""
    находки = _пришпилено()
    assert not находки, (
        "сторож снова пришпиливает формулировку промпта. Проверяй КОНТРАКТ "
        "(имя флага, путь, ключ), ОТРИЦАНИЕ (вредного нет) или ВЫВОД КОДА. "
        "Если проверка всё же нужна — пометь строку `# pin-ok: <почему>`:\n  "
        + "\n  ".join(находки))


def test_the_detector_itself_can_see_a_pin() -> None:
    """Отрицательный контроль ВНУТРИ сторожа.

    Без него `_пришпилено()` могло бы всегда возвращать пустой список — из-за
    опечатки в имени переменной или в регулярке, — и тест был бы зелёным на
    пустом месте. Проверяем на заведомо пришпиленном образце.
    """
    образец = ast.parse('assert "нельзя вот так" in body\n')
    узел = образец.body[0]
    assert isinstance(узел, ast.Assert)
    t = узел.test
    assert isinstance(t, ast.Compare)
    assert ПРОЗА.search(t.left.value), "регулярка перестала видеть русскую прозу"
    assert re.split(r"[.\[(]", ast.unparse(t.comparators[0]))[0] in ТЕКСТ_ПРОМПТА, (
        "список переменных с текстом промпта перестал включать `body`")
