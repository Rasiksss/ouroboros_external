from __future__ import annotations

from pathlib import Path


# Запрет живёт в КОНСТИТУЦИИ, а не в телах (решение владельца 31.08.2026:
# «зачем это в навыке извлечения?»). `.model-rpc` — свойство комнаты, общее
# для всех навыков; конституция едет в промпт ВСЕГДА, тело навыка — только
# когда навык выбран, так что запрет в конституции строже, а не мягче.
КОНСТИТУЦИЯ = Path("agent-workspace/bootstrap/TOOLS.md")


def _body(name: str) -> str:
    return Path(f"station-skills/{name}/SKILL.md").read_text(encoding="utf-8")


def test_service_channel_is_declared_off_limits():
    """Про `.model-rpc` сказано, и сказано в конституции комнаты."""
    body = КОНСТИТУЦИЯ.read_text(encoding="utf-8")
    assert ".model-rpc" in body, (
        "про служебный канал в конституции ни слова — модель найдёт его сама "
        "и начнёт вычитывать (живой ход 15.08: 82 КБ канала в контекст). "
        "Правило переехало сюда из тел навыков — не возвращай его в тела, "
        "верни в TOOLS.md")
    # 🔴 ПРОВЕРКИ ФОРМУЛИРОВОК УБРАНЫ (решение владельца 25.08.2026): искалась
    # точная фраза «НЕ ЧИТАЙ» — краснела бы от любой переписи. Осталось ИМЯ
    # КАНАЛА: контракт между текстом для модели и раскладкой комнаты.

def test_the_launch_command_stays_one_command():
    """Команда запуска не должна быть составной — песочница её отобьёт.

    🔴 ИЗ ЭТОГО СТОРОЖА УБРАНЫ ПРОВЕРКИ ФОРМУЛИРОВОК (решение владельца
    25.08.2026). Он держал в теле навыка слова «ДОЖДИСЬ» и «ПЕРЕЗАПУСК
    ЗАПРЕЩЁН» — то есть требовал конкретных фраз в ПРОМПТЕ.

    Довод владельца: «мы будем менять промпты ещё тысячу раз, каждый раз
    переписывать сторожей — бред». Он прав, и цена видна на этом же тесте: за
    неделю его переписывали дважды вслед за переформулировками, и оба раза он
    краснел не потому, что правило исчезло, а потому что его сказали иначе.
    Сторож, который ломается от синонима, не охраняет — он берёт налог.

    ЧТО ОСТАЛОСЬ. Проверка, не зависящая от формулировок: команда запуска —
    ОДНА, без `;`. Это свойство САМОЙ КОМАНДЫ, а не её описания: составную
    строку преflight песочницы отбивает, и текст вокруг можно переписывать как
    угодно — проверка останется верной.

    ⚠️ ТРЕБОВАНИЕ «дождись возврата» из тела навыка НИКУДА НЕ ДЕЛОСЬ. Его
    просто больше не сторожит текстовое сравнение: сломать переформулировкой
    нельзя, а выкинуть намеренно — это правка навыка, видная в ревью.
    """
    import re

    body = _body("aifa-extract")
    # Сама команда — инлайн-код со скриптом запуска, а не текст вокруг:
    # прежний вариант резал тело по заголовку «Необязательные флаги» и
    # покраснел на переписи структуры, поймав `;` из ПРОЗЫ рядом.
    команда = next(c for c in re.findall(r"`([^`]+)`", body)
                   if "extract_run.sh" in c)
    assert ";" not in команда, (
        "в команде запуска снова появился разделитель — эстафету делает "
        "обёртка, а составную команду песочница отбивает преflight'ом")
