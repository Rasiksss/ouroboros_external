"""Зацикленный ответ модели не доезжает до экрана (17.08.2026).

ЖИВОЙ СЛУЧАЙ НА ПРОДЕ. Ответ оборвался на фразе «в собранном дайджесте за по»,
и дальше шло 394 подряд «П» — пользователь увидел экран мусора. По истории
диалогов это третий случай, все на `qwen/qwen3.6-plus` в базовом пути:
    10.06 12:40  ' ' ×28
    10.06 13:04  ' ' ×65
    17.08 16:02  'П' ×394
То есть модель срывается сама и делала это задолго до сегодняшних правок.
Защищаться надо на нашей стороне: показать то осмысленное, что успело прийти,
и честно сказать, что дальше был мусор.

ДВА ПОРОГА, А НЕ ОДИН — в этом вся тонкость. Буквы и цифры подряд в осмысленном
тексте не идут никогда. А дефисы, равно, решётки и пробелы идут законно:
разделители таблиц, горизонтальные линии, выравнивание. Один общий порог либо
пропускал бы вырождение, либо рубил бы нормальную разметку.
"""
from __future__ import annotations

import pytest

from finengine.policy.guardrails import (
    _RUN_LIMIT_ALNUM,
    _RUN_LIMIT_OTHER,
    StreamScrubber,
)


def _stream(chunks: list[str]) -> str:
    sc = StreamScrubber()
    out = "".join(sc.feed(c) for c in chunks)
    return out + sc.flush()


def test_letter_loop_is_cut_and_named():
    """Отрицательный контроль: снял обрезку — в выводе 400 знаков мусора."""
    out = _stream(["В собранном дайджесте за по", "П" * 200, "П" * 200, " хвост"])
    assert "П" * 40 not in out, "повтор доехал до экрана"
    assert "В собранном дайджесте за по" in out, "осмысленный текст потерян"
    assert "зациклилась" in out, "пользователю не сказали, что случилось"


def test_repeat_split_across_chunks_is_caught():
    """Повтор приходит порциями по 5–50 знаков: в отдельном куске его не
    видно, состояние обязано тянуться между вызовами."""
    out = _stream(["текст "] + ["П" * 5] * 20)
    assert "П" * 40 not in out
    assert "зациклилась" in out


def test_nothing_is_emitted_after_the_cut():
    """Досыпать мусор после обрыва незачем — сказали один раз."""
    sc = StreamScrubber()
    sc.feed("начало " + "Ж" * 100)
    assert sc.feed("Ж" * 100) == ""
    assert sc.feed("и ещё немного текста") == ""


@pytest.mark.parametrize("rule", ["-" * 80, "=" * 90, "_" * 70, "|" * 60, "#" * 50])
def test_markdown_rules_are_not_touched(rule):
    """ЛОЖНОЕ СРАБАТЫВАНИЕ ХУЖЕ ПРОПУСКА: разделитель таблицы или линия —
    нормальная разметка, и рубить её нельзя."""
    out = _stream([f"Заголовок\n{rule}\nстрока таблицы"])
    assert rule in out
    assert "зациклилась" not in out


def test_wide_table_alignment_survives():
    """Выравнивание пробелами в таблице — тоже законный длинный ряд."""
    out = _stream(["| Показатель" + " " * 100 + "| Значение |"])
    assert "зациклилась" not in out


def test_thresholds_differ_and_alnum_is_stricter():
    """Смысл двух порогов: у букв он заведомо ниже."""
    assert _RUN_LIMIT_ALNUM < _RUN_LIMIT_OTHER
    assert _RUN_LIMIT_OTHER > 64, "порог для разметки ниже разумной ширины таблицы"


def test_normal_text_passes_through_unchanged():
    """Главное свойство не сломано."""
    text = "Обычный ответ про IBM и NVIDIA. Ничего необычного тут нет.\n\nВторой абзац."
    assert _stream([text]) == text
