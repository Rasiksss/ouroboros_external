#!/bin/bash
# Общий лаунчер станционных навыков: одно тело на все `station-skills/*/run.sh`.
#
# ЗАЧЕМ ОДНО ТЕЛО. Лаунчер — единственная развилка между двумя копиями нашего
# кода: свежей, приехавшей ПОЛКОЙ в комнату станции, и запечённой в образ. В
# этом теле живёт #181 (громкий отказ вместо молчаливой подмены версии) и #155
# (отпечаток «чем считали»). Копий было две, и они уже разошлись: у analyze
# появилась проверка КОМПЛЕКТА (методика), у extract — нет. С четырьмя навыками
# копий стало бы четыре, а починить такое однажды означает починить в трёх.
#
# Вызов из навыка — три строки:
#   SKILL=aifa-extract
#   SKILL_REL="aifa_station_skills/aifa-extract/scripts/extract.py"
#   exec bash "$(dirname "$0")/../_runner/launch.sh" "$@"
# Необязательный METHOD_REL добавляет в проверку комплекта второй файл.
#
# ⚠️ Поведение обязано остаться 1:1 с прежними run.sh — это доказывает
# `tests/test_station_launcher_is_loud.py`, который прошёл БЕЗ правок.

# Запечатанная станция: вызовы модели уходят в файловый мост вместо HTTP, а
# писать можно только в рабочую папку комнаты — отсюда относительные дефолты.
# Без FE_RPC_DIR движок пошёл бы прямым HTTP-вызовом, не соединился и свалился
# бы на путь, которому нужны лишние библиотеки.
export FE_RPC_DIR="${FE_RPC_DIR:-./.model-rpc}"
export FINENGINE_DATA_DIR="${FINENGINE_DATA_DIR:-./fe-data}"
export FINENGINE_DOCS_DIR="${FINENGINE_DOCS_DIR:-./fe-data/documents}"

if [ -z "${SKILL:-}" ] || [ -z "${SKILL_REL:-}" ]; then
  echo "[_runner] 🔴 ОТКАЗ: лаунчер вызван без SKILL/SKILL_REL" >&2
  exit 2
fi

# Замка от дубля здесь БОЛЬШЕ НЕТ — и это выстраданное решение (17.08.2026).
# Файловый замок в этом месте прожил один прогон: модель сняла его командой
# `rm -rf .aifa-extract.lock` и ушла мимо лаунчера самодельной обёрткой.
# Файл в писчей папке — не запрет, а приглашение. Запрет дубля теперь внутри
# самих скриптов навыков по ЖИВЫМ процессам комнаты — см.
# finengine/skills/station_guard.py: его нельзя ни стереть, ни обойти прямым
# `python3 …/extract.py`.

BAKED="${FE_BAKED_DIR:-/usr/lib64/python3.12/site-packages}"

_say() { echo "[$SKILL] $*" >&2; }

# Отпечаток исполняемого файла печатается ВСЕГДА — чтобы «чем считали» было
# видно постфактум по логу прогона (#155, паспорт версий). sha256sum в сессии
# станции может быть не в allowlist, поэтому считаем питоном — он тут заведомо есть.
_stamp() {
  python3 - "$SKILL" "$1" <<'PY' || true
import hashlib, sys
skill, p = sys.argv[1], sys.argv[2]
try:
    b = open(p, "rb").read()
    print(f"[{skill}] исполняю {p} "
          f"({len(b)} б, sha256 {hashlib.sha256(b).hexdigest()[:12]})", file=sys.stderr)
except OSError as exc:
    print(f"[{skill}] отпечаток не снят: {exc}", file=sys.stderr)
PY
}

# #51 Фаза 1 «полка вместо запекания»: движок и скрипт навыка едут в комнату
# станции файлом (files:upload), а не пекутся в образ. Распаковка идемпотентна,
# через python-zipfile (tar/unzip в allowlist сессии может не быть).
#
# #181 ГРОМКИЙ ОТКАЗ ВМЕСТО МОЛЧАЛИВОЙ ПОДМЕНЫ (09.08.2026). До того отсутствие
# полки МОЛЧА уводило исполнение на запечённую в образ копию. Замер 05.08: полка
# 11 667 б, запечённая копия 8 784 б от 29 июня — на четверть короче, без #147
# (реестр ячейки доезжает до промпта) и #141 (роль сужает состав), и без каталога
# method/ (методика переехала в файлы 09.08). Пользователь получил бы результат,
# посчитанный позапрошлой методикой, и отличить его было бы НЕ ПО ЧЕМУ.
# Теперь: полки нет → отказ с кодом 3. Осознанный откат на запечённую копию
# остаётся, но только по явному FE_SKILL_SHELF=0 и с записью в лог.
if [ "${FE_SKILL_SHELF:-auto}" = "0" ]; then
  _say "ВНИМАНИЕ: FE_SKILL_SHELF=0 — полка выключена вручную, беру ЗАПЕЧЁННУЮ копию образа"
  _stamp "$BAKED/$SKILL_REL"
  exec python3 "$BAKED/$SKILL_REL" "$@"
fi

# 🔴 ПУТИ ОТНОСИТЕЛЬНЫЕ, И ЭТО НЕ НЕДОСМОТР — ДВА ПРОСТРАНСТВА ИМЁН.
#
# 16.08.2026 я сделал их абсолютными (`/workspace/.shelf`) на догадке, что
# относительный путь и есть причина ENOENT у модели. Живой прогон опроверг это
# в тот же час: рабочий каталог комнаты — `/tmp/ws/<id>/workspace`, никакого
# `/workspace` в её файловой системе нет. Лаунчер перестал находить полку,
# модель чинила прогон руками через FE_SHELF_DIR. Откатано.
#
# КАК ЕСТЬ НА САМОМ ДЕЛЕ. Одно и то же место зовётся по-разному:
#   * файловый API гейтвея (`files:upload`, тул `read`) — `/workspace/.shelf.zip`;
#     это ЕГО корень, плагин кладёт архив именно туда;
#   * `exec` в комнате — рабочий каталог `/tmp/ws/<id>/workspace`, и `/workspace`
#     оттуда недостижим.
# Лаунчер исполняется внутри exec, значит его путь — ОТНОСИТЕЛЬНО cwd. Тем же
# правилом живут FE_RPC_DIR и FINENGINE_DATA_DIR выше: они работали всегда.
#
# ⚠️ Прежде чем снова «чинить» это на абсолютный путь — прочитай абзац выше и
# посмотри `pwd` в живой комнате. Сторож: `tests/test_shelf_path_is_one.py`.
SHELF="${FE_SHELF_DIR:-./.shelf}"
SHELF_ZIP="${FE_SHELF_ZIP:-./.shelf.zip}"
if [ ! -d "$SHELF" ] && [ -f "$SHELF_ZIP" ]; then
  python3 -m zipfile -e "$SHELF_ZIP" "$SHELF" || true
fi

# Комплект, а не один файл: без method/ анализ поднимется и упадёт уже В ХОДЕ —
# через минуты работы и потраченный вызов модели. Проверяем сразу.
NEEDS="$SKILL_REL"
[ -n "${METHOD_REL:-}" ] && NEEDS="$NEEDS $METHOD_REL"
for need in $NEEDS; do
  if [ ! -f "$SHELF/$need" ]; then
    _say "🔴 ОТКАЗ: на полке нет '$need' (искал в $SHELF, зип $SHELF_ZIP)"
    _say "   Полка — это наш код, который гейтвей кладёт в комнату станции."
    _say "   Что проверить: доехал ли shelf.zip (плагин workstation-sandbox, files:upload)"
    _say "   и собран ли он целиком (deploy/skill-hub/pack.sh)."
    _say "   Запечённую в образ копию НЕ беру: она от 29.06 и посчитала бы прогон"
    _say "   позапрошлой методикой молча. Осознанный откат — FE_SKILL_SHELF=0."
    exit 3
  fi
done

export PYTHONPATH="$SHELF${PYTHONPATH:+:$PYTHONPATH}"
_stamp "$SHELF/$SKILL_REL"
exec python3 "$SHELF/$SKILL_REL" "$@"
